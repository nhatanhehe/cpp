inline ll add(ll a, ll b)
{
    ll res = a + b;
    if (res >= mod)
        res -= mod;
    return res;
}
ll sub(ll a, ll b)
{
    return ((a - b) % mod + mod) % mod;
}
inline ll mul(ll a, ll b)
{
    ll res = a * b;
    if (res >= mod)
        res %= mod;
    return res;
}
int t, n, m;
string s[11];
void solve()
{
    string ans = s[1];
    for (int i = 0; i < m; i++)
    {
        char sv = ans[i];
        for (char c = 'a'; c <= 'z'; c++)
        {
            ans[i] = c;
            bool check = 1;
            for (int k = 1; k <= n; k++)
            {
                int cnt = 0;
                for (int p = 0; p < m; p++)
                {
                    if (s[k][p] != ans[p])
                        cnt++;
                }
                if (cnt > 1)
                {
                    check = 0;
                    break;
                }
            }
            if (check)
            {
                cout << ans << '\n';
                return;
            }
        }
        ans[i] = sv;
    }
    cout << -1 << '\n';
}
main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);
    if (fopen(Task ".inp", "r"))
    {
        freopen(Task ".inp", "r", stdin);
        freopen(Task ".out", "w", stdout);
    }
    cin >> t;
    while (t--)
    {
        cin >> n >> m;
        for (int i = 1; i <= n; i++)
        {
            cin >> s[i];
        }
        solve();
    }
}
