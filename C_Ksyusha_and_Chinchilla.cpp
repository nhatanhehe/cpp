const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n,u,v;
vector<ii>g[N];
vector<int>sz,dp;
// dp[u] min cost cua cay con goc u
// sum[u] tong min cost cua cac con u
bool ans=1;
vector<int>cut;
void dfs(int u,int p){
    dp[u]=1;
    for(auto [v,id]:g[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]+=dp[v];
            if(dp[v]==0) cut.pb(id);
        }
    }
    if(dp[u]>3){
        ans=0;
        return;
    }
    if(dp[u]==3) dp[u]=0;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n;
        sz.resize(n+3,1);
        dp.resize(n+4,0);
        for(int i=1;i<=n;i++) g[i].clear();
        for(int i=1;i<n;i++){
            cin>>u>>v;
            g[u].pb(ii(v,i));
            g[v].pb(ii(u,i));
        }
        ans=1;
        cut.clear();
        dfs(1,-1);
        // for(int i=1;i<=n;i++){
        //     cerr<<i<<" "; debug(dp[i]);
        // }
        if(!ans||dp[1]||n%3!=0) cout<<-1<<'\n';
        else{
            cout<<cut.size()<<'\n';
            for(int x:cut) cout<<x<<" "; cout<<'\n';
        }
    }
}
