ll mul(ll a,ll b,ll mod){
    ll res=0;
    while(b){
        if(b&1) res=(res+a)%mod;
        a=(a+a)%mod;
        b>>=1;
    }
    return res;
}
ll exp(ll a,ll n,ll mod){
    if(n==0) return 1;
    if(n==1) return a;
    ll t=exp(a,n/2,mod);
    t=mul(t,t,mod);
    if(n&1) return mul(t,a,mod);
    else return t;
}

void sieve(){
    memset(p,1,sizeof p);
    p[0]=p[1]=0;
    for(int i=2;i<=1e3;i++){
        if(p[i]){
            for(int j=i*i;j<=1e6;j+=i){
                p[j]=0;
            }
        }
    }
    for(int i=2;i<=1e6;i++) if(p[i]) primes.pb(i);
}
ll C(int n,int k){
    map<int,ll>mp1,mp2,Mbappe;
    for(int p:primes){
        for(ll j=p;j<=n;j*=p){
            mp1[p]+=n/j;
        }
    }
    for(int p:primes){
        for(ll j=p;j<=n-k;j*=p){
            mp2[p]+=(n-k)/j;
        }
    }
    for(int p:primes){
        for(ll j=p;j<=k;j*=p){
            Mbappe[p]+=k/j;
        }
    }
    for(auto [val,cnt]:mp2){
        mp1[val]-=cnt;
    }
    for(auto [val,cnt]:Mbappe){
        mp1[val]-=cnt;
    }
    ll res=1;
    for(auto [val,cnt]:mp1){
        res=mul(res,exp(val,cnt,mod),mod);
    }
    return res;
}
