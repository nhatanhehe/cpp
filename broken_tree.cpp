const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,u,v,w,p,st[N],en[N],ben[N],wei[N],timer,bit[N],ver[N],heavy[N],idx[N],par[N],child[N],wip[N];
struct pt{
    int v,w,p,id;
};
vector<pt>g[N];
vector<int>store;
ii edges[N];
int dfs(int u,int par){
    st[u]=++timer;
    ver[timer]=u;
    int mx=0,child_sz,sz=1;
    for(auto [v,w,p,id]:g[u]){
        if(v!=par){
            child[u]++;
            wei[v]=w;
            ben[v]=p;
            idx[id]=v;
            child_sz=dfs(v,u);
            if(mx<child_sz){
                mx=child_sz;
                heavy[u]=v;
            }
            sz+=child_sz;
        }
    }
    en[u]=timer;
    return sz;
}
void up(int i,int k){
    for(;i<=n;i+=i&-i) bit[i]+=k;
}
ll get(int i){
    ll res=0;
    for(;i;i-=i&-i){
        res+=bit[i];
    }
    return res;
}
ll query(int l,int r){
    if(l>r) return 0;
    return get(r)-get(l-1);
}
void add_(int u){
    wip[u]=child[u];
    for(auto [v,w,p,id]:g[u]){
        add_(v);
    }
    if(!child[u]) store.pb(u);
}
void Sack(int u,int keep){
    for(auto [v,w,p,id]:g[u]){
        if(v!=heavy[u]) Sack(v,0);
    }
    if(heavy[u]){
        wip[heavy[u]]=child[heavy[u]];
        Sack(heavy[u],1);
        if(wip[heavy[u]]==0) store.pb(heavy[u]);
        for(auto [v,w,p,id]:g[u]){
            if(v!=heavy[u]) add_(v);
        }
    }
    if(u==1) return;
    int sub_w=query(st[u]+1,en[u]);
    int needed=sub_w-ben[u];
    while(needed>0&&store.size()){
        int uz=store.back();
        store.pop_back();
        int can=ben[uz]-query(st[uz]+1,en[uz]);
        int allow=min(wei[uz]-1,max(0LL,can));
        if(allow==0){
            wip[par[uz]]--;
            if(!wip[par[uz]]&&par[uz]!=u) store.pb(par[uz]);
            continue;
        }
        int rem=min(allow,needed);
        wei[uz]-=rem;
        ben[uz]-=rem;
        up(st[uz],-rem);
        needed-=rem;
        allow-=rem;
        if(allow==0){
            wip[par[uz]]--;
            if(!wip[par[uz]]&&par[uz]!=u) store.pb(par[uz]);
        }
        else store.pb(uz);
    }
    if(needed>0){
        cout<<-1;
        exit(0);
    }
    if(!keep){
        store.clear();
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<n;i++){
        cin>>u>>v>>w>>p;
        g[u].pb({v,w,p,i});
        par[v]=u;
        edges[i]=ii(u,v);
    }
    dfs(1,-1);
    for(int i=2;i<=n;i++){
        up(st[i],wei[i]);
    }
    Sack(1,0);
    cout<<n<<'\n';
    for(int i=1;i<n;i++){
        auto [u,v]=edges[i];
       // cout<<idx[i]<<'\n';
        cout<<u<<" "<<v<<" "<<wei[idx[i]]<<" "<<ben[idx[i]]<<'\n';
    }
}
