inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,a,b,c,d,f[N],inv[N];
string s;
ll exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    ll t=exp(a,n/2);
    if(n&1) return mul(t,mul(t,a));
    return mul(t,t);
}
void precum(){
    f[0]=1;
    for(int i=1;i<=1e6;i++){
        f[i]=mul(f[i-1],i);
    }
    int maxn=1e6;
    inv[maxn]=exp(f[maxn],mod-2);
    for(int i=maxn-1;i>=0;i--){
        inv[i]=mul(inv[i+1],i+1);
    }
}
ll nCr(int n,int k){
    if(k<0||k>n||n<0) return 0;
    return mul(f[n],mul(inv[k],inv[n-k]));
}
