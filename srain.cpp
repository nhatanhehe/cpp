inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],b[N],q;
struct Segtree{
    struct Node{
        int sum,cnt,Min;
        Node(): sum(0),Min(inf),cnt(0) {}
    };
    vector<Node>tree;
    vector<int>lz;
    int n;
    void init(int _n){
        n=_n;
        tree.assign(n*4+4,Node());
        lz.assign(n*4+4,0);
    }
    Node merge(Node l,Node r){
        Node ans;
        ans.cnt=l.cnt+r.cnt;
        ans.sum=l.sum+r.sum;
        ans.Min=min(l.Min,r.Min);
        return ans;
    }
    void build(int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l==r){
            if(a[l]==b[l]){
                tree[id].cnt=0;
                tree[id].Min=inf;
                tree[id].sum=a[l];
            }
            else{
                tree[id].cnt=1;
                tree[id].Min=a[l]-b[l];
                tree[id].sum=b[l];
            }
            return;
        }
        int mid=(l+r)>>1;
        build(id*2,l,mid);
        build(id*2+1,mid+1,r);
        tree[id]=merge(tree[id*2],tree[id*2+1]);
    }
    void fix(int id,int k){
        if(tree[id].cnt==0) return;
        tree[id].sum+=tree[id].cnt*k;
        tree[id].Min-=k;
        lz[id]+=k;
    }
    void push(int id){
        if(lz[id]){
            fix(id*2,lz[id]);
            fix(id*2+1,lz[id]);
            lz[id]=0;
        }
    }
    void up(int u,int v,int d,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u||tree[id].cnt==0) return;
        if(u<=l&&r<=v&&d<=tree[id].Min){
            fix(id,d);
            return;
        }
        if(l==r){
            tree[id].sum=a[l];
            tree[id].cnt=0;
            tree[id].Min=inf;
            return;
        }
        push(id);
        int mid=(l+r)>>1;
        up(u,v,d,id*2,l,mid);
        up(u,v,d,id*2+1,mid+1,r);
        tree[id]=merge(tree[id*2],tree[id*2+1]);
    }
    int get(int u,int v,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return 0;
        if(u<=l&&r<=v) return tree[id].sum;
        push(id);
        int mid=(l+r)>>1;
        return get(u,v,id*2,l,mid)+get(u,v,id*2+1,mid+1,r);
    }
};
