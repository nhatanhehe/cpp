#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int dp[50][N][N],c[N][N],n,k,f[N],sum[N][N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    dp[0][0][1]=1;
    for(int i=0;i<=45;i++){
        for(int j=0;j<=1000;j++){
            for(int t=0;t<=1000;t++){
                if(!dp[i][j][t]) continue;
                dp[i][j][t+1]=add(dp[i][j][t+1],dp[i][j][t]);
                if(j+t<=1000) dp[i+1][j+t][t+1]=add(dp[i+1][j+t][t+1],dp[i][j][t]);
            }
        }
    }
    f[0]=1;
    for(int i=0;i<=1000;i++){
        c[i][0]=1;
        c[i][i]=1;
        if(i)f[i]=mul(f[i-1],i);
    }
    for(int i=1;i<=1000;i++){
        for(int j=1;j<i;j++){
            c[i][j]=add(c[i-1][j],c[i-1][j-1]);
        }
    }
    for (int n=1;n<=1000;n++) {
        for (int k=1;k<=45;k++) {
            ll ans=0;
            for(int len=k*(k+1)/2;len<=n;len++) {
                long long chiakeo=c[n-len+k][k];
                ans=add(ans,mul(mul(dp[k][len][n+1],f[k]),chiakeo));
            }
            sum[n][k]=ans;
        }
    }
    int t;
    cin>>t;
    while(t--){
        cin>>n>>k;
        cout<<sum[n][k]<<'\n';
    }
}
