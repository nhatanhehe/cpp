ll dnc(int l,int r){
    if(l==r){
        return 0;
    }
    int mid=(l+r)>>1;
    ll sum=0,res=0;
    ll mx=-1e9;
    int j=mid, ptr=off;
    // Case #1: max ở bên trái, bên phải có thể <=
    for(int i=mid;i>=l;i--){
        mx=max(mx,pre[i]);
        while(j+1<=r&&pre[j+1]<=mx){
            j++;
            cnt[pre[j]+off]++;
            if(pre[j]+off>=ptr) sum++;
        }
        while(ptr>mx-pre[i]+off){
            ptr--;
            sum+=cnt[ptr];
        }
        while(ptr<mx-pre[i]+off){
            sum-=cnt[ptr];
            ptr++;
        }
        res+=sum;
    }
    for(int k=mid+1; k<=j; k++){
        cnt[pre[k]+off]--;
    }

    // Case #2: max ở bên phải, bên trái <
    j=mid+1, ptr=off, mx=-1e9, sum=0;
    for(int i=mid+1;i<=r;i++){
        mx=max(mx,pre[i]);
        while(j-1>=l&&pre[j-1]<mx){
            j--;
            cnt[pre[j]+off]++;
            if(pre[j]+off>=ptr) sum++;
        }
        while(ptr>mx-pre[i]+off){
            ptr--;
            sum+=cnt[ptr];
        }
        while(ptr<mx-pre[i]+off){
            sum-=cnt[ptr];
            ptr++;
        }
        res+=sum;
    }
    for(int k=j; k<=mid; k++){
        cnt[pre[k]+off]--;
    }
    return res+dnc(l,mid)+dnc(mid+1,r);
}
