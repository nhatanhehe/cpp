ii sol(int x,int y,int u,int v){
    if(x==u){
        if(v==y+1){
            return {x+1,y};
        }
        if(v==y-1){
            return {x-1,y};
        }
    }
    if(y==v){
        if(u==x+1){
            return {x,y-1};
        }
        if(u==x-1){
            return {x,y+1};
        }
    }
}
