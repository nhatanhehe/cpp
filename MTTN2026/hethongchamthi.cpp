#define fi first
#define se second
const ll inf=1e18;
const ll N=5e3+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,t,s,dp[N][2004],sum=0;
ii trace[N][2004];
struct pt{
    ll a,p,id;
}x[N];
vector<int>cand;
void Trace(int i,int j){
    //cout<<i<<" "<<j<<'\n';
    if(i==0||j==0) return;
    auto [u,v]=trace[i][j];
    if(i==u+1&&j==v) Trace(u,v);
    else{
        cand.pb(x[i].id);
        Trace(u,v);
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>t>>s;
    for(int i=1;i<=n;i++){
        cin>>x[i].a;
        sum+=x[i].a;
        x[i].id=i;
    }
    if(sum<=t&&t<=s){
        sort(x+1,x+n+1,[&](const pt &x,const pt &y){
            return (y.p*x.a<x.p*y.a||(y.p*x.a==x.p*y.a&&x.p>y.p));
        });
        ll tim=0,score=0;
        for(int i=1;i<=n;i++){
            tim+=x[i].a;
            score+=(s-tim)*x[i].p;
        }
        cout<<n<<" "<<score<<'\n';
        for(int i=1;i<=n;i++){
            cout<<x[i].id<<" ";
        }
        return 0;
    }
    bool check=1;
    for(int i=1;i<=n;i++){
        cin>>x[i].p;
        if(i>=2){
            if(x[i].p!=x[i-1].p){
                check=0;
            }
        }
    }
    if(check){
        sort(x+1,x+n+1,[&](const pt &x,const pt &y){
            return x.a<y.a;
        });
        ll tim=0,score=0,cnt;
        for(int i=1;i<=n;i++){
            tim+=x[i].a;
            if(tim>t||(s-tim)*x[i].p<=0){
                    cnt=i-1;
                    break;
            }
            score+=(s-tim)*x[i].p;
        }
        cout<<cnt<<' '<<score<<'\n';
        for(int i=1;i<=cnt;i++){
            cout<<x[i].id<<" ";
        }
    }
    else{
        sort(x+1,x+n+1,[&](const pt &x,const pt &y){
            return (y.p*x.a<x.p*y.a||(y.p*x.a==x.p*y.a&&x.p>y.p));
        });
        dp[0][0]=0;
        for(int i=1;i<=n;i++){
            for(int j=0;j<=t;j++){
                dp[i][j]=dp[i-1][j];
                trace[i][j]=ii(i-1,j);
                if(j>=x[i].a){
                    if(dp[i][j]<dp[i-1][j-x[i].a]+(s-j)*x[i].p){
                        dp[i][j]=dp[i-1][j-x[i].a]+(s-j)*x[i].p;
                        trace[i][j]=ii(i-1,j-x[i].a);
                    }
                }
            }
        }
        ll ans=0,cnt=0,I=0,J=0;
        for(int i=1;i<=n;i++){
            for(int j=0;j<=t;j++){
                if(ans<dp[i][j]){
                    ans=dp[i][j];
                    I=i;
                    J=j;
                    //cout<<ans<<" "<<I<<" "<<J<<'\n';
                }
            }
        }
        if(ans==0){
            cout<<"0 0 \n";
            return 0;
        }
        Trace(I,J);
        reverse(all(cand));
        cout<<cand.size()<<" "<<ans<<'\n';
        for(int x:cand) cout<<x<<" ";
    }
}
