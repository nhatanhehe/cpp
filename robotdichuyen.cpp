inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,k,m,n;
const int MAXN = 100000;
int spf[MAXN+1];
void sieve(){
    for(int i=1;i<=MAXN;i++) spf[i]=i;
    for(int i=2;i<=sqrt(MAXN);i++) {
        if(spf[i]==i) {
            for(int j=i*i;j<=MAXN;j+=i)
                if(spf[j]==j) spf[j]=i;
        }
    }
}
vector<ii>com;
