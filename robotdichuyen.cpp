int exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    int t=exp(a,n/2);
    if(n&1) return mul(mul(t,t),a);
    else return mul(t,t);
}
void get_prime(){
    for(int i=2;i<=MAXN;i++){
        if(spf[i]==i) primes.pb(i);
    }
}
ll C(int k,int n){
    map<ll,int>mp;
    for(int i:primes){
        for(ll t=i;t<=n;t*=i){
            mp[i]+=n/t;
        }
    }
    for(int i:primes){
        for(ll t=i;t<=n-k;t*=i){
            mp[i]-=(n-k)/t;
        }
    }
    for(int i:primes){
        for(ll t=i;t<=k;t*=i){
            mp[i]-=k/t;
        }
    }
    ll ans=1;
    for(auto [num,pw]:mp){
        ans=mul(ans,exp(num,pw));
    }
    return ans;
}
