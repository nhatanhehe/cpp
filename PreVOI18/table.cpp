#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=3e2+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,k,a[N][N],u,v,p,q;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n>>k;
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
        }
    }
    while(k--){
        cin>>u>>v>>p>>q;
        vector<vector<ll>>b(p-u+4,vector<ll>(q-v+3,0));
        vector<vector<ll>>dp(p-u+4,vector<ll>(q-v+3,0));
        vector<vector<ll>>dp1(p-u+4,vector<ll>(q-v+3,0));
        vector<vector<ll>>dp2(p-u+4,vector<ll>(q-v+3,0));
        vector<vector<ll>>dp3(p-u+4,vector<ll>(q-v+3,0));
        for(int i=u;i<=p;i++){
            for(int j=v;j<=q;j++){
                b[i-u+1][j-v+1]=a[i][j];
            }
        }
        int msz=p-u+1,nsz=q-v+1;
        dp.assign(msz+3,vector<ll>(nsz+2,-inf));
        dp[1][1]=b[1][1];
        dp1[1][1]=1;
        for(int i=1;i<=msz;i++){
            for(int j=1;j<=nsz;j++){
                if(i+1<=msz){
                    if(dp[i+1][j]<dp[i][j]+b[i+1][j]){
                        dp[i+1][j]=dp[i][j]+b[i+1][j];
                        dp1[i+1][j]=0;
                    }
                    if(dp[i+1][j]==dp[i][j]+b[i+1][j]){
                        dp1[i+1][j]=add(dp1[i+1][j],dp1[i][j]);
                    }
                }
                if(j+1<=nsz){
                    if(dp[i][j+1]<dp[i][j]+b[i][j+1]){
                        dp[i][j+1]=dp[i][j]+b[i][j+1];
                        dp1[i][j+1]=0;
                    }
                    if(dp[i][j+1]==dp[i][j]+b[i][j+1]){
                        dp1[i][j+1]=add(dp1[i][j+1],dp1[i][j]);
                    }
                }
            }
        }
        dp3.assign(msz+3,vector<ll>(nsz+2,-inf));
        dp3[msz][nsz]=b[msz][nsz];
        dp2[msz][nsz]=1;
        for(int i=msz;i>=1;i--){
            for(int j=nsz;j>=1;j--){
                if(i-1>=1){
                    if(dp3[i-1][j]<dp3[i][j]+b[i-1][j]){
                        dp3[i-1][j]=dp3[i][j]+b[i-1][j];
                        dp2[i-1][j]=0;
                    }
                    if(dp3[i-1][j]==dp3[i][j]+b[i-1][j]){
                        dp2[i-1][j]=add(dp2[i-1][j],dp2[i][j]);
                    }
                }
                if(j-1>=1){
                    if(dp3[i][j-1]<dp3[i][j]+b[i][j-1]){
                        dp3[i][j-1]=dp3[i][j]+b[i][j-1];
                        dp2[i][j-1]=0;
                    }
                    if(dp3[i][j-1]==dp3[i][j]+b[i][j-1]){
                        dp2[i][j-1]=add(dp2[i][j-1],dp2[i][j]);
                    }
                }
            }
        }
        vector<ii>sig;
        for(int i=1;i<=msz;i++){
            for(int j=1;j<=nsz;j++){
                if(i==1&&j==1) continue;
                if(i==msz&&j==nsz) continue;
                if(mul(dp1[i][j],dp2[i][j])==dp1[msz][nsz]&&dp[i][j]+dp3[i][j]-b[i][j]==dp[msz][nsz]&&b[i][j]>0){
                    sig.pb(ii(i,j));
                }
            }
        }
        ll Max=1e18;
        for(auto [u_,v_]:sig){
            //cout<<u<<" "<<v<<'\n';
            int old=b[u_][v_];
            b[u_][v_]=0;
            vector<vector<ll>>dp_(p-u+4,vector<ll>(q-v+3,-inf));
            dp_[1][1]=b[1][1];
            for(int i=1;i<=msz;i++){
                for(int j=1;j<=nsz;j++){
                    if(i==u_&&j==v_) continue;
                    if(i+1<=msz) dp_[i+1][j]=max(dp_[i+1][j],dp_[i][j]+b[i+1][j]);
                    if(j+1<=nsz) dp_[i][j+1]=max(dp_[i][j+1],dp_[i][j]+b[i][j+1]);
                }
            }
            Max=min(Max,dp_[msz][nsz]);
            b[u_][v_]=old;
        }
        cout<<Max<<'\n';
      // cout<<'\n';
    }
}
