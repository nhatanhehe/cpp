struct Hasharr{
    vector<int>arr;
    vector<ll>has;
    int n;
    void init(vector<int>a,int _n){
        n=_n;
        arr.resize(n+4);
        has.resize(n+4);
        for(int i=0;i<n;i++) arr[i]=lower_bound(all(cp),a[i])-cp.begin()+1;
        arr[n]=1001;
        has[0]=0;
        for(int i=0;i<=n;i++){
            has[i+1]=add(mul(has[i],base),arr[i]);
        }
    }
    ll get(int i,int len){
        if(i+len>n) return -1;
        return sub(has[i+len],mul(has[i],pw[len]));
    }
};
void buildfact(){
    pw[0]=1;
    for(int i=1;i<=3000;i++){
        pw[i]=mul(pw[i-1],base);
    }
}
Hasharr ha,hb;
bool cmpsuf(int i,int j){
    int l=0,r=min(ha.n-i,hb.n-j);
    int lcp=0;
    while(l<=r){
        int mid=(l+r)>>1;
        if(ha.get(i,mid)==hb.get(j,mid)){
            lcp=mid;
            l=mid+1;
        }
        else r=mid-1;
    }
    return ha.arr[i+lcp]<hb.arr[j+lcp];
}
