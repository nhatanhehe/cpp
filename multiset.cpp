inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct Node{
    int child[2];
    int cnt;
}T[N*21];
int nodes;
int nw(){
    nodes++;
    T[nodes].child[0]=T[nodes].child[1]=0;
    T[nodes].cnt=0;
    return nodes;
}
void ins(int x){
    int p=1;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        if(!T[p].child[c]){
            T[p].child[c]=nw();
        }
        p=T[p].child[c];
        T[p].cnt++;
    }
}
void del(int x){
    int p=1;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        p=T[p].child[c];
        T[p].cnt--;
    }
}
int get(int x){
    int p=1,res=0;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        if(T[p].child[c^1]){
            if(T[T[p].child[c^1]].cnt){
                res+=(1<<i);
                p=T[p].child[c^1];
                continue;
            }
        }
        if(T[p].child[c]){
            if(T[T[p].child[c]].cnt){
                p=T[p].child[c];
                continue;
            }
        }
        break;
    }
    return res;
}
void cls(){
     nodes=0;
     nw();
}
int q;
char tp;
int n;
