#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,timer,d[N],low[N],out[N],tplt;
stack<int>st;
vector<int>g[N];
void dfs(int u){
    d[u]=low[u]=++timer;
    st.push(u);
    for(int v:g[u]){
        if(out[v]) continue;
        if(!d[v]){
            dfs(v);
            low[u]=min(low[u],low[v]);
        }
        else{
            low[u]=min(low[u],d[v]);
        }
    }
    if(d[u]==low[u]){
        int v;
        tplt++;
        do{
            v=st.top();
            out[v]=1;
            st.pop();
        }while(v!=u);
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>u>>v;
        g[u].pb(v);
    }
    for(int i=1;i<=n;i++){
        if(!d[i]) dfs(i);
    }
    cout<<tplt;
}
