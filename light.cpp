#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],x,y,q;
int solve(int n,int c1,int c2){
    vector<vector<int>>dist(n+3,vector<int>(n+3,1e9));
    queue<ii>q;
    dist[c1][c2]=0;
    q.push({c1,c2});
    while(q.size()){
        ii ext=q.front(); q.pop();
        int u1=ext.fi;
        int u2=ext.se;
        if(u1==0&&u2==0){
            return dist[0][0];
        }
        int u0=n-u1-u2;
        /// k +1
        /// t -1
        for(int k0=0;k0<=x;k0++){
            for(int k1=0;k1<=x-k0;k1++){
                int k2=x-k1-k0;
                for(int t0=0;t0<=y;t0++){
                    for(int t1=0;t1<=y-t0;t1++){
                        int t2=y-t1-t0;
                        if(k0+t0<=u0&& k1+t1<=u1 && k2+t2<=u2){
                            int v1=u1-k1-t1+k0+t2;
                            int v2=u2-k2-t2+k1+t0;
                            if(dist[v1][v2]>dist[u1][u2]+1){
                                dist[v1][v2]=dist[u1][u2]+1;
                                q.push({v1,v2});
                            }
                        }
                    }
                }
            }
        }
    }
        return -1;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q>>x>>y;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    while(q--){
        int l,r;
        int c1=0,c2=0;
        cin>>l>>r;
        for(int i=l;i<=r;i++){
            if(a[i]%3==1) c1++;
            if(a[i]%3==2) c2++;
        }
        cout<<solve(r-l+1,c1,c2)<<'\n';
    }
}
