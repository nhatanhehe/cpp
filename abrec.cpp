#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "abrec"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n,k;
vector<vector<char>>a;
vector<vector<ii>>f;
ii get(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return ii(min(f[l][k].fi,f[r-(1<<k)+1][k].fi),max(f[l][k].se,f[r-(1<<k)+1][k].se));
}
int t;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>m>>n>>k;
        a=vector<vector<char>>(m+1,vector<char>(n+2));
        for(int i=1;i<=m;i++){
            for(int j=1;j<=n;j++){
                cin>>a[i][j];
            }
        }
        vector<vector<char>>b;
        if(n>m){
            b=vector<vector<char>>(n+3,vector<char>(m+3));
            for(int i=1;i<=m;i++){
                for (int j=1;j<=n;j++){
                    b[j][m-i+1]=a[i][j];
                }
            }
            swap(m,n);
        }
        else{
            b=vector<vector<char>>(m+3,vector<char>(n+3));
            for(int i=1;i<=m;i++){
                for (int j=1;j<=n;j++){
                    b[i][j]=a[i][j];
                }
            }
        }
        vector<vector<int>>pre=vector<vector<int>>(m+3,vector<int>(n+2));
        for(int i=1;i<=m;i++){
            for(int j=1;j<=n;j++){
                pre[i][j]=pre[i][j-1]+(b[i][j]=='A'? 1:-1);
            }
        }
        f=vector<vector<ii>>(m+1,vector<ii>(ceil(log2(m))+1));
        vector<ii>Q=vector<ii>(m+3);
        ll ans=0;
        for(int l=1;l<=n;l++){
            for(int r=l;r<=n;r++){
                Q[0]=ii(0,0);
                for(int i=1;i<=m;i++){
                    Q[i].fi=Q[i-1].fi+pre[i][r]-pre[i][l-1];
                    Q[i].se=i;
                }
                sort(Q.begin(),Q.begin()+m+1);
                f[0][0]=ii(Q[0].se,Q[0].se);
                for(int i=1;i<=m;i++){
                    f[i][0].fi=Q[i].se;
                    f[i][0].se=Q[i].se;
                }
                for(int j=1;(1<<j)<=m;j++){
                    for(int i=0;i+(1<<(j-1))<=m;i++){
                        f[i][j].fi=min(f[i][j-1].fi,f[i+(1<<(j-1))][j-1].fi);
                        f[i][j].se=max(f[i][j-1].se,f[i+(1<<(j-1))][j-1].se);
                    }
                }
                int left=0;
                for (int i=0;i<=m;i++){
                    while(Q[i].fi-Q[left].fi>k) left++;
                    if (left>=i) continue;
                    ii res=get(left,i);
                    ans=max(ans,max(abs(res.fi-Q[i].se),abs(res.se-Q[i].se))*(r-l+1)*1LL);
                }
            }
        }
        cout<<ans<<'\n';
    }
}
