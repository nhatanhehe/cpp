inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,a[N];
struct Node{
    ll Min,pre,suf,ans,lz,len;
};
struct SegmentTree{
    vector<Node>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(n*4+10);
    }
    void build(int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        tree[id].Min=0;
        tree[id].len=r-l+1;
        tree[id].pre=tree[id].len;
        tree[id].suf=tree[id].len;
        tree[id].ans=tree[id].len*(tree[id].len+1)/2;
        tree[id].lz=0;
        if(l==r) return;
        int mid=(l+r)>>1;
        build(id*2,l,mid);
        build(id*2+1,mid+1,r);
    }
    Node merge(Node L,Node R){
        Node res;
        if(L.Min==R.Min){
            res.Min=L.Min;
            res.len=L.len+R.len;
            res.ans=L.ans+R.ans+L.suf*R.pre;
            res.pre=(L.pre==L.len? L.len+R.pre: L.pre);
            res.suf=(R.suf==R.len? R.len+L.suf: R.suf);
        }
        else if(L.Min<R.Min){
            res.Min=L.Min;
            res.ans=L.ans;
            res.pre=L.pre;
            res.suf=0;
            res.len=L.len+R.len;
        }
        else{
            res.Min=R.Min;
            res.suf=R.suf;
            res.ans=R.ans;
            res.pre=0;
            res.len=L.len+R.len;
        }
        return res;
    }
    void apply(int id,int k){
        tree[id].Min+=k;
        tree[id].lz+=k;
    }
    void push(int id){
        if(tree[id].lz){
            apply(id*2,tree[id].lz);
            apply(id*2+1,tree[id].lz);
        }
        tree[id].lz=0;
    }
    void up(int u,int v,int k,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return;
        if(u<=l&&r<=v){
            apply(id,k);
            return;
        }
        push(id);
        int mid=(l+r)>>1;
        up(u,v,k,id*2,l,mid);
        up(u,v,k,id*2+1,mid+1,r);
        tree[id]=merge(tree[id*2],tree[id*2+1]);
    }
}seg;
void calc(int i,int val){
    int l=min(a[i],a[n-i+1]);
    int r=max(a[i],a[n-i+1]);
    if(l<r) seg.up(l+1,r,val);
}
