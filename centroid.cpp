inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,u,v,w,sz[N],cen[N],k;
vector<ii>g[N];
int dfs(int u,int p){
    sz[u]=1;
    for(auto [v,w]:g[u]){
        if(v!=p&&!cen[v]){
            sz[u]+=dfs(v,u);
        }
    }
    return sz[u];
}
int fcen(int u,int p,int total){
    for(auto [v,w]:g[u]){
        if(v!=p&&!cen[v]&&sz[v]>total/2) return fcen(v,u,total);
    }
    return u;
}
void dfs2(int u,int p,ll d,vector<ll>&dist){
    dist.pb(d);
    for(auto [v,w]:g[u]){
        if(v!=p&&!cen[v]){
            dfs2(v,u,d+w,dist);
        }
    }
}
ll calc(int u,ll cost){
    vector<ll>dist;
    dfs2(u,-1,cost,dist);
    sort(all(dist));
    ll res=0;
    int l=0,r=dist.size()-1;
    while(l<r){
        if(dist[l]+dist[r]<=k){
            res+=(r-l);
            l++;
        }
        else r--;
    }
    return res;
}
ll ans;
void build(int u){
    dfs(u,-1);
    int centroid=fcen(u,-1,sz[u]);
    cen[centroid]=1;
    ans+=calc(centroid,0);
    for(auto [v,w]:g[centroid]){
        if(!cen[v]){
            ans-=calc(v,w);
        }
    }
    for(auto [v,w]:g[centroid]){
        if(!cen[v]) build(v);
    }
}
