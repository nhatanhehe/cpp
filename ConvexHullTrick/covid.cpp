#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t;
vector<int>g[10];
int graycode[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    vector<int>tem={0,1};
    for(int i=1;i<=10;i++){
        vector<int>tmp(tem.rbegin(),tem.rend());
        for(auto &x:tmp){
            x+=(1<<i);
        }
        tem.insert(tem.end(),all(tmp));
    }
    for(int i=1;i<=1000;i++){
        graycode[tem[i]]=i;
    }
    while(t--){
        /// 1000 chai ruou
        for(int i=1;i<=1000;i++){
            for(int j=9;j>=0;j--){
                if((tem[i]>>j)&1) g[j].pb(i);
            }
        }
        for(int i=0;i<=9;i++){
            cout<<g[i].size()<<" ";
            for(auto x:g[i]) cout<<x<<" ";
            cout<<endl;
            g[i].clear();
        }
        cout.flush();
        int ans=0;
        string s;
        cin>>s;
        for(int i=0;i<=9;i++){
            if(s[i]=='+') ans+=(1<<i);
        }
        cout<<graycode[ans]<<endl;
        cout.flush();
    }
}
