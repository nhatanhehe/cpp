inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,x[N],y[N],u[N],v[N],vgx[N],dist[N],mx[N],my[N];
vector<int>g[N];
bool bfs(){
    queue<int>q;
    for(int i=1;i<=n;i++){
        if(vgx[i]){
            if(!mx[i]){
                dist[i]=0;
                q.push(i);
            }
            else dist[i]=-1;
        }
    }
    bool tf=0;
    while(q.size()){
        int u=q.front();
        q.pop();
        for(int v:g[u]){
            if(!my[v]){
                tf=1;
            }
            else if(dist[my[v]]<0){
                dist[my[v]]=dist[u]+1;
                q.push(my[v]);
            }
        }
    }
    return tf;
}
bool dfs(int u){
    for(int v:g[u]){
        if(!my[v]){
            my[v]=u;
            mx[u]=v;
            return 1;
        }
        else if(dist[my[v]]==dist[u]+1&&dfs(my[v])){
            mx[u]=v;
            my[v]=u;
            return 1;
        }
    }
    return 0;
}
bool check1(int x,int u,int x2){
    if(x>=x2&&u<=x2) return 1;
    if(x<=x2&&u>=x2) return 1;
    return 0;
}
bool check2(int y,int v,int y2){
    if(y>=y2&&v<=y2) return 1;
    if(y<=y2&&v>=y2) return 1;
    return 0;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>x[i]>>y[i]>>u[i]>>v[i];
        if(x[i]==u[i]) vgx[i]=1;
    }
    for(int i=1;i<=n;i++){
        if(vgx[i]){
            for(int j=1;j<=n;j++){
                if(!vgx[j]){
                    if (check2(y[i],v[i],y[j])&&check1(x[j],u[j],x[i])){
                        g[i].pb(j);
                    }
                }
            }
        }
    }
    while(bfs()){
        for(int i=1;i<=n;i++) if(vgx[i]) if(!mx[i]) dfs(i);
    }
    int ans=0;
    for(int i=1;i<=n;i++){
        if(vgx[i]) ans+=(mx[i]>0);
    }
    cout<<n-ans;
}
