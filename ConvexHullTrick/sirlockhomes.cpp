#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "sirlockhome"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m;
vector<char>dp[405][28005],s[405];
int cmp(vector<char>a,vector<char>b){
    if(a.size()!=m) return 1;
    for(int i=0;i<a.size();i++){
        if(a[i]<b[i]) return 0;
        if(a[i]>b[i]) return 1;
    }
    return 2;
}
void print(vector<char>a){
    for(auto x:a) cout<<x;
    cout<<'\n';
}
vector<vector<char>>res;
ii trace[405][28005];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        for(int j=0;j<m;j++){
            char x;
            cin>>x;
            s[i].pb(x);
        }
    }
    int cnt=0;
    dp[1][0]=s[1];
    for(int i=0;i<m;i++){
        if(s[1][i]=='0') dp[1][cnt]=s[i];
        else{
            s[1][i]='0';
            dp[1][++cnt]=s[1];
        }
    }
    for(int i=1; i<n; i++){
        for(int j=0; j<=m*i; j++){
            if(dp[i][j].size() != m) continue;
            vector<char> next_s = s[i+1];
            if(cmp(next_s, dp[i][j]) == 1){
                if(cmp(dp[i+1][j], next_s) == 1){
                    dp[i+1][j] = next_s;
                    trace[i+1][j] = {i, j};
                }
            }
            for(int t=1; t<=m; t++){
                cnt+=(dp[i][j][t-1]==next_s);
                next_s[t-1]=dp[i][j][t-1];
                if(cmp(next_s,dp[i][j])==1){
                    if(cmp(dp[i+1][j+t-cnt],next_s)==1){
                        dp[i+1][j+t-cnt]=next_s;
                        trace[i+1][j+t-cnt]={i, j};
                    }
                }
                else{
                    if(dp[i][j][t-1]=='9') continue;
                    next_s[t-1]=dp[i][j][t-1] + 1;
                    if(cmp(dp[i+1][j+t], next_s) == 1){
                        dp[i+1][j+t] = next_s;
                        trace[i+1][j+t] = {i, j};
                    }
                    next_s[t-1] = dp[i][j][t-1];
                }
            }
        }
    }
    int cs;
    for(int j=0;j<=m*n;j++){
        if(dp[n][j].size()==m){
            cout<<j<<'\n';
            cs=j;
            break;
        }
    }
    ii x=ii(n,cs);
    while(n--){
        //cout<<x.fi<<" "<<x.se<<'\n';
        res.pb(dp[x.fi][x.se]);
        x=trace[x.fi][x.se];
    }
    reverse(all(res));
    for(auto x:res){
        print(x);
    }
}
