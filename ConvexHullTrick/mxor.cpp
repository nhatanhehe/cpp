#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,Xor,res[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    int ans=0;
    for(int j=16;j>=0;j--){
        vector<int>v0,v1;
        for(int i=1;i<=n;i++){
            if((i>>j)&1) v1.pb(i);
            else v0.pb(i);
        }
        if(v0.empty()||v1.empty()) continue;
        cout<<"? ";
        cout<<v0.size()<<" ";
        for(int x:v0) cout<<x<<" ";
        cout<<v1.size()<<" ";
        for(int x:v1) cout<<x<<" ";
        cout.flush();
        cin>>res[j];
        ans=max(ans,res[j]);
    }

    vector<int>V1,V0;
    for(int j=16;j>=0;j--){
        vector<int>v0,v1;
        for(int i=1;i<=n;i++){
            if((i>>j)&1) v1.pb(i);
            else v0.pb(i);
        }
        if(v0.empty()||v1.empty()) continue;
        if(res[j]==ans){
            V0=v0;
            V1=v1;
            Xor+=(1<<j);
        }

    }
    int l=0,r=V1.size()-1;
    //cout<<"ngu "<<V1.size()<<'\n';
    while(l<r){
        int mid=(l+r)>>1;
        cout<<"? ";
        cout<<V0.size()<<" ";
        for(int x:V0) cout<<x<<" ";
        cout<<r-mid<<" ";
        for(int i=mid+1;i<=r;i++) cout<<V1[i]<<" ";
        cout.flush();
        int check_right;
        cin>>check_right;
        if(check_right==ans) l=mid+1;
        else r=mid;
    }
    cout<<"! "<<min(V1[l],(Xor^V1[l]))<<" "<<max(Xor^V1[l],V1[l]);
    cout.flush();
}
