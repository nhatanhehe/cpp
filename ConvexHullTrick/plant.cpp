#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,l,r,tree[N<<2],lz[N<<2];
void fix(int id,int k,int l,int r){
    tree[id]+=(r-l+1)*k;
    lz[id]+=k;
}
void push(int id,int l,int r){
    int mid=(l+r)>>1;
    fix(id*2,lz[id],l,mid);
    fix(id*2+1,lz[id],mid+1,r);
    lz[id]=0;
}
void up(int u,int v,int k,int id=1,int l=1,int r=1e5){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
        fix(id,k,l,r);
        return;
    }
    push(id,l,r);
    int mid=(l+r)>>1;
    up(u,v,k,id*2,l,mid);
    up(u,v,k,id*2+1,mid+1,r);
    tree[id]=tree[id*2]+tree[id*2+1];
}
int get(int pos,int id=1,int l=1,int r=1e5){
    if(l==r){
        return tree[id];
    }
    push(id,l,r);
    int mid=(l+r)>>1;
    if(pos<=mid) return get(pos,id*2,l,mid);
    else return get(pos,id*2+1,mid+1,r);
}
