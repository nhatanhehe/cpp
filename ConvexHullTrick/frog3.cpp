const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,c,h[N],dp[N];
struct Line{
    int a,b;
    Line(){
        a=b=0;
    }
    Line(int a,int b): a(a),b(b){}

    ll val(int x){
        return a*x+b;
    }
};
struct CHT{
    vector<Line>hull;
    CHT(){
        hull.clear();
    }
    bool bad(Line d1,Line d2,Line d3){
        //cerr<<1.0*(d3.b-d1.b)/(d1.a-d3.a)<<' '<<1.0*(d2.b-d1.b)/(d1.a-d2.a)<<'\n';
         return 1.0*(d3.b-d1.b)/(d1.a-d3.a)<1.0*(d2.b-d1.b)/(d1.a-d2.a);
    }
    void addline(Line x){
        while(hull.size()>=2){
            if(bad(hull[hull.size()-2],hull.back(),x)) hull.pop_back();
            else break;
        }
        hull.pb(x);
    }
    int get(int x){
        int l=0,r=hull.size()-1;
        int ans=inf;
        while(l<=r){
            int mid=(l+r)>>1;
            int cur=hull[mid].val(x);
            ans=min(ans,cur);
            if(mid>0&&hull[mid-1].val(x)<cur) r=mid-1;
            else if(mid<hull.size()-1&&hull[mid+1].val(x)<cur) l=mid+1;
            else break;
        }
        return ans;
    }
};
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>c;
    for(int i=1;i<=n;i++){
        cin>>h[i];
    }
    CHT cht;
    dp[1]=0;
    cht.addline(Line(-2*h[1],dp[1]+h[1]*h[1]));
    for(int i=2;i<=n;i++){
        dp[i]=c+h[i]*h[i]+cht.get(h[i]);
        cht.addline(Line(-2*h[i],dp[i]+h[i]*h[i]));
    }
    cout<<dp[n];
}
