const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,k,u,v,w,dist1[N],dist2[N];
ii dist[N];
vector<ii>g[N];
void ditcha(int s,int dist[N]){
    fill(dist+1,dist+n+1,inf);
    dist[s]=0;
    priority_queue<ii,vector<ii>,greater<ii>>pq;
    pq.push({0,s});
    while(pq.size()){
        auto [cost,u]=pq.top();
        pq.pop();
        if(cost>dist[u]) continue;
        for(auto [v,w]:g[u]){
            if(dist[v]>dist[u]+w){
                dist[v]=dist[u]+w;
                pq.push({dist[v],v});
            }
        }
    }
}
struct Line{
    ld a,b;
    Line(ll a,ll b): a(a),b(b) {}
    ld val(ld x){
        return a*x+b;
    }
};
struct CHT{
    vector<Line>hull;
    CHT(){
        hull.clear();
    }
    bool bad(Line d1,Line d2,Line d3){
        return 1.0*(d2.b-d1.b)/(d1.a-d2.a)>=1.0*(d3.b-d1.b)/(d1.a-d3.a);
    }
    void addline(Line x){
        while(hull.size()>=2){
            if(bad(hull[hull.size()-2],hull.back(),x)) hull.pop_back();
            else break;
        }
        hull.pb(x);
    }
    ld get(ld x){
        int l=0,r=hull.size()-1;
        ld ans=inf;
        while(l<=r){
            int mid=(l+r)>>1;
            ld cur=hull[mid].val(x);
            ans=min(ans,cur);
            if(mid>0&&hull[mid-1].val(x)<cur) r=mid-1;
            else if(mid<hull.size()-1&&hull[mid+1].val(x)<cur) l=mid+1;
            else break;
        }
        return ans;
    }
};
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>k;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        g[u].pb({v,w});
    }
    ditcha(1,dist1);
    ditcha(n,dist2);
    for(int i=1;i<=n;i++){
        dist[i]=ii(dist1[i],dist2[i]);
    }
    sort(dist+1,dist+n+1,greater<ii>());
    CHT cht;
    for(int i=1;i<=n;i++){
        if(dist[i].fi==inf&&dist[i].se==inf) continue;
        cht.addline(Line(dist[i].fi,dist[i].se));
    }
    while(k--){
        ld a,b;
        cin>>a>>b;
        cout<<fixed<<setprecision(0)<<b*cht.get(a/b)<<'\n';
    }
}
