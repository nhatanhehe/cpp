inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,k,a[N],zs,pre[130][N],suf[130][N],cost[130][N],pos[N],bit[N],cnt,dp[130][N];
void up(int i,int val){
    for(;i<=k;i+=i&-i){
        bit[i]+=val;
    }
}
int get(int i){
    int res=0;
    for(;i;i-=i&-i){
        res+=bit[i];
    }
    return res;
}
struct Line{
    int a,b;
    Line(int a,int b): a(a),b(b) {}
    int val(int x){
        return a*x+b;
    }
};
struct CHT{
    vector<Line>hull;
    CHT(){
        hull.clear();
    }
    bool bad(Line d1,Line d2,Line d3){
        return 1.0*(d2.b-d1.b)/(d1.a-d2.a)>=1.0*(d3.b-d1.b)/(d1.a-d3.a);
    }
    void addline(Line x){
        while(hull.size()>=2){
            if(bad(hull[hull.size()-2],hull.back(),x)) hull.pop_back();
            else break;
        }
        hull.pb(x);
    }
    int get(int x){
        int l=0,r=hull.size()-1,ans=0;
        while(l<=r){
            int mid=(l+r)>>1;
            int cur=hull[mid].val(x);
            ans=max(ans,cur);
            if(mid>0&&hull[mid-1].val(x)>cur) r=mid-1;
            else if(mid<hull.size()-1&&hull[mid+1].val(x)>cur) l=mid+1;
            else break;
        }
        return ans;
    }

};
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    //if(n>1000) return 0;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        if(!a[i]){
            pos[++zs]=i;
        }
    }
    for(int i=1;i<=n;i++){
        if(a[i]){
            cnt+=get(k)-get(a[i]);
            up(a[i],1);
        }
    }

    for(int j=1;j<=k;j++){
        for(int i=1;i<=n;i++){
            pre[j][i]=pre[j][i-1];
            if(a[i]!=0) pre[j][i]+=(a[i]>j);
        }
        for(int i=n;i>=0;i--){
            suf[j][i]=suf[j][i+1];
            if(a[i]!=0) suf[j][i]+=(a[i]<j);
        }
        for(int i=1;i<=n;i++){
            if(a[i]==0){
                cost[j][i]=pre[j][i-1]+suf[j][i+1];
            }
        }
        for(int i=1;i<=n;i++){
            cost[j][i]+=cost[j][i-1];
        }
    }
    for(int j=k;j>=1;j--){
        CHT cht;
        cht.addline(Line(0,dp[j+1][0]-cost[j][pos[0]]));
        for(int i=1;i<=zs;i++){
//            for(int p=0;p<=i;p++){
//                if(p<i) dp[j][i]=cost[j][pos[i]]+max(dp[j][i],i*p+dp[j+1][p]-cost[j][pos[p]]-p*p);
//                else dp[j][i]=max(dp[j][i],dp[j+1][i]);
//            }
            dp[j][i]=max(cost[j][pos[i]]+cht.get(i),dp[j+1][i]);

            cht.addline(Line(i,dp[j+1][i]-cost[j][pos[i]]-i*i));
        }
    }
    cout<<dp[1][zs]+cnt;
}
