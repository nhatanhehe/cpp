#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "invmax"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,k,a[N],zs,pre[200][N],suf[200][N],cost[200][N],pos[N],bit[N],cnt,dp[200][N];
void up(int i,int val){
    for(;i<=k;i+=i&-i){
        bit[i]+=val;
    }
}
int get(int i){
    int res=0;
    for(;i;i-=i&-i){
        res+=bit[i];
    }
    return res;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".ans","w", stdout);
    }
    cin>>n>>k;
    //if(n>1000) return 0;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        if(!a[i]){
            pos[++zs]=i;
        }
    }
    for(int i=1;i<=n;i++){
        if(a[i]){
            cnt+=get(k)-get(a[i]);
            up(a[i],1);
        }
    }
    for(int i=0;i<=k;i++){
        for(int j=0;j<=n;j++){
            dp[i][j]=-inf;
        }
    }
    dp[k+1][0]=0;
    for(int j=1;j<=k;j++){
        for(int i=1;i<=n;i++){
            pre[j][i]=pre[j][i-1];
            if(a[i]!=0) pre[j][i]+=(a[i]>j);
        }
        for(int i=n;i>=0;i--){
            suf[j][i]=suf[j][i+1];
            if(a[i]!=0) suf[j][i]+=(a[i]<j);
        }
        for(int i=1;i<=n;i++){
            if(a[i]==0){
                cost[j][i]=pre[j][i]+suf[j][i];
            }
        }
        for(int i=1;i<=n;i++){
            cost[j][i]+=cost[j][i-1];
        }
    }
    for(int j=k;j>=1;j--){
        for(int i=1;i<=zs;i++){
            if(dp[j+1][i]==-inf) continue;
            for(int p=0;p<=i;p++){
                //if(j==1&&i==2&&p==1) cout<<dp[j][i]<<" "<<dp[j+1][p]<<" "<<cost[j][pos[i]]-cost[j][pos[p]]<<" "<<(i-p)*p<<'\n';
                if(p<i) dp[j][i]=max(dp[j][i],dp[j+1][p]+cost[j][pos[i]]-cost[j][pos[p]]+(i-p)*p);
                else dp[j][i]=max(dp[j][i],dp[j+1][i]);
            }
        }
    }
    cout<<dp[1][zs]+cnt;
}
