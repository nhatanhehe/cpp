inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,l,r,m,root[N],cur;
char tp;
string s;
struct NODE{
    int open,close;
};
struct Node{
    int l,r;
    NODE val;
    Node(){
        l = r = 0;
        val = {0,0};
    }
}tree[N*21];
NODE merge(NODE l,NODE r){
    int match=min(l.open,r.close);
    NODE C;
    C.open=l.open+r.open-match;
    C.close=l.close+r.close-match;
    return C;
}
void build(int id=1,int l=1,int r=m){
    if(l==r){
        tree[id].val.open=(s[l]=='(');
        tree[id].val.close=(s[l]==')');
        return;
    }
    int mid=(l+r)>>1;
    tree[id].l=++cur;
    tree[id].r=++cur;
    build(tree[id].l,l,mid);
    build(tree[id].r,mid+1,r);
    tree[id].val=merge(tree[tree[id].l].val,tree[tree[id].r].val);
}
void up(int id,int pos,int l=1,int r=m){
    if(l==r){
        swap(tree[id].val.open,tree[id].val.close);
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid){
        tree[++cur]=tree[tree[id].l];
        tree[id].l=cur;
        up(tree[id].l,pos,l,mid);
    }
    else{
        tree[++cur]=tree[tree[id].r];
        tree[id].r=cur;
        up(tree[id].r,pos,mid+1,r);
    }
    tree[id].val=merge(tree[tree[id].l].val,tree[tree[id].r].val);
}
NODE get(int id,int u,int v,int l=1,int r=m){
    if(l>v||r<u) return {0,0};
    if(u<=l&&r<=v) return tree[id].val;
    int mid=(l+r)>>1;
    return merge(get(tree[id].l,u,v,l,mid),get(tree[id].r,u,v,mid+1,r));
}
