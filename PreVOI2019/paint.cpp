inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],p[N],root[N],col[N];
int acs(int u){
    return u==p[u]? u:p[u]=acs(p[u]);
}
void join(int u,int v){
    u=acs(u);
    v=acs(v);
    if(u!=v){
        p[v]=u;
    }
}
void print(){
    for(int i=1;i<=n;i++){
        int cha=acs(i);
        if(col[cha]) cout<<(char)col[cha];
        else break;
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n+'z'-'a'+1;i++){
        p[i]=i;
    }
    int cur=1;
    for(int i=1;i<=n;i++){
        int tp;
        cin>>tp;
        if(tp==1){
            char c;
            cin>>c;
            if(!root[c]){
                root[c]=cur;
                col[cur]=c;
            }
            else{
                join(root[c],cur);
            }
            cur++;
        }
        else{
            char x,y;
            cin>>x>>y;
            if(x==y) continue;
            if(!root[x]) continue;
            if(!root[y]){
                int rt=root[x];
                col[rt]=y;
                root[x]=0;
                //if(x=='a') cout<<root['a']<<'\n';
                root[y]=rt;

            }
            else{
                join(root[y],root[x]);
                root[x]=0;
            }
        }
    }
    print();
}
