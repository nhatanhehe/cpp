int mul(int a,int b){
    return (a%mod)*(b%mod)%mod;
}
int sub(int a,int b){
    return ((a-b)%mod+mod)%mod;
}
int add(int a,int b){
    return (a%mod+b%mod)%mod;
}
struct biconnect{
    int n,m;
    stack<int>s;
    int timer=0;
    int cnt,tplt;
    int u[N],v[N],d[N],low[N],c[N],scc[N],rep[N];
    int vis[N];
    int in[N];
    vector<vector<ii>>adj;
    vector<vector<int>>g;
    void dfs(int u,int id){
        low[u]=d[u]=++cnt;
        s.push(u);
        for(auto x:adj[u]){
            int v=x.fi;
            int idx=x.se;
            if(idx!=id&&!vis[v]){
                if(d[v]) low[u]=min(low[u],d[v]);
                else{
                    dfs(v,idx);
                    low[u]=min(low[u],low[v]);
                }
            }
        }
        if(low[u]==d[u]){
            tplt++;
            int v;
            do{
                v=s.top();
                vis[v]=1;
                scc[v]=tplt;
                rep[tplt]=v;
                s.pop();
            }while(u!=v);
        }
    }
    vector<int>nodes;
    void DFS(int u,int par){
        in[u]=++timer;
        if(c[u]==1) nodes.pb(u);
        for(int v:g[u]){
            if(v!=par){
                DFS(v,u);
            }
        }
    }
    inline void reset(int a[],int n,int val){
        for(int i=0;i<=n;i++){
            a[i]=val;
        }
    }
    void solve(int _n,int _m){
        n=_n;
        m=_m;
        timer=cnt=tplt=0;
        while(s.size()) s.pop();
        reset(u,m,0);
        reset(v,m,0);
        reset(d,n,0);
        reset(low,n,0);
        reset(c,n,0);
        reset(rep,n,0);
        reset(scc,n,0);
        reset(in,n,0);
        for(int i=1;i<=n;i++) vis[i]=0;
        adj.assign(n+3, {});
        g.assign(n+3, {});
        for(int i=1;i<=m;i++){
            cin>>u[i]>>v[i];
            adj[u[i]].pb({v[i],i});
            adj[v[i]].pb({u[i],i});
        }
        dfs(1,-1);
        if(tplt==1){
            cout<<0<<'\n';
            return;
        }
        int ans=0,root=1;
        for(int i=1;i<=m;i++){
            int U=scc[u[i]];
            int V=scc[v[i]];
           // cout<<U<<" "<<V<<'\n';
            if(U!=V){
                c[U]++;
                c[V]++;
                if(c[U]>=2) root=U;
                if(c[V]>=2) root=V;
                g[U].pb(V);
                g[V].pb(U);
            }
        }
        DFS(root,-1);
        for(int i=1;i<=tplt;i++){
            ans+=(c[i]==1);
        }
        cout<<(ans+1)/2<<'\n';
        int sz=nodes.size();
        for(int i=0;i+sz/2<nodes.size();i++){
            cout<<rep[nodes[i]]<<" "<<rep[nodes[i+sz/2]]<<"\n";
        }
        nodes.clear();
    }
}heh;
