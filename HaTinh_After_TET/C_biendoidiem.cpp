inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,prmx[N],sufmx[N],prmn[N],sufmn[N];
ii p[N];
bool check(ll mid){
    int j=1;
    for(int i=1;i<=n;i++){
        while(j<=i&&(p[i].fi-p[j].fi)*(p[i].fi-p[j].fi)>mid) j++;
        ll mx,mn;
        if(i!=n||j!=1){
            mx=max(prmx[j-1],sufmx[i+1]);
            mn=min(prmn[j-1],sufmn[i+1]);
            ll xmx=p[i].fi;
            ll xmn=p[j].fi;
            ll res = mx*mx + xmx*xmx;
            res = max(res, mx*mx + xmn*xmn);
            res = max(res, mn*mn + xmx*xmx);
            res = max(res, mn*mn + xmn*xmn);
            res = max(res, (mx-mn)*(mx-mn));
            if(res<=mid){
               // cout<<"type 1:";
                return 1;
            }
        }
        else{
            //cout<<"type2 ";
        return 1;}
    }
    return 0;
}
ll solve(){
    sort(p+1,p+n+1,[&](const ii &x,const ii &y){
        return x.fi<y.fi;
    });
    prmx[0]=-inf;
    sufmx[n+1]=-inf;
    prmn[0]=inf;
    sufmn[n+1]=inf;
    for(int i=1;i<=n;i++){
        prmx[i]=max(prmx[i-1],p[i].se);
        prmn[i]=min(prmn[i-1],p[i].se);
    }
    for(int i=n;i>=1;i--){
        sufmx[i]=max(sufmx[i+1],p[i].se);
        sufmn[i]=min(sufmn[i+1],p[i].se);
    }
    ll xmin=inf, xmax=-inf;
    ll ymin=inf, ymax=-inf;
    for(int i=1;i<=n;i++){
        xmin=min(xmin,p[i].fi);
        xmax=max(xmax,p[i].fi);
        ymin=min(ymin,p[i].se);
        ymax=max(ymax,p[i].se);
    }
    ll r = (xmax-xmin)*(xmax-xmin) + (ymax-ymin)*(ymax-ymin);
    ll l=1,ans=0;
    while(l<=r){
        ll mid=(l+r)>>1LL;
        if(check(mid)){
            ans=mid;
            r=mid-1;
        }
        else l=mid+1;
    }
    return ans;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>p[i].fi>>p[i].se;
    }
    ll res=solve();
    for(int i=1;i<=n;i++){
        swap(p[i].fi,p[i].se);
    }
    res=min(res,solve());
    cout<<res;
}
