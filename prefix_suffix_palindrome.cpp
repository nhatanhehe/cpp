string manacher(string ss){
    if(ss.empty()) return "";
    string s;
    for(char c:ss){
        s.pb('#');
        s.pb(c);
    }
    s+='#';
    int n=s.size();
    s=" "+s;
  //  cout<<s<<'\n';
    vector<int>d(n+3);
    int l=0,r=1;
    for(int i=1;i<=n;i++){
        if(r<i) d[i]=0;
        else d[i]=min(r-i,d[l+(r-i)]);
        while(i-d[i]-1>=1&&i+d[i]+1<=n&&s[i-d[i]-1]==s[i+d[i]+1]) d[i]++;
        if(r<i+d[i]){
            r=i+d[i];
            l=i-d[i];
        }
    }
  //  cout<<d[2]<<" "<<s[2]<<'\n';
    ii ans=ii(0,0);
    for(int i=1;i<=n;i++){
        if(i+d[i]==n||i-d[i]==1){
            if(d[i]==0&&s[i]=='#') continue;
            ans=max(ii(d[i],i-d[i]),ans);
        }
    }
    string res;
    for(int i=ans.se;i<=ans.se+2*ans.fi;i++){
        if(s[i]!='#') res.pb(s[i]);
    }
    return res;
}
