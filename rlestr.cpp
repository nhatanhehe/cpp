string add_(string a,string b){
    vector<pair<char,int>>A,B;
    int sum=0;
    for(int i=0;i<a.size();i++){
        if(isalpha(a[i])) A.pb({a[i],0});
        else A.back().se=A.back().se*10+(a[i]-'0');
    }
    for(int i=0;i<b.size();i++){
        if(isalpha(b[i])) B.pb({b[i],0});
        else B.back().se=B.back().se*10+(b[i]-'0');
    }
    string res;
    if(A.back().fi==B[0].fi){
        for(int i=0;i<A.size()-1;i++){
            res+=A[i].fi+to_string(A[i].se);
        }
        res+=A.back().fi+to_string(A.back().se+B[0].se);
        for(int i=1;i<B.size();i++){
            res+=B[i].fi+to_string(B[i].se);
        }
    }
    else res=a+b;
    return res;
}
string cop(string s,int p,int cap){
    vector<pair<char,int>>A;
    int sum=0;
    for(int i=0;i<s.size();i++){
        if(isalpha(s[i])) A.pb({s[i],0});
        else A.back().se=A.back().se*10+(s[i]-'0');
    }
    string res;
    sum=0;
    bool state=0;
    for(auto [c,cnt]:A){
      //  cout<<cap<<" ";
        if(cap==0) break;
        if(state==0){
            if(sum+cnt>=p){
                if(sum<p){
                    res+=c+to_string(min(cap,sum+cnt-p+1));
                    cap-=min(cap,sum+cnt-p+1);
                }
                state=1;
            }
        }
        else{
            int tmp=min(cnt,cap);
            res+=c+to_string(tmp);
            cap-=tmp;
        }
        sum+=cnt;
    }
    return res;
}
int sum_str(string s){
    vector<pair<char,int>>A;
    int sum=0;
    for(int i=0;i<s.size();i++){
        if(isalpha(s[i])) A.pb({s[i],0});
        else A.back().se=A.back().se*10+(s[i]-'0');
    }
    int res=0;
    for(auto [c,cnt]:A){
        res+=cnt;
    }
    return res;
}
