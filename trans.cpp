inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int a,b,d;
int calc(int x){
    vector<int>divs;
    for(int i=2;i<=sqrt(x);i++){
        if(x%i==0){
            int y=x/i;
            divs.pb(x);
            divs.pb(y);
        }
    }
    sort(all(divs)); divs.erase(unique(all(divs)),divs.end());
    divs.pb(x);
    map<int,int>dist;
    dist[x]=0;
    queue<int>q; q.push(x);
    while(q.size()){
        int num=q.front(); q.pop();
        for(int u:divs){
            if(u>d) break;
            if(num%u==0){
                if(!dist.count(num/u)||dist[num/u]>dist[num]+1){
                    dist[num/u]=dist[num]+1;
                    q.push(num/u);
                }
            }
        }
    }
    return dist.count(1)? dist[1]:-1e9;
}
