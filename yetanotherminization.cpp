inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,a[N],b[N],suma,sumb,dp[N][20004],s,sb,t;
main(){;
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n;
        ll tct=0;
        suma=0;
        sumb=0;
        s=0;
        for(int i=1;i<=n;i++){
            cin>>a[i];
            suma+=a[i]*a[i];
            s+=a[i];
        }
        for(int i=1;i<=n;i++){
            cin>>b[i];
            sumb+=b[i]*b[i];
            s+=b[i];
        }
        memset(dp,0,sizeof dp);
        dp[0][0]=1;
        for(int i=1;i<=n;i++){
            for(int j=0;j<=2e4;j++){
                //dp[i][j]|=dp[i-1][j];
                if(j>=a[i]) dp[i][j]|=dp[i-1][j-a[i]];
                if(j>=b[i]) dp[i][j]|=dp[i-1][j-b[i]];
            }
        }
        ll ans=inf;
        for(int j=0;j<=2e4;j++){
            if(dp[n][j]) ans=min(ans,j*j+(s-j)*(s-j));
        }
        cout<<ans+(n-2)*(suma+sumb)<<'\n';
    }
}
