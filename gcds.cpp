#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    a+=b;
    return a>=mod?a-mod:a;
}

inline ll sub(ll a,ll b){
    a-=b;
    return a<0?a+mod:a;
}

inline ll mul(ll a,ll b){
    return (a*b)%mod;
}
ll n,q,a[N],s[N],ssq[N],cnt[N],inv[N];
vector<int>u[N];
ll exp(ll a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    ll t=exp(a,n/2);
    if(n&1) return ((t*t)%mod*a%mod)%mod;
    else return (t*t)%mod;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        cnt[a[i]]++;
    }
    ll sum=0;
    for(int i=1;i<=5e5;i++){
        for(int j=i;j<=5e5;j+=i){
            s[i]=add(s[i],cnt[j]*j);
            ssq[i]=add(ssq[i],mul(mul(cnt[j],j),j));
            u[j].pb(i);
        }
    }
    for(int i=1;i<=5e5;i++){
        inv[i]=exp(mul(i,i),mod-2);
    }
    for(int i=1;i<=5e5;i++){
        ll saq=mul(s[i],s[i]);
        sum=add(sum,mul(sub(saq,ssq[i]),inv[i]));
        //cout<<s[i]<<" "<<ssq[i]<<'\n';
    }
    sum=mul(sum,500000004);
    cout<<sum<<'\n';
    while(q--){
        int x,y;
        cin>>x>>y;
        for(int i:u[a[x]]){
            s[i]=sub(s[i],a[x]);
            sum=sub(sum,mul(mul(a[x],s[i]),inv[i]));
        }
        a[x]=y;
        //cout<<sum<<'\n';
        for(int i:u[y]){
            sum=add(sum,mul(mul(y,s[i]),inv[i]));
            s[i]=add(s[i],y);
        }
        cout<<sum<<'\n';
    }
}
