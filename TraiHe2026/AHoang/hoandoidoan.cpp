inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,tp,p[20][N],l,r,Min[N],Max[N],len;
int acs(int k,int u){
    return u==p[k][u]? u:p[k][u]=acs(k,p[k][u]);
}
void join(int k,int u,int v){
    int root_u=acs(k,u);
    int root_v=acs(k,v);
    if(root_u==root_v) return;
    if(k==0){
        p[0][root_v]=root_u;
        Min[root_u]=min(Min[root_u],Min[root_v]);
        Max[root_u]=max(Max[root_u],Max[root_v]);
        return;
    }
    join(k-1,u,v);
    join(k-1,u+(1<<(k-1)),v+(1<<(k-1)));
    p[k][root_v]=root_u;
}
