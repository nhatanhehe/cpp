ll exp(int a,int n,int mod){
    if(n==0) return 1;
    if(n==1) return a;
    ll t=exp(a,n/2,mod);
    if(n&1) return ((t*t)%mod*a%mod)%mod;
    else return (t*t)%mod;
}
struct Hash{
    const ll base=311;
    const ll mod1=1000000007;
    const ll mod2=1000000009;
    vector<ll>pw1,pw2,h1,h2;
    inline ll sub(ll a,ll b,ll mod){
        a%=mod;
        b%=mod;
        a-=b;
        if(a<0)a+=mod;
        return a;
    }
    inline ll mul(ll a,ll b,ll mod){
        return (a%mod)*(b%mod)%mod;
    }
    Hash(){
        pw1.assign(n+1,0);
        pw2.assign(n+1,0);
        h1.assign(n+1,0);
        h2.assign(n+1,0);
        pw1[0]=pw2[0]=1;
        stack<int>st;
        for(int i=1;i<=n;i++){
            pw1[i]=pw1[i-1]*base%mod1;
            pw2[i]=pw2[i-1]*base%mod2;
            if(st.size()&&st.top()+a[i]==k){
                h1[i]=h1[i-1];
                h2[i]=h2[i-1];
                h1[i]=mul(sub(h1[i],st.top(),mod1),exp(base,mod1-2,mod1),mod1);
                h2[i]=mul(sub(h2[i],st.top(),mod2),exp(base,mod2-2,mod2),mod2);
                st.pop();
            }
            else{
                st.push(a[i]);
                h1[i]=(h1[i-1]*base+a[i])%mod1;
                h2[i]=(h2[i-1]*base+a[i])%mod2;
            }
        }
    }
    ii get(int l,int r){
        ll x1=(h1[r]-h1[l-1]*pw1[r-l+1])%mod1;
        if(x1<0)x1+=mod1;
        ll x2=(h2[r]-h2[l-1]*pw2[r-l+1])%mod2;
        if(x2<0)x2+=mod2;
        return {x1,x2};
    }
};
