inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,nodes,c[N],pos[N],p[N][20],h[N];
map<int,int>ed[N];
int lca(int u,int v){
    if(h[u]<h[v]) swap(u,v);
    for(int i=19;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)) u=p[u][i];
    }
    if(u==v) return u;
    for(int i=19;i>=0;i--){
        if(p[u][i]!=p[v][i]){
            u=p[u][i];
            v=p[v][i];
        }
    }
    return p[u][0];
}
int dist(int u,int v){
    return h[u]+h[v]-2*h[lca(u,v)];
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q;
    stack<int>st;
    for(int i=1;i<=n;i++){
        cin>>c[i];
        if(st.size()&&st.top()==c[i]){
            pos[i]=p[pos[i-1]][0];
            st.pop();
        }
        else{
            auto it=ed[pos[i-1]].find(c[i]);
            if(it==ed[pos[i-1]].end()){
                pos[i]=++nodes;
                ed[pos[i-1]][c[i]]=pos[i];
                h[pos[i]]=h[pos[i-1]]+1;
                p[pos[i]][0]=pos[i-1];
            }
            else{
                pos[i]=it->se;
            }
            st.push(c[i]);
        }
    }
    for(int j=1;j<=19;j++){
        for(int i=1;i<=nodes;i++){
            p[i][j]=p[p[i][j-1]][j-1];
        }
    }
    while(q--){
        int l,r;
        cin>>l>>r;
        cout<<dist(pos[l-1],pos[r])<<'\n';
    }
}
