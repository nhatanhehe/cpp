#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,S,res;
ii x[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>S;
    for(int i=1;i<=n;i++){
        cin>>x[i].fi;
    }
    for(int i=1;i<=n;i++){
        cin>>x[i].se;
    }
    sort(x+1,x+n+1,[&](const ii &x,const ii &y){
        return (1LL*x.se*y.fi>1LL*y.se*x.fi)||(1LL*x.se*y.fi==1LL*y.se*x.fi&&x.fi<y.fi);
    });
    int lim=3e5;
    if(S>lim){
        ll tmp=(S-lim)/x[1].fi;
        res+=tmp*x[1].se;
        S-=tmp*x[1].fi;
    }
    vector<ll>dp(S+4,0);
    for(int i=1;i<=n;i++){
        for(int j=x[i].fi;j<=S;j++){
            dp[j]=max(dp[j],dp[j-x[i].fi]+x[i].se);
        }
    }
    cout<<res+dp[S];
}
