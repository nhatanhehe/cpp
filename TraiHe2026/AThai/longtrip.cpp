#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "skibudu"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n;
ii a[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i].fi;
        a[i].se=i;
    }
    sort(a+1,a+n+1);
    int lst=(n+1)/2;
    vector<int>res;
    res.pb(a[lst].se);
    int l=1,r=n;
    while(l<=r){
        if(l==(n+1)/2) l++;
        if(r==(n+1)/2) r--;
        if(abs(a[lst].fi-a[l].fi)>abs(a[lst].fi-a[r].fi)){
            res.pb(a[l].se);
            lst=l;
            l++;
        }
        else{
            res.pb(a[r].se);
            lst=r;
            r--;
        }
    }
    for(int x:res) cout<<x<<" ";
}
