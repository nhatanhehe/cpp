inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,e,u,v,a[N],b[N],p[N],ans[N],cnt,mark[N];
struct DSU{
    vector<int>p;
    int n;
    void init(int _n){
        n=_n;
        p.resize(n+3,0);
        for(int i=1;i<=n;i++) p[i]=i;
    }
    int acs(int u){
        return u==p[u]? u:p[u]=acs(p[u]);
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            p[u]=v;
        }
    }
}dsu1,dsu2;
vector<ii>g[N];
int h[N],par[N][20],pid[N];
void dfs(int u,int p){
    for(auto [v,id]:g[u]){
        if(v!=p){
            pid[v]=id;
            h[v]=h[u]+1;
            par[v][0]=u;
            dfs(v,u);
        }
    }
}
int lca(int u,int v){
    if(h[u]<h[v]) swap(u,v);
    for(int i=19;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)) u=par[u][i];
    }
    if(u==v) return u;
    for(int i=19;i>=0;i--){
        if(par[u][i]!=par[v][i]){
            u=par[u][i];
            v=par[v][i];
        }
    }
    return par[u][0];
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>e;
    for(int i=1;i<=n;i++) p[i]=i;
    for(int i=1;i<=e;i++){
        cin>>a[i]>>b[i];
    }
    for(int i=1;i<n;i++){
        int x;
        cin>>x;
        mark[x]=1;
        g[a[x]].pb(ii(b[x],x));
        g[b[x]].pb(ii(a[x],x));
    }
    dfs(1,-1);
    for(int j=1;j<=19;j++){
        for(int i=1;i<=n;i++){
            par[i][j]=par[par[i][j-1]][j-1];
        }
    }
    dsu1.init(n);
    dsu2.init(n);
    for(int i=1;i<=e;i++){
        if(!mark[i]){
            if(dsu2.acs(a[i])==dsu2.acs(b[i])) ans[i]=++cnt;
            else{
                auto [u,v]=ii(a[i],b[i]);
                int acs=lca(u,v);
                vector<int>ass;
                while(h[u]>h[acs]&&h[u]>0){
                   // cerr<<u<<'\n';
                    u=dsu1.acs(u);
                    if(h[u]<=h[acs]) break;
                    int idx=pid[u];
                    if(!ans[idx]){
                        ass.pb(idx);
                        dsu1.join(u,par[u][0]);
                    }
                    u=dsu1.acs(par[u][0]);
                }
                while(h[v]>h[acs]&&h[v]>0){
                    //cerr<<v<<'\n';
                    v=dsu1.acs(v);
                    if(h[v]<=h[acs]) break;
                    int idx=pid[v];
                    if(!ans[idx]){
                        ass.pb(idx);
                        dsu1.join(v,par[v][0]);
                    }
                    v=dsu1.acs(par[v][0]);
                }
                sort(all(ass));
                for(int id:ass){
                    //cout<<id<<" ";
                    ans[id]=++cnt;
                }
                ans[i]=++cnt;

                //cout<<'\n';
            }
        }
        else{
            if(!ans[i]) ans[i]=++cnt;
            dsu2.join(a[i],b[i]);
        }
    }
    for(int i=1;i<=e;i++) cout<<(ans[i])<<" ";
}
