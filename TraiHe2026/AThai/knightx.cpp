inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,vis[103][103],deg[103][103],ans[103][103];
int dx[] = {-2, -2, -1, -1, 1, 1, 2, 2};
int dy[] = {-1, 1, -2, 2, -2, 2, -1, 1};
bool inside(int x,int y){
    return 1<=x&&x<=n&&1<=y&&y<=n;
}
void reset(){
    memset(vis,0,sizeof vis);
    memset(deg,0,sizeof deg);
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            for(int k=0;k<8;k++){
                int x=i+dx[k],y=j+dy[k];
                if(inside(x,y)){
                    deg[x][y]++;
                }
            }
        }
    }
}
vector<ii>res;
bool findroute(int i,int j,int step){
    //cout<<i<<" "<<j<<" "<<step<<'\n';
    if(step==n*n) return 1;
    vis[i][j]=1;
    iii ans={inf,{inf,inf}};
    for(int k=0;k<8;k++){
        int x=i+dx[k],y=j+dy[k];
        if(inside(x,y)&&!vis[x][y]){
            deg[x][y]--;
            ans=min(ans,{deg[x][y],{x,y}});
        }
    }
    if(ans.fi==1e9) return 0;
    res.pb(ans.se);
    return findroute(ans.se.fi,ans.se.se,step+1);
}
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    vector<ii>starterpack;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            starterpack.pb(ii(i,j));
        }
    }
    shuffle(all(starterpack),rng);
    for(auto [x,y]:starterpack){
        res.clear();
        res.pb(ii(x,y));
        reset();
        bool tf=findroute(x,y,1);
        if(tf){
            int len=n*n/k;
            int rem=(n*n)%k;
            for(int i=0;i<res.size();i++){
                if(i<(len+1)*rem){
                    ans[res[i].fi][res[i].se]=i/(len+1);
                }
                else ans[res[i].fi][res[i].se]=rem+(i-(len+1)*rem)/len;
            }
            for(int i=1;i<=n;i++){
                for(int j=1;j<=n;j++){
                    cout<<ans[i][j]+1<<" ";
                }
                cout<<'\n';
            }
            exit(0);

        }
    }
}
