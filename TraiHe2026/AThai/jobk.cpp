inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,dep[N],out[N],in[N],par[N];
vector<int>g[N];
void dfs(int u,int p){
    for(int v:g[u]){
        if(v!=p){
            dep[v]=dep[u]+1;
            par[v]=u;
            dfs(v,u);
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<n;i++){
        cin>>u>>v;
        in[v]++;
        out[u]++;
        g[v].pb(u);
    }
    priority_queue<ii>pq;
    int root;
    for(int i=1;i<=n;i++){
        if(!out[i]){
            root=i;
        }
    }
    dfs(root,-1);
    for(int i=1;i<=n;i++)
        if(!in[i]){
            pq.push(ii(dep[i],i));
        }
    int cnt=0;
    while(pq.size()){
        vector<int>v;
        for(int j=1;j<=m;j++){
            if(pq.size()){
                auto [d,i]=pq.top(); pq.pop();
                //cout<<i<<" ";
                in[par[i]]--;
                if(!in[par[i]]){
                    v.pb(par[i]);
                }
            }
        }
        for(int i:v){
                        pq.push(ii(dep[i],i));
        }
       // cout<<'\n';
        cnt++;
    }
    cout<<cnt;
}
