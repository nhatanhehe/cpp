inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,l[N],r[N],c[N],p[N][21],lc[N],f[N][20];
 int fgcd ( unsigned  int u ,  unsigned  int v )  {
  int shift , uz , vz ;
  if  ( u ==  0 )  return v ;
  if  ( v ==  0 )  return u ;
  uz = __builtin_ctz ( u ) ;
  vz = __builtin_ctz ( v ) ;
  shift = uz > vz ? vz : uz ;
  u >>=uz ;
  do  {
   v>>= vz ;
   int diff = v ;
   diff -= u ;
   vz = __builtin_ctz ( diff ) ;
   if  ( diff ==  0 )  break ;
   if  ( v < u ) u = v ;
   v =  abs ( diff ) ;
  }  while  ( 1 ) ;
  return u << shift ;
}
ll LCM(int u,int v){
    return u*(v/fgcd(u,v));
}
ll get(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return fgcd(f[l][k],f[r-(1<<k)+1][k]);
}
