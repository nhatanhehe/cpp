inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,a,b,dp[N],q;
ll cost(int n,int k){
    return max(dp[k]+a,dp[n-k]+b);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>q;
    while(q--){
        cin>>n>>a>>b;
        memset(dp,0x3f,sizeof dp);
        dp[1]=0;
        int k=1;
        for(int i=2;i<=n;i++){
            while(k<i&&cost(i,k)>cost(i,k+1)){
                k++;
            }
            dp[i]=max(dp[k]+a,dp[i-k]+b);
        }
        cout<<dp[n]<<'\n';
    }
}
