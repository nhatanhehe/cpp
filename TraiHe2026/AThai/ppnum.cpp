ll calc(int fixed,int pos,int tL,int tR,deque<int>&s){
    int len=fixed-pos;
    if(pos>len){
        if(tL) return 1;
        return tR;
    }
    ll &ans=dp[pos][tL][tR];
    if(ans!=-1) return ans;
    int lim=(tL? 9:s[pos]);
    ans=0;
   // cout<<pos<<" "<<len<<" "<<lim<<'\n';
    for(int i=(pos==0);i<=lim;i++){
        for(int j:match[i]){
            if(pos==len&&j!=i) continue;
            bool nxtl,nxtr=tR;
            nxtl=tL||(i<s[pos]);
            if(j<s[len]) nxtr=1;
            if(j>s[len]) nxtr=0;
            //cout<<j<<" "<<s[len]<<" "<<nxtr<<'\n';
            ans+=calc(fixed,pos+1,nxtl,nxtr,s);
        }
    }
    //cout<<'\n';
    return ans;
}
string sub(string a,string b){
    while(b.size()<a.size()) b='0'+b;
    int borrow=0;
    string res="";
    for(int i=a.size()-1;i>=0;i--){
        int x=a[i]-'0';
        int y=b[i]-'0'+borrow;
        if(x<y){
            x+=10;
            borrow=1;
        }
        else borrow=0;
        res+=char(x-y+'0');
    }
    reverse(res.begin(),res.end());
    int pos=0;
    while(pos+1<res.size()&&res[pos]=='0') pos++;
    return res.substr(pos);
}
ll cnt(string s){
    deque<int>dq;
    for(auto c:s) dq.pb(c-'0');
    ll res=0,cc=0;
    while(dq.size()){
        memset(dp,-1,sizeof dp);
        res+=calc(dq.size()-1,0,cc!=0,1,dq);
        //cout<<"res= "<<res<<'\n';
        cc++;
        dq.pop_front();
    }
    return res;
}
