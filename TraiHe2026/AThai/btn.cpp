bool match(char x, char y) {
    if (x == '(') return y == ')' || y == '?';
    if (x == '[') return y == ']' || y == '?';
    if (x == '{') return y == '}' || y == '?';
    if (x != '?') return 0;
    return y == ')' || y == ']' || y == '}';
}
ll n,k,dp[103][103][103][2];
ll calc(int l,int r,int k,bool split){
    ll &ans=dp[l][r][k][split];
    if(l>r) return ans=1;
    if(k==0) return ans=0;
    if(ans!=-1) return ans;
    bool cl=s[l]=='?',cr=s[r]=='?';
    ans=0;
    if(cl&&cr){
        ans=calc(l+1,r-1,k-1,1)*3;
    }
    else{
        if(match(s[l],s[r])) ans=calc(l+1,r-1,k-1,1);
    }
    if(split){
        for(int i=l+1;i<r;i+=2){
            ans+=calc(l,i,k,0)*calc(i+1,r,k,1);
        }
    }
    return ans;
}
