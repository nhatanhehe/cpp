inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll ans=0;
struct DSU{
    vector<int>p,sz;
    int n;
    void init(int _n){
        n=_n;
        p.resize(n+3,0);
        sz.resize(n+3,1);
        for(int i=1;i<=n;i++) p[i]=i;
    }
    int acs(int u){
        return u==p[u]? u:p[u]=acs(p[u]);
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            ans-=(sz[v]+1)*sz[v]/2;
            ans-=(sz[u]+1)*sz[u]/2;
            sz[u]+=sz[v];
            ans+=sz[u]*(sz[u]+1)/2;
            p[v]=u;
        }
    }
}dsu;
ll n,q,vis[N],res[N];
ii h[N];
ii y[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q;
    for(int i=1;i<=n;i++){
        cin>>h[i].fi;
        h[i].se=i;
    }
    for(int i=1;i<=q;i++){
        cin>>y[i].fi;
        y[i].se=i;
    }
    sort(h+1,h+n+1);
    sort(y+1,y+q+1);
    int j=1;
    dsu.init(n);
    for(int i=1;i<=q;i++){
        while(j<=n&&h[j].fi<=y[i].fi){
            vis[h[j].se]=1;
            ans+=1;
            if(h[j].se>=2&&vis[h[j].se-1]) dsu.join(h[j].se,h[j].se-1);
            if(h[j].se<n&&vis[h[j].se+1]) dsu.join(h[j].se,h[j].se+1);
            j++;
        }
        res[y[i].se]=ans;
    }
    for(int i=1;i<=q;i++) cout<<res[i]<<'\n';
}
