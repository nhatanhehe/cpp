    int n,k,u,v,w,dp[N],dia[N];
    vector<ii>g[N];
    int cnt;
    void dfs(int u,int p,int lim){
        vector<int>len;
        for(auto [v,w]:g[u]){
            if(v!=p){
                dfs(v,u,lim);
                len.pb(dp[v]+w);
            }
        }
        sort(all(len));
        while(len.size()){
            if(len.size()==1){
                if(len[0]>lim){
                    cnt++;
                }
                else{
                    dp[u]=len[0];
                    break;
                }
                len.pop_back();
            }
            else{
                if(len.back()+len[len.size()-2]>lim){
                    cnt++;
                }
                else{
                    dp[u]=len.back();
                    break;
                }
                len.pop_back();
            }
        }
    }
    bool check(int lim){
        memset(dp,0,sizeof dp);
        cnt=1;
        dfs(1,-1,lim);
        return cnt<=k;
    }
