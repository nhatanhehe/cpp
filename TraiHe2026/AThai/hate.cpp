#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll t,n,u,v,a[N];
set<int>adj[N];
vector<ii>g[N];
bool vis[N];
int bu,bv,eid=-1;
void dfs(int u,int p){
    vis[u]=1;
    for(auto [v,id]:g[u]){
        if(v!=p){
            if(vis[v]){
                bu=u;
                bv=v;
                eid=id;
            }
            else dfs(v,u);
        }
    }
}
ll dp[N][2];
void tdp(int u,int p,int ban,int bid){
    dp[u][0]=0;
    dp[u][1]= u==ban? -inf:a[u];
    for(auto [v,id]:g[u]){
        if(v!=p&&id!=bid){
            tdp(v,u,ban,bid);
            dp[u][0]+=max(dp[v][0],dp[v][1]);
            dp[u][1]+=dp[v][0];
        }

    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        memset(vis,0,sizeof vis);
        cin>>n;
        int cnt=0;
        for(int i=1;i<=n;i++){
            cin>>a[i]>>v;
            if(v!=-1){
                adj[i].insert(v);
            }
        }
        for(int i=1;i<=n;i++){
            for(auto v:adj[i]){
                g[i].pb(ii(v,++cnt));
                g[v].pb(ii(i,cnt));
            }
        }
        ll res=0;
        for(int i=1;i<=n;i++){
            if(!vis[i]){
                bu=bv=eid=-1;
                dfs(i,-1);
                if(eid==-1){
                    tdp(i,-1,-1,-1);
                    res+=max(dp[i][0],dp[i][1]);
                }
                else{
                    tdp(bu,-1,bv,eid);
                    ll ans1=max(dp[bu][1],dp[bu][0]);
                    tdp(bv,-1,bu,eid);
                    ll ans2=max(dp[bv][1],dp[bv][0]);
                    res+=max(ans1,ans2);
                }
            }
        }
        cout<<res<<'\n';
        for(int i=1;i<=n;i++){
            g[i].clear();
            adj[i].clear();
        }
    }
}
