const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,x[N],q,s,f1[N][19],f2[N][19];
ll mx(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return max(f1[l][k],f1[r-(1<<k)+1][k]);
}
ll mn(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return min(f2[l][k],f2[r-(1<<k)+1][k]);
}

main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>x[i];
    }
    for(int i=1;i<=n;i++){
        if(i>=2) f1[i][0]=2*x[i]-x[i-1];
        if(i<n) f2[i][0]=2*x[i]-x[i+1];
    }
    for(int j=1;j<=18;j++){
        for(int i=1;i+(1<<j)-1<=n;i++){
            f1[i][j]=max(f1[i][j-1],f1[i+(1<<(j-1))][j-1]);
            f2[i][j]=min(f2[i][j-1],f2[i+(1<<(j-1))][j-1]);
        }
    }
    cin>>q;
    while(q--){
        cin>>s;
        ll pl=upper_bound(x+1,x+n+1,s)-x-1;
        ll pr=upper_bound(x+1,x+n+1,s)-x;
        ll dist_L=(pl >= 1) ? s - x[pl] : inf;
        ll dist_R=(pr <= n) ? x[pr] - s : inf;
        int st;
        ll dist=0;
        cout<<dist_L<<" "<<dist_R<<'\n';
        if(dist_L<=dist_R){
            st=pl;
            dist+=dist_L;
        }
        else{
            st=pr;
            dist+=dist_R;
        }
        int L=st,R=st;
       // cout<<L<<" "<<R<<" "<<n<<'\n';
        while(L>1||R<n){
            if(L==1){
                dist+=x[n]-x[1];
                //cout<<dist<<'\n';
                break;
            }
            if(R==n&&!stt){
                dist+=x[n]-x[1];
                break;
            }
            if(x[L]-x[L-1]>x[R+1]-x[R]){
                if(L==1){
                    dist+=x[n]-x[1];
                    break;
                }
                int l=2,r=L,res=-1;
                while(l<=r){
                    int mid=(l+r)>>1;
                    if(mx(mid,L)>x[R+1]){
                        l=mid+1;
                        res=mid;
                    }
                    else r=mid-1;
                }
                if(res!=-1){
                    dist+=x[L]-x[res];
                    dist+=x[R+1]-x[res];
                    L=res;
                    stt^=1;
                }
                R++;
               // cout<<res<<" "<<L<<" "<<R<<" "<<dist<<'\n';
            }
            if(stt&&L>1){
                if(R==n){
                    dist+=x[n]-x[1];
                    break;
                }
                int l=R,r=n-1,res=-1;
                while(l<=r){
                    int mid=(l+r)>>1;
                    if(mn(R,mid)<=x[l-1]){
                        r=mid-1;
                        res=mid;
                    }
                    else l=mid+1;
                }
                if(res!=-1){
                    dist+=x[res]-x[L-1];
                    dist+=x[res]-x[R];
                    stt^=1;
                }
                L--;
                R=res;
            }
          //  cout<<dist<<" "<<L<<" "<<R<<'\n';
        }
        cout<<dist<<'\n';
    }
}
