inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct Node{
    ll sum,pre,suf,mx;
};
struct SegmentTree{
    vector<Node>tree;
    Node merge(Node l,Node r){
        Node res;
        res.pre=max(l.pre,l.sum+r.pre);
        res.suf=max(r.suf,r.sum+l.suf);
        res.mx=max({l.mx,r.mx,l.suf+r.pre});
        res.sum=l.sum+r.sum;
        return res;
    }
    int n;
    void init(int _n){
        n=_n;
        tree.resize(4*n+5,Node());
    }
    void up(int pos,int k,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l==r){
            if(k<0) tree[id]={-1,0,0,0};
            else tree[id]={1,1,1,1};
            return;
        }
        int mid=(l+r)>>1;
        if(pos<=mid) up(pos,k,id*2,l,mid);
        else up(pos,k,id*2+1,mid+1,r);
        tree[id]=merge(tree[id*2],tree[id*2+1]);
    }

    Node get(int u,int v,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return {0,-inf,-inf,-inf};
        if(u<=l&&r<=v) return tree[id];
        int mid=(l+r)>>1;
        return merge(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
    }

}seg;
