#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct pt{
    int a,b,id;
} x[N];
int n;
vector<int>st[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    vector<int>cp;
    multiset<ii>ms;
    for(int i=1;i<=n;i++){
        cin>>x[i].a>>x[i].b;
        x[i].id=i;
        ms.insert(ii(0,i));
    }
    sort(x+1,x+n+1,[&](const pt &x,const pt &y){
        return x.a<y.a||(x.a==y.a&&x.b>y.b);
    });
    for(int i=1;i<=n;i++){
        auto it=ms.lower_bound(ii(x[i].b,-1));
        it--;
        auto [lst,idx]=*it;
        //cout<<x[i].se<<" "<<lst<<" "<<idx<<'\n';
        st[idx].pb(x[i].id);
        ms.erase(it);
        ms.insert(ii(x[i].b,idx));
    }
    while(ms.size()){
        auto [lst,idx]=*ms.begin();
        if(lst==0) ms.erase(ms.begin());
        else break;
    }
    cout<<ms.size()<<'\n';
    for(auto [lst,idx]:ms){
        cout<<st[idx].size()<<" ";
        reverse(all(st[idx]));
        for(int x:st[idx]) cout<<x<<" ";
        cout<<'\n';
    }
}
