     vector<int> A2B(vector<int> _A, int _K){
        if(_K==1){
            ll sum=0,pro=1;
            for(int i=1;i<=100;i++){
                sum+=i;
                sum%=100;
            }
            ll sumA=0,proA=1;
            for(int x:_A){
                sumA+=x;
                sumA%=100;
            }
            if(sum>=sumA) return {sum-sumA+1};
            return {sum-sumA+100+1};
        }
        if(_K==2){
            ll sumA=0,proA=1;
            for(int x:_A){
                sumA+=x;
                sumA%=101;
                proA*=x;
                proA%=101;
            }
            if(sumA==0) sumA=101;
            if(proA==0) proA=101;
            return {sumA,proA};
        }
     }
