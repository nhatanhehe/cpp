inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll cv[N],ce[N],n,m,x,y,u,v,h[N],p[N][20];
vector<int>g[N];
void dfs(int u,int par){
    for(int v:g[u]){
        if(v!=par){
            h[v]=h[u]+1;
            p[v][0]=u;
            dfs(v,u);
        }
    }
}
int lca(int u,int v){
    if(h[u]<h[v]) swap(u,v);
    for(int i=19;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)) u=p[u][i];
    }
    if(u==v) return u;
    for(int i=19;i>=0;i--){
        if(p[u][i]!=p[v][i]){
            u=p[u][i];
            v=p[v][i];
        }
    }
    return p[u][0];
}
void DFS(int u,int p){
    for(int v:g[u]){
        if(v!=p){
            DFS(v,u);
            ce[u]+=ce[v];
            cv[u]+=cv[v];
        }
    }
}
ll exp(ll a,ll n){
    if(n==0) return 1;
    if(n==1) return a;
    ll t=exp(a,n/2);
    if(n&1) return ((t*t)%mod*a%mod)%mod;
    else return (t*t)%mod;
}
