inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll dp[N],n;
int opt[N];
void hanoi3(int n,char A,char B,char C){
    if(n==0) return;
    if(n==1){
        cout<<A<<C<<'\n';
        return;
    }
    hanoi3(n-1,A,C,B);
    cout<<A<<C<<'\n';
    hanoi3(n-1,B,A,C);
}
void hanoi4(int n,char A,char B,char C,char D){
    if(n==0) return;
    if(n==1){
        cout<<A<<D<<'\n';
        return;
    }
    hanoi4(opt[n],A,C,D,B);
    hanoi3(n-opt[n],A,C,D);
    hanoi4(opt[n],B,A,C,D);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    memset(dp,0x3f,sizeof dp);
    dp[0]=0;
    dp[1]=1;
    for(int i=2;i<=n;i++){
        for(int k=0;k<=i;k++){
            if(i-k>=36) continue;
            else{
                if(dp[i]>2*dp[k]+(1LL<<(i-k))-1){
                    dp[i]=2*dp[k]+(1LL<<(i-k))-1;
                    opt[i]=k;
                }
            }
        }
    }
    cout<<dp[n]<<'\n';
    hanoi4(n,'A','B','C','D');
}
