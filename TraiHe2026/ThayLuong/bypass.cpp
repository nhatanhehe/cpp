inline ll add(ll a,ll b)
{
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b)
{
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b)
{
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n,pre[1003][1003],ans[N],q;
char a[1003][1003];
struct Queries
{
    int a,b,x,y,id;
};
vector<Queries>Q;
bitset<1005>up1[505][1003],up0[505][1003],cur0[1003],cur1[1003],pre0[1003],pre1[1003]; //up[x][y] la danh dau vi tri duoc den dc vi tri nao cua mid
void dnc(int l,int r,vector<Queries>&vec)
{
    if(l==r)
    {
        for(auto [a,b,x,y,id]:vec)
        {
            ans[id]=(pre[a][y]-pre[a][b-1]<=1);
        }
        return;
    }
    int mid=(l+r)>>1;
    vector<Queries>L,R,cross[505];
    for(Queries x:vec)
    {
        if(x.x<=mid) L.pb(x);
        else if(x.a>mid) R.pb(x);
        else cross[x.a].pb(x);
    }
    for(int ti=mid+1; ti<=r; ti++)
    {
        int i=ti-mid;
        for(int j=1; j<=n; j++)
        {
            up0[i][j].reset();
            up1[i][j].reset();
            bitset<1005>b0,b1;
            if(i==1)
            {
                b0.set(j);
                b1.set(j);
            }
            else
            {
                b0|=up0[i-1][j];
                b1|=up1[i-1][j];
            }
            if(j>1)
            {
                b0|=up0[i][j-1];
                b1|=up1[i][j-1];
            }
            if(a[ti][j]=='#')
            {
                up1[i][j]=b0;
            }
            else
            {
                up0[i][j]=b0;
                up1[i][j]=b1;
            }
        }
    }
    for(int ti=mid; ti>=l; ti--)
    {
        int i=ti-l+1;
        for(int j=n; j>=1; j--)
        {
            cur0[j].reset();
            cur1[j].reset();
            bitset<1005>b0,b1;
            if(ti==mid)
            {
                b0.set(j);
                b1.set(j);
            }
            else
            {
                b0|=pre0[j];
                b1|=pre1[j];
            }
            if(j<n)
            {
                b0|=cur0[j+1];
                b1|=cur1[j+1];
            }
            if(a[ti][j]=='#')
            {
                cur1[j]=b0;
            }
            else
            {
                cur0[j]=b0;
                cur1[j]=b1;
            }
        }
        for(int j=1; j<=n; j++)
        {
            pre0[j]=cur0[j];
            pre1[j]=cur1[j];
        }
        for(auto [a,b,x,y,id]:cross[])
        {
            bitset<1005>res;
            res=(cur0[b]&up0[x-mid][y])|(cur0[b]&up1[x-mid][y])|(cur1[b]&up0[x-mid][y]);
            ans[id]=res.any();
        }
    }
    dnc(l,mid,L);
    dnc(mid+1,r,R);
}
main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);
    if (fopen(Task ".inp","r"))
    {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n;
    for(int i=1; i<=m; i++)
    {
        for(int j=1; j<=n; j++)
        {
            cin>>a[i][j];
            pre[i][j]=pre[i][j-1]+(a[i][j]=='#');
        }
    }
    cin>>q;
    for(int i=1; i<=q; i++)
    {
        int a,b,x,y,id;
        cin>>a>>b>>x>>y;
        Q.pb({a,b,x,y,i});
    }
    dnc(1,m,Q);
    for(int i=1; i<=q; i++) cout<<(ans[i]? "Yes\n":"No\n");
}
