inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll c[35][35];
void cal(){
    for(int i=0;i<=30;i++){
        c[i][0]=1;
        for(int j=1;j<=i;j++){
            c[i][j]=c[i-1][j-1]+c[i-1][j];
        }
    }
}
ll calc(int m,int n,int p){
    if(m<0||n<0||p<0) return 0;
    return c[m+n+p][m]*c[n+p][n];
}
int m,n,p;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n>>p;
    cal();
    int q;
    cin>>q;
    while(q--){
        ll k;
        cin>>k;
        int cm=m,cn=n,cp=p;
        string res="";
        for(int i=1;i<=m+n+p;i++){
            if(cm){
                int X=calc(cm-1,cn,cp);
                if(k>X){
                    k-=X;
                }
                else{
                    res+='X';
                    cm--;
                    continue;
                }
            }
            if(cn){
                int Y=calc(cm,cn-1,cp);
                if(k>Y){
                    k-=Y;
                }
                else{
                    res+='Y';
                    cn--;
                    continue;
                }
            }
            if(cp){
                int Z=calc(cm,cn,cp-1);
                if(k>Z){
                    k-=Z;
                }
                else{
                    res+='Z';
                    cp--;
                    continue;
                }
            }
        }
        cout<<res<<'\n';
    }
}
