    Dinic    dinic=Dinic(2*n+5,S,T);
    for(int i=1; i<=n; i++)
    {
        cin>>a>>b;
        dinic.add_edge(i,i+n,b-a);
        d[i]-=a;
        d[i+n]+=a;
    }
    for(int i=1; i<=m; i++)
    {
        cin>>u>>v>>l>>r;
        out[u]++;
        in[v]++;
        dinic.add_edge(u+n,v,r-l);
        d[u+n]-=l;
        d[v]+=l;
    }
    ll tflow=0;
    for(int i=1; i<=n; i++)
    {
        if(!in[i])
        {
            dinic.add_edge(s,i,inf);
        }
        if(!out[i])
        {
            dinic.add_edge(i+n,t,inf);
        }
    }
    for(int i=1; i<=t; i++)
    {
        if(d[i]>0)
        {
            dinic.add_edge(S,i,d[i]);
            tflow+=d[i];
        }
        if(d[i]<0) dinic.add_edge(i,T,-d[i]);
    }
    dinic.add_edge(t,s,inf);
    ll flow2=dinic.max_flow();
    if(flow2==tflow)
    {
        ll ans=0;
        for(auto [v,cap,flow,rev]:dinic.adj[t])
        {
            if(v==s)
            {
                ans+=flow;
                break;
            }
        }
        cout<<ans;
    }
    else
    {
        cout<<-1;
    }
