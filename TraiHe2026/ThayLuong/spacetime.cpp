inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll m,n,A[505][505],q,pre[505][505],ans[N];
struct Queries
{
    int a,b,x,y,id;
};
vector<Queries>Q;
ll dp0[505][505],dp1[505][505];
void dnc(int l,int r,vector<Queries>&vec){
    if(l==r){
        for(auto [a,b,x,y,id]:vec){
            ans[id]=pre[a][y]-pre[a][b-1];
        }
        return;
    }
    int mid=(l+r)>>1;
    vector<Queries>L,R,cross;
    for(Queries x:vec){
        if(x.x<=mid) L.pb(x);
        else if(x.a>mid) R.pb(x);
        else cross.pb(x);
    }
    for(int idx=1;idx<=n;idx++){
        dp0[mid][idx]=A[mid][idx];
        for(int i=mid;i>=l;i--){
            for(int j=idx;j>=1;j--){
                if(i==mid&&j==idx) continue;
                if(i<mid) dp0[i][j]=min(dp0[i][j],dp0[i+1][j]+A[i][j]);
                if(j<idx) dp0[i][j]=min(dp0[i][j],dp0[i][j+1]+A[i][j]);
            }
        }
        dp1[mid][idx]=A[mid][idx];
        for(int i=mid;i<=r;i++){
            for(int j=idx;j<=n;j++){
                if(i==mid&&j==idx) continue;
                if(i>mid) dp1[i][j]=min(dp1[i][j],dp1[i-1][j]+A[i][j]);
                if(j>idx) dp1[i][j]=min(dp1[i][j],dp1[i][j-1]+A[i][j]);
            }
        }
        for(auto [a,b,x,y,id]:cross){
            ans[id]=min(ans[id],dp0[a][b]+dp1[x][y]-A[mid][idx]);
        }
        for(int i=mid;i>=l;i--){
            for(int j=idx;j>=1;j--){
                dp0[i][j]=inf;
            }
        }
        for(int i=mid;i<=r;i++){
            for(int j=idx;j<=n;j++){
                dp1[i][j]=inf;
            }
        }
    }
    dnc(l,mid,L);
    dnc(mid+1,r,R);
}
