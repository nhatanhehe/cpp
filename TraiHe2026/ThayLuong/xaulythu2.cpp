inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll dp[N],n,m,k,d[N],L[N];
ll calc(int i){
    if(i>n) return 1;
    ll &ans=dp[i];
    if(ans!=-1) return ans;
    int choices=m-(i-L[i]);
    if(choices<=0) return ans=0;
    return ans=choices*calc(i+1);
}
string a,b;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        cin>>d[i];
    }
    cin>>a>>b;
    for(int i=1;i<=n;i++){
        int l=1,r=i,ans=i;
        while(l<=r){
            int mid=(l+r)>>1;
            if(i-mid<=d[i]||i-mid<=d[mid]){
                r=mid-1;
                ans=mid;
            }
            else l=mid+1;
        }
        L[i]=ans;
        //cout<<L[i]<<" ";
    }
    //cout<<'\n';
    memset(dp,-1,sizeof dp);
    ll ka=0,kb=0;
    for(int i=1;i<=n;i++){
        vector<bool>used(m);
        for(int j=L[i]-1;j<i-1;j++){
            used[a[j]-'a']=1;
        }
        for(int c=0;c<a[i-1]-'a';c++){
            if(used[c]) continue;
            ll ways=calc(i+1);
            ka+=ways;
        }
    }
    for(int i=1;i<=n;i++){
        vector<bool>used(m);
        for(int j=L[i]-1;j<i-1;j++){
            used[b[j]-'a']=1;
        }
        for(int c=0;c<b[i-1]-'a';c++){
            if(used[c]) continue;
            ll ways=calc(i+1);
            kb+=ways;
        }
    }
    k=ka+kb+1;
    ll total_ways = calc(1);
    if(k>total_ways||total_ways==0) {
        cout << -1;
        return 0;
    }
    string ans;
    for(int i=1;i<=n;i++){
        vector<bool>used(m);
        for(int j=L[i]-1;j<i-1;j++){
            used[ans[j]-'a']=1;
        }
        for(int c=0;c<m;c++){
            if(used[c]) continue;
            ll ways=calc(i+1);
            if(k>ways) k-=ways;
            else{
                ans+=(char)(c+'a');
                break;
            }
        }
    }
    cout<<ans;
}
