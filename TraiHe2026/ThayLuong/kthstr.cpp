inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,k,dp[103][103];
ll calc(int pos,int md){
    ll &ans=dp[pos][md];
    if(pos>n){
        if(md==0) return ans=1;
        return ans=0;
    }
    if(ans!=-1) return ans;
    ans=(md==0);
    for(char c='a';c<='z';c++){
        ans+=calc(pos+1,(md+c-'a'+1)%m);
    }
    return ans;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>k;
    memset(dp,-1,sizeof dp);
    if(calc(1,0)<k){
        return cout<<-1,0;
    }
    string res="";
    int pos=1;
    int md=0;
    bool chose=0;
    while(pos<=n){
        if(md==0){
            k--;
            if(!k) break;
        }

        for(int c=1;c<=26;c++){
            ll cnt=calc(pos+1,(md+c)%m);
            if(k>cnt) k-=cnt;
            else{
                res.push_back(char('a'+c-1));
                md=(md+c)%m;
                break;
            }
        }
        pos++;
    }
    cout<<res;
}
