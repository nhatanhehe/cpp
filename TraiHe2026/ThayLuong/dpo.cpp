inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,k,a[N],dp_before[N],dp_cur[N],phi[N],cnt[N],divs_st[N],divs_en[N];
vector<int>divisors[100005];
const int maxn=1e5+3;
ll ans,l=1,r;
int divs_list[1200005];
void sieve()
{
    for (int i = 1; i <= maxn; i++)
    {
        phi[i] = i;
    }
    for (int i = 2; i <= maxn; i++)
    {
        if (phi[i] == i)
        {
            for (int j = i; j <= maxn; j += i)
            {
                phi[j] -= phi[j] / i;
            }
        }
    }

    static int cnt_divs[maxn + 7];
    for (int i = 1; i <= maxn; i++)
    {
        for (int j = i; j <= maxn; j += i)
        {
            cnt_divs[j]++;
        }
    }

    int cur = 0;
    for (int i = 1; i <= maxn; i++)
    {
        divs_st[i] = cur;
        cur += cnt_divs[i];
        divs_en[i] = divs_st[i];
    }

    for (int i = 1; i <= maxn; i++)
    {
        for (int j = i; j <= maxn; j += i)
        {
            divs_list[divs_en[j]++] = i;
        }
    }
}

inline void add(int idx)
{
    int val = a[idx];
    for (int i = divs_st[val]; i < divs_en[val]; ++i)
    {
        int x = divs_list[i];
        ans += 1LL * phi[x] * cnt[x];
        cnt[x]++;
    }
}

inline void del(int idx)
{
    int val = a[idx];
    for (int i = divs_st[val]; i < divs_en[val]; ++i)
    {
        int x = divs_list[i];
        cnt[x]--;
        ans -= 1LL * phi[x] * cnt[x];
    }
}

ll C(int newL,int newR){
    if (newL > newR) return 0;
    while(l>newL){
        add(--l);
    }
    while(r<newR){
        add(++r);
    }
    while(l<newL){
        del(l++);
    }
    while(r>newR){
        del(r--);
    }
    return ans;
}
void dnc(int l,int r,int optl,int optr){
    if(l>r) return;
    int mid=(l+r)>>1;
    ll best=inf;
    int opt=-1;
    int lim=min(optr,mid);

    for(int i=lim;i>=optl;i--){
        ll cur=dp_before[i]+C(i+1,mid);
        if(cur<best){
            best=cur;
            opt=i;
        }
    }

    dp_cur[mid]=best;
    dnc(l,mid-1,optl,opt);
    dnc(mid+1,r,opt,optr);
}
