inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,a[N],dp_cur[N],dp_before[N],k,pre[N],l=1,r,ans,cnt[N];
void add(int idx){
    ans+=cnt[pre[idx]];
    cnt[pre[idx]]++;
}
void del(int idx){
    cnt[pre[idx]]--;
    ans-=cnt[pre[idx]];
}
ll C(int newL,int newR){
    if (newL > newR) return 0;
    while(l>newL){
        add(--l);
    }
    while(r<newR){
        add(++r);
    }
    while(l<newL){
        del(l++);
    }
    while(r>newR){
        del(r--);
    }
    return ans;
}
void dnc(int l,int r,int optl,int optr){
    if(l>r) return;
    int mid=(l+r)>>1;
    ll best=inf;
    int opt=-1;
    int lim=min(optr,mid);

    for(int i=lim;i>=optl;i--){
        ll cur=dp_before[i]+C(i,mid);
        if(cur<best){
            best=cur;
            opt=i;
        }
    }

    dp_cur[mid]=best;
    dnc(l,mid-1,optl,opt);
    dnc(mid+1,r,opt,optr);
}
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());
ll Rand(ll l,ll r){
    return uniform_int_distribution<ll>(l,r)(rng);
}
