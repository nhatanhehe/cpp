inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,c[N],h[N],cen[N],sz[N],u,v,comp[N],dp1[N][2001],dp2[N][2001],q,ans[5*N];
vector<int>g[N];
int dfs(int u,int p){
    sz[u]=1;
    for(int v:g[u]){
        if(v!=p&&!cen[v]){
            dfs(v,u);
            sz[u]+=sz[v];
        }
    }
    return sz[u];
}
int get_centroid(int u,int p,int total_sz){
    for(int v:g[u]){
        if(v!=p&&!cen[v]){
            if(sz[v]>total_sz/2){
                return get_centroid(v,u,total_sz);
            }
        }
    }
    return u;
}
vector<int>nodes;
void dfs_label(int u,int p,int lb){
    comp[u]=lb;
    nodes.pb(u);
    for(int v:g[u]){
        if(v!=p&&!cen[v]){
            dfs_label(v,u,lb);
        }
    }
}
void dfs_dp(int u,int p){
    for(int w=0;w<=2000;w++){
        dp1[u][w]=dp1[p][w];
        if(w>=c[u]){
            dp1[u][w]=max(dp1[u][w],
                          dp1[p][w-c[u]]+h[u]);
        }
        dp2[u][w]=dp2[p][w];
        if(w>=c[u]){
            dp2[u][w]=max(dp2[u][w],
                          dp2[p][w-c[u]]+h[u]);
        }
    }

    for(int v:g[u]){
        if(v!=p&&!cen[v]) dfs_dp(v,u);
    }
}
struct Queries{
    int u,v,b,id;
};
vector<Queries>Q,childq[N];
void build(int u,vector<Queries>&vec){
    if(vec.empty()) return;
    dfs(u,-1);
    int centroid=get_centroid(u,-1,sz[u]);
    nodes.clear();
    comp[centroid]=centroid;
    cen[centroid]=1;
    nodes.pb(centroid);
    for(int v:g[centroid]){
        if(!cen[v]){
            dfs_label(v,centroid,v);
        }
    }
    for(int w=0;w<=2000;w++){
        dp1[centroid][w]=(w>=c[centroid]? h[centroid]:0);
        dp2[centroid][w]=0;
    }
    for(int v:g[centroid]){
        if(!cen[v]) dfs_dp(v,centroid);
    }
    for(auto x:vec){
        auto [U,V,B,idx]=x;
        if(comp[U]!=comp[V]||U==centroid||V==centroid){
            for(int cst=0;cst<=B;cst++){
                ans[idx]=max(ans[idx],dp1[U][cst]+dp2[V][B-cst]);
            }
        }
        else{
            childq[comp[U]].pb(x);
        }
    }
    for(int x:nodes){
        comp[x]=0;
    }
    cen[centroid]=1;
    for(int v:g[centroid]){
        if(!cen[v]){
            build(v,childq[v]);
        }
        childq[v].clear();
    }

}
