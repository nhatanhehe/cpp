struct Dinic
{
    struct Edge
    {
        int to;
        long long cap, flow, rev;
    };
    int n, s, t;
    std::vector<std::vector<Edge>> adj;
    std::vector<int> level, ptr;
    const long long INF = 1e18;
    Dinic(int n, int s, int t) : n(n), s(s), t(t)
    {
        adj.resize(2 * n + 7);
        level.resize(2 * n + 7);
        ptr.resize(2 * n + 7);
    }

    void add_edge(int from, int to, long long cap)
    {
        adj[from].push_back({to, cap, 0, (long long)adj[to].size()});
        adj[to].push_back({from, 0, 0, (long long)adj[from].size() - 1});
    }

    bool bfs()
    {
std::fill(level.begin(), level.end(), -1);
        level[s] = 0;
        std::queue<int> q;
        q.push(s);
        while (!q.empty())
        {
            int v = q.front();
            q.pop();
            for (auto &edge : adj[v])
            {
                if (edge.cap - edge.flow > 0 && level[edge.to] == -1)
                {
                    level[edge.to] = level[v] + 1;
                    q.push(edge.to);
                }
            }
        }
        return level[t] != -1;
    }

    long long dfs(int v, long long pushed)
    {
        if (pushed == 0 | v == t)
            return pushed;
        for (int &cid = ptr[v]; cid < adj[v].size(); ++cid)
        {
            auto &edge = adj[v][cid];
            int tr = edge.to;
            if (level[v] + 1 != level[tr] || edge.cap - edge.flow == 0)
                continue;
            long long push = dfs(tr, std::min(pushed, edge.cap - edge.flow));
            if (push == 0)
                continue;
            edge.flow += push;
            adj[tr][edge.rev].flow -= push;
            return push;
        }
        return 0;
    }

    long long max_flow()
    {
        long long flow = 0;
        while (bfs())
        {
            std::fill(ptr.begin(), ptr.end(), 0);
            while (long long pushed = dfs(s, INF))
            {
                flow += pushed;
            }
        }
        return flow;
    }
};
struct KMP
{
    std::string s;
    int n;
    std::vector<int> pi;
    KMP(){}
    KMP(std::string pattern)
    {
        s = pattern;
        n = s.length();
        pi.assign(n, 0);
        for (int i = 1; i < n; i++)
        {
            int j = pi[i - 1];
            while (j > 0 && s[i] != s[j])
            {
                j = pi[j - 1];
            }
            if (s[i] == s[j])
            {
                j++;
            }
            pi[i] = j;
        }
    }

    int search(std::string t)
    {
        int m = t.length();
        int ans = 0;
        int j = 0;
        for (int i = 0; i < m; i++)
        {
            while (j > 0 && t[i] != s[j])
            {
                j = pi[j - 1];
            }
            if (t[i] == s[j])
            {
                j++;
            }
            if (j == n)
            {
                ans++;
                j = pi[j - 1];
            }
        }
        return ans;
    }
};
