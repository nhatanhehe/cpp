const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,u,v,w,k;
vector<ii>g[N];
vector<tuple<int,int,int>>edg;
void dijk(vector<ll>&d){
    priority_queue<ii,vector<ii>,greater<ii>>pq;
    for(int i=1;i<=n;i++){
        if(d[i]!=inf) pq.push(ii(d[i],i));
    }
    while(pq.size()){
        auto [cost,u]=pq.top(); pq.pop();
        if(d[u]<cost) continue;
        for(auto [v,w]:g[u]){
            if(d[v]>d[u]+w){
                d[v]=d[u]+w;
                pq.push({d[v],v});
            }
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>k;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        g[u].pb({v,w});
        edg.pb({u,v,w});
    }
    vector<ll>dist(n+1,inf),ndist(n+1,inf);
    dist[1]=0;
    dijk(dist);
    ll ans=dist[n];
    for(int t=1;t<=k;t++){
        ndist.assign(n+1,inf);
        for(auto [u,v,w]:edg){
            if(dist[u]!=inf) ndist[v]=min(ndist[v],dist[u]-w);
        }
        dijk(ndist);
        ans=min(ans,ndist[n]);
        dist.swap(ndist);
    }
    cout<<ans;
}
