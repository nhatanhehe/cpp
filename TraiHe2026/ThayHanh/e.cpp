inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int s[N],n,dp[3000],trace[55][200],d[N],pre[N],take[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<n;i++){
        cin>>s[i];
    }
    memset(dp,-0x3f,sizeof(dp));
    dp[0]=n*s[1];
    for(int i=1;i<=n;i++) d[i]=1;
    for(int i=1;i<=n-2;i++){
        for(int j=i;j<=n-2;j++){
            if(dp[j]<dp[j-i]+s[i+1]-s[1]){
                dp[j]=dp[j-i]+s[i+1]-s[1];
                pre[j]=j-i;
            }
        }
    }
    cout<<dp[n-2]<<'\n'<<n-1<<'\n';
    int s=n-2;
    vector<int>change;
    while(s){
        int nxt_s=pre[s];
        change.pb(s-pre[s]);
        s=pre[s];
    }
    int cnt=1;
    for(int x:change){
        d[cnt]+=x;
        cnt++;
    }
    set<int>leaf,big;
    for(int i=1;i<=n;i++){
        if(d[i]==1) leaf.insert(i);
        else big.insert(i);
    }
    //for(int i=1;i<=n;i++) cout<<d[i]<<" "; cout<<'\n';
    vector<ii>edg;
    while(big.size()){
        int u=*leaf.begin();
        leaf.erase(leaf.begin());
        int v=*big.begin();
        edg.pb(ii(u,v));
        d[u]--;
        d[v]--;
        if(d[v]==1){
            big.erase(v);
            leaf.insert(v);
        }
    }
    auto it=leaf.begin();
    int u=*it++;
    int v=*it;
    edg.pb(ii(u,v));
    for(auto [x,y]:edg) cout<<x<<" "<<y<<'\n';
}
