inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n;
string s[N];
int dp[N][26];
int mx[26][26];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>s[i];
    }
    for(int c1=0;c1<26;c1++){
        for(int c2=0;c2<26;c2++){
            mx[c1][c2]=-1e9;
        }
    }
    // mx[c1][c2] la dp co do dai lon nhat bat dau tai c1, ket thuc tai c2 truoc do
    for(int i=1;i<=n;i++){
        for(int c=0;c<26;c++){
            dp[i][c]=mx[c][s[i][0]-'a']+s[i].size();
            if(s[i][0]==c+'a'){
                dp[i][c]=max(dp[i][c],(int)s[i].size());
            }
            mx[c][s[i].back()-'a']=max(mx[c][s[i].back()-'a'],dp[i][c]);
        }
    }
    int ans=0;
    for(int c=0;c<26;c++){
        ans=max(ans,mx[c][c]);
    }
    cout<<ans;
}
