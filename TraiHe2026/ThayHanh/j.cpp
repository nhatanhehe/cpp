#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=500*500+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,a[N],dpl[N],dpr[N],f[N][21],theta,q,mx[N][21],mn[N][21],premx[N],premn[N],sufmx[N],sufmn[N];
ll get_max(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return max(f[l][k],f[r-(1<<k)+1][k]);
}
ll get_mn(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return min(mn[l][k],mn[r-(1<<k)+1][k]);
}
ll get_mx(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return max(mx[l][k],mx[r-(1<<k)+1][k]);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>theta>>n>>q;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        mx[i][0]=a[i];
        mn[i][0]=a[i];
    }
    ll Max=a[1],Min=-a[1];
    premx[1]=Max;
    premn[1]=Min;
    for(int i=2;i<=n;i++){
        dpl[i]=max(Max-a[i],a[i]+Min);
        dpl[i]=max(dpl[i],dpl[i-1]);
        Max=max(Max,dpl[i-1]+a[i]);
        Min=max(Min,dpl[i-1]-a[i]);
        premx[i]=Max;
        premn[i]=Min;
    }
    Max=a[n],Min=-a[n];
    sufmx[n]=Max;
    sufmn[n]=Min;
    premn[0] = -inf; premx[0] = -inf;
    sufmn[n+1] = -inf; sufmx[n+1] = -inf;
    for(int i=n-1;i>=1;i--){
        dpr[i]=max(Max-a[i],a[i]+Min);
        dpr[i]=max(dpr[i],dpr[i+1]);
        Max=max(Max,dpr[i+1]+a[i]);
        Min=max(Min,dpr[i+1]-a[i]);
        sufmx[i]=Max;
        sufmn[i]=Min;
    }
    cout<<dpl[n]<<' ';
    for(int i=1;i<n;i++){
        f[i][0]=dpl[i]+dpr[i+1];
    }
    for(int j=1;j<=20;j++){
        for(int i=1;i+(1<<j)-1<n;i++){
            f[i][j]=max(f[i][j-1],f[i+(1<<(j-1))][j-1]);
        }
    }
    for(int j=1;j<=20;j++){
        for(int i=1;i+(1<<j)-1<=n;i++){
            mx[i][j]=max(mx[i][j-1],mx[i+(1<<(j-1))][j-1]);
            mn[i][j]=min(mn[i][j-1],mn[i+(1<<(j-1))][j-1]);
        }
    }
    while(q--){
        char tp;
        int x,y;
        cin>>tp>>x>>y;
        if(x>y) swap(x,y);
        if(tp=='H'){
            cout<<get_max(x,y-1)<<' ';
        }
        else{
            ll res=-inf;
            // c1
            res=max(res,dpl[x-1]+dpr[y+1]+get_mx(x,y)-get_mn(x,y));
            // c2 max trai , min [x,y]
            res=max(res,premx[x-1]-get_mn(x,y)+dpr[y+1]);
            // c3 max phai , min [x,y]
            res=max(res,dpl[x-1]-get_mn(x,y)+sufmx[y+1]);
            // c4 min trai, max [x,y]
            res=max(res,premn[x-1]+get_mx(x,y)+dpr[y+1]);
            // c5 min phai, max [x,y]
            res=max(res,dpl[x-1]+get_mx(x,y)+sufmn[y+1]);
            // c6 min phai, max trai
            res=max(res,premn[x-1]+sufmx[y+1]);
            // c7 max trai, min phai
            res=max(res,premx[x-1]+sufmn[y+1]);
            cout<<res<<' ';
        }
    }
}
