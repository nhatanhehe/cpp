inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k;
string s;
int cnt['z'+1],dist;
void add(char c){
    if(!cnt[c]) dist++;
    cnt[c]++;
}
void del(char c){
    if(cnt[c]==1) dist--;
    cnt[c]--;
}
