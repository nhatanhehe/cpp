inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,q,a[N],L[N],R[N],s[N];
struct SegmentTree{
    vector<ll>lz,tree,res;
    int n;
    void init(int _n){
        n=_n;
        lz.resize(n*4+5,0);
        tree.resize(n*4+5,0);
        res.resize(n*4+5,1e9);
    }
    void push(int id){
        if(lz[id]){
            tree[id*2]+=lz[id];
            tree[id*2+1]+=lz[id];
            lz[id*2]+=lz[id];
            lz[id*2+1]+=lz[id];
        }
        lz[id]=0;
    }
    void up(int u,int v,ll k,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return;
        if(u<=l&&r<=v){
            tree[id]+=k;
            lz[id]+=k;
            return;
        }
        push(id);
        int mid=(l+r)>>1;
        up(u,v,k,id*2,l,mid);
        up(u,v,k,id*2+1,mid+1,r);
        tree[id]=min(tree[id*2],tree[id*2+1]);
    }
    void kill(int u,int v,int q,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return;
        if(tree[id]>0) return;
        if(l==r){
            tree[id]=inf;
            res[l]=q;
            return;
        }
        push(id);
        int mid=(l+r)>>1;
        kill(u,v,q,id*2,l,mid);
        kill(u,v,q,id*2+1,mid+1,r);
        tree[id]=min(tree[id*2],tree[id*2+1]);
    }
}seg;
