inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll t,n,m,q;
namespace sub3{
    ll t[N],d[N],a[N][N],b[N][N],r[N],c[N],ans[N];
    void calc(ll a[N][N]){
        vector<ll>sum_col,sum_row;
        sum_col.resize(n+4,0);
        sum_row.resize(n+4,0);
        vector<vector<int>>swep(n+4);
        multiset<ll,greater<ll>>row,col;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=n;j++){
                sum_row[i]+=a[i][j];
            }
            row.insert(sum_row[i]);
        }
        for(int j=1;j<=n;j++){
            for(int i=1;i<=n;i++){
                sum_col[j]+=a[i][j];
            }
            col.insert(sum_col[j]);
        }
        for(int i=1;i<=m;i++){
            swep[r[i]].pb(c[i]);
        }
        for(int Q=0;Q<=q;Q++){
            int R=r[t[Q]];
            int C=c[t[Q]];
            a[R][C]+=d[Q];
            row.erase(row.find(sum_row[R]));
            sum_row[R]+=d[Q];
            row.insert(sum_row[R]);
            col.erase(col.find(sum_col[C]));
            sum_col[C]+=d[Q];
            col.insert(sum_col[C]);
            ll mx=-1e18;
            /// 3 hang
            auto it=row.begin();
            auto it2=next(it);
            auto it3=next(it2);
            mx=max(mx,(*it)+(*it2)+(*it3));
            /// 1 hang 2 cot
            for(int i=1;i<=n;i++){
                for(int c_:swep[i]){
                    col.erase(col.find(sum_col[c_]));
                    sum_col[c_]-=a[i][c_];
                    col.insert(sum_col[c_]);
                }
                auto IT=col.begin();
                auto IT2=next(IT);
                mx=max(mx,sum_row[i]+(*IT)+(*IT2));
                for(int c_:swep[i]){
                    col.erase(col.find(sum_col[c_]));
                    sum_col[c_]+=a[i][c_];
                    col.insert(sum_col[c_]);
                }
            }
            ans[Q]=max(ans[Q],mx);
            row.erase(row.find(sum_row[R]));
            sum_row[R]-=d[Q];
            row.insert(sum_row[R]);
            col.erase(col.find(sum_col[C]));
            sum_col[C]-=d[Q];
            col.insert(sum_col[C]);
            a[R][C]-=d[Q];
        }
    }
    void solve(){
        for(int i=1;i<=m;i++){
            int w;
            cin>>r[i]>>c[i]>>w;
            a[r[i]][c[i]]=w;
        }
        for(int i=1;i<=n;i++){
            for(int j=1;j<=n;j++){
                b[n-j+1][i]=a[i][j];
            }
        }
        t[0]=1;
        d[0]=0;
        for(int i=1;i<=q;i++){
            cin>>t[i]>>d[i];
            ans[i]=-1e18;
        }
        ans[0]=-1e18;
        calc(a);
        for(int i=1;i<=m;i++){
            swap(r[i],c[i]);
            r[i]=n-r[i]+1;
        }
        calc(b);
        for(int i=0;i<=q;i++) cout<<ans[i]<<'\n';
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    if(t==1){
        cin>>n>>m>>q;
        if(n<=5e2&&m<=5e2&&q<=5e2) sub3::solve();
    }
}
