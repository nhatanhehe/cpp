const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,z,dp[2000006],a[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>z;
    for(int mask=0;mask<(1<<z);mask++) dp[mask]=1e9;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        dp[a[i]]=a[i];
    }
    for(int i=0;i<z;i++){
        for(int mask=0;mask<(1<<z);mask++){
            if(mask>>i&1){
                dp[mask]=min(dp[mask],dp[Off(mask,i)]);
            }
        }
    }
    for(int i=0;i<(1<<z);i++){
        ll fmask=(1<<z)-1;
        fmask^=i;
        cout<<(dp[fmask]==1e9? -1:dp[fmask])<<" ";
    }
}
