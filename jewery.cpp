inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct Line{
    ll a,b;
    Line(ll a,ll b): a(a),b(b){}
    ll cal(int x){
        return a*x+b;
    }
};
struct LichaoTree{
    vector<Line>st;
    int n;
    void init(int _n){
        n=_n;
        st.assign(n*4+10,Line(0,0));
    }
    void addline(int id,Line li,int l,int r){
        if(l==r){
            if(li.cal(l)>st[id].cal(l)) st[id]=li;
            return;
        }
        int mid=(l+r)>>1;
        if(li.cal(mid)>st[id].cal(mid)){
            swap(li,st[id]);
        }
        if(li.a<st[id].a) addline(id*2,li,l,mid);
        else addline(id*2+1,li,mid+1,r);
    }
    void up(Line li,int u,int v,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return;
        if(u<=l&&r<=v){
            addline(id,li,l,r);
            return;
        }
        int mid=(l+r)>>1;
        up(li,u,v,id*2,l,mid);
        up(li,u,v,id*2+1,mid+1,r);
    }
    ll get(int x,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l==r){
            return st[id].cal(x);
        }
        int mid=(l+r)>>1;
        if(x<=mid) return max(st[id].cal(x),get(x,id*2,l,mid));
        else return max(st[id].cal(x), get(x,id*2+1,mid+1,r));
    }
}nihao;
