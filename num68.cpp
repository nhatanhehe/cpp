inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
string s;
ll dp[20][2][2][2];
ll calc(int i,int c,bool sa,bool sb,string &s){
    if(i==-1){
        return (!c&&(sa||sb));
    }
    ll &ans=dp[i][c][sa][sb];
    if(ans!=-1) return ans;
    ans=0;
    for(int x=0;x<=9;x++){
        for(int y=0;y<=9;y++){
            int sum=x+y+c;
            if(sum%10==s[i]-'0'){
                ans+=calc(i-1,sum/10,sa||(x==6||x==8),sb||(y==6||y==8),s);
            }
        }
    }
    return ans;
}
bool check(ll n){
    if(n&1) return 0;
    n/=2;
    while(n){
        int tmp=n%10;
        if(tmp==6||tmp==8){
            return 1;
        }
        n/=10;
    }
    return 0;
}
