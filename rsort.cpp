inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],b[N],en[N];
vector<int>sol[N];
void QS(int k,vector<int>cur){
    if(k==0){
        return;
    }
    vector<int>b1,b2;
    int mid=cur.size()/2;
    for(int i=0;i<mid;i++){
        b1.pb(cur[i]);
    }
    for(int i=mid;i<cur.size();i++){
        b2.pb(cur[i]);
    }
    sol[k].insert(sol[k].begin(),all(b1));
    reverse(all(b1));
    QS(k-1,b1);
    QS(k-1,b2);
}
