inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,q,u,v,w,ans[N];
tuple<int,int,int>edg[N];
struct Basis{
    vector<int>b;
    void init(){
        b.resize(33,0);
    }
    void add(int x){
        for(int i=31;i>=0;i--){
            if((x>>i)&1){
                if(!b[i]){
                    b[i]=x;
                    break;
                }
                else{
                    x^=b[i];
                }
            }
        }
    }
    int find_max(int x){
        for(int i=31;i>=0;i--){
            x=min(x,x^b[i]);
        }
        return x;
    }
};
struct DSU{
    vector<int>p,dist;
    vector<Basis>bs;
    int n;
    void init(int _n){
        n=_n;
        p.resize(n+3,0);
        dist.resize(n+3,0);
        bs.resize(n+4);
        for(int i=1;i<=n;i++){
            p[i]=i;
            bs[i].init();
        }
    }
    int acs(int u){
        if(u==p[u]) return u;
        int par=p[u];
        p[u]=acs(p[u]);
        dist[u]^=dist[par];
        return p[u];
    }
    void join(int u,int v,int w){
        int ru=acs(u);
        int rv=acs(v);
        int dv=dist[v];
        int du=dist[u];
        if(ru!=rv){
            p[rv]=ru;
            dist[rv]^=w^du^dv;
            for(int i=31;i>=0;i--){
                bs[ru].add(bs[rv].b[i]);
            }
        }
        else{
            bs[ru].add(w^du^dv);
        }
    }
}dsu;
struct Query{
    int tp,i,u,v;
}Q[N];
int mark[N];
int dist(int u){
    dsu.acs(u);
    return dsu.dist[u];
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>q;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        edg[i]={u,v,w};
    }
    dsu.init(n);
    for(int i=1;i<=q;i++){
        cin>>Q[i].tp;
        if(Q[i].tp==1){
            cin>>Q[i].i;
            mark[Q[i].i]=1;
        }
        else cin>>Q[i].u>>Q[i].v;
    }
    for(int i=1;i<=m;i++){
        if(!mark[i]){
            auto [u,v,w]=edg[i];
            dsu.join(u,v,w);
        }
    }
    vector<int>ans;
    for(int i=q;i>=1;i--){
        if(Q[i].tp==1){
            auto [u,v,w]=edg[Q[i].i];
            dsu.join(u,v,w);
        }
        else{
            int u=Q[i].u,v=Q[i].v;
            if(dsu.acs(u)!=dsu.acs(v)) ans.pb(-1);
            else{
                ans.pb(dsu.bs[dsu.acs(u)].find_max(dist(u)^dist(v)));
            }
        }
    }
    reverse(all(ans));
    for(int x:ans) cout<<x<<'\n';
}
