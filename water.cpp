#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "water"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,far[N],nxt[N][20],l,r;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>l>>r;
        if(l<=r){
            far[l]=max(far[l],r+1);
            far[l+n]=max(far[l+n],r+n+1);
        }
        else far[l]=max(far[l],r+n+1);
    }
    for(int i=1;i<=2*n;i++){
        far[i]=max(far[i],far[i-1]);
        nxt[i][0]=far[i];
    }
    for(int j=1;(1<<j)<=2*n;j++){
        for(int i=1;i+(1<<(j-1))<=n;i++){
            nxt[i][j]=nxt[nxt[i][j-1]][j-1];
            if(nxt[i][j]==nxt[i][j-1]) nxt[i][j]=0;
        }
    }
    int ans=1e9;
    for(int i=1;i<=n;i++){
        int s=i;
        int en=i+n-1;
        int sum=0;
        for(int j=19;j>=0;j--){
            if(nxt[s][j]<=en&&nxt[s][j]>s){
                s=nxt[s][j];
                sum+=(1<<j);
            }
        }
        if(s<=en&&nxt[s][0]>s){
            s=nxt[s][0];
            sum++;
        }
        if(s>en){
            ans=min(ans,sum);
        }
    }
    cout<<m-ans;
}
