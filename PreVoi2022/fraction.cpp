inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,a[N],b[N],pr[N];
void sang(){
    for(int i=1;i<=1e6;i++){
        pr[i]=i;
    }
    for(int i=2;i<=sqrt(1e6);i++){
        if(pr[i]==i)
        for(int j=i*i;j<=1e6;j+=i){
            if(pr[j]==j) pr[j]=i;
        }
    }
}
void pt(int n,map<int,int>&mp){
    while(n>1){
        int h=pr[n];
        while(n%h==0){
            mp[h]++;
            n/=h;
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    int t;
    sang();
    cin>>t;
    while(t--){
        cin>>n;
        map<int,int>mpa,mpb;
        for(int i=1;i<=n;i++){
            cin>>a[i];
            pt(a[i],mpa);
        }
        for(int i=1;i<=n;i++){
            cin>>b[i];
            pt(b[i],mpb);
        }
        int mx=0,c=0;
        for(auto &e:mpb){
            auto [val,cnt]=e;
            int tmp=min(cnt,mpa[val]);
            e.se-=tmp;
            c+=e.se;
            mx=max(mx,e.se);
        }
        if(mx==0) cout<<"Integer\n";
        else if(c==mpb[2]+mpb[5]) cout<<"Finite\n";
        else if(!mpb[2]&&!mpb[5]) cout<<"Single\n";
        else cout<<"Mixed\n";
    }
}
