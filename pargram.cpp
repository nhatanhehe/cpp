#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n,x[N],y[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n;
        vector<ii>x;
        for(int i=1;i<=n;i++){
            int u,v;
            cin>>u>>v;
            x.pb({u,v});
        }
        sort(all(x));
        x.erase(unique(all(x)),x.end());
        vector<ii>cp;
        for(int i=0;i<x.size();i++){
            for(int j=i+1;j<x.size();j++){
                cp.pb(ii(x[i].fi+x[j].fi,x[i].se+x[j].se));
            }
        }
        sort(all(cp));
        cp.pb(ii(2e9+1,2e9+1));
        ll ans=0,cnt=0;
        for(int i=0;i<cp.size()-1;i++){
            //cout<<cp[i].fi<<" "<<cp[i].se<<'\n';
            if(cp[i+1]!=cp[i]){
                cnt++;
                ans+=cnt*(cnt-1)/2;
                cnt=0;
            }
            else cnt++;
        }
        cout<<ans<<'\n';
    }
}
