#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "aaa"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=4e3+5;
const ll mod=1e9+19972207;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,t,f[N],inv[N],invf[N],a[N];
ii Q[N];
int exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    int t=exp(a,n/2);
    if(n&1) return mul(a,mul(t,t));
    return mul(t,t);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    for(int i=1;i<=t;i++){
        cin>>n>>k;
        Q[i]=ii(n,k);
    }
    f[0]=1;
    for(int i=1;i<=4e3;i++){
        f[i]=mul(f[i-1],i);
    }
    inv[1]=1;
    for(int i=2;i<=4e3;i++){
        inv[i]=sub(mod,mul((mod/i),inv[mod%i]));
    }
    invf[4000]=exp(f[4000],mod-2);
    for(int i=4000;i>=1;i--) invf[i-1]=mul(invf[i],i);
    for(int q=1;q<=t;q++){
        n=Q[q].fi;
        k=Q[q].se;
        if(n<=1){
            cout<<"0\n";
            continue;
        }
        a[0]=1;
        for(int i=1;i<n;i++){
            int sum=0;
            int len=i-k;
            if(len<0) len=0;
            for(int j=len;j<=i-1;j++){
                sum=add(a[j],sum);
            }
            a[i]=mul(sum,inv[i]);
        }
        int S=0,res=0;
        for(int T=0;T<n;T++){
            S=add(S,a[T]);
            res=add(res,mul(S,invf[n-T-1]));
        }
        int sell=mul(f[n-1],res);
        int ans=0;
        for(int y=0;y<n;y++){
            int v=mul(sub(n,y),invf[y]);
            ans=add(ans,v);
        }
        int rem=mul(f[n-1],ans);
        cout<<sub(add(rem,mod),sell)<<'\n';
    }
}
