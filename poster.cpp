inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,w[N],h[N];
ii f[N][19];
ii get(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return min(f[l][k],f[r-(1<<k)+1][k]);
}
ll dnc(int l,int r,int lst){
    if(l>r) return 0;
    auto [val,p]=get(l,r);
    return dnc(l,p-1,val)+dnc(p+1,r,val)+(val!=lst);
}
