inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],p[N],cnt[103][N],op;
vector<int>pr;
void sang(){
    memset(p,1,sizeof p);
    p[0]=p[1]=1;
    for(int i=2;i<=1e3;i++){
        if(p[i])
        for(int j=i*i;j<=1e6;j+=i){
            p[j]=0;
        }
    }
    for(int i=1;i<=1e6;i++) if(p[i]) pr.pb(i);
}
void pt(int idx,int n){
    for(int i=2;i<=sqrt(n);i++){
        while(n%i==0){
            n/=i;
            cnt[idx][i]++;
        }
    }
    if(n>1) cnt[idx][n]++;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        pt(i,a[i]);
    }
    sang();
    for(int x:pr){
        int avg=0;
        for(int i=1;i<=n;i++){
            avg+=cnt[i][x];
        }
        avg/=n;
        int sum=0;
        for(int i=1;i<=n;i++){
            while(cnt[i][x]>avg){
                a[i]/=x;
                sum++;
                cnt[i][x]--;
                op++;
            }
        }
        for(int i=1;i<=n;i++){
            while(cnt[i][x]<avg&&sum){
                sum--;
                cnt[i][x]++;
                a[i]*=x;
            }
        }
        op-=sum;
    }
    int gcd=0;
    for(int i=1;i<=n;i++){
        gcd=__gcd(a[i],gcd);
    }
    cout<<gcd<<" "<<op;
}
