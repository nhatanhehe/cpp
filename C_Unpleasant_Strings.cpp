inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,nxt[N][26],q,mx_nxt[N],res[N];
string s,t;
vector<int>g[26];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    cin>>n>>k>>s;
    s=" "+s;
    for(int i=0;i<26;i++) nxt[n+1][i]=n+1;
    for(int i=n;i>=0;i--){
        for(int j=0;j<26;j++){
            if(s[i]==j+'a') nxt[i][j]=i;
            else nxt[i][j]=nxt[i+1][j];
        }
    }
    for (int i=0;i<=n+1;i++){
        int mx=0;
        for(int j=0;j<k;j++){
            mx=max(mx,nxt[i][j]);
        }
        mx_nxt[i]=mx;
    }
    res[n+1]=0;
    for(int i=n;i>=0;i--){
        res[i]=res[mx_nxt[i+1]]+1;
    }
    cin>>q;
    while(q--){
        cin>>t;
        int pos=0;
        for(char c:t){
            if(pos>n) break;
            pos=nxt[pos+1][c-'a'];
            //cerr<<pos<<'\n';
        }
        //cerr<<pos<<'\n';
        cout<<res[pos]<<'\n';
    }
}
