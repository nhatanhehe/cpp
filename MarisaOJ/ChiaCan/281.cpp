inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,a[N],u,v,st[N],en[N],cnt,h[N],p[N][22],tour[N],S;
vector<int>g[N];
void dfs(int u,int par){
    st[u]=++cnt;
    tour[cnt]=u;
    for(int v:g[u]){
        if(v!=par){
            h[v]=h[u]+1;
            p[v][0]=u;
            dfs(v,u);
        }
    }
    en[u]=++cnt;
    tour[cnt]=u;
}
int lca(int u,int v){
    if(h[u]<h[v]) swap(u,v);
    for(int i=19;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)) u=p[u][i];
    }
    if(u==v) return u;
    for(int i=19;i>=0;i--){
        if(p[u][i]!=p[v][i]){
            u=p[u][i];
            v=p[v][i];
        }
    }
    return p[u][0];
}
struct Query{
    int l,r,lc,idx;
}Q[N];
ii tree[N<<2];
map<int,int>mp;
void build(int id=1,int l=1,int r=n){
    if(l==r){
        tree[id].se=l;
        return;
    }
    int mid=(l+r)>>1;
    build(id*2,l,mid);
    build(id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
void up(int pos,int k,int id=1,int l=1,int r=n){
    if(l==r){
        tree[id].fi+=k;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid) up(pos,k,id*2,l,mid);
    else up(pos,k,id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
int vis[N],ans[N];
void add_(int u){
   // debug(u);
   // debug(a[u]);
    if(!vis[u]) up(a[u],1);
    else up(a[u],-1);
   // debug(tree[1].fi);
    //debug(tree[1].se);
    vis[u]^=1;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    vector<int>cp;
    cin>>n>>q;
    S=sqrt(2*n);
    for(int i=1;i<=n;i++){
        cin>>a[i];
        cp.pb(a[i]);
    }
    sort(all(cp));
    cp.erase(unique(all(cp)),cp.end());
    for(int i=1;i<=n;i++){
        mp[lower_bound(all(cp),a[i])-cp.begin()+1]=a[i];
        a[i]=lower_bound(all(cp),a[i])-cp.begin()+1;
    }
    for(int i=1;i<n;i++){
        cin>>u>>v;
        g[u].pb(v);
        g[v].pb(u);
    }
    dfs(1,-1);
    for(int j=1;j<=19;j++){
        for(int i=1;i<=n;i++){
            p[i][j]=p[p[i][j-1]][j-1];
        }
    }
    for(int i=1;i<=q;i++){
        cin>>u>>v;
        if(st[u]>st[v]) swap(u,v);
        int acs=lca(u,v);
        if(acs==u||acs==v) Q[i]={st[u],st[v],acs,i};
        else Q[i]={en[u],st[v],acs,i};
    }
    sort(Q+1,Q+q+1,[&](const Query &x,const Query &y){
         if(x.l/S!=y.l/S) return x.l<y.l;
         return x.r<y.r;
    });
    build();
    int l=1,r=0;
    for(int i=1;i<=q;i++){
        while(l>Q[i].l){
            add_(tour[--l]);
        }
        while(r<Q[i].r){
            add_(tour[++r]);
            //debug(tour[r]);
        }
        while(l<Q[i].l){
            add_(tour[l++]);
        }
        while(r>Q[i].r){
            add_(tour[r--]);
        }
        int lc=Q[i].lc;
        int u=tour[Q[i].l];
        int v=tour[Q[i].r];
        if(lc!=u&&lc!=v) add_(lc);
        int dist=h[u]+h[v]-2*h[lc];
     //   debug(tree[1].fi);
      //  debug(tree[1].se);
        if(tree[1].fi>=(dist+1)/2+1) ans[Q[i].idx]=mp[tree[1].se];
        else ans[Q[i].idx]=-1;
        if(lc!=u&&lc!=v) add_(lc);
    }
    for(int i=1;i<=q;i++){
        cout<<ans[i]<<'\n';
    }
}
