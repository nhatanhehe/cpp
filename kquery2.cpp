inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
const int BLOCK=sqrt(1e5);
int n,a[N],m;
char tp;
struct BIT{
    vector<int>bit;
    int n;
    void init(int _n){
        n=_n;
        bit.resize(n+4,0);
    }
    void up(int i,int k){
        for(;i<=n;i+=i&-i){
            bit[i]=k;
        }
    }
    int get(int i){
        int res=0;
        for(;i;i-=i&-i){
            res+=bit[i];
        }
        return res;
    }
    int query(int l,int r){
        return get(r)-get(l-1);
    }
}bit[100005/BLOCK+4];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    const int MAXA=1e4;
    cin>>n;
    for(int i=0;i<=BLOCK;i++){
        bit[i].init(MAXA+4);
    }
    for(int i=1;i<=n;i++){
        cin>>a[i];
        bit[i/BLOCK].up(a[i],1);
    }
    cin>>m;
    while(m--){
        cin>>tp;
        if(tp=='0'){
            int i,v;
            cin>>i>>v;
            bit[i/BLOCK].up(a[i],-1);
            a[i]=v;
            bit[i/BLOCK].up(v,1);
        }
        else{
            int l,r,k;
            cin>>l>>r>>k;
            int cnt=0;
            if(r-l+1<=BLOCK){
                for(int i=l;i<=r;i++){
                    cnt+=(a[i]>k);
                }
                cout<<cnt<<'\n';
                continue;
            }
            while(l%BLOCK!=1){
                cnt+=(a[l]>k);
                l++;
            }
            while(r%BLOCK!=BLOCK-1){
                cnt+=(a[r]>k);
                r--;
            }
            int bl=l/BLOCK;
            int br=r/BLOCK;
            for(int i=bl;i<=br;i++){
                cnt+=bit[i].query(k+1,1e4);
            }
            cout<<cnt<<'\n';
        }
    }
}
