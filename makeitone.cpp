mint exp(mint a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    mint t=exp(a,n/2);
    if(n&1) return t*t*a;
    else return t*t;
}
mint C(int n,int k){
    if(k>n) return 0;
    mint a=f[n];
    mint b=(f[k]*(f[n-k]));
    return a*exp(b,mod-2);
}
