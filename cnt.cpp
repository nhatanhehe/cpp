inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,k;
namespace sub1{
    void solve(){
        vector<vector<int>>a(m+2,vector<int>(n+3,0));
        vector<vector<ll>>dp(m+2,vector<ll>(n+3,0));
        while(k--){
            int x,y;
            cin>>x>>y;
            a[x][y]=1;
        }
        dp[1][1]=1;
        for(int i=1;i<=m;i++){
            for(int j=1;j<=n;j++){
                if(a[i][j]==1) dp[i][j]=0;
                else{
                    if(i>=2&&a[i-1][j]!=1) dp[i][j]=add(dp[i-1][j],dp[i][j]);
                    if(j>=2&&a[i][j-1]!=1) dp[i][j]=add(dp[i][j-1],dp[i][j]);
                }
            }
        }
        cout<<dp[m][n];
    }
}
namespace sub2{
    ll f[N];
    ll exp(int a,int n){
        if(n==0) return 1;
        if(n==1) return a;
        ll t=exp(a,n/2);
        if(n&1) return mul(mul(t,t),a);
        return mul(t,t);
    }
    int C(int n,int k){
        return mul(f[n],exp(mul(f[n-k],f[k]),mod-2));
    }
    void solve(){
        f[0]=1;
        for(int i=1;i<=n+m;i++){
            f[i]=mul(f[i-1],i);
        }
        cout<<C(m+n-2,m-1);
    }
}
namespace sub3{
    ll f[N],x,y,dp[N];
    ll exp(int a,int n){
        if(n==0) return 1;
        if(n==1) return a;
        ll t=exp(a,n/2);
        if(n&1) return mul(mul(t,t),a);
        return mul(t,t);
    }
    ll C(int n,int k){
        return mul(f[n],exp(mul(f[n-k],f[k]),mod-2));
    }
    ll cal_dist(int x1,int y1,int x2,int y2){
        return C(x2-x1+y2-y1,x2-x1);
    }
    ii p[N];
    void solve(){
        for(int i=1;i<=k;i++){
            cin>>p[i].fi>>p[i].se;
        }
        sort(p+1,p+k+1);
        p[k+1]=ii(m,n);
        p[0]=ii(1,1);
        f[0]=1;
        for(int i=1;i<=n+m;i++){
            f[i]=mul(f[i-1],i);
        }
        for(int i=1;i<=k+1;i++){
            ll sum=0;
            for(int j=0;j<i;j++){
                sum=add(sum,mul(dp[j],cal_dist(p[j].fi,p[j].se,p[i].fi,p[i].se)));
            }
            dp[i]=sub(cal_dist(1,1,p[i].fi,p[i].se),sum);
        }
        cout<<dp[k+1];
    }
}
