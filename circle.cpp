inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,s[N],w[N],pre[N],pre2[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    for(int i=1;i<=n;i++){
        cin>>w[i];
    }
    for(int i=1;i<=k;i++){
        cin>>s[i];
        pre2[s[i]]+=w[s[i]];
    }
    for(int i=1;i<=n;i++){
        pre[i]=pre[i-1]+w[i];
        pre2[i]+=pre2[i-1];
    }
    for(int i=1;i<=n;i++){
        pre[i]-=2*pre[i];
    }
    ll ans=inf;
    for(int i=1;i<=n;i++){
        for(int j=i;j<=n;j++){
            ll val=pre[j]-pre[i-1]-2*(pre2[j]-pre2[i-1]);
            ans=min({ans,val,pre[n]-2*pre2[n]-val});
        }
    }
    cout<<ans+pre2[n];
}
