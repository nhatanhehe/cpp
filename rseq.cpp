inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,t,a[N],v[N],mark[N],res[N];
struct DSU{
    vector<int>p,sz;
    multiset<ll,greater<ll>>s;
    int n;
    void active(int id){
        sz[id]=a[id];
        s.insert(sz[id]);
    }
    void init(int _n){
        n=_n;
        p.resize(n+3,0);
        sz.resize(n+4,0);
        for(int i=1;i<=n;i++){
            p[i]=i;
        }
    }
    int acs(int u){
        return u==p[u]? u:p[u]=acs(p[u]);
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            ll sum=sz[u]+sz[v];
            s.erase(s.find(sz[u]));
            s.erase(s.find(sz[v]));
            s.insert(sum);
            p[v]=u;
            sz[u]+=sz[v];
        }
    }
}dsu;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>t;
    dsu.init(n);
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    for(int i=1;i<=t;i++){
        cin>>v[i];
        mark[v[i]]=1;
    }
    for(int i=1;i<=n;i++){
        if(mark[i]) continue;
        dsu.active(i);
        if(i>=2&&!mark[i-1]) dsu.join(i-1,i);
    }
    for(int i=t;i>=1;i--){
        multiset<ll,greater<ll>>&ms=dsu.s;
        if(ms.size()) res[i]=(*ms.begin());
        dsu.active(v[i]);
        mark[v[i]]=0;
        if(v[i]>=2&&!mark[v[i]-1]) dsu.join(v[i],v[i]-1);
        if(v[i]<n&&!mark[v[i]+1]) dsu.join(v[i],v[i]+1);
    }
    for(int i=1;i<=t;i++) cout<<res[i]<<'\n';
}
