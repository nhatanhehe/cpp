    ll res=0;
    for(int i=0;i<n;i++){
        for(int j=0;j<=1e4;j++){
            dp[i+1][j]=add(dp[i+1][j],dp[i][j]);
            dp[i+1][min(10000LL,j+l[i+1])]=add(dp[i+1][min(10000LL,j+l[i+1])],dp[i][j]);
            if(j>l[i+1]){
                res=add(res,dp[i][j]);
            }
        }
    }
