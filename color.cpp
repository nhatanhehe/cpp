inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int delta;
ll n,m,u,v,w,pre,Max=-1e9,Min=1e9,c[N],ans=0,cnt,mx_sz=0,a[N],last[N];
vector<ii>g[N];
unordered_map<int,int>mp;
bool vis[N];
map<int,int>dem;
void DFS(int u,int p){
    dem[c[u]]++;
    if(dem[c[u]]==1) cnt++;
    ans+=cnt;
    for(auto [to,w]:g[u]){
        if(to!=p){
            DFS(to,u);
        }
    }
    dem[c[u]]--;
    if(!dem[c[u]]) cnt--;
}
ll dp[N],sz[N],sz_up[N],up[N];
void dfs(int u,int p){
    sz[u]=1;
    for(auto [v,w]:g[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]+=w*sz[v]+dp[v];
            sz[u]+=sz[v];
        }
    }
}
void reroot(int u,int p){
    for(auto [v,w]:g[u]){
        if(v!=p){
            sz_up[v]=sz_up[u]+sz[u]-sz[v];
            up[v]=dp[u]-(w*sz[v]+dp[v])+up[u]+sz_up[u]*w+(sz[u]-sz[v])*w;
            reroot(v,u);
        }
    }
}
void dfs_2(int u,int p,int cnt){
    a[cnt]=c[u];
    for(auto [v,w]:g[u]){
        if(v!=p){
            dfs_2(v,u,cnt+1);
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        cin>>c[i];
        Max=max(c[i],Max);
        Min=min(c[i],Min);
        mp[c[i]]++;
    }
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        w=1;
        g[u].pb({v,w});
        g[v].pb({u,w});
        mx_sz=max({mx_sz,(ll)g[u].size(),(ll)g[v].size()});
    }
    if(Max==Min){
        for(int i=1;i<=n;i++){
            cout<<n<<" ";
        }
    }
    else if(n<=5000){
        for(int i=1;i<=n;i++){
            ans=0;
            DFS(i,-1);
            cout<<ans<<' ';
        }
    }
    else if(mp.size()==n){
        dfs(1,-1);
        reroot(1,-1);
        for(int i=1;i<=n;i++){
            cout<<up[i]+dp[i]+n<<' ';
        }
    }
    else if(mx_sz==2){
        int root;
        for(int i=1;i<=n;i++){
            if(g[i].size()==1){
                root=i;
                break;
            }
        }
        dfs_2(root,-1,1);
        ll res=0;
        for(int i=1;i<=n;i++){
            ll pre=last[a[i]];
            res+=1LL*(i-pre)*(n-i+1);
            last[a[i]]=i;
        }
        cout<<res;
    }
}
