inline int mul(int a,int b){
    return (a%mod)*(b%mod)%mod;
}
inline int sub(int a,int b){
    return ((a-b)%mod+mod)%mod;
}
inline int add(int a,int b){
    return ((a%mod+b%mod)%mod+mod)%mod;
}
int n,m,k,u,v,w,a[N][N];
struct Matrix{
    int x[N][N];
    Matrix(){}
    Matrix(int a[N][N]){
        for(int i=1;i<=n;i++){
            for(int j=1;j<=n;j++) x[i][j]=a[i][j];
        }
    }

    Matrix operator * (Matrix const &b){
        Matrix c;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=n;j++){
                c.x[i][j]=-inf;
                for(int k=1;k<=n;k++){
                    c.x[i][j]=max({c.x[i][j],x[i][k]+b.x[k][j]});
                }
            }
        }
        return c;
    }

    friend Matrix operator ^ (Matrix const &b,int const &n){
        if(n==1) return b;
        Matrix t=b^(n/2);
        if(n&1) return t*t*b;
        return t*t;
    }
};
