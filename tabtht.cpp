inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N][N],sz;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    sz=n;
    int top=1,bot=n,l=1,r=n;
    if(n&1){
        while(sz>3){
            a[top][l]=1;
            a[top][r]=2;
            a[bot][l]=2;
            a[bot][r]=1;
            sz-=2;
            top++;
            bot--;
            l++;
            r--;
        }
        a[top][l+1]=1;
        a[top][l+2]=2;
        a[top+1][l]=1;
        a[top+1][l+1]=2;
        a[top+2][l]=2;
        a[top+2][l+2]=1;
    }
    else{
        while(sz>2){
            a[top][l]=1;
            a[top][r]=2;
            a[bot][l]=2;
            a[bot][r]=1;
            sz-=2;
            top++;
            bot--;
            l++;
            r--;
        }
        a[top][l]=1;
        a[top][l+1]=2;
        a[top+1][l]=2;
        a[top+1][l+1]=1;
    }
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            cout<<a[i][j]<<" ";
        }
        cout<<'\n';
    }
}
