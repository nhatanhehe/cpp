inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct Matrix{
    int n,m;
    vector<vector<ll>> a;

    Matrix(int _n,int _m){
        n=_n;
        m=_m;
        a.assign(n,vector<ll>(m,0));
    }

    Matrix operator*(const Matrix &o)const{
        Matrix res(n,o.m);
        for(int i=0;i<n;i++)
            for(int k=0;k<m;k++){
                if(a[i][k]==0) continue;
                for(int j=0;j<o.m;j++)
                    res.a[i][j]=(res.a[i][j]+a[i][k]*o.a[k][j])%mod;
            }
        return res;
    }
};

Matrix power(Matrix a,ll k){
    Matrix res(a.n,a.n);
    for(int i=0;i<a.n;i++) res.a[i][i]=1;
    while(k){
        if(k&1) res=res*a;
        a=a*a;
        k>>=1;
    }
    return res;
}
