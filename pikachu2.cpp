#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "pikachu"
#define ii pair<int,int>
#define iiii pair<ii,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n,C[506],vis[503];
int dx[]={-1,0,1,0};
int dy[]={0,-1,0,1};
vector<vector<int>>a;
vector<vector<vector<int>>>dist;
struct pt{
    int u,v,dir;
};
void sol(int X,int Y){
    for(int i=0;i<=m+1;i++){
        for(int j=0;j<=n+1;j++){
            dist[i][j][0]=dist[i][j][1]=1e9;
        }
    }
    dist[X][Y][0]=1;
    dist[X][Y][1]=1;
    deque<pt>q;
    q.pb({X,Y,0});
    q.pb({X,Y,1});
    while(q.size()){
        auto [u,v,dir]=q.front();
        q.pop_front();
        for(int k=0;k<4;k++){
            int x=dx[k]+u,y=dy[k]+v;
            if(0<=x&&x<=m+1&&0<=y&&y<=n+1){
                if(dir==0){
                    if(dy[k]==0){
                        if(dist[x][y][0]>dist[u][v][0]){
                            dist[x][y][0]=dist[u][v][0];
                            if(!a[x][y]) q.push_front({x,y,0});
                        }
                    }
                    else{
                        if(dist[x][y][1]>dist[u][v][0]+1){
                            dist[x][y][1]=dist[u][v][0]+1;
                            if(!a[x][y]) q.push_back({x,y,1});
                        }
                    }
                }
                else{
                    if(dx[k]==0){
                        if(dist[x][y][1]>dist[u][v][1]){
                            dist[x][y][1]=dist[u][v][1];
                            if(!a[x][y]) q.push_front({x,y,1});
                        }
                    }
                    else{
                        if(dist[x][y][0]>dist[u][v][1]+1){
                            dist[x][y][0]=dist[u][v][1]+1;
                            if(!a[x][y]) q.push_back({x,y,0});
                        }
                    }
                }
            }
        }
    }
}
iiii col[502];
map<int,int>mp;
int cnt;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n;
    a=vector<vector<int>>(m+3,vector<int>(n+2,0));
    dist=vector<vector<vector<int>>>(m+3,vector<vector<int>>(n+3,vector<int>(2)));
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
            if(a[i][j]) mp[a[i][j]]++;
        }
    }
    //cout<<mp.size()<<'\n';
    for(auto &b:mp){
        b.se=++cnt;
    }
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            a[i][j]=mp[a[i][j]];
            if(col[a[i][j]].fi==ii(0,0)){
                col[a[i][j]].fi={i,j};
            }
            else col[a[i][j]].se={i,j};
        }
    }
    for(int i=1;i<=cnt;i++) C[i]=1e9;
    priority_queue<ii,vector<ii>,greater<ii>>pq;
    for(int i=1;i<=cnt;i++){
        iiii a=col[i];
        sol(a.fi.fi,a.fi.se);
        //cout<<C[i]<<'\n';

        C[i]=min(dist[a.se.fi][a.se.se][0],dist[a.se.fi][a.se.se][1]);
        //cout<<C[i]<<" ";
        if(C[i]!=1e9) pq.push({C[i],i});
    }
    int res=0;
    while(pq.size()){
        auto [cost,c]=pq.top();
        pq.pop();
        if(cost>C[c]) continue;
       // cout<<cost<<' '<<c<<'\n';
        vis[c]=1;
        res=max(res,cost);
        iiii x=col[c];
        a[x.fi.fi][x.fi.se]=0;
        a[x.se.fi][x.se.se]=0;
        sol(x.fi.fi,x.fi.se);
        for(int i=1;i<=cnt;i++){
            if(!vis[i]){
                iiii Q=col[i];
                ll cost=min(dist[Q.fi.fi][Q.fi.se][0],dist[Q.fi.fi][Q.fi.se][1])+min(dist[Q.se.fi][Q.se.se][0],dist[Q.se.fi][Q.se.se][1]);
                if(C[i]>cost){
                    C[i]=cost;
                    pq.push({C[i],i});
                }
            }
        }
        sol(x.se.fi,x.se.se);
        for(int i=1;i<=cnt;i++){
            if(!vis[i]){
                iiii Q=col[i];
                ll cost=min(dist[Q.fi.fi][Q.fi.se][0],dist[Q.fi.fi][Q.fi.se][1])+min(dist[Q.se.fi][Q.se.se][0],dist[Q.se.fi][Q.se.se][1]);
                if(C[i]>cost){
                    C[i]=cost;
                    pq.push({C[i],i});
                }
            }
        }
    }
    cout<<res;
}
