inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int dp[N][140],n,m,a[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    for(int i=1;i<=n;i++){
        if(a[i]){
            if(i==1) dp[i][a[i]]=1;
            else{
                dp[i][a[i]]=add(dp[i][a[i]],dp[i-1][a[i]-1]);
                dp[i][a[i]]=add(dp[i][a[i]],dp[i-1][a[i]+1]);
                dp[i][a[i]]=add(dp[i][a[i]],dp[i-1][a[i]]);
            }
        }
        else{
            for(int j=1;j<=m;j++){
                if(i==1) dp[i][j]=1;
                else{
                    dp[i][j]=add(dp[i][j],dp[i-1][j-1]);
                    dp[i][j]=add(dp[i][j],dp[i-1][j+1]);
                    dp[i][j]=add(dp[i][j],dp[i-1][j]);
                }
            }
        }
    }
    int ans=0;
    for(int j=1;j<=m;j++) ans=add(ans,dp[n][j]);
    cout<<ans;
}

