inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],l[N],r[N],dp[N];
ii h[N];
struct SegmentTree{
    vector<int>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(n*4+2,0);
    }
    void up(int pos,int k,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l==r){
            tree[id]=k;
            return;
        }
        int mid=(l+r)>>1;
        if(pos<=mid) up(pos,k,id*2,l,mid);
        else up(pos,k,id*2+1,mid+1,r);
        tree[id]=max(tree[id*2],tree[id*2+1]);
    }
    int get(int u,int v,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return 0;
        if(u<=l&&r<=v) return tree[id];
        int mid=(l+r)>>1;
        return max(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
    }
}seg;
