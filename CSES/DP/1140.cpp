inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],b[N],p[N],pre[N],dp[N];
vector<ii>g[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    vector<int>cp;
    for(int i=1;i<=n;i++){
        cin>>a[i]>>b[i]>>p[i];
        cp.pb(a[i]);
        cp.pb(b[i]);
    }
    sort(all(cp));
    cp.erase(unique(all(cp)),cp.end());
    for(int i=1;i<=n;i++){
        a[i]=upper_bound(all(cp),a[i])-cp.begin();
        b[i]=upper_bound(all(cp),b[i])-cp.begin();
       // cout<<a[i]<<" "<<b[i]<<'\n';
        g[b[i]].pb({a[i],p[i]});
    }
    for(int r=1;r<=1e6;r++){
        for(auto [l,w]:g[r]){
           // cout<<l<<" "<<w<<'\n';
            dp[r]=max(dp[r],pre[l-1]+w);
        }
        pre[r]=max(pre[r-1],dp[r]);
    }
    //cout<<dp[3]<<'\n';
    cout<<pre[1000000];
}
