#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
int mul(int a,int b){
    return (a%mod)*(b%mod)%mod;
}
int sub(int a,int b){
    return ((a-b)%mod+mod)%mod;
}
int add(int a,int b){
    return (a%mod+b%mod)%mod;
}
int n,m,dp[N][N],x[N],y[N];
vector<int> ans;
void trace(int i,int j){
    if(i==0||j==0) return;
    if(dp[i][j]==dp[i-1][j-1]+1&&x[i]==y[j]){
        ans.pb(x[i]);
        trace(i-1,j-1);
    }
    else if(dp[i][j]==dp[i-1][j]) trace(i-1,j);
    else trace(i,j-1);
}
