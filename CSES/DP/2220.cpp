inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int dp[20][10][2][2],l,r;
string s;
int calc(int i,int last,int lower,int lead){
    if(i==s.size()){
        return dp[i][last][lower][lead]=(lead==0);
    }
    int &ans=dp[i][last][lower][lead];
    if(ans!=-1) return ans;
    ans=0;
    int limit=(lower? 9:s[i]-'0');
    if(lead){
        ans+=calc(i+1,0,1,1);
        for(int j=1;j<=limit;j++){
            ans+=calc(i+1,j,lower|(j<s[i]-'0'),0);
        }
    }
    else{
        for(int j=0;j<=limit;j++){
            if(j!=last){
                ans+=calc(i+1,j,lower|(j<s[i]-'0'),0);
            }
        }
    }
    return ans;
}
int solve(int n){
    memset(dp,-1,sizeof dp);
    s=to_string(n);
    return calc(0,0,0,1);
}
