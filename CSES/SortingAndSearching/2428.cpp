inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,a[N],bad;
map<int,int>mp;
void add(int x){
    mp[x]++;
    if(mp[x]==1) bad++;
}
void del(int x){
    mp[x]--;
    if(mp[x]==0) bad--;
}
