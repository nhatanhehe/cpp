inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N];
struct SegmentTree{
    vector<int>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(4*n+3,1e9);
    }
    void build(int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l==r){
            tree[id]=a[l];
            return;
        }
        int mid=(l+r)>>1;
        build(id*2,l,mid);
        build(id*2+1,mid+1,r);
        tree[id]=min(tree[id*2],tree[id*2+1]);
    }

    int walk(int val,int u,int v,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(r<u||l>v||tree[id]>=val) return 0;
        if(l==r){
            return l;
        }
        int mid=(l+r)>>1;
        int res=walk(val,u,v,id*2+1,mid+1,r);
        if(res) return res;
        return walk(val,u,v,id*2,l,mid);
    }
};
