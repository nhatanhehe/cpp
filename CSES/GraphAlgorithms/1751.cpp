inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int des[N],n,step,vis[N],len[N];
queue<int>path;
void dfs(int u){
    path.push(u);
    if(vis[u]){
        step+=len[u];
        return;
    }
    vis[u]=1;
    step++;
    dfs(des[u]);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>des[i];
    }
    for(int i=1;i<=n;i++){
        if(!vis[i]){
            step=0;
            dfs(i);
            int dec=1;
            while(path.size()){
                if(path.front()==path.back()) dec=0;
                len[path.front()]=step;
                step-=dec;
                path.pop();
            }
        }
    }
    for(int i=1;i<=n;i++) cout<<len[i]<<" ";
}
