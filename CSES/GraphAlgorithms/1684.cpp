inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,id[N],low[N],cnt,scc,scc_id[N];
vector<int>adj[N];
map<int,int>M;
bool vis[N];
vector<int>SCC[N];
vector<int>topo;
stack<int>s;
void dfs(int u){
    id[u]=low[u]=++cnt;
    s.push(u);
    for(auto v:adj[u]){
        if(!vis[v]){
            if(id[v]) low[u]=min(low[u],low[v]);
            else dfs(v),low[u]=min(low[u],low[v]);
        }
    }
    if(low[u]==id[u]){
        scc++;
        int v;
        do{
            v=s.top();
            vis[v]=1;
            scc_id[v]=scc;
            SCC[scc].pb(v);
            s.pop();
        }while(u!=v);
        topo.pb(scc);
    }
}
int NOT(int u){
    return u+ (u<=m? m:-m);
}
