#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,distM[1004][1004],dist[1004][1004];
char a[1003][1003];
ii st;
queue<ii>q;
int dx[]={1,-1,0,0};
int dy[]={0,0,1,-1};
ii trace[1003][1003];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n;
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            distM[i][j]=1e9;
            dist[i][j]=1e9;
            cin>>a[i][j];
            if(a[i][j]=='A'){
                st=ii(i,j);
                dist[i][j]=0;
            }
            if(a[i][j]=='M'){
                q.push(ii(i,j));
                distM[i][j]=0;
            }
        }
    }
    //cout<<distM[2][1]<<'\n';
    while(q.size()){
        auto [u,v]=q.front();
        q.pop();
        for(int k=0;k<=3;k++){
            int x=u+dx[k],y=v+dy[k];
            if(1<=x&&x<=m&&1<=y&&y<=n&&a[x][y]!='#'){
                if(distM[x][y]>distM[u][v]+1){
                    distM[x][y]=distM[u][v]+1;
                    q.push(ii(x,y));
                }
            }
        }
    }
    q.push(st);
    while(q.size()){
        auto [u,v]=q.front();
        q.pop();
        if(u==m||v==n||u==1||v==1){
            cout<<"YES\n"<<dist[u][v]<<'\n';
            vector<char>res;
            while(u&&v){
                auto [x,y]=trace[u][v];
                if(!x||!y) break;
                if(x-u==1) res.pb('U');
                if(u-x==1) res.pb('D');
                if(y-v==1) res.pb('L');
                if(v-y==1) res.pb('R');
                u=x;
                v=y;
            }
            reverse(all(res));
            for(auto c:res) cout<<c;
            return 0;
        }
        for(int k=0;k<=3;k++){
            int x=u+dx[k],y=v+dy[k];
            if(1<=x&&x<=m&&1<=y&&y<=n&&a[x][y]!='#'){
                //cout<<x<<" "<<y<<'\n';
                if(dist[x][y]>dist[u][v]+1){
                    dist[x][y]=dist[u][v]+1;
                    if(dist[x][y]<distM[x][y]){
                        trace[x][y]=ii(u,v);
                        q.push(ii(x,y));
                    }
                   // else cout<<"dumb";
                }
            }
        }
    }
    cout<<"NO";
}
