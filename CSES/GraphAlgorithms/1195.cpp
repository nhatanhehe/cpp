#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int ll
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,u,v,w,dist[N][2];
vector<ii>g[N];
struct pt{
    int cost,u,coup;
};
struct cmp{
    bool operator()(pt a,pt b){
        return a.cost>b.cost;
    }
};
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        g[u].pb({v,w});
    }
    for(int i=1;i<=n;i++){
        dist[i][0]=dist[i][1]=1e18;
    }
    dist[1][0]=0;
    priority_queue<pt,vector<pt>,cmp>pq;
    pq.push(pt{0,1,0});
    while(pq.size()){
        auto [cost,u,coup]=pq.top();
        pq.pop();
        if(u==n){
            return cout<<dist[u][coup],0;
        }
        if(cost>dist[u][coup]) continue;
        for(auto [v,w]:g[u]){
            if(dist[v][coup]>dist[u][coup]+w){
                dist[v][coup]=dist[u][coup]+w;
                pq.push(pt{dist[v][coup],v,coup});
            }
            if(!coup){
                if(dist[v][1]>dist[u][0]+w/2){
                    dist[v][1]=dist[u][0]+w/2;
                    pq.push(pt{dist[v][1],v,1});
                }
            }
        }
    }
}
