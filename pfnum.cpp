ll dp[20][2][2][11][11];
// i , tight , lead , l1, l2
ll calc(int i,int tight,int lead,int l1,int l2,string &s){
    ll &ans=dp[i][tight][lead][l1][l2];
    if(i==s.size()){
        return ans=1;
    }
    if(ans!=-1) return ans;
    ans=0;
    int limit=tight? 9:s[i]-'0';
    if(lead){
        ans+=calc(i+1,1,1,10,10,s);
        for(int j=1;j<=limit;j++){
            ans+=calc(i+1,tight|(j<s[i]-'0'),0,j,10,s);
        }
    }
    else{
        for(int j=0;j<=limit;j++){
            if(j!=l1&&j!=l2) ans+=calc(i+1,tight|(j<s[i]-'0'),0,j,l1,s);
        }
    }
    return ans;
}
ll solve(string s){
    memset(dp,-1,sizeof dp);
    return calc(0,0,1,10,10,s);
}
ll check(string s){
    for(int i=0;i<s.size();i++){
        if(i-1>=0) if(s[i]==s[i-1]) return 0;
        if(i-2>=0) if(s[i]==s[i-2]) return 0;
    }
    return 1;
}
