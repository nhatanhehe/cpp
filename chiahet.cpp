int exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a%p;
    int t=exp(a,n/2)%p;
    if(n&1) return (t%p)*(t%p)*(a%p)%p;
    return (t%p)*(t%p)%p;
}
