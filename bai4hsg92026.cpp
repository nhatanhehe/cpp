inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],m;
ll cal(int m){
    vector<ll>pre(n+4,0),cnt(3*n+4,0);
    cnt[n+1]=1;
    ll s=0,cur=1,res=0;
    for(int i=1;i<=n;i++){
        if(a[i]>=m){
            s++;
            cur+=cnt[s+n];
        }
        else{
            cur-=cnt[s+n];
            s--;
        }
        res+=cur;
        cnt[s+n+1]++;
    }
    return res;
}
