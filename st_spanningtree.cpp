#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "aa"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=4e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,s,t,ds,dt,p[N];
int acs(int u){
    return u==p[u]? u:p[u]=acs(p[u]);
}
void join(int u,int v){
    u=acs(u);
    v=acs(v);
    if(u!=v){
        p[v]=u;
    }
}
ii edges[N];
vector<ii>ans;
vector<int>g[N];
bool check;
int d[N];
struct pt{
    int st,u,v,t;
};
bool vis[N];
vector<pt>edg;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++) p[i]=i;
    for(int i=1;i<=m;i++){
        cin>>edges[i].fi>>edges[i].se;
        g[edges[i].fi].pb(edges[i].se);
        g[edges[i].se].pb(edges[i].fi);
    }
    cin>>s>>t>>ds>>dt;
    for(int i=1;i<=m;i++){
        auto [u,v]=edges[i];
        if(u==s||v==s||t==v||u==t) continue;
        if(acs(u)!=acs(v)){
            join(u,v);
            ans.pb(edges[i]);
        }
    }
    int cnt_s=0,cnt_t=0;
    for(int v:g[s]){
        if(vis[acs(v)]||v==t) continue;
        d[acs(v)]+=1;
        vis[acs(v)]=1;
    }
    memset(vis,0,sizeof vis);
    for(int v:g[t]){
        if(vis[acs(v)]||v==s) continue;
        d[acs(v)]+=2;
        vis[acs(v)]=1;
    }
    for(int v:g[s]){
        if(v!=t){
            edg.pb({d[acs(v)],s,t,v});
        }
    }
    for(int v:g[t]){
        if(v!=s){
            if(d[acs(v)]!=3) edg.pb({d[acs(v)],t,-1,v});
        }
    }
    sort(all(edg),[](const pt &x,const pt &y){
        return x.st<y.st;
    });
    int need=0;
    for(auto [st,u,v,z]:edg){
        if(st==1){
            if(acs(u)!=acs(z)){
                join(u,z);
                ans.pb(ii(u,z));
                cnt_s++;
            }
        }
        else if(st==2){
            if(acs(u)!=acs(z)){
                join(u,z);
                ans.pb(ii(u,z));
                cnt_t++;
            }
        }
        else{
            if(acs(z)!=acs(u)&&acs(v)!=acs(z)){
                if(cnt_s<ds){
                    join(u,z);
                    ans.pb(ii(u,z));
                    cnt_s++;
                }
                else if(cnt_t<dt){
                    join(v,z);
                    ans.pb(ii(v,z));
                    cnt_t++;
                }
                else need++;
            }
        }
        if(cnt_s>ds||cnt_t>dt) return cout<<"No",0;
    }
    if(need) return cout<<"No",0;
    for(int i=1;i<=m;i++){
        int u = edges[i].fi;
        int v = edges[i].se;
        if(acs(u) != acs(v)){
            if ((u==s && v==t) || (u==t && v==s)) {
                if (cnt_s < ds && cnt_t < dt) {
                    cnt_s++;
                    cnt_t++;
                    join(u,v);
                    ans.pb(ii(u,v));
                }
            } else if (u==s || v==s) {
                int other = (u==s ? v : u);
                if (cnt_s < ds) {
                    join(s, other);
                    cnt_s++;
                    ans.pb(ii(s, other));
                }
            } else if (u==t || v==t) {
                int other = (u==t ? v : u);
                if (cnt_t < dt) {
                    join(t, other);
                    cnt_t++;
                    ans.pb(ii(t, other));
                }
            }
        }
    }

    if(ans.size()<n-1) return cout<<"No",0;
    cout<<"Yes\n";
    for(auto [u,v]:ans) cout<<u<<" "<<v<<'\n';
}
