const ll inf=1e18;
const ll N=3e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,a[N],tg[N],f[N],c[N];
ll C(int mask,int m,int fil){
    ll res=0;
    for(int i=0;i<m;i++){
        if(mask>>i&1){
            res+=c[i+fil];
        }
    }
    return res;
}
vector<int>g[50];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    for(int i=2;i<=n;i++){
        g[a[i]].pb(a[i-1]);
        g[a[i-1]].pb(a[i]);
    }
    for(int i=1;i<=m;i++){
        sort(all(g[i]));
        g[i].erase(unique(all(g[i])),g[i].end());
    }
    for(int i=1;i<=m;i++) cin>>c[i];
    int m1=m/2;
    int m2=m-m1;
    vector<int>vec;
    for(int mask=0;mask<(1<<m2);mask++) f[mask]=inf;
    for(int mask=0;mask<(1<<m2);mask++){
        bool check=1;
        if(a[1] > m1 && !(mask >> (a[1] - m1 - 1) & 1)) check = 0;
        if(a[n] > m1 && !(mask >> (a[n] - m1 - 1) & 1)) check = 0;
        for(int j=0;j<m2;j++){
            for(int id:g[j+m1+1]){
                int ri=id-m1-1;
                if(ri<0) continue;
                if(!(mask>>j&1)){
                    if(!(mask>>ri&1)) check=0;
                }
            }
        }
        if(check){
            f[mask]=C(mask,m2,m1+1);
        }
    }
    for(int i=0;i<m2;i++){
        for(int mask=0;mask<(1<<m2);mask++){
            if(!(mask>>i&1)){
                f[mask]=min(f[mask],f[On(mask,i)]);
            }
        }
    }
    ll ans=inf;
    for(int mask=0;mask<(1<<m1);mask++){
        bool check=1;
        if(a[1] <= m1 && !(mask >> (a[1] - 1) & 1)) check = 0;
        if(a[n] <= m1 && !(mask >> (a[n] - 1) & 1)) check = 0;
        int target=0;
        for(int j=0;j<m1;j++){
            for(int id:g[j+1]){
                int ri=id-1;
                if(!(mask>>j&1)){
                    if(ri<m1) {if(!(mask>>ri&1)) check=0;}
                    else{
                        target=On(target,id-m1-1);
                    }
                }
            }
        }
        if(check){
            // tim min cost cua superset target
            ll cost=C(mask,m1,1);
            ans=min({ans,C(mask,m1,1)+f[target]});
        }
    }
    cout<<ans;
}
