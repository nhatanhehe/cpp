inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],nodes;
struct Node{
    int child[2];
    int cnt;
}T[N*21];
int nw(){
    nodes++;
    T[nodes].child[0]=T[nodes].child[1]=0;
    T[nodes].cnt=0;
    return nodes;
}
void ins(int x){
    int p=1;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        if(!T[p].child[c]){
            T[p].child[c]=nw();
        }
        p=T[p].child[c];
        T[p].cnt++;
    }
}
int get(int x){
    int p=1,res=0;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        if(T[p].child[c^1]){
            if(T[T[p].child[c^1]].cnt){
                res+=(1<<i);
                p=T[p].child[c^1];
                continue;
            }
        }
        if(T[p].child[c]){
            if(T[T[p].child[c]].cnt){
                p=T[p].child[c];
                continue;
            }
        }
        break;
    }
    return res;
}
int ans=0;
int dnc(int l,int r){
    if(l==r){
        return ans;
    }
    int mid=(l+r)>>1;
    int j=mid+1,mx=0,suml=0,sumr=0,res=0;
    vector<int>add;
    for(int i=mid;i>=l;i--){
        mx=max(mx,a[i]);
        suml^=a[i];
        while(j<=r&&a[j]<=mx){
            sumr^=a[j];
            add.pb(sumr);
            ins(sumr);
            j++;
        }
        res=max(res,get(suml^mx));
    }
    nodes=0;
    nw();
    j=mid; mx = suml = sumr = 0;
    for(int i=mid+1;i<=r;i++){
        mx=max(mx,a[i]);
        sumr^=a[i];
        while(j>=l&&a[j]<=mx){
            suml^=a[j];
            ins(suml);
            add.pb(suml);
            j--;
        }
        res=max(res,get(sumr^mx));
    }
    nodes=0;
    nw();
    return max({res,dnc(l,mid),dnc(mid+1,r)});
}
