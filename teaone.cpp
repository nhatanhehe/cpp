#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "teaone"
#define ii pair<unsigned ll,unsigned ll>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=1e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
unsigned ll n,m,dam[N],hp[N],atk[N],def[N];
struct cmp{
    bool operator()(const ii &x,const ii &y) const{
        return x.fi>y.fi||(x.fi==y.fi&&x.se<y.se);
    }
};
unsigned ll sqr(unsigned ll n){
    return n*n;
}
multiset<ii,cmp>tc,pt;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++) cin>>dam[i];
    for(int i=1;i<=n;i++) cin>>hp[i];
    for(int i=1;i<=m;i++){
        cin>>atk[i];
        tc.insert({atk[i],i});
    }
    for(int i=1;i<=m;i++){
        cin>>def[i];
        pt.insert({def[i],i});
    }
    for(int i=1;i<=n;i++){
        auto it1=tc.begin();
        auto it2=pt.begin();
        if(sqr(it1->fi+dam[i])+sqr(hp[i])>sqr(dam[i])+sqr(hp[i]+it2->fi)){
            cout<<it1->se<<" ";
            pt.erase({def[it1->se],it1->se});
            tc.erase(it1);
        }
        else if(sqr(it1->fi+dam[i])+sqr(hp[i])<sqr(dam[i])+sqr(hp[i]+it2->fi)){
            cout<<it2->se<<" ";
            tc.erase({atk[it2->se],it2->se});
            pt.erase(it2);
        }
        else{
            if(it1->se<it2->se){
                cout<<it1->se<<" ";
                pt.erase({def[it1->se],it1->se});
                tc.erase(it1);
            }
            else{
                cout<<it2->se<<" ";
                tc.erase({atk[it2->se],it2->se});
                pt.erase(it2);
            }
        }
    }
}
