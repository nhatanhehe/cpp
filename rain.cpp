#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<ll,ll>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=5e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,q,t,h[N],lastans,res,l,r,H,nl[N][20],sl[N][20],nr[N][20],sr[N][20],pre[N];
stack<int>st;
ii mx[N][20];
struct Node{
    ll l,r,val,cnt;
}tree[N*25];
ll root[N],val[N],cur;
ii Max(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return max(mx[l][k],mx[r-(1<<k)+1][k]);
}
vector<int>cp;
void build(int id=1,int l=1,int r=cp.size()){
    if(l==r){
        tree[id].val=tree[id].cnt=0;
        return;
    }
    int mid=(l+r)>>1;
    tree[id].l=++cur;
    tree[id].r=++cur;
    build(tree[id].l,l,mid);
    build(tree[id].r,mid+1,r);
}
void up(int id,int pos,ll k,int l=1,int r=cp.size()){
    if(l==r){
        tree[id].cnt++;
        tree[id].val+=k;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid){
        tree[++cur]=tree[tree[id].l];
        tree[id].l=cur;
        up(tree[id].l,pos,k,l,mid);
    }
    else{
        tree[++cur]=tree[tree[id].r];
        tree[id].r=cur;
        up(tree[id].r,pos,k,mid+1,r);
    }
    tree[id].cnt=tree[tree[id].l].cnt+tree[tree[id].r].cnt;
    tree[id].val=tree[tree[id].l].val+tree[tree[id].r].val;
}
ii get(int id1,int id2,int u,int v,int l=1,int r=cp.size()){
    if(l>v||r<u||u>v) return ii(0,0);
    //cout<<l<<" "<<r<<'\n';
    if(u<=l&&r<=v) return ii(tree[id2].val-tree[id1].val,tree[id2].cnt-tree[id1].cnt);
    int mid=(l+r)>>1;
    ii p1=get(tree[id1].l,tree[id2].l,u,v,l,mid);
    ii p2=get(tree[id1].r,tree[id2].r,u,v,mid+1,r);
    return ii(p1.fi+p2.fi,p1.se+p2.se);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q>>t;
    for(int i=1;i<=n;i++){
        cin>>h[i];
        cp.pb(h[i]);
        mx[i][0]=ii(h[i],i);
        pre[i]=pre[i-1]+h[i];
    }
    sort(all(cp));
    cp.erase(unique(all(cp)),cp.end());
    //for(int i=1;i<=n;i++) val[upper_bound(all(cp),h[i])-cp.begin()]=h[i];
    root[0]=cur=1;
    build();
    for(int i=1;i<=n;i++){
        int pos=upper_bound(all(cp),h[i])-cp.begin();
        root[i]=++cur;
        tree[root[i]]=tree[root[i-1]];
        up(root[i],pos,h[i]);
    }
    for(int j=1;j<19;j++){
        for(int i=1;i+(1<<j)-1<=n;i++){
            mx[i][j]=max(mx[i][j-1],mx[i+(1<<(j-1))][j-1]);
        }
    }
    for(int j=0;j<19;j++){
        nr[n+1][j]=n+1;
        nl[0][j]=0;
    }
    // tinh bin lift ben trai sang phai
    for(int i=n;i>=1;i--){
        while(st.size()&&h[st.top()]<h[i]) st.pop();
        if(st.size()){
            nr[i][0]=st.top();
            sr[i][0]=h[i]*(st.top()-i-1)-(pre[st.top()-1]-pre[i]);
        }
        else nr[i][0]=n+1;
        st.push(i);
    }
    for(int j=1;j<19;j++){
        for(int i=1;i<=n;i++){
            nr[i][j]=nr[nr[i][j-1]][j-1];
            sr[i][j]=sr[i][j-1]+sr[nr[i][j-1]][j-1];
        }
    }
    while(st.size()) st.pop();
    // tinh bin lift ben phai sang trai
    for(int i=1;i<=n;i++){
        while(st.size()&&h[st.top()]<h[i]) st.pop();
        if(st.size()){
            nl[i][0]=st.top();
            sl[i][0]=h[i]*(i-st.top()-1)-(pre[i-1]-pre[st.top()]);
        }
        else nl[i][0]=0;
        st.push(i);
    }
    for(int j=1;j<19;j++){
        for(int i=1;i<=n;i++){
            nl[i][j]=nl[nl[i][j-1]][j-1];
            sl[i][j]=sl[i][j-1]+sl[nl[i][j-1]][j-1];
        }
    }
    //cout<<get(root[1],root[4],1,1).fi<<'\n';
    while(q--){
        cin>>l>>r>>H;
        l^=(t*lastans);
        r^=(t*lastans);
        H^=(t*lastans);
        auto [M,P]=Max(l,r);
        H=min(H,M);
        /// nhảy bên trái sang bên phải
        ll sparkle=0;
        int p=l;
        for(int i=18;i>=0;i--){
            int nxt=nr[p][i];
            if(nxt<=P&&h[nxt]<=H){
                sparkle+=sr[p][i];
                p=nxt;
            }
        }
        if(h[p]>=H){
            int ps=upper_bound(all(cp),H)-cp.begin();
            auto [sum,cnt]=get(root[p],root[P],1,ps);
           // cout<<p<<" "<<P<<" "<<ps<<" "<<sum<<" "<<cnt<<'\n';
            sparkle+=cnt*H-sum;
        }
        else if(h[nr[p][0]]>=H){
            sparkle+=sr[p][0];
            int ps=upper_bound(all(cp),H)-cp.begin();
            auto [sum,cnt]=get(root[nr[p][0]],root[P],1,ps);
            sparkle+=cnt*H-sum;
        }
        /// nhảy phải sang trái
        p=r;
        for(int i=18;i>=0;i--){
            int nxt=nl[p][i];
            if(nxt>=P&&h[nxt]<=H){
                sparkle+=sl[p][i];
                p=nxt;
            }
        }
        if(h[p]>=H){
            int ps=upper_bound(all(cp),H)-cp.begin();
            auto [sum,cnt]=get(root[P],root[p],1,ps);
            sparkle+=cnt*H-sum;
        }
        else if(h[nl[p][0]]>=H){
            sparkle+=sl[p][0];
            int ps=upper_bound(all(cp),H)-cp.begin();
            auto [sum,cnt]=get(root[P],root[nl[p][0]],1,ps);
            sparkle+=cnt*H-sum;
        }
        lastans=sparkle;
        res^=sparkle;
    }
    cout<<res;
}
