inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,a[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    multiset<ll>ms;
    int j=1;
    int ans=0;
    for(int i=1;i<=n;i++){
        ms.insert(a[i]);
        while(ms.size()>=3){
            auto it=ms.begin();
            ll x=*it;
            ll y=*next(it);
            ll z=*ms.rbegin();
            if(x+y>z) break;
            ms.erase(ms.find(a[j++]));
        }
        ans=max(ans,(int)ms.size());
    }
    cout<<ans;
}
