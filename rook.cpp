#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "rook"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n;
int x_st,x_en,y_st,y_en;
ii cord[N];
int x[N],y[N],dist[2004][2004][2],ban[2003][2003];
int dx[]={-1,0,1,0};
int dy[]={0,-1,0,1};
struct pt{
    int u,v,dir;
};
void solve(){
    cin>>x_st>>y_st>>x_en>>y_en;
    cin>>n;
    for(int i=1;i<=n+2;i++){
        if(i==1){
            x[i]=x_st;
            y[i]=y_st;
            continue;
        }
        if(i==n+2){
            x[i]=x_en;
            y[i]=y_en;
            continue;
        }
        int X,Y;
        cin>>X>>Y;
        x[i]=X;
        y[i]=Y;
        cord[i]={X,Y};
    }
    sort(x+1,x+n+3,greater<int>());
    map<int,int>cpr_x,cpr_y;
    int cnt_x=1;
    cpr_x[x[1]]=++cnt_x;
    //for(int i=1;i<=n+2;i++) cerr<<x[i]<<" "; cerr<<'\n';
    for(int i=2;i<=n+2;i++){
        if(x[i]==x[i-1]) continue;
        if(x[i-1]-x[i]>=2) cnt_x++;
        cpr_x[x[i]]=++cnt_x;
    }
    ++cnt_x;
    //cerr<<cnt_x<<" ";
    sort(y+1,y+n+3);
    int cnt_y=1;
    cpr_y[y[1]]=++cnt_y;
    for(int i=2;i<=n+2;i++){
        if(y[i]==y[i-1]) continue;
        if(y[i]-y[i-1]>=2) cnt_y++;
        cpr_y[y[i]]=++cnt_y;
    }
    ++cnt_y;
    //cerr<<cnt_y<<'\n';
    x_st=cpr_x[x_st];
    y_st=cpr_y[y_st];
    x_en=cpr_x[x_en];
    y_en=cpr_y[y_en];
    memset(ban,0,sizeof ban);
    //cerr<<x_st<<" "<<y_st<<" "<<x_en<<" "<<y_en<<'\n';
    for(int i=2;i<=n+1;i++){
        //cerr<<cpr_x[cord[i].fi]<<" "<<cpr_y[cord[i].se]<<'\n';
        ban[cpr_x[cord[i].fi]][cpr_y[cord[i].se]]=1;
    }





    memset(dist,0x3f,sizeof dist);
    dist[x_st][y_st][0]=1;
    dist[x_st][y_st][1]=1;
    deque<pt>q;
    q.push_back({x_st,y_st,0});
    q.push_back({x_st,y_st,1});
    while(q.size()){
        auto [u,v,dir]=q.front();
        q.pop_front();
        if(u==x_en&&v==y_en){
            cout<<dist[u][v][dir]<<'\n';
            return;
        }
        // 0 di thang
        // 1 di ngang
        for(int k=0;k<4;k++){
            int x=dx[k]+u,y=dy[k]+v;
            if(1<=x&&x<=cnt_x&&1<=y&&y<=cnt_y&&!ban[x][y]){
                if(dir==0){
                    if(dy[k]==0){
                        if(dist[x][y][0]>dist[u][v][0]){
                            dist[x][y][0]=dist[u][v][0];
                            q.push_front({x,y,0});
                        }
                    }
                    else{
                        if(dist[x][y][1]>dist[u][v][0]+1){
                            dist[x][y][1]=dist[u][v][0]+1;
                            q.push_back({x,y,1});
                        }
                    }
                }
                else{
                    if(dx[k]==0){
                        if(dist[x][y][1]>dist[u][v][1]){
                            dist[x][y][1]=dist[u][v][1];
                            q.push_front({x,y,1});
                        }
                    }
                    else{
                        if(dist[x][y][0]>dist[u][v][1]+1){
                            dist[x][y][0]=dist[u][v][1]+1;
                            q.push_back({x,y,0});
                        }
                    }
                }
            }
        }
    }
    cout<<-1<<'\n';
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        solve();
    }
}
