#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,c[20][20],dp[20][(1<<17)];
ii trace[20][1<<17];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=0;i<n;i++){
        for(int j=0;j<n;j++){
            cin>>c[i][j];
        }
    }
    for(int i=0;i<n;i++){
        for(int mask=0;mask<(1<<n);mask++){
            dp[i][mask]=1e18;
        }
    }
    dp[0][1<<0]=0;
    for(int mask=1;mask<(1<<n);mask++){
        for(int i=0;i<n;i++){
            if((mask>>i)&1){
                for(int j=0;j<n;j++){
                    if((mask>>j)&1){
                        if(i!=j&&dp[j][Off(mask,i)]!=1e18){
                            if(dp[i][mask]>dp[j][Off(mask,i)]+c[j][i]){
                                dp[i][mask]=dp[j][Off(mask,i)]+c[j][i];
                                trace[i][mask]=ii(j,Off(mask,i));
                            }
                        }
                    }
                }
            }
        }
    }
    ll ans=1e18;
    int idx=-1;
    for(int i=1;i<n;i++){
        if(ans>dp[i][(1<<n)-1]+c[i][0]){
            ans=dp[i][(1<<n)-1]+c[i][0];
            idx=i;
        }
    }
    cout<<ans<<'\n';
    vector<int>path;
    ll mask=(1<<n)-1;
    while(idx!=0){
        path.pb(idx);
        idx=trace[idx][mask].fi;
        mask=Off(mask,idx);
    }
    reverse(all(path));
    for(int x:path) cout<<x<<" ";
    cout<<1;
}
