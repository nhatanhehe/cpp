inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,x[N],y[N];
vector<int>cx,cy;
bool check(int t){
    int mx1=-2e18,mx2=-2e18,mn1=2e18,mn2=2e18;
    for(int i=1;i<=n;i++){
        mn1=min(mn1,x[i]+y[i]+t);
        mx1=max(mx1,x[i]+y[i]-t);
        mx2=max(mx2,x[i]-y[i]-t);
        mn2=min(mn2,x[i]-y[i]+t);
    }
    return mn1>=mx1&&mn2>=mx2;
}
