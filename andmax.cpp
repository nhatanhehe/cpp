inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n;
ll dp[70][3];
ll calc(int i,int carry){
    ll &ans=dp[i][carry];
    if(i>60){
        if(!carry) return 0;
        else return -inf;
    }
    if(ans!=-1) return ans;
    ans=-inf;
    int cbit=n>>i&1;
    for(int j=0;j<=3;j++){
        ll cnt=carry+j;
        if(cnt%2==cbit){
            ll tmp=calc(i+1,cnt/2);
            ans=max(ans,tmp+((j==3)? (1<<i):0LL));
        }
    }
    return ans;
}
