inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll pre[N],suf[N],a[N],m,p,q,d,n;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>d>>p>>q>>m;
    for(int i=1;i<=n;i++){
        a[i]=(p*i)%m+q+d*i;
    }
    for(int i=1;i<=n;i++){
        pre[i]=max(pre[i-1],a[i]);
    }
    for(int i=n;i>=1;i--){
        suf[i]=max(suf[i+1],a[i]);
    }
    ll res=inf;
    for(int i=1;i<=n;i++){
        ll cnt=max(pre[i]+d*(n-i),suf[i+1]-d*i);
        res=min(res,cnt);
    }
    cout<<res;
}
