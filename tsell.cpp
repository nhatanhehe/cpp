    #include<bits/stdc++.h>
    using namespace std;
    #define ll long long
    typedef long double ld;
    #define pb push_back
    #define pf push_front
    #define Task "a=tsell"
    #define ii pair<int,int>
    #define iii pair<int,ii>
    #define all(x) x.begin(),x.end()
    #define fi first
    #define se second
    const ll inf=1e18;
    const ll N=1e5+5;
    const ll mod=1e9+7;
    const ll base=311;
    #define On(mask,i) (mask|(1LL<<i))
    #define Off(mask,i) (mask^(1LL<<i))
    inline ll add(ll a,ll b){
        ll res=a+b;
        if(res>=mod) res-=mod;
        return res;
    }
    ll sub(ll a,ll b){
        return ((a-b)%mod+mod)%mod;
    }
    inline ll mul(ll a,ll b){
        ll res=a*b;
        if(res>=mod) res%=mod;
        return res;
    }
    int n,k,w[N],a,b,u,v,c,h[N],p[N],heavy[N],pos[N],dist[N],head[N],fil,work[N];
    vector<int>g[N];
    int cnt;
    struct edge{
        int to,rev,flow,cap;
    };
    vector<edge>adj[N];
    int source,sink;
    int dfs(int u,int par){
        int mx=0,child_sz,sz=1;
        for(int v:g[u]){
            if(v!=par){
                h[v]=h[u]+1;
                p[v]=u;
                child_sz=dfs(v,u);
                if(mx<child_sz){
                    mx=child_sz;
                    heavy[u]=v;
                }
                sz+=child_sz;
            }
        }
        return sz;
    }
    void hld(int u,int h){
        head[u]=h;
        pos[u]=++cnt;
        if(heavy[u]) hld(heavy[u],h);
        for(int v:g[u]){
            if(v!=p[u]&&v!=heavy[u]) hld(v,v);
        }
    }
    void addedge(int u,int v,int c){
        //cout<<u<<" "<<v<<" "<<c<<'\n';
        edge a={v,adj[v].size(),0,c};
        edge b={u,adj[u].size(),0,0};
        adj[u].pb(a);
        adj[v].pb(b);
    }
    void noi(int u,int v,int s,int id=1,int l=1,int r=n){
        if(l>v||r<u) return;
        if(u<=l&&r<=v){
            addedge(s,id,1e9);
            return;
        }
        int mid=(l+r)>>1;
        noi(u,v,s,id*2,l,mid);
        noi(u,v,s,id*2+1,mid+1,r);
    }
    void join(int x,int y,int s){
        for(;head[x]!=head[y];y=p[head[y]]){
            if(h[head[x]]>h[head[y]]){
                swap(x,y);
            }
            noi(pos[head[y]],pos[y],s);
        }
        if(h[x]>h[y]) swap(x,y);
        noi(pos[x],pos[y],s);
    }
    void build(int id=1,int l=1,int r=n){
        if(l==r){
            addedge(id,l+k+fil,1e9);
            return;
        }
        int mid=(l+r)>>1;
        build(id*2,l,mid);
        build(id*2+1,mid+1,r);
        addedge(id,id*2,1e9);
        addedge(id,id*2+1,1e9);
    }
    bool bfs(){
        queue<int>q;
        memset(dist,-1,sizeof dist);
        dist[source]=0;
        q.push(source);
        while(q.size()){
            int u=q.front();
            q.pop();
            for(auto [v,rev,flow,cap]:adj[u]){
                if(dist[v]<0&&flow<cap){
                    dist[v]=dist[u]+1;
                    q.push(v);
                }
            }
        }
        return dist[sink]>0;
    }
    int dfs_s(int u,int fl){
        if(u==sink) return fl;
        for(int &s=work[u];s<adj[u].size();s++){
            edge &e=adj[u][s];
            int v=e.to;
            if(dist[v]==dist[u]+1&&e.flow<e.cap){
                int df=dfs_s(v,min(fl,e.cap-e.flow));
                if(df<=0) continue;
                e.flow+=df;
                adj[v][e.rev].flow-=df;
                return df;
            }
        }
        return 0;
    }
