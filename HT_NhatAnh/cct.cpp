inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,a[N],q,x,new_t;
namespace sub1{
    multiset<int,greater<int>>s;
    void solve(){
        for(int i=1;i<=n;i++) s.insert(a[i]);
        cin>>q;
        while(q--){
            cin>>x>>new_t;
            s.erase(s.find(a[x]));
            s.insert(new_t);
            a[x]=new_t;
            ll ans=0,sum=0,cnt=0,cnt2=1;
            for(int x:s){
                sum+=x;
                cnt++;
                if(cnt==m){
                    ans+=cnt2*sum;
                    sum=0;
                    cnt=0;
                    cnt2++;
                }
            }
            if(sum){
                ans+=cnt2*sum;
            }
            cout<<ans<<'\n';
        }
    }
}
