#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,u,v,st[N],en[N],dp[N],mx;
vector<int>g[N];
int cnt;
void dfs(int u,int p){
    dp[u]=1;
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]+=dp[v];
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<n;i++){
        cin>>u>>v;
        g[u].pb(v);
        g[v].pb(u);
        mx=max(mx,(int)g[i].size());
    }
    if(n<=1000){
        ll res=0;
        for(int i=1;i<=n;i++){
            fill(dp+1,dp+n+1,0);
            dfs(i,-1);
            ll ans=0;
            for(int j=1;j<=n;j++){
                ans+=dp[j]-1;
            }
            res=max(res,ans);
        }
        cout<<res;
    }
    else{
        ll ans=0,cnt=0;
        for(int i=1;i<=n-1;i++){
            cnt++;
            ans=max(ans,(n-cnt)*(cnt)+cnt);
        }
        cout<<ans;
    }
}
