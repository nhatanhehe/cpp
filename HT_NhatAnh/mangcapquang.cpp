inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,t[N],u,v,w,dp[N],tsum[N],tdist[N],sz[N],up[N],up_sz[N],up_sum[N],up_dist[N];
vector<ii>g[N];
void dfs(int u,int p){
    sz[u]=1;
    tsum[u]=t[u];
    for(auto [v,w]:g[u]){
        if(v!=p){
            dfs(v,u);
            tsum[u]+=tsum[v];
            tdist[u]+=tsum[v]*w+tdist[v]    ;
            sz[u]+=sz[v];
            dp[u]+=sz[v]*w+dp[v];
        }
    }
}
void reroot(int u,int p){
    for(auto [v,w]:g[u]){
        if(v!=p){
            up_sz[v]=up_sz[u]+sz[u]-sz[v];
            up[v]=dp[u]-(sz[v]*w+dp[v])+up[u]+up_sz[u]*w+(sz[u]-sz[v])*w;
            up_sum[v]=up_sum[u]+tsum[u]-tsum[v];
            up_dist[v]=tdist[u]-(tsum[v]*w+tdist[v])+up_dist[u]+up_sum[u]*w+(tsum[u]-tsum[v])*w;
            reroot(v,u);
        }
    }
}
