const ll inf=1e18;
const ll N=2e3+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask  |(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,s[N],p[N],e[N],a[N],dp[N][N][2];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>s[i]>>p[i]>>e[i]>>a[i];
    }
    for(int i=0;i<=n;i++){
        for(int j=0;j<=n;j++){
            for(int k=0;k<2;k++){
                dp[i][j][k]=-inf;
            }
        }
    }
    dp[0][0][0]=0;
    dp[0][0][1]=0;
    for(int i=1;i<=n;i++){
        for(int j=0;j<=i;j++){
            dp[i][j][0]=max(dp[i-1][j][0]+(s[i]-e[i-1]),dp[i-1][j][1]+(s[i]-p[i-1]));
            if(j>=1) dp[i][j][1]=max(dp[i-1][j-1][0]+(s[i]-e[i-1])-a[i],dp[i-1][j-1][1]+(s[i]-p[i-1])-a[i]);
            if(dp[i][j][0]<0) dp[i][j][0]=-inf;
            if(dp[i][j][1]<0) dp[i][j][1]=-inf;
        }
    }
    int ans=0;
    for(int i=n;i>=0;i--){
        if(dp[n][i][0]>=0||dp[n][i][1]>=0){
            return cout<<i,0;
        }
    }
}
