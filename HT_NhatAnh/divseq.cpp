namespace sub2{
    int S;
    struct Query{
        int l,r,pos;
    }Q[N];
    bool cmp(Query x,Query y){
        if(x.l/S!=y.l/S) return x.l<y.l;
        return x.r<y.r;
    }
    multiset<int>s;
    int bad=0;
    string ans[N];
    void ins(int n){
        if(s.empty()){
            s.insert(n);
            return;
        }
        auto it=s.upper_bound(n);
        if(it!=s.begin()){
            auto it2=prev(it);
            if(n%(*it2)!=0){
                bad++;
            }
        }
        if(it!=s.end()){
            if((*it)%n!=0){
                bad++;
            }
            if(it!=s.begin()){
                auto it2=prev(it);
                if((*it)%(*it2)!=0){
                    bad--;
                }
            }
        }
        s.insert(n);
    }
    void del(int n){
        auto it=s.lower_bound(n);
        if(it!=s.begin()){
            int pre=*prev(it);
          //  cout<<pre<<' '<<n<<'\n';
            if(n%pre!=0){
                bad--;
            }
        }
        if(next(it)!=s.end()){
            int nxt=*next(it);
          //  cout<<n<<" "<<nxt<<'\n';
            if(nxt%n!=0){
                bad--;
            }
            if(it!=s.begin()){
                int pre=*prev(it);
               // cout<<pre<<" "<<nxt<<'\n';
                if(nxt%pre!=0){
                    bad++;
                }
            }
        }
        s.erase(it);
    }
    void solve(){
        S=sqrt(n);
        for(int i=1;i<=q;i++){
            cin>>Q[i].l>>Q[i].r;
            Q[i].pos=i;
        }
        sort(Q+1,Q+q+1,cmp);
        int l=1,r=n;
        for(int i=1;i<=n;i++){
            ins(a[i]);
        }
        for(int i=1;i<=q;i++){
            while(l>Q[i].l){
                ins(a[--l]);
            }
            while(r<Q[i].r){
                ins(a[++r]);
            }
            while(l<Q[i].l){
                del(a[l++]);
            }
            while(r>Q[i].r){
                del(a[r--]);
               // cout<<bad<<'\n';
            }
            ans[Q[i].pos]=(bad? "NO\n":"YES\n");
        }
        for(int i=1;i<=q;i++){
            cout<<ans[i];
        }
    }
}
