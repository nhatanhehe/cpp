inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,p[N],sz[N],d[N],pr[N],pre[N];
vector<int>g[N];
void dfs(int u,int p){
    sz[u]=1;
    int sum_sz=0;
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
            sum_sz+=sz[v];
            sz[u]+=sz[v];
        }
    }
    for(int i=0;i<(int)g[u].size()-1;i++){
        int v=g[u][i];
        if(v==p) continue;
        int k=sz[v];
        int n=sum_sz;
        d[1]++; d[n+1]--;
        d[1]--; d[k+1]++;
        d[1]--; d[n-k+1]++;
        sum_sz-=sz[v];
    }
}
void sang(){
    for(int i=1;i<=1e6;i++) pr[i]=i;
    for(int i=2;i<=sqrt(1e6);i++){
        if(pr[i]==i){
            for(int j=i*i;j<=1e6;j+=i){
                if(pr[j]==j) pr[j]=i;
            }
        }
    }
}
void pt(int n,int heso){
    while(n!=1){
        int h=pr[n];
        while(n%h==0){
            pre[h]+=heso;
            n/=h;
        }
    }
}
