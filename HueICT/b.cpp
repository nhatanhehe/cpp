int tree[4*N];
void up(int pos,int val,int id=1,int l=1,int r=n){
    if(l==r){
        tree[id]=val;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid) up(pos,val,id*2,l,mid);
    else up(pos,val,id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
int get(int u,int v,int id=1,int l=1,int r=n){
    if(l>v||r<u) return 0;
    if(u<=l&&r<=v) return tree[id];
    int mid=(l+r)>>1;
    return max(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
}
