inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n;
bool p[N];
void sang(){
    for(int i=1;i<=1e6;i++) p[i]=1;
    p[0]=p[1]=0;
    for(int i=2;i<=1e3;i++){
        if(p[i]){
            for(int j=i*i;j<=1e6;j+=i){
                p[j]=0;
            }
        }
    }
}
vector<vector<int>>a;
bool check(int mid){
    for(int i=1;i<=m-mid+1;i++){
        for(int j=1;j<=n-mid+1;j++){
            int x=i+mid-1;
            int y=j+mid-1;
            int sum=a[x][y]-a[i-1][y]-a[x][j-1]+a[i-1][j-1];
            if(abs(mid*mid-sum)<=1) return 1;
        }
    }
    return 0;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n;
    sang();
    a.assign(m+4,vector<int>(n+4,0));
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            int x;
            cin>>x;
            a[i][j]=a[i][j-1]+a[i-1][j]-a[i-1][j-1]+(p[x]);
        }
    }
    ll l=1,r=min(m,n),ans=0;
    while(l<=r){
        ll mid=(l+r)>>1;
        if(check(mid)){
            l=mid+1;
            ans=mid;
        }
        else r=mid-1;
    }
    cout<<ans*ans;
}
