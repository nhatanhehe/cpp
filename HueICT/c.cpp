inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int tree[4*N];
int n,L,R,b[N],g[N],p[N],pre[N],ps[N],dp[N];
ii x[N];
void up(int pos,int val,int id=1,int l=0,int r=n){
    if(l==r){
        tree[id]=val;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid) up(pos,val,id*2,l,mid);
    else up(pos,val,id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
int get(int u,int v,int id=1,int l=0,int r=n){
    if(l>v||r<u) return -1e9;
    if(u<=l&&r<=v) return tree[id];
    int mid=(l+r)>>1;
    return max(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
}
int fL(int id){
    int ans=id;
    int l=0,r=n;
    while(l<=r){
        int mid=(l+r)>>1;
        if(x[mid].fi>=x[id].fi){
            ans=mid;
            r=mid-1;
        }
        else l=mid+1;
    }
    return ans;
}
int fR(int id){
    int ans=id;
    int l=0,r=n;
    while(l<=r){
        int mid=(l+r)>>1;
        if(x[mid].fi<=x[id].fi){
            ans=mid;
            l=mid+1;
        }
        else r=mid-1;
    }
    return ans;
}
