inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,k,u,v,w,x[N];
struct DSU{
    vector<int>p;
    int n;
    void init(int _n){
        n=_n;
        p.resize(n+3,0);
        for(int i=1;i<=n;i++) p[i]=i;
    }
    int acs(int u){
        return u==p[u]? u:p[u]=acs(p[u]);
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            p[v]=u;
        }
    }
}dsu;
struct edge{
    ll u,v,w;
};
vector<edge>e;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>k;
    dsu.init(n);
    for(int i=1;i<=k;i++){
        cin>>x[i];
        if(i>=2) dsu.join(x[i],x[i-1]);
    }
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        e.pb({u,v,w});
    }
    sort(all(e),[&](const edge &x,const edge &y){
        return x.w<y.w;
    });
    ll res=0;
    for(auto [u,v,w]:e){
        if(dsu.acs(u)!=dsu.acs(v)){
            dsu.join(u,v);
            res+=w;
        }
    }
    int comp=0;
    for(int i=1;i<=n;i++)
        if(dsu.acs(i)==i) comp++;
    if(comp!=1) cout<<-1<<'\n';
    else cout<<res;
}
