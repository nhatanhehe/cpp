#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n,m,k,a[N],u,v;
queue<ii>q;
queue<ii>qc;
struct DSU{
    vector<int>p,col;
    vector<multiset<ii>>ms;
    vector<map<int,int>>mp;
    int n;
    void init(int _n){
        n=_n;
        p.assign(n+3,0);
        col.assign(k+3,0);
        multiset<ii>dumb;
        map<int,int>mpp;
        ms.assign(n+4,dumb);
        mp.assign(n+4,mpp);
        for(int i=1;i<=n;i++){
            p[i]=i;
            col[a[i]]++;
        }
    }
    int acs(int u){
        return u==p[u]? u:p[u]=acs(p[u]);
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            if(ms[u].size()<ms[v].size()) swap(u,v);
            while(ms[v].size()){
                auto it=ms[v].begin();
                if(acs(it->se)!=acs(u)) ms[u].insert(*it);
                ms[v].erase(it);
            }
            if(--col[a[u]]==1) qc.push(ii(a[u],u));
            p[v]=u;
        }
    }
    void bluelock(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            if(mp[u].size()<mp[v].size()) swap(u,v);
            for(auto [key,val]:mp[v]){
                if(mp[u].find(key)==mp[u].end()) mp[u][key]=val;
                else{
                    q.push(ii(mp[u][key],val));
                }
            }
            p[v]=u;
        }
    }
}dsu;
void spawn_edge(int u,int v){
    int ku=dsu.acs(u);
    int kv=dsu.acs(v);
    dsu.ms[ku].insert(ii(a[v],kv));
    dsu.ms[kv].insert(ii(a[u],ku));
}
void work(){
    while(q.size()){
        auto [u,v]=q.front(); q.pop();
        dsu.join(u,v);
    }
}
void active(multiset<ii>&ms,int id){
    if(ms.empty()) return;
    vector<ii>alter;
    for(auto it=ms.begin();it!=ms.end();it++){
        if(next(it)!=ms.end()){
            auto it2=next(it);
            auto [x,y]=(*it);
            auto [l,r]=(*it2);
            if(x==l){
                //cout<<x<<" "<<y<<" "<<l<<" "<<r<<'\n';
                q.push(ii(y,r));
            }
        }
        if(alter.empty()) alter.pb(*it);
        else{
            if(alter.back().fi!=it->fi) alter.pb(*it);
        }
    }
    ms.clear();
    for(auto x:alter) dsu.mp[id].insert(x);
    work();
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        while(q.size()) q.pop();
        while(qc.size()) qc.pop();
        cin>>n>>m>>k;
        for(int i=1;i<=n;i++){
            cin>>a[i];
        }
        dsu.init(n);
        for(int i=1;i<=m;i++){
            cin>>u>>v;
            if(a[u]==a[v]){
                q.push(ii(u,v));
                work();
            }
            else{
                spawn_edge(u,v);
            }
        }
        vector<bool>check(k+4,0);
        for(int i=1;i<=n;i++){
            if(dsu.col[a[i]]==1) qc.push(ii(a[i],i));
        }
        //cout<<qc.size()<<'\n';
        while(qc.size()){
            auto [c,u]=qc.front();
            qc.pop();
            if(check[c]) continue;
            check[c]=1;
            u=dsu.acs(u);
            multiset<ii>&ms=dsu.ms[u];
            //cout<<u<<"\n";
            active(ms,u);
            active(ms,u);
            if(dsu.mp[u].empty()) continue;
            vector<int>to;
            for(auto [x, y] : dsu.mp[u]){
                if(check[x]){
                    to.pb(y);
                }
            }
            for(int y:to) dsu.bluelock(y,u);
            work();
        }
        bool tf=1;
        for(int i=1;i<=k;i++){
            if(dsu.col[i]>=2) tf=0;
        }
        cout<<(tf? "YES\n":"NO\n");
    }
}
