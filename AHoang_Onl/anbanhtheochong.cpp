const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll m,n,k;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    // Nhan xet
    // Voi cac chong khong tang, se toi uu nhat neu merge toan bo day nay lai va chon nhung thang dau tien
    // 
    cin>>m>>n>>k;
    vector<vector<ll>>v;
    vector<ll>b,sa(m+4,0);
    vector<vector<ll>>a(m+4,vector<ll>(n,0));
    for(int i=1;i<=m;i++){
        for(int j=0;j<n;j++) cin>>a[i][j];
        if(is_sorted(all(a[i]))) v.pb(a[i]);
        else{
            b.insert(b.end(),all(a[i]));
        }
    }
    sort(all(b),greater<ll>());
    vector<vector<ll>>sum(v.size(),vector<ll>(n,0)),suf_mx(v.size()+4,vector<ll>(n+4,-inf)),pre_mx=suf_mx;
    for(int j=0;j<v.size();j++){
        vector<ll>&vec=v[j];
        sum[j][0]=vec[0];
        for(int i=1;i<vec.size();i++){
            sum[j][i]+=sum[j][i-1]+vec[i];
        }
    }
    vector<int>p(v.size());
    iota(all(p),0);
    sort(all(p),[&](const int &x,const int &y){
        return sum[x][n-1]>sum[y][n-1];
    });

    for(int i=0;i<v.size();i++){
        for(int j=0;j<v[p[i]].size();j++){
            pre_mx[i+1][j+1]=max(pre_mx[i][j+1],sum[p[i]][j]-sum[p[i]][n-1]);
        }
    }
    for(int i=v.size()-1;i>=0;i--){
        for(int j=0;j<v[p[i]].size();j++){
            suf_mx[i+1][j+1]=max(suf_mx[i+2][j+1],sum[p[i]][j]);
        }
    }
    for(int i=0;i<p.size();i++){
        sa[i+1]=sa[i]+sum[p[i]][n-1];
    }
    //for(int id:p) cout<<id<<'\n';
    ll ans=-inf,tong=0,cnt=0;
    for(int i=-1;i<(int)b.size();i++){
        int rem;
        if(i<0){
            rem=k;
        }
        else{
            tong+=b[i];
            cnt++;
            rem=(k-cnt);
        }
        if(rem<0) break;
        if(rem>((int)p.size()*n)) continue;
        int tmp=rem/n;
        int thua=rem%n;
        if(!tmp&&!thua){
            ans=max(ans,tong);
            continue;
        }
        if(!thua) ans=max(ans,tong+sa[tmp]);
        else{
            ans=max(ans,tong+sa[tmp]+suf_mx[tmp+1][thua]);
            if(tmp+1<=p.size()) ans=max(ans,tong+sa[tmp+1]+pre_mx[tmp][thua]);
        }
    }
    cout<<ans;
}
