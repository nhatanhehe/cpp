inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int ans[N];
vector<int>cp;
int id(int u){
    return upper_bound(all(cp),u)-cp.begin();
}
struct DSU{
    vector<int>p,sz;
    stack<ii>st;
    int n;
    void init(int _n){
        n=_n;
        sz.assign(n+3,1);
        p.resize(n+3,0);
        iota(all(p),0);
    }
    int acs(int u){
        while(u!=p[u]) u=p[u];
        return u;
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            if(sz[u]<sz[v]) swap(u,v);
            st.push(ii(v,p[v]));
            st.push(ii(u,sz[u]));
            p[v]=u;
            sz[u]+=sz[v];
        }
    }
    void rollback(int cnt){
        while(cnt--){
            auto [u,szu]=st.top(); st.pop();
            sz[u]=szu;
            auto [v,pv]=st.top(); st.pop();
            p[v]=pv;
        }
    }
}dsu;
int n,m,q;
struct ee{
    int qid;
    vector<ii>vec;
};
vector<ee>Q[N];
vector<ii>g[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>q;
    vector<tuple<int,int,int>>edges;
    dsu.init(n);
    for(int i=1,u,v,w;i<=m;i++){
        cin>>u>>v>>w;
        edges.pb({u,v,w});
        cp.pb(w);
    }
    edges.pb({n+1,n+1,2e9});
    sort(all(cp));
    cp.erase(unique(all(cp)),cp.end());
    for(auto [u,v,w]:edges){
        g[id(w)].pb(ii(u,v));
    }
    //cin>>q;
    for(int _=1;_<=q;_++){
        ans[_]=1;
        int en;
        cin>>en;
        vector<int>V(en+1);
        for(int i=1,it;i<=en;i++){
            cin>>V[i];
        }
        sort(V.begin()+1,V.begin()+en+1,[&](const int &x,const int &y){
            return get<2>(edges[x-1])<get<2>(edges[y-1]);
        });
        vector<ii>vec;
        for(int i=1;i<=en;i++){
            auto [u,v,w]=edges[V[i]-1];
            vec.pb(ii(u,v));
            if(i==en||get<2>(edges[V[i+1]-1])!=w){
                Q[id(w)].pb({_,vec});
                vec.clear();
            }
        }
    }
    for(auto w:cp){
        for(auto [qid,vec]:Q[id(w)]){
            int cnt=0;
            for(auto [u,v]:vec){
                if(dsu.acs(u)!=dsu.acs(v)){
                    dsu.join(u,v);
                    cnt++;
                }
            }
            if(cnt==vec.size()) ans[qid]&=1;
            else ans[qid]=0;
            dsu.rollback(cnt);
        }
        for(auto [u,v]:g[id(w)]){
            dsu.join(u,v);
        }
    }
    for(int i=1;i<=q;i++){
        cout<<(ans[i]? "YES\n":"NO\n");
    }
}
