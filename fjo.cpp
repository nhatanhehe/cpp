inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,a,b,p[N],ans;
set<int>ic[N],oc[N],ip[N],s[N];
/// Nhan xet
// ic la tap cac clique huong vao clique u
// oc la tap cac clique houng ra clique u
// ip la tap cac dinh huong vao clique u
// Neu a -> b, ma a thuoc clique X, b thuoc clique Y, ma clique Y co canh noi toi clique X => merge X va Y
// Cong thuc tinh so canh trong clique X co s phan tu va k canh noi vao, s(s-1) + sk;
// Neu clique Z noi toi clique X, ma X merge vao Y va Y co canh noi toi Z => relax Y va Z
int acs(int u){
    return p[u]==u? u:p[u]=acs(p[u]);
}
ll calc(int u){
    u=acs(u);
    return 1ll*s[u].size()*(s[u].size()-1)+1ll*ip[u].size()*s[u].size();
}
queue<ii>q;
void join(int u,int v){
    u=acs(u);
    v=acs(v);
    ans-=calc(u);
    ans-=calc(v);
    if(s[u].size()<s[v].size()) swap(u,v);
    p[v]=u;
    ic[u].erase(v);
    oc[u].erase(v);
    while(s[v].size()){
        int num=*s[v].begin();
        if(ip[u].count(num)) ip[u].erase(num);
        s[u].insert(num);
        s[v].erase(num);
    }
    while(ip[v].size()){
        int num=*ip[v].begin();
        // neu num nam trong clique U thi thoi
        if(!s[u].count(num)){
            ip[u].insert(num);
        }
        ip[v].erase(num);
    }
    while(ic[v].size()){
        int num=*ic[v].begin();
        if(acs(num)==u){
            ic[v].erase(num);
            continue;
        }
        ic[u].insert(num);
        oc[num].erase(v);
        oc[num].insert(u);
        if(oc[u].count(num)) q.push(ii(u,num));
        ic[v].erase(num);
    }
    while(oc[v].size()){
        int num=*oc[v].begin();
        if(acs(num)==u){
            oc[v].erase(num);
            continue;
        }
        oc[u].insert(num);
        ic[num].erase(v);
        ic[num].insert(u);
        if(ic[u].count(num)) q.push(ii(u,num));
        oc[v].erase(num);
    }
    ans+=calc(u);
}
void work(){
    while(q.size()){
        auto [u,v]=q.front(); q.pop();
        if(acs(u)!=acs(v)) join(u,v);
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        p[i]=i;
        s[i].insert(i);
    }
    for(int i=1;i<=m;i++){
        cin>>a>>b;
        int fa=acs(a);
        int fb=acs(b);
        if(fa==fb){
            cout<<ans<<'\n';
            continue;
        }
        // canh a noi toi tplt b
        // neu trong tlpt cua b co a thi join a,b
        if(oc[fb].count(fa)){
            q.push(ii(fa,fb));
            work();
        }
        else{
            ans-=calc(fb);
            ans-=calc(fa);
            ip[fb].insert(a);
            ic[fb].insert(fa);
            oc[fa].insert(fb);
            ans+=calc(fb)+calc(fa);
        }
        cout<<ans<<'\n';
    }
}
