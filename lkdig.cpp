void ql(int n,string tmp){
    if(n==1) return;
    if(tmp.size()>=1&&tmp[0]=='0') return;
    if(n==0){
        res.pb(tmp);
        return;
    }
    for(int j='0';j<='9';j++){
        if(n>=cost[j-'0']){
            string jj=to_string(j-'0');
            ql(n-cost[j-'0'],tmp+jj);
        }
    }
}
