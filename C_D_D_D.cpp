const ll inf=1e18;
const ll N=4e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n,m,dist[N][2],l,a[N],u,v;
vector<int>g[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n>>m>>l;
        int Min=1e9,sum=0;
        for(int i=1;i<=l;i++){
            cin>>a[i];
            sum+=a[i];
            if(a[i]&1) Min=min(Min,a[i]);
        }
        for(int i=1;i<=m;i++){
            cin>>u>>v;
            g[u].pb(v);
            g[v].pb(u);
        }
        queue<ii>q;
        for(int i=1;i<=n;i++){
            dist[i][0]=dist[i][1]=1e18;
        }
        dist[1][0]=0;
        q.push({1,0});
        while(q.size()){
            auto [u,p]=q.front(); q.pop();
            for(int v:g[u]){
                if(dist[v][p^1]>dist[u][p]+1){
                    dist[v][p^1]=dist[u][p]+1;
                    q.push({v,p^1});
                }
            }
        }
        for(int i=1;i<=n;i++){
            g[i].clear();
            int tf=0;
            if(dist[i][sum%2]<1e18){
                //cout<<"Case 1: ";
                if(dist[i][sum%2]<=sum) tf|=1;
                //cout<<'\n';
            }
            if(Min!=1e9&&dist[i][(sum%2)^1]<1e18){
                //cout<<"Case 2: ";
                if(dist[i][(sum%2)^1]<=sum-Min) tf|=1;
                //else cout<<0
                //cout<<'\n';
            }
            cout<<tf;
           // else cout<<0;
        }
        cout<<'\n';
    }
}
