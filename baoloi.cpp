#include<bits/stdc++.h>
using namespace std;
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define ii pair<int,int>
#define iii pair<int,pair<int,int>>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const int inf=1e18;
const int N=2e5+5;
const int mod=1e9+7;
const int base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline int mul(int a,int b){
    return (a%mod)*(b%mod)%mod;
}
inline int sub(int a,int b){
    return ((a-b)%mod+mod)%mod;
}
inline int add(int a,int b){
 return ((a%mod+b%mod)%mod+mod)%mod;
}
ii a[N];
int n;
int ccw(ii a,ii b,ii c){
    return (b.fi-a.fi)*(c.se-a.se)-(b.se-a.se)*(c.fi-a.fi);
}
ld dist(ii a,ii b){
    return sqrt((b.fi-a.fi)*(b.fi-a.fi)+(b.se-a.se)*(b.se-a.se));
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i].fi>>a[i].se;
    }
    sort(a+1,a+n+1);
    vector<ii>convex;
    for(int i=1;i<=n;i++){
        while(convex.size()>1&&ccw(convex[convex.size()-2],convex.back(),a[i])>0) convex.pop_back();
        convex.push_back(a[i]);
    }
    int cnt=convex.size();
    for(int i=n-1;i>=1;i--){
        while(convex.size()>cnt&&ccw(convex[convex.size()-2],convex.back(),a[i])>0) convex.pop_back();
        convex.push_back(a[i]);
    }
    convex.pop_back();
    ld cv=0;
    for(int i=0;i<convex.size();i++){
        cv+=dist(convex[i],convex[(i+1)%convex.size()]);
    }
    ld ans=0;
    for(int i=0;i<convex.size();i++){
       int j=(i+1)%((int)convex.size());
       ans+=convex[i].fi*convex[j].se-convex[j].fi*convex[i].se;
    }
    cout<<convex.size()<<"\n"<<fixed<<setprecision(3)<<cv<<'\n'<<abs(ans)*0.5;
}
