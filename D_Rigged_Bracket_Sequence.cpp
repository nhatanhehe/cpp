inline ll add(ll a, ll b)
{
    ll res = a + b;
    if (res >= mod)
        res -= mod;
    return res;
}
ll sub(ll a, ll b)
{
    return ((a - b) % mod + mod) % mod;
}
inline ll mul(ll a, ll b)
{
    ll res = a * b;
    if (res >= mod)
        res %= mod;
    return res;
}
int dp[2], t, n, pre[N];
string s;
main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);
    if (fopen(Task ".inp", "r"))
    {
        freopen(Task ".inp", "r", stdin);
        freopen(Task ".out", "w", stdout);
    }
    cin >> t;
    while (t--)
    {
        string s;
        cin >> n >> s;
        s = " " + s;
        ll ans = 0, res = 1;
        for (int i = 1; i <= n; i++)
        {
            if (s[i] == '(')
            {
                ans = add(ans, res);
            }
            res = mul(res, 2);
        }
        pre[0] = 0;
        for (int i = 1; i <= n; i++)
        {
            pre[i] = pre[i - 1] + (s[i] == '(') - (s[i] == ')');
        }
        dp[0] = dp[1] = 0;
        for (int i = 1; i <= n; i++)
        {
            if (pre[i - 1] < 2)
            {
                dp[0] = 0;
            }
            if (s[i] == ')')
            {
                ans = add(ans, add(dp[0], dp[1] + 1));



                
                dp[1] = add(dp[1], add(dp[0], dp[1]) + 1);
            }
            else
            {
                dp[0] = add(dp[0], add(dp[0], dp[1]) + 1);
            }
        }
        cout << ans << '\n';
    }
}
