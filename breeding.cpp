const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,p[N],prime[N*100];
void sang(){
    memset(prime,1,sizeof prime);
    prime[0]=prime[1]=0;
    for(int i=2;i<=sqrt(2e7);i++){
        if(prime[i])
        for(int j=i*i;j<=2e7;j+=i){
            prime[j]=0;
        }
    }
}
int mx[800],my[800],dist[800];
vector<int>adj[N];
bool bfs(){
    queue<int>q;
    for(int i=1;i<=n;i++){
        if(!mx[i]&&(p[i]&1)) q.push(i),dist[i]=0;
        else dist[i]=-1;
    }
    bool tf=0;
    while(q.size()){
        int u=q.front();
        q.pop();
        for(int v:adj[u]){
            if(!my[v]){
                tf=1;
            }
            else if(dist[my[v]]<0){
                dist[my[v]]=dist[u]+1;
                q.push(my[v]);
            }
        }
    }
    return tf;
}
bool dfs(int u){
    for(int v:adj[u]){
        if(!my[v]){
            mx[u]=v;
            my[v]=u;
            return 1;
        }
        else if(dist[my[v]]==dist[u]+1&&dfs(my[v])){
            mx[u]=v;
            my[v]=u;
            return 1;
        }
    }
    return 0;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    sang();
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>p[i];
    }
    sort(p+1,p+n+1,greater<int>());
    while(p[n]==1){
        n--;
        if(p[n]!=1){
            p[++n]=1;
            break;
        }
    }
    for(int i=1;i<=n;i++){
        if(p[i]&1){
            for(int j=1;j<=n;j++){
                if(p[j]%2==0){
                    if(prime[p[i]+p[j]])adj[i].pb(j);
                }
            }
        }
    }
    while(bfs()){
        for(int i=1;i<=n;i++) if(!mx[i]&&(p[i]&1)) dfs(i);
    }
    int ans=0;
    for(int i=1;i<=n;i++) ans+=(mx[i]>0);
    cout<<n-ans;
}
