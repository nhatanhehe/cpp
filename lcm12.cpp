inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,res[N],cnt[N],p[N];
void sieve(){
    for(int i=1;i<=1e6;i++) p[i]=i;
    for(int i=2;i<=1e3;i++){
        if(p[i]==i){
            for(int j=i*i;j<=1e6;j+=i){
                if(p[j]==j) p[j]=i;
            }
        }
    }
    for(int i=0;i<=1e6;i++) res[i]=1;
    for(int pr=3;pr<=1e6;pr++){
        if(p[pr]==pr&&pr!=5){
            ll val=pr;
            while(val<1e6){
                res[val]=mul(res[val],pr);
                val*=pr;
            }
        }
    }
    for(int i=1;i<=1e6;i++){
        res[i]=mul(res[i],res[i-1]);
    }
}
int exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    int t=exp(a,n/2);
    if(n&1) return ((t*t)%mod*a%mod)%mod;
    else return (t*t)%mod;
}
