inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,d['9'+23],dist[N],so[N];
int trace[N];
string s;
vector<int>dig;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>s;
    for(char c:s) d[c]=1;
    for(int c='0';c<='9';c++){
        if(d[c]) dig.pb(c-'0');
    }
    memset(dist,0x3f,sizeof dist);
    memset(trace,-1,sizeof trace);
    queue<int>q;
    for(int num:dig){
        if(dist[num%n]!=1){
            dist[num%n]=1;
            so[num%n]=num;
            q.push(num%n);
        }
    }
    while(q.size()){
        int u=q.front();
        q.pop();
        for(int num:dig){
            int v=(u*10+num)%n;
            if(dist[v]>dist[u]+1){
                dist[v]=dist[u]+1;
                so[v]=num;
                trace[v]=u;
                q.push(v);
            }
        }
    }
    if(dist[0]<1e10){
        string ans;
        for(int u=0;u!=-1;u=trace[u]){
            ans.pb(so[u]+'0');
        }
        reverse(all(ans));
        cout<<ans;
    }

}
