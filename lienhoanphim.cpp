inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,l[N],r[N],dp[N];
vector<int>g[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    vector<int>cp;
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>l[i]>>r[i];
        r[i]--;
        cp.pb(l[i]);
        cp.pb(r[i]);
    }
    sort(all(cp));
    cp.erase(unique(all(cp)),cp.end());
    for(int i=1;i<=n;i++){
        l[i]=lower_bound(all(cp),l[i])-cp.begin()+1;
        r[i]=lower_bound(all(cp),r[i])-cp.begin()+1;
        g[r[i]].pb(l[i]);
    }
    for(int r=1;r<=5e5;r++){
        dp[r]=max(dp[r],dp[r-1]);
        for(int l:g[r]){
            dp[r]=max(dp[r],dp[l-1]+1);
        }
    }
    cout<<dp[500000];
}
