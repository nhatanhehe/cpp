inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,p[N],tplt,q[N],ans[N],d[N];
vector<int>g[N];
int acs(int u){
    return u==p[u]? u:p[u]=acs(p[u]);
}
void join(int u,int v){
    u=acs(u); v=acs(v);
    if(u!=v){
        p[v]=u;
        tplt--;
    }
}
main(){
     ios_base::sync_with_stdio(false);
     cin.tie(NULL);
       cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++) p[i]=i;
    for(int i=1;i<=m;i++){
        cin>>u>>v;
        g[u].pb(v);
        g[v].pb(u);
    }
    for(int i=1;i<=n;i++) cin>>q[i];
    for(int i=n;i>=1;i--){
        d[q[i]]=1;
        tplt++;
        for(int v:g[q[i]]){
            if(d[v]) join(v,q[i]);
        }
        ans[i]=tplt;
    }
    for(int i=1;i<=n;i++) cout<<ans[i]<<'\n';
}
