inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,nxt[N][2];
string s;
ll cal(int k){
    vector<vector<ll>>dp(n+3,vector<ll>(k+2,0));
    dp[0][0]=1;
    for(int i=0;i<=n;i++){
        for(int j=0;j<=k;j++){
            if(j+1<=k){
                dp[nxt[i][0]][j+1]=add(dp[nxt[i][0]][j+1],dp[i][j]);
            }
            if(j-1>=0){
                dp[nxt[i][1]][j-1]=add(dp[nxt[i][1]][j-1],dp[i][j]);
            }
        }
    }
    ll res=0;
    for(int i=1;i<=n;i++){
        res=add(res,dp[i][0]);
    }
    return res;
}
