#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m;
ii x[N];
struct cmp{
    bool operator()(const ii &a,const ii &b){
        return a.fi<b.fi||(a.fi==b.fi&&a.se<b.se);
    }
};
multiset<ii,cmp>ms;
vector<int>dis[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>x[i].fi>>x[i].se;
        ms.insert(ii(x[i].se,x[i].fi));
        dis[x[i].fi+1].pb(x[i].se);
    }
    ll ans=0;
    for(int i=1;i<=m;i++){
        for(int id:dis[i]){
            auto it=ms.find(ii(id,i-1));
            if(it!=ms.end()) ms.erase(it);
        }
        if(ms.size()){
            auto it=ms.begin();
            ans+=(*it).fi;
            ms.erase(it);
        }
    }
    cout<<ans;
}
