inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int color[N],t,n,m,u,v;
vector<int>g[N];
bool dfs(int u,int c){
    color[u]=c;
    for(int v:g[u]){
        if(color[v]==-1){
            if(dfs(v,c^1)) return 1;
        }
        else if(color[v]==c) return 1;
    }
    return 0;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        memset(color,-1,sizeof color);
        cin>>n>>m;
        for(int i=1;i<=n;i++) g[i].clear();
        for(int i=1;i<=m;i++){
            cin>>u>>v;
            g[u].pb(v);
            g[v].pb(u);
        }
        bool ok=0;
        for(int i=1;i<=n;i++){
            if(color[i]==-1){
                if(dfs(i,0)){
                    ok=1;
                    break;
                }
            }
        }
        cout<< (ok? "YES\n":"NO\n");
    }
}
