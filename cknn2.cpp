inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n;
struct pt{
    ll x,y,id;
};
struct DSU{
    vector<int>p;
    int n;
    ll ans=0;
    void init(int _n){
        n=_n;
        ans=0;
        p.resize(n+3,0);
        for(int i=1;i<=n;i++) p[i]=i;
    }
    int acs(int u){
        return u==p[u]? u:p[u]=acs(p[u]);
    }
    void join(int u,int v,ll w){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            ans+=w;
            p[v]=u;
        }
    }
}dsu;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    dsu.init(n);
    vector<pt>nodes,edg;
    for(int i=1,x,y;i<=n;i++){
        cin>>x>>y;
        nodes.pb({x,y,i});
    }
    sort(all(nodes),[&](const pt &x, const pt &y){
        return x.x<y.x;
    });
    for(int i=0;i<n;i++){
        if(i>0) edg.pb({nodes[i-1].id,nodes[i].id,nodes[i].x-nodes[i-1].x});
        if(i<n-1) edg.pb({nodes[i+1].id,nodes[i].id,nodes[i+1].x-nodes[i].x});
    }
    sort(all(nodes),[&](const pt &x, const pt &y){
        return x.y<y.y;
    });
    for(int i=0;i<n;i++){
        if(i>0) edg.pb({nodes[i-1].id,nodes[i].id,nodes[i].y-nodes[i-1].y});
        if(i<n-1) edg.pb({nodes[i+1].id,nodes[i].id,nodes[i+1].y-nodes[i].y});
    }
    sort(all(edg),[&](const pt &x,const pt &y){
        return x.id<y.id;
    });
    for(auto [u,v,w]:edg){
        dsu.join(u,v,w);
    }
    cout<<dsu.ans;
}
