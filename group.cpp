inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,R,a[N],t;
struct BIT{
    vector<int>bit;
    int n;
    void init(int _n){
        n=_n;
        bit.resize(n+4,0);
    }
    void up(int i,int k){
        for(;i<=n;i+=i&-i){
            bit[i]+=k;
        }
    }

    int get(int i){
        int res=0;
        for(;i;i-=i&-i){
            res+=bit[i];
        }
        return res;
    }

    int query(int l,int r){
        return get(r)-get(l-1);
    }
};
set<int>s;
BIT bit_s,bit_cnt;
unordered_map<int,int>mp;
bool check(int p,int n){
    auto it=s.upper_bound(p);
    int suml,sl;
    if(it==s.begin()){
        suml=0;
        sl=n;
    }
    else{
        it--;
        suml=bit_s.query(1,mp[*it]);
        sl=n-bit_cnt.query(1,mp[*it]);
    }
    return suml+sl*p>=k*p;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n>>k>>R;
        vector<int>cp;
        for(int i=1;i<=n;i++){
            cin>>a[i];
            cp.pb(a[i]);
        }
        sort(all(cp));
        cp.erase(unique(all(cp)),cp.end());
        for(int i=1;i<=n;i++){
            mp[a[i]]=upper_bound(all(cp),a[i])-cp.begin();
        }
        bit_s.init(cp.size());
        bit_cnt.init(cp.size());
        for(int i=1;i<=R;i++){
            bit_s.up(mp[a[i]],a[i]);
            bit_cnt.up(mp[a[i]],1);
            s.insert(a[i]);
        }
        for(int i=R+1;i<=n;i++){
            bit_s.up(mp[a[i]],a[i]);
            bit_cnt.up(mp[a[i]],1);
            s.insert(a[i]);
            int l=0,r=1e14/k,ans=0;
            while(l<=r){
                int mid=(l+r)>>1;
                if(check(mid,i)){
                    l=mid+1;
                    ans=mid;
                }
                else r=mid-1;
            }
            cout<<ans<<" ";
        }
        cout<<'\n';
        s.clear();
        mp.clear();
    }
}
