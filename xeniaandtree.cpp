inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,cen[N],sz[N];
vector<int>g[N];
int par[N],h[N],p[N][20];
bool vis[N];
void DFS(int u,int par){
    for(int v:g[u]){
        if(v!=par){
            h[v]=h[u]+1;
            p[v][0]=u;
            DFS(v,u);
        }
    }
}
int lca(int u,int v){
    if(h[u]<h[v]) swap(u,v);
    for(int i=18;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)) u=p[u][i];
    }
    if(u==v) return u;
    for(int i=18;i>=0;i--){
        if(p[u][i]!=p[v][i]){
            u=p[u][i];
            v=p[v][i];
        }
    }
    return p[u][0];
}
int dist(int u,int v){
    return h[u]+h[v]-2*h[lca(u,v)];
}
void dfs_sz(int u,int p){
    sz[u]=1;
    for(int v:g[u]){
        if(v==p|vis[v])continue;
        dfs_sz(v,u);
        sz[u]+=sz[v];
    }
}
int centroid(int u,int p,int n){
    for(int v:g[u]){
        if(v==p||vis[v])continue;
        if(sz[v]>n/2)return centroid(v,u,n);
    }
    return u;
}

void build(int u,int p){
    dfs_sz(u,0);
    int c=centroid(u,0,sz[u]);
    par[c]=p;
    vis[c]=1;
    for(int v:g[c]){
        if(!vis[v]){
            build(v,c);
        }
    }
}
int ans[N];
void up(int u){
    int cur=u;
    while(cur!=0){
        ans[cur]=min(ans[cur],dist(u,cur));
        cur=par[cur];
    }
}
int get(int u){
    int res=1e9;
    int cur=u;
    while(cur){
        res=min(res,ans[cur]+dist(u,cur));
        cur=par[cur];
    }
    return res;
}
