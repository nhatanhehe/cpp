#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "pour"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (masks|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int v,n,m,p[N],dist[21][50005];
queue<ii>q;
void pour(int a,int b,int x){
    for(int i=0;i<=n;i++){
        if(p[i]>a+b) break;
        if(dist[i][min(a+b-p[i],v-a-b)]>x+1){
            dist[i][min(a+b-p[i],v-a-b)]=x+1;
            q.push({i,min(a+b-p[i],v-a-b)});
        }
    }
}
// a sang b để a có vạch p[i] => p[i] và b+a-p[i]
// b sang a để a có vạch p[i] => p[i] và b-(p[i]-a)
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>v>>n>>m;
    p[0]=0;
    for(int i=1;i<=n;i++){
        cin>>p[i];
    }
    memset(dist,0x3f,sizeof dist);
    dist[0][0]=0;
    q.push({0,0});
    while(q.size()){
        auto [i,x]=q.front();
        q.pop();
        int y=v-p[i]-x;
        //cerr<<p[i]<<" "<<x<<" "<<y<<'\n';
        if(p[i]==m||x==m||y==m){
            return cout<<dist[i][x],0;
        }
        /*
            Các bình là 1,2,3
            1 đang chứa p[idx] lít nc
            2 đang chứa x lít nc
            3 đang chưa y lít nc
        */
        pour(x,y,dist[i][x]);
        pour(x,p[i],dist[i][x]);
        pour(y,x,dist[i][x]);
        pour(y,p[i],dist[i][x]);
        pour(p[i],x,dist[i][x]);
        pour(p[i],y,dist[i][x]);
    }
}
