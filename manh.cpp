inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll f[20],sum,ans=1e9;
void ql(int i,ll cnt,ll dem){
    if(i>14){
        if(cnt>sum) return;
        else{
            ans=min(ans,dem+__builtin_popcountll(sum-cnt));
        }
        return;
    }
    ql(i+1,cnt,dem);
    ql(i+1,cnt+f[i],dem+1);
}
