#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,a[N],m,b[N],val[1000004],pre[N];
unordered_map<ll,ll>mp[N];
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());
ll Rand(ll l,ll r){
    return uniform_int_distribution<ll>(l,r)(rng);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        if(!val[a[i]]){
            val[a[i]]=Rand(1,1e18);
        }
        pre[i]=pre[i-1]+val[a[i]];
    }
    cin>>m;
    for(int i=1;i<=m;i++){
        cin>>b[i];
        if(!val[b[i]]){
            val[b[i]]=Rand(1,1e18);
        }
    }   
    for(int i=1;i<=m;i++){
        ll cum=0;
        for(int j=i;j>=1;j--){
            cum+=val[b[j]];
            mp[i-j+1][cum]=j;
        }
    }
    for(int k=min(m,n);k>=1;k--){
        for(int p=k;p<=n;p++){
            ll tmp=pre[p]-pre[p-k];
            if(mp[k].count(tmp)){
                cout<<k<<" "<<p-k+1<<" "<<mp[k][tmp];
                return 0;
            }
        }
    }
    cout<<"0 -1 -1";
}
