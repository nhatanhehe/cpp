#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "fnum"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=1e5+5;
const ll mod=1e9+7;
const ll base=311;
ll blsz=320;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll cnt[320][N],n,a[N],bll[N],blr[N],nb,l[N],r[N],bit[N],tp,x,y,sum[320],q,block[N];
void up(int i,int k){
    for(;i<=n;i+=i&-i){
        bit[i]+=k;
    }
}
ll get(int i){
    ll res=0;
    for(;i;i-=i&-i){
        res+=bit[i];
    }
    return res;
}
ll query(int l,int r){
    return get(r)-get(l-1);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    blsz=sqrt(n);
    for(int i=1;i<=n;i++){
        cin>>a[i];
        up(i,a[i]);
        block[i]=(i-1)/blsz+1;
    }
    for(int i=1;i<=n;i++){
        cin>>l[i]>>r[i];
    }
    nb=(n+blsz-1)/blsz;
    for(int i=1;i<=nb;i++){
        bll[i]=(i-1)*blsz+1;
        blr[i]=min(n,blsz*i);
        for(int j=bll[i];j<=blr[i];j++){
            cnt[i][l[j]]++;
            cnt[i][r[j]+1]--;
        }
        for(int j=1;j<=n;j++){
            cnt[i][j]+=cnt[i][j-1];
            sum[i]+=cnt[i][j]*a[j];
        }
    }
    cin>>q;
    while(q--){
        cin>>tp>>x>>y;
        if(tp==1){
            for(int i=1;i<=nb;i++){
                sum[i]-=cnt[i][x]*a[x];
                sum[i]+=cnt[i][x]*y;
            }
            up(x,-a[x]);
            up(x,y);
            a[x]=y;
        }
        else{
            ll ans=0;
            if(block[x]==block[y]){
                for(int j=x;j<=y;j++){
                    ans+=query(l[j],r[j]);
                }
            }
            else{
                for(int i=block[x]+1;i<block[y];i++) ans+=sum[i];
                for(int i=x;i<=block[x]*blsz;i++) ans+=query(l[i],r[i]);
                for(int i=(block[y]-1)*blsz+1;i<=y;i++) ans+=query(l[i],r[i]);
            }
            cout<<ans<<'\n';
        }
    }
}
