inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
vector<ii>adj[N];
ll n,u,v,w,m,inq[N];
ld d[N];
bool spfa(ld x){
    fill(d+1,d+n+1,0.0);
    fill(inq+1,inq+n+1,0);
    
    vector<int> cnt(n+1,0);
    queue<int> q;
    for(int i=1;i<=n;i++){
        q.push(i);
        inq[i]=1;
    }
    
    while(!q.empty()){
        int u=q.front();
        q.pop();
        inq[u]=0;
        
        for(auto [v,W]:adj[u]){
            ld w=1.0*W-x;
            if(d[v]>d[u]+w){
                d[v]=d[u]+w;
                cnt[v]++;
                
                if(cnt[v]>=n) return 1;
                
                if(!inq[v]){
                    q.push(v);
                    inq[v]=1;
                }
            }
        }
    }
    return 0;
}

main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        adj[u].pb({v,w});
    }
    ld l=0,r=1e9,ans=inf;
    for(int cnt=0;cnt<=36;cnt++){
        ld mid=(l+r)/2.0;
        if(spfa(mid)){
            ans=mid;
            r=mid;
        }
        else l=mid;
    }
    if(ans==inf) cout<<"NO TOUR";
    else cout<<fixed<<setprecision(2)<<ans;
}
