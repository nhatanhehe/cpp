#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,c,w[N],u,v,dp[N][N];
vector<int>g[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>c;
    for(int i=1;i<=n;i++){
        cin>>w[i];
    }
    for(int i=1;i<=m;i++){
        cin>>u>>v;
        g[v].pb(u);
    }
    for(int i=0;i<=n;i++){
        for(int j=0;j<=2000;j++){
            dp[i][j]=-1e18;
        }
    }
    dp[1][0]=0;
    for(int j=1;j<=1000;j++){
        for(int u=1;u<=n;u++){
            for(int v:g[u]){
                if(dp[v][j-1]!=-1e18){
                    dp[u][j]=max(dp[u][j],dp[v][j-1]+w[u]);
                }
            }
        }
    }
    ll ans=0;
    for(int i=1;i<=1000;i++){
        ans=max(ans,dp[1][i]-c*i*i);
    }
    cout<<ans;
}
