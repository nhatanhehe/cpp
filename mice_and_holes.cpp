#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "aaa"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=5e3+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,x[N],dp[N][N],sum[N];
ii holes[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        cin>>x[i];
    }
    for(int i=1;i<=m;i++){
        cin>>holes[i].fi>>holes[i].se;
    }
    sort(x+1,x+n+1);
    sort(holes+1,holes+m+1);
    memset(dp,0x3f,sizeof dp);
    dp[0][0]=0;
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            sum[j]=sum[j-1]+abs(holes[i].fi-x[j]);
        }
        deque<ii>dq;
        dq.push_back({dp[i-1][0]-sum[0],0});
        dp[i][0]=dp[i-1][0];
        for(int j=1;j<=n;j++){
            dp[i][j]=dp[i-1][j];
            while(dq.size()&&dq.back().fi>=dp[i-1][j]-sum[j]) dq.pop_back();
            dq.push_back({dp[i-1][j]-sum[j],j});
            while(dq.front().se+holes[i].se<j) dq.pop_front();
            dp[i][j]=min(dp[i][j],dq.front().fi+sum[j]);
        }
    }
    cout<<(dp[m][n]<=1e13? dp[m][n]:-1);
}
