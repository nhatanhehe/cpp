#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],dp[1002][1002];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=2*n;i++){
        cin>>a[i];
    }
    vector<ii>block;
    int fir=1,cur=0;
    a[2*n+1]=1e9+4;
    for(int i=1;i<=2*n+1;i++){
        if(a[i]>a[fir]){
            block.pb(ii(fir,cur));
            cur=1;
            fir=i;
        }
        else{
            cur++;
        }
    }
    ///for(auto [x,y]:block) cerr<<x<<" "<<y<<'\n';
    vector<vector<int>>dp(block.size()+4,vector<int>(n+4,0));
    vector<vector<ii>>trace(block.size()+4,vector<ii>(n+4));
    dp[0][0]=1;
    int state1=-1,state2=n;
    for(int i=0;i<block.size();i++){
        for(int j=0;j<=n;j++){
            if(dp[i][j]){
                dp[i+1][j]=dp[i][j];
                trace[i+1][j]=ii(i,j);
            }
            if(j>=block[i].se&&dp[i][j-block[i].se]){
                dp[i+1][j]=dp[i][j-block[i].se];
                trace[i+1][j]=ii(i,j-block[i].se);
                cerr<<trace[i+1][j].se<<" ";

            }
        }
        if(dp[i+1][n]){
            state1=i+1;
            break;
        }
    }
    if(state1==-1) cout<<"-1\n";
    else{
        vector<int>mark(2*n+4,0);
        while(state1&&state2){
            //cout<<state1<<" "<<state2<<'\n';
            auto [nxt1,nxt2]=trace[state1][state2];
            if(nxt2!=state2){
                for(int i=block[nxt1].fi;block[nxt1].se;block[nxt1].se--,i++){
                    mark[i]=1;
                }
            }
            state1=nxt1;
            state2=nxt2;
        }
        for(int i=1;i<=2*n;i++){
            if(mark[i]) cout<<a[i]<<" ";
        }
        cout<<'\n';
        for(int i=1;i<=2*n;i++){
            if(!mark[i]) cout<<a[i]<<" ";
        }
        cout<<'\n';
    }
}
