#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n;
ii a[N],b[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i].fi;
        a[i].se=i;
    }
    for(int i=1;i<=n;i++){
        cin>>b[i].fi;
        b[i].se=i;
    }
    sort(a+1,a+n+1);
    sort(b+1,b+n+1);
    vector<ii>res;
    int score=0;
    int la=1,lb=1,ra=n,rb=n;
    while(la<=ra){
        if(a[ra].fi>b[rb].fi){
            res.pb(ii(a[ra].se,b[rb].se));
            ra--;
            rb--;
            score++;
        }
        else if(a[la].fi>b[lb].fi){
            res.pb(ii(a[la].se,b[lb].se));
            la++;
            lb++;
            score++;
        }
        else{
            res.pb(ii(a[la].se,b[rb].se));
            rb--;
            la++;
            if(a[la].fi<b[rb].fi) score--;
        }
    }
    for(auto [u,v]:res) cout<<u<<" "<<v<<'\n';
}
