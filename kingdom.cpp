    #define On(mask,i) (mask|(1LL<<i))
    #define Off(mask,i) (mask^(1LL<<i))
    inline ll add(ll a,ll b){
        ll res=a+b;
        if(res>=mod) res-=mod;
        return res;
    }
    ll sub(ll a,ll b){
        return ((a-b)%mod+mod)%mod;
    }
    inline ll mul(ll a,ll b){
        ll res=a*b;
        if(res>=mod) res%=mod;
        return res;
    }
    int l,r,n,q,u,v,mx_sz;
    struct pt{
        int l,r,pos;
    };
    vector<int>g[N];
    pt Q[125004];
    namespace sub3{
        int h[2003],p[2003][13],S,st[2003],en[2003],timer=0,res=0,ans[125004];
        multiset<ii>ver;
        void dfs(int u,int par){
            st[u]=++timer;
            for(int v:g[u]){
                if(v!=par){
                    h[v]=h[u]+1;
                    p[v][0]=u;
                    dfs(v,u);
                }
            }
            en[u]=timer;
        }
        int lca(int u,int v){
            if(h[u]<h[v]) swap(u,v);
            for(int i=12;i>=0;i--){
                if(h[u]-h[v]>=(1<<i)) u=p[u][i];
            }
            if(u==v) return u;
            for(int i=12;i>=0;i--){
                if(p[u][i]!=p[v][i]){
                    u=p[u][i];
                    v=p[v][i];
                }
            }
            return p[u][0];
        }
        bool cmp(pt x,pt y){
            if(x.l/S!=y.l/S) return x.l<y.l;
            return x.r<y.r;
        }
        int dist(int u,int v){
            int acs=lca(u,v);
            return h[u]+h[v]-2*h[acs];
        }
        void add_v(int u){
            if(ver.empty()){
                ver.insert(ii(st[u],u));
                res=0;
                return;
            }
            auto it=ver.upper_bound(ii(st[u],u));
            if(it==ver.end()) it=ver.begin();
            auto prev_it=(it==ver.begin()? prev(ver.end()):prev(it));
            res-=dist(prev_it->se,it->se);
            res+=dist(prev_it->se,u);
            res+=dist(u,it->se);
            ver.insert(ii(st[u],u));
        }
        void del_v(int u){
            auto it=ver.find(ii(st[u],u));
            if(it==ver.end()) return;
            if(ver.size()==1){
                res=-2;
                ver.erase(it);
                return;
            }
            auto next_it=next(it);
            if(next_it==ver.end()) next_it=ver.begin();
            auto prev_it=(it==ver.begin()? prev(ver.end()):prev(it));
            res-=dist(it->se,next_it->se)+dist(it->se,prev_it->se);
            res+=dist(next_it->se,prev_it->se);
            ver.erase(it);
        }
        void solve(){
            memset(h,0,sizeof h);
            memset(p,0,sizeof p);
            S=sqrt(n);
            dfs(1,-1);
            for(int j=1;(1<<j)<=n;j++){
                for(int i=1;i<=n;i++){
                    p[i][j]=p[p[i][j-1]][j-1];
                }
            }
            sort(Q+1,Q+q+1,cmp);
            int l=1,r=0;
            for(int i=1;i<=q;i++){
                while(l>Q[i].l){
                    add_v(--l);
                }
                while(r<Q[i].r){
                    add_v(++r);
                }
                while(l<Q[i].l){
                    del_v(l++);
                }
                while(r>Q[i].r){
                    del_v(r--);
                }
                ans[Q[i].pos]=res/2+1;
            }
            for(int i=1;i<=q;i++){
                cout<<ans[i]<<'\n';
            }
        }
    }
