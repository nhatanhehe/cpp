#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,a[N],f[N],g[N],h[N];
int flip(int n){
    int mask=(1<<(20))-1;
    return n^mask;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        h[a[i]]++;
    }
    for(int mask=0;mask<(1<<20);mask++){
        f[mask]=h[mask];
        g[mask]=h[mask];
    }
    for(int k=0;k<20;k++){
        for(int mask=0;mask<(1<<20);mask++){
            if((mask>>k)&1) f[mask]+=f[Off(mask,k)];
        }
        for(int mask=(1<<20)-1;mask>=0;mask--){
            if(!((mask>>k)&1)) g[mask]+=g[On(mask,k)];
        }
    }
    for(int i=1;i<=n;i++){
        cout<<f[a[i]]<<" "<<g[a[i]]<<" "<<n-f[flip(a[i])]<<'\n';
    }
}
