const ll inf=1e18;
const ll N=2e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,k,a[N],dp[N],h[N];
int flip(int n){
    int mask=(1<<(20))-1;
    return n^mask;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            dp[a[i]&a[j]]++;
        }
    }
    for(int k=0;k<20;k++){
        for(int mask=0;mask<(1<<20);mask++){
            if((mask>>k)&1) dp[mask]+=dp[Off(mask,k)];
        }
    }
    int x,y,u,v,check=0;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            if(k>dp[flip(a[i]&a[j])]){
                k-=dp[flip(a[i]&a[j])];
            }
            else{
                x=i;
                y=j;
                check=1;
                break;
            }
        }
        if(check) break;
    }
    if(!check) return cout<< -1,0;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            if((a[i]&a[j]&a[x]&a[y])==0) k--;
            if(!k){
                u=i;
                v=j;
                goto OUT1;
            }
        }
    }
    OUT1:
    cout<<x<<" "<<y<<" "<<u<<" "<<v;
}
