#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "pizza"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,dp[N],f;
ii cost[N];
vector<ii>self[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        cin>>f;
        int mask=0;
        for(int j=1;j<=f;j++){
            int x;
            cin>>x;
            mask=On(mask,x-1);
        }
        dp[mask]++;
    }
    for(int k=0;k<9;k++){
        for(int mask=0;mask<(1<<9);mask++){
            if((mask>>k)&1) dp[mask]+=dp[Off(mask,k)];
        }
    }
    fill(cost,cost+1024+1,ii(2e9,-1));
    for(int i=1;i<=m;i++){
        int c;
        cin>>c>>f;
        int mask=0;
        for(int j=1;j<=f;j++){
            int x;
            cin>>x;
            mask=On(mask,x-1);
        }
        cost[mask]=min(cost[mask],ii(c,i));
        if(self[mask].size()<2) self[mask].pb(ii(c,i));
    }
    int ans=0,cs1,cs2,min_cost=inf;
    for(int mask=0;mask<(1<<9);mask++){
        if(self[mask].size()==2){
            if(ans<dp[mask]){
                ans=dp[mask];
                min_cost=self[mask][0].fi+self[mask][1].fi;
                cs1=self[mask][0].se;
                cs2=self[mask][1].se;
            }
            else if(ans==dp[mask]){
                if(min_cost>self[mask][0].fi+self[mask][1].fi){
                    min_cost=self[mask][0].fi+self[mask][1].fi;
                    cs1=self[mask][0].se;
                    cs2=self[mask][1].se;
                }
            }
        }
    }
    for(int mask1=0;mask1<(1<<9);mask1++){
        for(int mask2=0;mask2<(1<<9);mask2++){
            if(cost[mask1].fi!=2e9&&cost[mask2].fi!=2e9&&mask1!=mask2){
                int mask=mask1|mask2;
                if(ans<dp[mask]){
                    ans=dp[mask];
                    min_cost=cost[mask1].fi+cost[mask2].fi;
                    cs1=cost[mask1].se;
                    cs2=cost[mask2].se;
                }
                else if(ans==dp[mask]){
                    if(min_cost>cost[mask1].fi+cost[mask2].fi){
                        min_cost=cost[mask1].fi+cost[mask2].fi;
                        cs1=cost[mask1].se;
                        cs2=cost[mask2].se;
                    }
                }
            }
        }
    }
    cout<<cs1<<" "<<cs2;
}
