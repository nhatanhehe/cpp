inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
template<int MOD>
struct ModInt{
    int v;
    ModInt(long long _v=0){
        _v%=MOD;
        if(_v<0) _v+=MOD;
        v=_v;
    }

    ModInt& operator+=(const ModInt &o){
        v+=o.v;
        if(v>=MOD) v-=MOD;
        return *this;
    }

    ModInt& operator-=(const ModInt &o){
        v-=o.v;
        if(v<0) v+=MOD;
        return *this;
    }

    ModInt& operator*=(const ModInt &o){
        v=1LL*v*o.v%MOD;
        return *this;
    }

    static ModInt qpow(ModInt a,long long e){
        ModInt r=1;
        while(e){
            if(e&1) r*=a;
            a*=a;
            e>>=1;
        }
        return r;
    }

    ModInt inv()const{
        return qpow(*this,MOD-2);
    }

    ModInt& operator/=(const ModInt &o){
        return (*this)*=o.inv();
    }

    friend ModInt operator+(ModInt a,const ModInt &b){ return a+=b; }
    friend ModInt operator-(ModInt a,const ModInt &b){ return a-=b; }
    friend ModInt operator*(ModInt a,const ModInt &b){ return a*=b; }
    friend ModInt operator/(ModInt a,const ModInt &b){ return a/=b; }

    friend bool operator==(const ModInt &a,const ModInt &b){
        return a.v==b.v;
    }

    friend bool operator!=(const ModInt &a,const ModInt &b){
        return a.v!=b.v;
    }

    friend ostream& operator<<(ostream &os,const ModInt &a){
        return os<<a.v;
    }

    friend istream& operator>>(istream &is,ModInt &a){
        long long x;
        is>>x;
        a=ModInt(x);
        return is;
    }
};
using mint=ModInt<mod>;
ll n,q,u,v,w,in[N],out[N],timer;
mint ans[N];
vector<ii>g[N],Q[N];
struct Node{
    mint sq,sum;
    Node(){
        sq=sum=0;
    }
};
struct SegmentTree{ 
    vector<Node>tree;
    vector<mint>lz;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(n*4+10,Node());
        lz.resize(n*4+10,0);
    }
    void apply(int id,int l,int r,mint x){
        tree[id].sq+=(r-l+1)*x*x+2*x*(tree[id].sum);
        tree[id].sum+=(r-l+1)*x;
        lz[id]+=x;
    }
    void push(int id,int l,int r){
        if(lz[id]==0) return;
        int mid=(l+r)>>1;
        apply(id*2,l,mid,lz[id]);
        apply(id*2+1,mid+1,r,lz[id]);
        lz[id]=0;
    }
    void up(int u,int v,mint x,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(r<l) return;
        if(l>v||r<u) return;
        if(u<=l&&r<=v){
            apply(id,l,r,x);
            return;
        }
        push(id,l,r);
        int mid=(l+r)>>1;
        up(u,v,x,id*2,l,mid);
        up(u,v,x,id*2+1,mid+1,r);
        tree[id].sq=tree[id*2].sq+tree[id*2+1].sq;
        tree[id].sum=tree[id*2].sum+tree[id*2+1].sum;
    }
    mint get(int u,int v,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return 0;
        if(u<=l&&r<=v) return tree[id].sq;
        push(id,l,r);
        int mid=(l+r)>>1;
        return get(u,v,id*2,l,mid)+get(u,v,id*2+1,mid+1,r);
    }
}seg;
void dfs(int u,int p,mint d){
    in[u]=++timer;
    for(auto [v,w]:g[u]){
        if(v!=p){
            dfs(v,u,d+w);
        }
    }
    out[u]=timer;
    seg.up(in[u],in[u],d);
}
void reroot(int u,int p){
    for(auto [v,id]:Q[u]){
        ans[id]=2*seg.get(in[v],out[v])-seg.get(1,n);
    }
    for(auto [v,w]:g[u]){
        if(v!=p){
            seg.up(1,in[v]-1,w);
            seg.up(out[v]+1,n,w);
            seg.up(in[v],out[v],-w);
            reroot(v,u);
            seg.up(1,in[v]-1,-w);
            seg.up(out[v]+1,n,-w);
            seg.up(in[v],out[v],w);
        }
    }
}
