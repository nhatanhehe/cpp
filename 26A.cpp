inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct Node{
    Node *child[2];
    int cnt;
    Node(){
        child[0]=child[1]=NULL;
        cnt=0;
    }
}*root=new Node();
void ins(int x){
    Node *p=root;
    for(int j=17;j>=0;j--){
        int c=(x>>j)&1;
        if(!p->child[c]) p->child[c]=new Node();
        p=p->child[c];
        p->cnt++;
    }
}
void del(int x){
    Node *p=root;
    for(int j=17;j>=0;j--){
        int c=(x>>j)&1;
        p=p->child[c];
        p->cnt--;
    }
}
int find_k(int k){
    Node *p=root;
    int res=0;
    for(int i=17;i>=0;i--){
        int cntl=p->child[0]? p->child[0]->cnt:0;
        if(cntl>=k){
            if(!p->child[0]) break;
            else p=p->child[0];
        }
        else{
            k-=cntl;
            res+=(1<<i);
            if(!p->child[1]) break;
            else p=p->child[1];
        }
    }
    return res;
}
struct SegmentTree{
    vector<int>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(n*4+3,0);
    }
    void build(int a[N],int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l==r){
            tree[id]=a[l];
            return;
        }
        int mid=(l+r)>>1;
        build(a,id*2,l,mid);
        build(a,id*2+1,mid+1,r);
        tree[id]=max(tree[id*2],tree[id*2+1]);
    }
    void up(int u,int v,int k,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u||tree[id]<k) return;
        if(l==r){
            del(tree[id]);
            tree[id]%=k;
            ins(tree[id]);
            return;
        }
        int mid=(l+r)>>1;
        up(u,v,k,id*2,l,mid);
        up(u,v,k,id*2+1,mid+1,r);
        tree[id]=max(tree[id*2],tree[id*2+1]);
    }
}seg;
