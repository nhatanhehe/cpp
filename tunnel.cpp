const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,s,t,trace[N],u,v,h,d,dist[N];
struct edges{
    int u,v,h,d;
};
vector<edges>e;
struct DSU{
    vector<int>p;
    int n;
    void init(int _n){
        n=_n;
        p.resize(n+3,0);
        for(int i=1;i<=n;i++) p[i]=i;
    }
    int acs(int u){
        return u==p[u]? u:p[u]=acs(p[u]);
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            p[v]=u;
        }
    }
}dsu;
vector<ii>g[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>s>>t;
    dsu.init(n);
    for(int i=1;i<=m;i++){
        cin>>u>>v>>h>>d;
        e.pb({u,v,h,d});
    }
    sort(all(e),[&](const edges &x,const edges &y){
       return x.h>y.h; 
    });
    int lim=-1e9;
    for(int i=0;i<m;i++){
        auto [u,v,h,d]=e[i];
        if(dsu.acs(u)!=dsu.acs(v)) dsu.join(u,v);
        if(dsu.acs(s)==dsu.acs(t)) {
            lim = e[i].h;
            break;
        }
    }
    for(int i=0;i<m;i++){
        if(e[i].h >= lim){
            g[e[i].u].pb({e[i].v,e[i].d});
            g[e[i].v].pb({e[i].u,e[i].d});
        }
    }
    priority_queue<ii,vector<ii>,greater<ii>>pq;
    memset(dist,0x3f,sizeof dist);
    dist[s]=0;
    pq.push({0,s});
    while(pq.size()){
        auto [cost,u]=pq.top(); pq.pop();
        if(u==t){
            vector<int>nodes;
            int x=t;
            while(true){
                if(x==s){
                    nodes.pb(x);
                    break;
                }
                nodes.pb(x);
                x=trace[x];
            }
            reverse(all(nodes));
            cout<<nodes.size()<<'\n';
            for(int x:nodes) cout<<x<<" ";
            return 0;
        }
        if(cost>dist[u]) continue;
        for(auto [v,w]:g[u]){
            if(dist[v]>dist[u]+w){
                dist[v]=dist[u]+w;
                trace[v]=u;
                pq.push({dist[v],v});
            }
        }
    }
}
