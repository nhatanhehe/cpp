const ll inf=1e18;
const ll N=8e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct Node{
    int child[26];
    int cnt;
}T[N];
int nodes;
int nw(){
    nodes++;
    for(int i=0;i<26;i++) T[nodes].child[i]=0;
    T[nodes].cnt=0;
    return nodes;
}
vector<int>act[N],vai[N];
ll ans=0;
void ins(string s,int id,int tp){
    int p=1;
    for(char x:s){
        int c=x-'a';
        if(!T[p].child[c]){
            T[p].child[c]=nw();
        }
        p=T[p].child[c];
        T[p].cnt++;
    }
    if(!tp) act[p].pb(id);
    else vai[p].pb(id);
}
void cls(){
     nodes=0;
     nw();
}
vector<ii>res;
void dfs(int p,int depth){
    for(int i=0;i<26;i++){
        int chid=T[p].child[i];
        if(chid){
            dfs(chid,depth+1);
            while(act[chid].size()){
                act[p].pb(act[chid].back());
                act[chid].pop_back();
            }
            while(vai[chid].size()){
                vai[p].pb(vai[chid].back());
                vai[chid].pop_back();
            }
        }
    }
    while(act[p].size()&&vai[p].size()){
        ans+=depth;
        res.pb(ii(act[p].back(),vai[p].back()));
        act[p].pop_back();
        vai[p].pop_back();
    }
}
string s[N];
int n;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cls();
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>s[i];
        ins(s[i],i,0);
    }
    for(int i=1;i<=n;i++){
        string x;
        cin>>x;
        ins(x,i,1);
    }
    dfs(1,0);
    cout<<ans<<'\n';
    for(auto [u,v]:res) cout<<u<<" "<<v<<'\n';
}
