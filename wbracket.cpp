inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
const int f=121;
ll n,k;
ll dp[300][300][2];
ll calc(int i,int depth,bool check){
    ll &ans=dp[i][depth+f][check];
    if(i>n){
        return ans=(depth!=0||check);
    }
    if(ans!=-1) return ans;
    ans=0;
    // chon (
    ans+=calc(i+1,depth+1,check);
    // chon )
    ans+=calc(i+1,depth-1,check||(depth-1<0));
    return ans;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    memset(dp,-1,sizeof dp);
    calc(1,0,0);
    int depth=0,check=0;
    string res;
    for(int i=1;i<=n;i++){
        ll tmp=calc(i+1,depth+1,check);
        if(k>tmp) k-=tmp;
        else {res+='(';
        depth++;
        continue;}
        tmp=calc(i+1,depth-1,check||(depth-1<0));
        if(k>tmp) k-=tmp;
        else{
            res+=')';
            depth--;
            check|=(depth-1<0);
        }
    }
    cout<<res;
}
