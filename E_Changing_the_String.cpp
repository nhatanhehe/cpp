inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
set<ci>st[4];
int t,n,q;
string s;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n>>q>>s;
        for(int i=1;i<=q;i++){
            char a,b;
            cin>>a>>b;
            st[a-'a'].insert(ci(b,i));
        }
        for(char &c:s){
            if(c=='b'){
                // b->a
                auto it=st[1].lower_bound(ci('a',-1));
                if(it!=st[1].end()&&(*it).fi=='a'){
                    c='a';
                    st[1].erase(it);
                    continue;
                }
                // b->c->a
                auto it2=st[1].lower_bound(ci('c',-1));
                if(it2!=st[1].end()&&(*it2).fi=='c'){
                    auto it3=st[2].lower_bound(ci('a',(*it2).se));
                    if(it3!=st[2].end()&&(*it3).fi=='a'){
                        c='a';
                        st[1].erase(it2);
                        st[2].erase(it3);
                    }
                }
            }
            else if(c=='c'){
                // c->a
                auto it=st[2].lower_bound(ci('a',-1));
                if(it!=st[2].end()&&(*it).fi=='a'){
                    //cout<<"skibidi2";
                    c='a';
                    st[2].erase(it);
                    continue;
                }
                auto it2=st[2].lower_bound(ci('b',-1));
                if(it2!=st[2].end()&&(*it2).fi=='b'){
                    // c->b
                    c='b';
                    //cout<<"skibidi3";
                    auto [ch,pos]=*it2;
                    st[2].erase(it2);
                    auto it3=st[1].lower_bound(ci('a',pos));
                    if(it3!=st[1].end()&&(*it3).fi=='a'){
                        c='a';
                        st[1].erase(it3);
                    }
                }
            }
        }
        for(char c:{'a','b','c'}) st[c-'a'].clear();
        cout<<s<<'\n';
    }
}
