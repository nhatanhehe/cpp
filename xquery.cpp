inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int q,t,val,Xor;
struct Node{
    Node *child[2];
    ll sum;
    int bit_cnt[18];
    int cnt;
    int val;
    Node(){
        child[0]=child[1]=NULL;
        memset(bit_cnt,0,sizeof bit_cnt);
        sum=0;
        cnt=0;
    }
}*root=new Node();
void ins(int x){
    Node *p=root;
    for(int i=17;i>=0;i--){
        int c=(x>>i)&1;
        if(!p->child[c]) p->child[c]=new Node();
        p=p->child[c];
        p->sum+=x;
        for(int j=0;j<=17;j++){
            if((x>>j)&1) p->bit_cnt[j]++;
        }
        p->cnt++;
    }
    p->val=x;
}
void del(int x){
    Node *p=root;
    for(int i=17;i>=0;i--){
        int c=(x>>i)&1;
        if(!p->child[c]||!p->child[c]->cnt) return;
        p=p->child[c];
    }
    p=root;
    for(int i=17;i>=0;i--){
        int c=(x>>i)&1;
        p=p->child[c];
        for(int j=0;j<=17;j++){
            if((x>>j)&1) p->bit_cnt[j]--;
        }
        p->sum-=x;
        p->cnt--;
    }
    if(!p->cnt) p->val=0;
}
ll riel_sum(Node *p){
    if(!p) return 0;
    ll sum=0;
    for(int i=0;i<=17;i++){
        ll ones=p->bit_cnt[i];
        if((Xor>>i)&1) ones=p->cnt-ones;
        sum+=ones*(1LL<<i);
    }
    return sum;
}
ll sum_k(int k){
    Node *p=root;
    ll res=0;
    for(int i=17;i>=0;i--){
        int c=(Xor>>i)&1;
        int z,o;
        if(c==1){
            z=1;
            o=0;
        }
        else z=0,o=1;
        int lcnt=p->child[z]? p->child[z]->cnt:0;
        if(lcnt>=k){
            p=p->child[z];
        }
        else{
            res+=riel_sum(p->child[z]);
            k-=lcnt;
            res+=k*(1LL<<i);
            if(!p->child[o]) break;
            p=p->child[o];
        }
    }
    if(k) res+=k*(p->val^Xor);
    return res;
}
