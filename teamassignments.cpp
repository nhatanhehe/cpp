inline ll add(ll a,ll b){
    ll res=a+b;
    if(res<0) res=res%mod+mod;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res<0) res=res%mod+mod;
    if(res>=mod) res%=mod;
    return res;
}
int f[N],n,k;
int exp(int a,int n){
	if(n==1) return a;
	if(n==0) return 1;
	int t=exp(a,n/2);
	if(n&1) return ((t*t)%mod*a%mod)%mod;
	else return (t*t)%mod;
}
int C(int n,int k){
	int a=f[n];
	int b=(f[k]*(f[n-k]))%mod;
	return a*exp(b,mod-2)%mod;
}
