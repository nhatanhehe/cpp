#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii tuple<int,int,int>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,c,p,re[N];
int dist[N];
struct pt{
    int v,c,p;
};
vector<pt>g[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>c>>p;
        g[u].pb({v,c,p});
        g[v].pb({u,c,p});
    }
    memset(dist,0x3f,sizeof dist);
    priority_queue<ii,vector<ii>,greater<ii>>pq;
    dist[1]=0;
    pq.push({0,1});
    vector<int>change;
    while(pq.size()){
        auto [cost,u]=pq.top(); pq.pop();
        if(u==n){
            return cout<<dist[n],0; 
        }
        if(cost>dist[u]) continue;
        for(auto [v,c,p]:g[u]){
            change.pb(c);
            re[c]+=p;
        }
        for(auto [v,c,p]:g[u]){
            int w=min(re[c]-p,p);
            if(dist[v]>dist[u]+w){
                dist[v]=dist[u]+w;
                pq.push({dist[v],v});
            }
        }
        for(int x:change) re[x]=0;
        change.clear();
    }
    cout<<-1;
}
