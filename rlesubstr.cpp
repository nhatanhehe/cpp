inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
vector<ci>decode(string a){
    vector<pair<char,int>>A;
    int sum=0;
    for(int i=0;i<a.size();i++){
        if(isalpha(a[i])) A.pb({a[i],0});
        else A.back().se=A.back().se*10+(a[i]-'0');
    }
    return A;
}
int t,nxt[N][30],dp[N],vis[N];
string s;
void solve(){
    vector<ci>a=decode(s);
    int n=a.size()-1;
    for(int i=0;i<26;i++){
        nxt[n][i]=n+1;
    }
    for(int i=n-1;i>=0;i--){
        for(int c='a'-'a';c<='z'-'a';c++){
            nxt[i][c]=nxt[i+1][c];
            if(a[i+1].fi==c+'a') nxt[i][c]=i+1;
        }
    }
    memset(dp,0,sizeof dp);
    memset(vis,0,sizeof vis);
    for(int i=0;i<=n;i++){
        if(!vis[a[i].fi]){
            vis[a[i].fi]=1;
            dp[i]=1;
        }
    }
    for(int i=0;i<=n;i++){
        for(int c=0;c<26;c++){
            int j=nxt[i][c];
            if(j==n+1) continue;
            if(a[j].fi==c+'a'){
                dp[j]=add(dp[j],dp[i]);
            }
            else dp[j]=add(dp[j],mul(dp[i],a[i].se));
        }
    }
    ll ans=0;
    for(int i=0;i<=n;i++){
        ans=add(ans,mul(dp[i],a[i].se));
    }
    cout<<ans<<'\n';
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>s;
        solve();
    }
}
