#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=5e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,dist[N],u,v,mask[N],m;
ii trace[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    if(n==1) return cout<<0,0;
    if(m==n*(n-1)/2) return cout<<0,0;
    for(int i=1;i<=m;i++){
        cin>>u>>v;
        mask[u]=On(mask[u],v-1);
        mask[v]=On(mask[v],u-1);
    }
    //cout<<mask[1]<<" "<<mask[2]<<'\n';
    memset(dist,0x3f,sizeof dist);
    queue<int>q;
    for(int i=0;i<n;i++){
        //mask[i+1]=On(mask[i+1],i);
        int state;
        for(int j=0;j<n;j++){
            if(mask[i+1]>>j&1){
                state=(1<<i)|(1<<j);
                if(dist[state]>0){
                    dist[state]=0;
                    q.push(state);
                }
            }
        }
    }
    while(q.size()){
        int u=q.front(); q.pop();
        for(int j=0;j<n;j++){
            if(u>>j&1){
                int nmask=u|mask[j+1];
                if(dist[nmask]>dist[u]+1){
                    dist[nmask]=dist[u]+1;
                    trace[nmask]=ii(j+1,u);
                    q.push(nmask);
                }
            }
        }
    }
    cout<<dist[(1<<n)-1]<<'\n';
    int mask=(1<<n)-1;
    vector<int>res;
    while(mask){
        auto [id,nmask]=trace[mask];
        res.pb(id);
        mask=nmask;
    }
    res.pop_back();
    reverse(all(res));
    for(int x:res) cout<<x<<" ";
}
