#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "ballgame"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e2+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,x,y,u[N],v[N],ban[N][N],dist[N][N][N];
int dx[]={0,0,1,-1};
int dy[]={1,-1,0,0};
void sub4(){
    for(int i=1;i<=n;i++){
        cin>>x>>y;
        ban[x][y]=1;
    }
    cin>>m;
    for(int i=1;i<=m;i++){
        cin>>u[i]>>v[i];
    }
    memset(dist,0x3f,sizeof dist);
    for(int i=1;i<=m;i++){
        queue<ii>q;
        dist[i][u[i]][v[i]]=0;
        q.push({u[i],v[i]});
        while(q.size()){
            auto [u,v]=q.front();
            q.pop();
            for(int k=0;k<4;k++){
                int x=u+dx[k],y=v+dy[k];
                if(0<=x&&x<=101&&0<=y&&y<=101&&!ban[x][y]){
                    if(dist[i][x][y]>dist[i][u][v]+1){
                        dist[i][x][y]=dist[i][u][v]+1;
                        q.push({x,y});
                    }
                }
            }
        }
    }
    ll res=inf;
    for(int i=0;i<=101;i++){
        for(int j=0;j<=101;j++){
            if(!ban[i][j]){
                ll ans=0;
                for(int k=1;k<=m;k++){
                    if(dist[k][i][j]<=1e6&&ans!=inf){
                        ans+=dist[k][i][j];
                    }
                    else ans=inf;
                }
                res=min(res,ans);
            }
        }
    }
    cout<<(res==inf? -1:res);
}
void sub5(){
    cin>>m;
    vector<int>x,y;
    for(int i=1;i<=m;i++){
        cin>>u[i]>>v[i];
        x.pb(u[i]);
        y.pb(v[i]);
    }
    sort(all(x));
    sort(all(y));
    ll X=x[(x.size()-1)/2];
    ll Y=y[(y.size()-1)/2];
    ll res=0;
    for(int i=1;i<=m;i++){
        res+=abs(X-u[i])+abs(Y-v[i]);
    }
    cout<<res<<'\n';
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    if(n){
        sub4();
    }
    else sub5();
}
