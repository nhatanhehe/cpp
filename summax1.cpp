inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll p[N],n,a[N],dp[N],mx;
vector<int>g[N];
void dfs(int u,int p){
    for(int v:g[u]){
        if(v!=p){
            dp[v]=dp[u]+a[v];
            mx=max(mx,dp[v]);
            dfs(v,u);
        }
    }
}
