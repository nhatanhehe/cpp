#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,u,v,w,dist[N],S,W[N],par[N];
vector<ii>g[N];
map<ii,int>mp;
ii ed[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        if(u>v) swap(u,v);
        mp[ii(u,v)]=i;
        g[u].pb({v,w});
        g[v].pb({u,w});
    }
    cin>>S;
    memset(dist,0x3f,sizeof dist);
    dist[S]=0;
    priority_queue<ii,vector<ii>,greater<ii>>pq;
    pq.push({0,S});
    while(pq.size()){
        auto [cost,u]=pq.top(); pq.pop();
        if(cost>dist[u]) continue;
        for(auto [v,w]:g[u]){
            if(dist[v]>dist[u]+w){
                dist[v]=dist[u]+w;
                par[v]=0;
                W[v]=1e9;
                pq.push({dist[v],v});
            }
            if(dist[v]==dist[u]+w){
                if(!par[v]||W[v]>w){
                    par[v]=u;
                    W[v]=w;
                }
            }
        }
    }
    vector<int>res;
    ll ans=0;
    for(int i=1;i<=n;i++){
        if(i!=S){
            int u=i;
            ans+=W[i];
            int v=par[i];
            if(u>v) swap(u,v);
            res.pb(mp[ii(u,v)]);
        }
    }
    cout<<ans<<'\n';
    for(int id:res) cout<<id<<" ";
}
