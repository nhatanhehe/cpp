inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int root1,root2,p1[N],p2[N],source,sink,n,dp1[N],dp2[N],a[N],b[N],work[N],dist[N];
vector<int>g1[N],g2[N];
struct edge{
    int to,rev,flow,cap;
};
vector<edge>g[N];
void addedge(int u,int v,int cap){
    edge a={v,g[v].size(),0,cap};
    edge b={u,g[u].size(),0,0};
    g[u].pb(a);
    g[v].pb(b);
}
void dfs1(int u,int p){
    dp1[u]=1;
    for(int v:g1[u]){
        if(v!=p){
            dfs1(v,u);
            dp1[u]+=dp1[v];
        }
    }
    addedge(p,u,dp1[u]-a[u]);
}
void dfs2(int u,int p){
    dp2[u]=1;
    for(int v:g2[u]){
        if(v!=p){
            dfs2(v,u);
            dp2[u]+=dp2[v];
        }
    }
    addedge(u+n,p+n,dp2[u]-b[u]);
}
bool bfs(){
    memset(dist,-1,sizeof dist);
    queue<int>q;
    q.push(source);
    dist[source]=0;
    while(q.size()){
        int u=q.front(); q.pop();
        for(auto [v,rev,flow,cap]:g[u]){
            if(dist[v]<0&&flow<cap){
                dist[v]=dist[u]+1;
                q.push(v);
            }
        }
    }
    return dist[sink]>0;
}
int dfs(int u,int fl){
    if(u==sink){
        return fl;
    }
    for(int &s=work[u];s<g[u].size();s++){
        edge &e=g[u][s];
        int v=e.to;
        if(dist[v]==dist[u]+1&&e.flow<e.cap){
            int df=dfs(v,min(fl,e.cap-e.flow));
            if(df<=0) continue;
            e.flow+=df;
            g[v][e.rev].flow-=df;
            return df;
        }
    }
    return 0;
}
