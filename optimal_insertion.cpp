inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,a[N],b[N],p[N],pre[N],suf[N],c[N],bit[N],cnt,t,sz;
int find_pos(int l,int r,int b){
    pre[l-1]=0;
    pre[r+1]=0;
    for(int i=l;i<=r;i++) pre[i]=pre[i-1]+(a[i]>b);
    for(int i=r;i>=l;i--) suf[i]=suf[i+1]+(b>a[i]);
    int pos=l;
    for(int i=l+1;i<=r;i++){
        if(pre[pos-1]+suf[pos]>pre[i-1]+suf[i]) pos=i;
    }
    return pos;
}
void dnc(int l,int r,int optl,int optr){
    if(l>r) return;
    int mid=(l+r)>>1;
    p[mid]=find_pos(optl,optr,b[mid]);
    dnc(l,mid-1,optl,p[mid]);
    dnc(mid+1,r,p[mid],optr);
}
void up(int i,int k){
    for(;i<=cnt;i+=i&-i){
        bit[i]+=k;
    }
}
ll get(int i){
    ll res=0;
    for(;i;i-=i&-i){
        res+=bit[i];
    }
    return res;
}
int compress_c() {
    vector<int>tmp(c+1,c+sz+1);
    sort(tmp.begin(), tmp.end());
    tmp.erase(unique(tmp.begin(),tmp.end()),tmp.end());
    for(int i=1;i<=sz;++i) c[i]=lower_bound(tmp.begin(),tmp.end(),c[i])-tmp.begin()+1;
    return tmp.size();
}
