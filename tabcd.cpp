map<vector<int>,int>dist;
void bfs(){
    queue<vector<int>>q;
    q.push(a);
    dist[a]=0;
    while(q.size()){
        vector<int>u=q.front(); q.pop();
        if(*max_element(all(u))==0){
            cout<<dist[u];
            return;
        }
        for(int i=0;i<u.size()-3;i++){
            vector<int>nxt=u;
            int A=nxt[i];
            int B=nxt[i+1];
            int C=nxt[i+2];
            int D=nxt[i+3];
            nxt[i]=abs(A-B);
            nxt[i+1]=abs(B-C);
            nxt[i+2]=abs(C-D);
            nxt[i+3]=abs(D-A);
            if(dist.find(nxt)==dist.end()){
                dist[nxt]=dist[u]+1;
                q.push(nxt);
            }
            else{
                if(dist[nxt]>dist[u]+1){
                    dist[nxt]=dist[u]+1;
                    q.push(nxt);
                }
            }
        }
    }
}
