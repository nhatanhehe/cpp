inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll a,b,c,d,t;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>a>>b>>c>>d;
        vector<ll>cnt={a,b,c};
        sort(all(cnt),greater<ll>());
        a=cnt[0];
        b=cnt[1];
        c=cnt[2];
        ll dif1=a-b;
        if(dif1>=d){
            cout<<""<<(a-d)*b*c<<'\n';
        }
        else{
            d-=dif1;
            ll dif2=2*b-2*c;
            if(dif2>=d){
                ll x=d/2;
                if(d&1){
                    cout<<""<<(b-x)*(b-x-1)*c<<'\n';
                }
                else cout<<""<<(b-x)*(b-x)*c<<'\n';
            }
            else{
                d-=dif2;
                ll x=d/3;
                if(d%3==0){
                    cout<<""<<(c-x)*(c-x)*(c-x)<<'\n';
                }
                else if(d%3==1){
                    cout<<""<<(c-x)*(c-x)*(c-x-1)<<'\n';
                }
                else if(d%3==2){
                    cout<<(c-x)*(c-x-1)*(c-x-1)<<'\n';
                }
            }
        }
    }
}
