inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
const int BLOCK_SIZE=400;
ll n,a[N],p,q,tax,total,k;
vector<vector<ll>>block;
inline void add(ll val){
    tax+=val*val;
}
inline void del(ll val){
    tax-=val*val;
}
ii fb(ll n){
    int b=0;
    while(b<block.size()&&block[b].size()<=n){
        n-=block[b].size();
        b++;
    }
    if(b==block.size()){
        b--;
        n=block[b].size();
    }
    return ii(b,n);
}
ll gval(ll n){
    auto [b,p]=fb(n);
    return block[b][p];
}
void up(int pos,ll k){
    auto [b,p]=fb(pos);
    del(block[b][p]);
    block[b][p]+=k;
    add(block[b][p]);
}
void ins(int pos,ll k){
    auto [b,p]=fb(pos);
    total++;
    block[b].insert(block[b].begin()+p,k);
    add(k);
    if(block[b].size()>2*BLOCK_SIZE){
        vector<ll>nw(block[b].begin()+BLOCK_SIZE,block[b].end());
        block[b].resize(BLOCK_SIZE);
        block.insert(block.begin()+b+1,nw);
    }
}
void ers(int pos){
    auto [b,p]=fb(pos);
    total--;
    del(block[b][p]);
    block[b].erase(block[b].begin()+p);
    if(block[b].empty()) block.erase(block.begin()+b);
}
