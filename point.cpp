#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,x[N],y[N];
map<ii,int>mp,freq;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>x[i]>>y[i];
    }
    ll ans=0,res=0;
    for(int i=1;i<=n;i++){
        map<ii,int> mp;
        int same=0;
        for(int j=1;j<=n;j++){
            if(i==j) continue;
            ll dx=x[j]-x[i];
            ll dy=y[j]-y[i];
            if(dx==0 && dy==0){
                same++;
                continue;
            }
            ll g=__gcd(dx,dy);
            dx/=g; dy/=g;
            if(dy<0 || (dy==0 && dx<0)){
                dx=-dx; dy=-dy;
            }
            mp[{dx,dy}]++;
        }
        for(auto &p:mp){
            ll cnt=p.se;
            ans+=1LL*cnt*(cnt-1)/2;
            ans+=1LL*cnt*same;
        }
        if(same>=2) ans+=1LL*same*(same-1)/2;
    }
    ans/=3;
    cout<<ans+res/3;
}
