inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int in[N],out[N],n,u,v,timer,q,r,h[N],p[N][20];
vector<int>g[N];

void dfs(int u,int par){
    in[u]=++timer;
    for(int v:g[u]){
        if(v!=par){
            h[v]=h[u]+1;
            p[v][0]=u;
            dfs(v,u);
        }
    }
    out[u]=timer;
}
bool is_acs(int u,int v){
    return in[u]<=in[v]&&out[v]<=out[u];
}

int lca(int u,int v){
    if(h[u]<h[v]) swap(u,v);
    for(int i=19;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)) u=p[u][i];
    }
    if(u==v) return u;
    for(int i=19;i>=0;i--){
        if(p[u][i]!=p[v][i]){
            u=p[u][i];
            v=p[v][i];
        }
    }
    return p[u][0];
}

int get(int x,int y,int z){
    int X=lca(y,z);
    int Y=lca(x,z);
    int Z=lca(x,y);
    return max({ii(h[X],X),ii(h[Y],Y),ii(h[Z],Z)}).se;
}

