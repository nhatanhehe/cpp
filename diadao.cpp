struct SegTree{
    vector<int>lz,tree;
    int n;
    void init(int _n){
        n=_n;
        lz.resize(4*n+4,-1);
        tree.resize(4*n+4,1);
    }
    void fix(int id,int k){
        tree[id]&=k;
        lz[id]&=k;
    }

    void push(int id){
        if(lz[id]!=-1){
            fix(id*2,lz[id]);
            fix(id*2+1,lz[id]);
            lz[id]=-1;
        }
    }

    void up(int id,int l,int r,int u,int v,int k){
        if(l>v||r<u) return;
        if(l<=u&&r<=v){
            fix(id,k);
            return;
        }
        push(id);
        int mid=(l+r)>>1;
        up(id*2,l,mid,u,v,k);
        up(id*2,mid+1,r,u,v,k);
    }

    int get(int id,int l,int r,int pos){
        if(l==r){
            return tree[id];
        }
        push(id);
        int mid=(l+r)>>1;
        if(pos<=mid) return get(id*2,l,mid);
        else return get(id*2+1,mid+1,r);
    }
};
