inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,w[N],h[N],p[N][20],k,dp[N],u,v,Max[N][20];
vector<int>g[N];
void dfs(int u,int par){
    for(int v:g[u]){
        if(v!=par){
            h[v]=h[u]+1;
            p[v][0]=u;
            Max[v][0]=max(w[v], w[u]);
            dfs(v,u);
        }
    }
}
ii lca(int u,int v){
    ll res=0;
    if(h[u]<h[v]) swap(u,v);
    for(int i=19;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)){
            res=max(res,Max[u][i]);
            u=p[u][i];
        }
    }
    if(u==v) return ii(u,res);
    for(int i=19;i>=0;i--){
        if(p[u][i]!=p[v][i]){
            res=max({res,Max[u][i],Max[v][i]});
            u=p[u][i];
            v=p[v][i];
        }
    }
    return ii(p[u][0],max({res,Max[u][0],Max[v][0]}));
}
