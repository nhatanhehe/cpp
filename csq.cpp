#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "csq"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=4e2+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n,k,x,y;
bitset<404>row[N][2],col[N][2],fo[N];
bitset<404>get(int l,int r,bitset<404>b){
    int len=r-l+1;
    return (b&(fo[len]<<l))>>l;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n>>k;
    for(int i=1;i<=401;i++){
        for(int j=0;j<i;j++){
            fo[i].set(j);
        }
    }
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            row[i][0].set(j);
            row[i][1].set(j);
        }
    }
    for(int i=1;i<=n;i++){
        for(int j=1;j<=m;j++){
            col[i][0].set(j);
            col[i][1].set(j);
        }
    }
    for(int i=1;i<=k;i++){
        cin>>x>>y;
        row[x][0].reset(y);
        row[x][1].reset(n-y+1);
        col[y][0].reset(x);
        col[y][1].reset(m-x+1);
    }
    ll ans=0;
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            for(int len=2;len+i<=m&&len+j<=n;len++){
                bitset<404>top=get(j+1,j+len-1,row[i][0]);
                bitset<404>bot=get(n-(j+len-1)+1,n-(j+1)+1,row[i+len][1]);
                bitset<404>l=get(m-(i+len-1)+1,m-(i+1)+1,col[j][1]);
                bitset<404>r=get(i+1,i+len-1,col[j+len][0]);
                ans+=(top&bot&l&r).count();
            }
        }
    }
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            for(int len=1;len+i<=m&&len+j<=n;len++){
                if(!row[i][0][j]||!row[i][0][j+len]||!row[i+len][0][j]||!row[i+len][0][j+len]) continue;
                ans++;
            }
        }
    }
    cout<<ans;
}
