inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,k,a[505][505],pre[505][505];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
            pre[i][j]=pre[i][j-1]+a[i][j];
        }
    }
    ll ans=inf;
    for(int i=1;i<=n-k+1;i++){
        for(int j=1;j<=n-k+1;j++){
            ll sum1=0,sum2=0,cur=j;
            for(int x=i;x<=i+k-1;x++){
                if(cur+1<=j+k-1){
                    sum1+=pre[x][j+k-1]-pre[x][cur];
                }
                if(cur-1>=j){
                    sum2+=pre[x][cur-1]-pre[x][j-1];
                }
                cur++;
            }
            ans=min(ans,abs(sum1-sum2));
        }
    }
    cout<<ans;
}
