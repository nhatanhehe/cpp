const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,tree[20][N<<2][2],lz[20][N<<2],a[N],x,l,r,tp;
void build(int bit,int id=1,int l=1,int r=n){
    if(l==r){
        tree[bit][id][(a[l]>>bit)&1]=1;
        return;
    }
    int mid=(l+r)>>1;
    build(bit,id*2,l,mid);
    build(bit,id*2+1,mid+1,r);
    for(int i=0;i<=1;i++) tree[bit][id][i]=tree[bit][id*2][i]+tree[bit][id*2+1][i];
}
inline void fix(int bit,int id,int k){
    if(k&1){
        swap(tree[bit][id][0],tree[bit][id][1]);
    }
    lz[bit][id]^=k;
}
inline void push(int bit,int id){
    if(lz[bit][id]){
        fix(bit,id*2,lz[bit][id]);
        fix(bit,id*2+1,lz[bit][id]);
    }
    lz[bit][id]=0;
}
void up(int bit,int u,int v,int id=1,int l=1,int r=n){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
        fix(bit,id,1);
        return;
    }
    push(bit,id);
    int mid=(l+r)>>1;
    up(bit,u,v,id*2,l,mid);
    up(bit,u,v,id*2+1,mid+1,r);
    for(int i=0;i<=1;i++) tree[bit][id][i]=tree[bit][id*2][i]+tree[bit][id*2+1][i];
}
int get(int bit,int u,int v,int id=1,int l=1,int r=n){
    if(l>v||r<u) return 0;
    if(u<=l&&r<=v){
        return tree[bit][id][1];
        //return;
    }
    push(bit,id);
    int mid=(l+r)>>1;
    return get(bit,u,v,id*2,l,mid)+get(bit,u,v,id*2+1,mid+1,r);
}
