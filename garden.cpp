#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=3e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],t;
ii f[N][23];
bool check(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    int Min=min(f[l][k].fi,f[r-(1<<k)+1][k].fi);
    int Max=max(f[l][k].se,f[r-(1<<k)+1][k].se);
    return Max-Min<=t;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        f[i][0].fi=a[i];
        f[i][0].se=a[i];
    }
    for(int j=1;j<=22;j++){
        for(int i=1;i+(1<<(j-1))<=n;i++){
            f[i][j].fi=min(f[i][j-1].fi,f[i+(1<<(j-1))][j-1].fi);
            f[i][j].se=max(f[i][j-1].se,f[i+(1<<(j-1))][j-1].se);
        }
    }
    int l=1,ans=0;
    for(int r=1;r<=n;r++){
        while(!check(l,r)){
            l++;
        }
        if(l<=r){
            ans=max(ans,r-l+1);
        }
    }
    cout<<ans;
}
