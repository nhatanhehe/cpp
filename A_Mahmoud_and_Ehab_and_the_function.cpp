set<int>s;
int calc(int S){
    auto it=s.upper_bound(-S);
    int Min=inf;
    if(it!=s.end()){
        Min=abs(S+(*it));
    }
    if(it!=s.begin()){
        Min=min(Min,abs(S+(*prev(it))));
    }
    return Min;
}
