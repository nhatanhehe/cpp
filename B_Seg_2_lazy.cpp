inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,q,l,r,x,a[N];
struct SegmentTree{
    vector<ll>lz1,lz2,tree;
    vector<bool>rem;
    int n;
    void init(int _n){
        n=_n;
        lz1.resize(4*n+10,0);
        lz2.resize(4*n+10,0);
        tree.resize(4*n+10,0);
        rem.resize(4*n+10,0);
    }
    void build(int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l==r){
            tree[id]=a[l];
            return;
        }
        int mid=(l+r)>>1;
        build(id*2,l,mid);
        build(id*2+1,mid+1,r);
        tree[id]=tree[id*2]+tree[id*2+1];
    }
    void fix1(int id,int l,int r,ll k){
        tree[id]+=(r-l+1)*k;
        lz1[id]+=k;
    }
    void fix2(int id,int l,int r,ll k){
        tree[id]=(r-l+1)*k;
        lz2[id]=k;
        rem[id]=1;
        lz1[id]=0;
    }
    void push(int id,int l,int r){
        if(rem[id]){
            int mid=(l+r)>>1;
            fix2(id*2,l,mid,lz2[id]);
            fix2(id*2+1,mid+1,r,lz2[id]);
            lz2[id]=0;
            rem[id]=0;
        }
        if(lz1[id]){
            int mid=(l+r)>>1;
            fix1(id*2,l,mid,lz1[id]);
            fix1(id*2+1,mid+1,r,lz1[id]);
            lz1[id]=0;
        }
        
    }
    void up1(int u,int v,ll k,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return;
        if(u<=l&&r<=v){
            fix1(id,l,r,k);
            return;
        }
        push(id,l,r);
        int mid=(l+r)>>1;
        up1(u,v,k,id*2,l,mid);
        up1(u,v,k,id*2+1,mid+1,r);
        tree[id]=tree[id*2]+tree[id*2+1];
    }
    void up2(int u,int v,ll k,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return;
        if(u<=l&&r<=v){
            fix2(id,l,r,k);
            return;
        }
        push(id,l,r);
        int mid=(l+r)>>1;
        up2(u,v,k,id*2,l,mid);
        up2(u,v,k,id*2+1,mid+1,r);
        tree[id]=tree[id*2]+tree[id*2+1];
    }
    ll get(int u,int v,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return 0;
        if(u<=l&&r<=v) return tree[id];
        push(id,l,r);
        int mid=(l+r)>>1;
        return get(u,v,id*2,l,mid)+get(u,v,id*2+1,mid+1,r);
    }
}seg;
