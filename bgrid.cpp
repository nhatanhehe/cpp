const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,P,t[N],w[N],p1[N],p2[N],q,s1[N],s2[N];
struct Ans{
    int x,y,pos;
}Q[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>P;
    for(int i=1;i<=P;i++){
        cin>>t[i]>>w[i];
    }
    cin>>q;
    for(int i=1;i<=q;i++){
        cin>>Q[i].x>>Q[i].y;
        Q[i].pos=i;
    }
    sort(Q+1,Q+q+1,[&](const Ans &x,const Ans &y){
        return max(x.x,x.y)<max(y.x,y.y);
    });
    for(int i=1;i<=q;i++){
        p1[Q[i].pos]=i;
    }
    for(int i=1;i<=P;i++){
        if(t[i]==1){
            int l=1,r=q,pos=-1;
            while(l<=r){
                int mid=(l+r)>>1;
                int mx=max(Q[mid].x,Q[mid].y);
                if(mx<=w[i]){
                    l=mid+1;
                    pos=mid;
                }
                else r=mid-1;
            }
            if(pos!=-1){
                s1[1]++;
                s1[pos+1]--;
            }
        }
    }
    for(int i=1;i<=q;i++) s1[i]+=s1[i-1];
    sort(Q+1,Q+q+1,[&](const Ans &x,const Ans &y){
        return min(x.x,x.y)<min(y.x,y.y);
    });
    for(int i=1;i<=q;i++){
        p2[Q[i].pos]=i;
    }
    for(int i=1;i<=P;i++){
        if(t[i]==2){
            int l=1,r=q,pos=-1;
            while(l<=r){
                int mid=(l+r)>>1;
                int mn=min(Q[mid].x,Q[mid].y);
                if(mn>=w[i]){
                    r=mid-1;
                    pos=mid;
                }
                else l=mid+1;
            }
            if(pos!=-1) s2[pos]++;
        }
    }
    for(int i=1;i<=q;i++) s2[i]+=s2[i-1];
    sort(Q+1,Q+q+1,[&](const Ans &x,const Ans &y){
        return x.pos<y.pos;
    });
    for(int i=1;i<=q;i++){
        cout<<(s1[p1[i]]+s2[p2[i]])%2<<'\n';
    }
}
