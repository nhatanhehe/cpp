const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    if(res<0) res+=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],smx[N],smn[N],pre[N];
ll ans;
void dnc(int l,int r){
    if(l==r){
        ans=add(ans,mul(a[l],a[l]));
        return;
    }
    int mid=(l+r)>>1;
    dnc(l,mid);
    dnc(mid+1,r);
    smx[mid]=smn[mid]=pre[mid]=0;
    int mn=1e9,mx=-1e9;
    for(int i=mid+1;i<=r;i++){
        mn=min(mn,a[i]);
        mx=max(mx,a[i]);
        smx[i]=add(smx[i-1],mx);
        smn[i]=add(smn[i-1],mn);
        pre[i]=add(pre[i-1],mx*mn);
    }
    int j=mid+1,k=mid+1;mx=-1e9,mn=1e9;
    for(int i=mid;i>=l;i--){
        mx=max(mx,a[i]);
        mn=min(mn,a[i]);
        while(j<=r&&a[j]>=mn) j++;
        while(k<=r&&a[k]<=mx) k++;
        if(j<k){
            ans=add(ans,mul(j-mid-1,mul(mn,mx)));
            ans=add(ans,mul(sub(smn[k-1],smn[j-1]),mx));
            ans=add(ans,sub(pre[r],pre[k-1]));
        }
        else{
            ans=add(ans,mul(k-mid-1,mul(mx,mn)));
            ans=add(ans,mul(sub(smx[j-1],smx[k-1]),mn));
            ans=add(ans,sub(pre[r],pre[j-1]));
        }
    }
    return;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    dnc(1,n);
    cout<<ans;
}
