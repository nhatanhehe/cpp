#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=5e3+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,a[N],cost[N][N],pre[N],dp_cur[N],dp_before[N];
void dnc(int l,int r,int optl,int optr){
    if(l>r) return;
    int mid=(l+r)>>1;
    ii best={1e9,-1};
    for(int i=optl;i<=min(optr,mid);i++){
        best=min(best,ii(dp_before[i]+cost[i+1][mid],i));
    }
    dp_cur[mid]=best.fi;
    dnc(l,mid-1,optl,best.se);
    dnc(mid+1,r,best.se,optr);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    sort(a+1,a+n+1);
    for(int i=1;i<=n;i++) pre[i]=pre[i-1]+a[i];
    for(int l=1;l<=n;l++){
        for(int r=l;r<=n;r++){
            int m=(l+r)>>1;
            cost[l][r]=(m-l+1)*a[m]-(pre[m]-pre[l-1])+(pre[r]-pre[m])-(r-m)*a[m];
        }
    }
    for(int i=1;i<=n;i++) dp_before[i]=1e9;
    for(int i=1;i<=k;i++){
        dnc(0,n,0,n);
        for(int j=0;j<=n;j++){
            dp_before[j]=dp_cur[j];
        }
    }
    cout<<dp_before[n];
}
