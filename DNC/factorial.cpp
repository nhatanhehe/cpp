#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "factorial"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e6+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b,ll mod){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m;
vector<int>prime;
int p[N];
void sang(){
    memset(p,1,sizeof p);
    p[0]=p[1]=0;
    for(int i=2;i<=sqrt(1e6);i++){
        if(p[i]){
            for(int j=i*i;j<=1e6;j+=i) p[j]=0;
        }
    }
    for(int i=2;i<=1e6;i++){
        if(p[i]){
            prime.pb(i);
        }
    }
}
int cnt[N],cnt_m[N];
ll exp(int a,int n,int mod){
    if(n==1) return a%mod;
    if(n==0) return 1;
    ll t=exp(a,n/2,mod);
    if(n&1) return mul(a,mul(t,t,mod),mod);
    return mul(t,t,mod);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    sang();
    for(int pr:prime){
        for(ll x=pr;x<=n;x*=pr){
           cnt[pr]+=(n/x);
        }
        //if(cnt[pr])cerr<<pr<<" "<<cnt[pr]<<"\n";
    }
    int tmp=m;
    for(int i=2;i<=sqrt(tmp);i++){
        while(tmp%i==0){
            cnt_m[i]++;
            tmp/=i;
        }
    }
    if(tmp>1) cnt_m[tmp]++;
    for(int pr:prime){
        int mn=min(cnt[pr],cnt_m[pr]);
        cnt[pr]-=mn;
        cnt_m[pr]-=mn;
        while(mn--){
            m/=pr;
        }
    }
    // a/b = a%mod*exp(b,mod-2)
    ll rem=1;
    for(int pr:prime){
        rem=mul(rem,exp(pr,cnt[pr],m),m);
    }
    ll rem_2=1;
    for(int pr:prime){
        rem_2=mul(rem_2,exp(pr,cnt[pr],mod),mod);
    }
    cout<<mul(sub(rem_2,rem),exp(m,mod-2,mod),mod);
}
