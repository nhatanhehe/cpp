#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int dp[N],n,u,v,t,w,up[N],sz[N],sz_up[N];
vector<ii>g[N];
void dfs(int u,int p){
    sz[u]=1;
    for(auto [v,w]:g[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]+=w*sz[v]+dp[v];
            sz[u]+=sz[v];
        }
    }
}
void reroot(int u,int p){
    for(auto [v,w]:g[u]){
        if(v!=p){
            sz_up[v]=sz_up[u]+sz[u]-sz[v];
            up[v]=dp[u]-(w*sz[v]+dp[v])+up[u]+sz_up[u]*w+(sz[u] - sz[v]) * w;
            reroot(v,u);
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n;
        for(int i=1;i<n;i++){
            cin>>u>>v>>w;
            g[u].pb({v,w});
            g[v].pb({u,w});
        }
        dfs(1,-1);
        reroot(1,-1);
        for(int i=1;i<=n;i++){
            cout<<dp[i]+up[i]<<'\n';
        }
        for(int i=1;i<=n;i++){
            dp[i]=up[i]=sz[i]=sz_up[i]=0;
            g[i].clear();
        }
    }
}
