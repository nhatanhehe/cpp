inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,xa,xb,xc,xd,ya,yb,yc,yd,Uma,Umi,Vma,Vmi;
ll calc(ll l,ll r,ll rem){
    while(abs(l%2)!=rem) l++;
    while(abs(r%2)!=rem) r--;
    // 3 6 -> 3 5
    return (r-l)/2+1;
}
