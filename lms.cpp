#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e6+5;
const ll mod=1e6+3;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int q,ans,tree[N<<2],lz[N<<2],cnt[N],ope;
char tp;
ii op[N];
void fix(int id,int k){
    tree[id]+=k;
    lz[id]+=k;
}
void push(int id){
    if(lz[id]){
        fix(id*2,lz[id]);
        fix(id*2+1,lz[id]);
        lz[id]=0;
    }
}
void up(int u,int v,int k,int id=1,int l=0,int r=1e6+3){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
        fix(id,k);
        return;
    }
    push(id);
    int mid=(l+r)>>1;
    up(u,v,k,id*2,l,mid);
    up(u,v,k,id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>q;
    while(q--){
        cin>>tp;
        if(tp=='A'){
            int s,t;
            cin>>s>>t;
            s=(s+ans)%mod;
            t=(t+ans)%mod;
            op[++ope]=ii(s,t);
            cnt[s]++;
            if(cnt[s]==1){
                up(s,s,s);
            }
            up(1,s,t);
        }
        else{
            int pos;
            cin>>pos;
            pos=(ans+pos)%mod;
            int s=op[pos].fi,t=op[pos].se;
            cnt[s]--;
            if(!cnt[s]) up(s,s,-s);
            up(1,s,-t);
        }
        cout<<tree[1]-1<<'\n';
        ans=tree[1]-1;

    }
}
