inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,u,v,q,tp,pos[N],sz[N],tree[N*4],a[N],son[N],timer,ri[N],top[N],h[N],par[N];
vector<int>g[N];
void dfs(int u,int p){
    sz[u]=1; par[u]=p;
    for(int v:g[u]){
        if(v!=p){
            h[v]=h[u]+1;
            dfs(v,u);
            sz[u]+=sz[v];
            if(!son[u]||sz[son[u]]<sz[v]){
                son[u]=v;
            }
        }
    }
}
struct Seg{
    int st[N*4];

    void build(int id,int l,int r){
        if(l==r){
            st[id]=ri[l];
            return;
        }
        int mid=(l+r)/2;
        build(id*2,l,mid);
        build(id*2+1,mid+1,r);
        st[id]=max(st[id*2],st[id*2+1]);
    }

    void up(int id,int l,int r,int p,int val){
        if(l==r){
            st[id]=val;
            return;
        }
        int mid=(l+r)/2;
        if(p<=mid) up(id*2,l,mid,p,val);
        else up(id*2+1,mid+1,r,p,val);
        st[id]=max(st[id*2],st[id*2+1]);
    }

    void up(int p,int val){
        up(1,1,n,pos[p],val);
    }

    int query(int id,int l,int r,int ql,int qr){
        if (ql > r || qr < l) return -1e9;
        if(ql<=l&&r<=qr) return st[id];
        int mid=(l+r)/2,ans=-1e9;
        if(ql<=mid) ans=max(ans,query(id*2,l,mid,ql,qr));
        if(qr>mid) ans=max(ans,query(id*2+1,mid+1,r,ql,qr));
        return ans;
    }

    int query(int l,int r){
        return query(1,1,n,l,r);
    }
}seg;
void hld(int u,int tp){
    pos[u]=++timer;
    top[u]=tp;
    ri[timer]=a[u];
    if(son[u]) hld(son[u],tp);
    for(int v:g[u]){
        if(v!=par[u]&&v!=son[u]) hld(v,v);
    }
}
int query(int u,int v){
    int ans=-1e9;
    while(top[u]!=top[v]){
        if(h[top[u]]<h[top[v]]) swap(u,v);
        ans=max(ans,seg.query(pos[top[u]],pos[u]));
        u=par[top[u]];
    }
    if(h[u]>h[v]) swap(u,v);
    ans=max(ans,seg.query(pos[u],pos[v]));
    return ans;
}
