#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=6e6+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,a[N],ans,trie[N][2],cur;
void ins(int x){
    int p=0;
    for(int i=29;i>=0;i--){
        int c=(x>>i)&1;
        if(!trie[p][c]){
            trie[p][c]=++cur;
            trie[cur][0]=trie[cur][1]=0;
        }
        p=trie[p][c];
    }
}
int get(int x){
    int p=0;
    int res=0;
    for(int i=29;i>=0;i--){
        int c=(x>>i)&1;
        if(trie[p][c]){
            p=trie[p][c];
        }
        else if(trie[p][c^1]){
            res+=(1<<i);
            p=trie[p][c^1];
        }
        else break;
    }
    return res;
}
void clear(){
    trie[0][0]=trie[0][1]=0;
    cur=0;
}
void dnc(int bit,vector<int>&a){
    if(bit<0) return;
    vector<int>ones,zeros;
    for(int x:a){
        if((x>>bit)&1) ones.pb(x);
        else zeros.pb(x);
    }
    if(ones.empty()||zeros.empty()) return dnc(bit-1,a);
    clear();
    for(int x:zeros){
        ins(x);
    }
    ll Min=1e9;
    for(int x:ones){
        Min=min(Min,1LL*get(x));
    }
    ans+=Min;
    dnc(bit-1,ones);
    dnc(bit-1,zeros);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    vector<int>b;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        b.pb(a[i]);
    }
    dnc(29,b);
    cout<<ans;
}
