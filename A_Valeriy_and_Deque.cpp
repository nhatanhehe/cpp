#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=3e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,q,a[N],m;
deque<int>dq;
ii op[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q;
    int Max=0;
    for(int i=1;i<=n;i++){
        int x;
        cin>>x;
        Max=max(Max,x);
        dq.pb(x); 
    }
    int cnt=0;
    while(dq.front()!=Max){
        cnt++;
        int a=dq.front();
        dq.pop_front();
        int b=dq.front();
        dq.pop_front();
        op[cnt]=ii(a,b);
        if(a>b) dq.push_front(a), dq.pb(b);
        else dq.push_front(b), dq.pb(a);
    }
    while(q--){
        cin>>m;
        if(m<=cnt) cout<<op[m].fi<<" "<<op[m].se<<'\n';
        else{
            m-=cnt;
            m%=n;
            cout<<dq[0]<<" "<<dq[m]<<'\n';
        }
    }
}
