inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N];
ll pre[N];
vector<int>dp[N],pref[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        pre[i]=pre[i-1]+a[i];
    }
    for(int i=1;i<=n;i++){
        pref[i].resize(i+1,0);
        dp[i].resize(i+1,0);
        for(int j=i;j>=1;j--){
            if(j==1) dp[i][j]=1;
            else{
                int l=1,r=j-1,ans=-1;
                while(l<=r){
                    int mid=(l+r)>>1;
                    if(pre[j-1]-pre[mid-1]<=pre[i]-pre[j-1]){
                        r=mid-1;
                        ans=mid;
                    }
                    else l=mid+1;
                }
                if(ans!=-1){
                    dp[i][j]=sub(pref[j-1][j-1],pref[j-1][ans-1]);
                }
            }
        }
        for(int j=1;j<=i;j++){
            pref[i][j]=(pref[i][j-1]+dp[i][j])%mod;
        }
    }
    cout<<pref[n][n];
}
