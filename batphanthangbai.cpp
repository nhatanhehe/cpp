#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=3e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b,ll mod){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b,ll mod){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,p,r[N],y[N],t[N],g[N],v[N],check[N],dp[N];
bitset<100005>sum_r,sum_y;
vector<ll>seq[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>p;
    sum_r[0]=1;
    sum_y[0]=1;
    for(int i=1;i<=n;i++){
        cin>>r[i];
        sum_r|=(sum_r<<r[i]);
    }
    for(int i=1;i<=n;i++){
        cin>>y[i];
        sum_y|=(sum_y<<y[i]);
    }
    for(int i=1;i<=m;i++){
        cin>>t[i];
    }
    for(int i=1;i<=m;i++){
        cin>>g[i];
    }
    for(int i=1;i<=m;i++){
        cin>>v[i];
    }
    int cnt=0;
    for(int i=1;i<=m;i++){
        if(sum_r[t[i]]&&sum_y[g[i]]){
            check[i]=1;
            if(!check[i-1]){
                cnt++;
                seq[cnt].pb(i);
            }
            else seq[cnt].pb(i);
        }
    }
    ll ans=0;
    for(int cnt_=1;cnt_<=cnt;cnt_++){
        for(int i=0;i<seq[cnt_].size();i++){
            dp[i+1]=0;
        }
        dp[0]=0;
        for(int i=0;i<seq[cnt_].size();i++){
            dp[i+1]=add(dp[i+1],mul(v[seq[cnt_][i]],add(dp[i],1,p),p),p);
        }
        for(int i=0;i<seq[cnt_].size();i++){
            ans=add(ans,dp[i+1],p);
        }
    }
    cout<<ans;
}
