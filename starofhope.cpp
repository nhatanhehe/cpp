const ll inf=1e18;
const ll N=2e3+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,m,n,dist[N][N][2],p,q,button[N][N],ban[N][N];
struct pt{
    int u,v,dir;
};
int dx[]={-1,1,0,0};
int dy[]={0,0,-1,1};
bool inside(int x,int y){
    return 1<=x&&x<=m&&1<=y&&y<=n;
}
void solve(){
        cin>>m>>n>>p>>q;
        for(int i=1;i<=m;i++){
            for(int j=1;j<=n;j++){
                dist[i][j][0]=dist[i][j][1]=1e9;
                button[i][j]=ban[i][j]=0;
            }
        }
        for(int i=1;i<=p;i++){
            int x,y;
            cin>>x>>y;
            button[x][y]=1;
        }
        for(int i=1;i<=q;i++){
            int x,y,u,v;
            cin>>x>>y>>u>>v;
            ban[u][v]+=1;
            ban[x-1][v]-=1;
            ban[u][y-1]-=1;
            ban[x-1][y-1]+=1;
        }
        for(int i=m;i>=1;i--){
            for(int j=n;j>=1;j--){
                ban[i][j]=ban[i+1][j]+ban[i][j + 1]-ban[i+1][j+1]+ban[i][j];
            }
        }
        queue<pt>q;
        dist[1][1][0]=0;
        q.push({1,1,0});
        while(q.size()){
            auto [u,v,dir]=q.front();
            q.pop();
            if(u==m&&v==n){
                cout<<dist[u][v][dir]<<'\n';
                return;
            }
            if(button[u][v]){
                if(dist[u][v][dir^1]>dist[u][v][dir]+1){
                    dist[u][v][dir^1]=dist[u][v][dir]+1;
                    q.push({u,v,dir^1});
                }
            }
            if(!dir){
                for(int k=0;k<2;k++){
                    int x=u+dx[k],y=v+dy[k];
                    if(inside(x,y)&&!ban[x][y]){
                        if(dist[x][y][dir]>dist[u][v][dir]+1){
                            dist[x][y][dir]=dist[u][v][dir]+1;
                            q.push({x,y,dir});
                        }
                    }
                }
            }
            else{
                for(int k=2;k<4;k++){
                    int x=u+dx[k],y=v+dy[k];
                    if(inside(x,y)&&!ban[x][y]){
                        if(dist[x][y][dir]>dist[u][v][dir]+1){
                            dist[x][y][dir]=dist[u][v][dir]+1;
                            q.push({x,y,dir});
                        }
                    }
                }
            }
        }
        cout<<-1<<'\n';
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        solve();
    }
}
