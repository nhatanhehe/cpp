inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a,b,dp[N][2],u,v,w;
vector<ii>g[N];
void dfs(int u,int p){
    int best1=0,best2=0,val=0,sum=0;
    for(auto [v,w]:g[u]){
        if(v!=p){
            dfs(v,u);
            sum+=dp[v][0];
            val=w+dp[v][1]-dp[v][0];
            if(val>0){
                if(best1<val){
                    best2=best1;
                    best1=val;
                }
                else if(best2<val) best2=val;
            }
        }
    }
    dp[u][0]=sum+best1+best2;
    dp[u][1]=sum+best1;
}
