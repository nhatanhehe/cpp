inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
vector<int>leaf;
int n,t,u,v;
vector<int>g[N],h,par,out;
queue<int>q;
void dfs(int u,int p){
    if(g[u].size()==1&&u!=n) leaf.pb(u); 
    for(int v:g[u]){
        if(v!=p){
            par[v]=u;
            h[v]=h[u]^1;
            dfs(v,u);
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n;
        h.assign(n+4,0);
        par.assign(n+4,0);
        out.assign(n+4,0);
        leaf.clear();
        for(int i=1;i<=n;i++){
            g[i].clear();
        }
        for(int i=1;i<n;i++){
            cin>>u>>v;
            out[u]++;
            out[v]++;
            g[u].pb(v);
            g[v].pb(u);
        }
        dfs(n,-1);
        int curr=h[1];
        vector<ii>ans;
        //for(int x:leaf) cout<<x<<' '; cout<<'\n';
        while(leaf.size()){
           // cout<<curr<<" "<<h[leaf.back()]<<" "<<leaf.back()<<'\n';
            //for(int id:leaf) cout<<id<<" "; cout<<'\n';
            if(h[leaf.back()]==curr){
                ans.pb(ii(1,-1));
                ans.pb(ii(2,leaf.back()));
                curr^=1;
                int p=par[leaf.back()];
                leaf.pop_back();
                if(--out[p]==1&&p!=n) leaf.pb(p),debug(p);
            }
            else{
                ans.pb(ii(1,-1));
                ans.pb(ii(1,-1));
                ans.pb(ii(2,leaf.back()));
                int p=par[leaf.back()];
                leaf.pop_back();
                if(--out[p]==1&&p!=n) leaf.pb(p), debug(p);
                //cout<<leaf.back()<<'\n';
            }
        }
        cout<<ans.size()<<'\n';
        for(auto [a,b]:ans){
            if(a==1) cout<<a<<"\n";
            if(a==2) cout<<a<<" "<<b<<'\n';
        }
    }
}
