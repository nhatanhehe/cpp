#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,p[N],dp[N],up[N];
vector<int>g[N];
void dfs(int u,int p){
    dp[u]=1;
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]=mul(dp[u],add(dp[v],1));
        }
    }
}
ll exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    ll t=exp(a,n/2);
    if(n&1) return mul(t,mul(t,a));
    return mul(t,t);
}
void reroot(int u,int p){
    vector<int>pre(g[u].size()+3,1),suf(g[u].size()+3,1);
    for(int i=0;i<g[u].size();i++){
        pre[i+1]=pre[i];
        if(g[u][i]!=p){
            pre[i+1]=mul(pre[i],add(dp[g[u][i]],1));
        }
    }
    for(int i=g[u].size()-1;i>=0;i--){
        suf[i]=suf[i+1];
        if(g[u][i]!=p) suf[i]=mul(suf[i],add(dp[g[u][i]],1));
    }
    for(int i=0;i<g[u].size();i++){
        if(g[u][i]!=p){
            ll exclude_v=mul(pre[i],suf[i+1]);
            up[g[u][i]]=add(mul(up[u],exclude_v),1);
            reroot(g[u][i],u);
        }
    }
}
