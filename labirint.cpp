#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,dist[N][N][17],q;
inline int id(int i,int j){
    return (i-1)*m+j;
}
inline ii dec(int id) {
    return ii((id-1)/m+1,(id-1)%m+1);
}
vector<ic>g[N*N];
//P, C, Z ,N
int cc['Z'+1];
int bfs(int a,int b,int c,int d){
    dist[a][b][0]=0;
    queue<tuple<int,int,int>>q;
    q.push({a,b,0});
    int min_col=5;
    while(q.size()){
        auto [u,v,mask]=q.front();
        q.pop();
        if(u==c&&v==d){
            min_col=min(min_col,__builtin_popcount(mask));
            continue;
        }
        for(auto [idx,col]:g[id(u,v)]){
            auto [x,y]=dec(idx);
            if(dist[x][y][On(mask,cc[col])]>dist[u][v][mask]+1){
                dist[x][y][On(mask,cc[col])]=dist[u][v][mask]+1;
                q.push({x,y,On(mask,cc[col])});
            }
        }
    }
    return min_col;
}
