void dnc(int l,int r,vector<int>&cur){
    cnt++;
    if(cnt==k||l+1>=r) return;
    int mid=(l+r)>>1;
    swap(cur[mid-1],cur[mid]);
    dnc(l,mid-1,cur);
    dnc(mid,r,cur);
}
