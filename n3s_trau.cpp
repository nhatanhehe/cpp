inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=(a%mod)*(b%mod)%mod;
    return res;
}
int t;
ll n,m,k;
ll cnt_rem(ll n,ll rem){
    if(rem>n) return 0;
    return (n-rem)/3+1;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".ans","w", stdout);
    }
    cin>>t;
    //cout<<cnt_rem(1,1)+cnt_rem(1,2)<<'\n';
    while(t--){
        cin>>k>>mod;
        ll l=1,r=1e18,mid,ans;
        while(l<=r){
            mid=(l+r)>>1;
            ll sum=cnt_rem(mid,1)+cnt_rem(mid,2);
            if(sum>=k){
                //debug(sum);
                r=mid-1;
                ans=mid;
                //debug(ans);
            }
            else l=mid+1;
        }
        cout<<sub(mul(ans,ans),1)<<'\n';
    }
}
