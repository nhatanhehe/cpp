#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k;
ld dp_cur[N],dp_before[N];
ll t[N],s[N];
ld A[N],B[N];
ld cost(int l,int r){
    return A[r]-A[l-1]-s[l-1]*(B[r]-B[l-1]);
}
void dnc(int l,int r,int optl,int optr){
    if(l>r) return;
    int mid=(l+r)>>1;
    pair<ld,int>best={inf,-1};
    for(int i=optl;i<=min(mid,optr);i++){
        best=min(best,pair<ld,int>(dp_before[i-1]+cost(i,mid),i));
    }
    dp_cur[mid]=best.fi;
    dnc(l,mid-1,optl,best.se);
    dnc(mid+1,r,best.se,optr);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    for(int i=1;i<=n;i++){
        cin>>t[i];
    }
    for(int i=1;i<=n;i++){
        s[i]=s[i-1]+t[i];
    }
    for(int i=1;i<=n;i++){
        A[i]=A[i-1]+1.0*s[i]/t[i];
    }
    for(int i=1;i<=n;i++){
        B[i]=B[i-1]+1.0/t[i];
    }
    for(int i=1;i<=n;i++){
        dp_before[i]=inf;
    }
    for(int j=1;j<=k;j++){
        dnc(0,n,0,n);
        for(int i=0;i<=n;i++){
            dp_before[i]=dp_cur[i];
        }
    }
    cout<<fixed<<setprecision(10)<<dp_cur[n];
}
