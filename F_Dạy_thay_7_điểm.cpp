#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "noledaden"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,e;
iii x[N];
vector<ii>vec;
int mark[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>e;
    for(int i=1;i<=n;i++){
        cin>>x[i].fi;
    }
    for(int i=1;i<=n;i++){
        cin>>x[i].se.fi; x[i].se.se=i;
    }
     sort(x+1,x+n+1,[&](const iii &a,const iii &b){
        return a.fi<b.fi||(a.fi==b.fi&&a.se.fi-a.fi<b.se.fi-b.fi);
    });
    priority_queue<ii>pq;
    for(int i=1;i<=n;i++){
        if(e>=x[i].fi){
            e-=x[i].fi;
            mark[x[i].se.se]++;
            pq.push({x[i].se.fi-x[i].fi,x[i].se.se});
        }
        else{
            if(x[i].se.fi<pq.top().fi){
                mark[pq.top().se]=0 ;
                mark[x[i].se.se]=2;
                e+=-x[i].se.fi+x[pq.top().se].fi;
                pq.pop();
            }
        }
    }
    while(pq.size()){
        vec.push_back(pq.top());
        pq.pop();
    }
    for(int i=vec.size()-1;i>=0;i--){
        if(e>=vec[i].fi){
            mark[vec[i].se]=2;
            e-=vec[i].fi;
        }
        else break;
    }
    for(int i=1;i<=n;i++) cout<<mark[i];
}
