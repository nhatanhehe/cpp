inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,k,q,a[505][505],x,y;
struct DSU{
    vector<int>p;
    int n;
    void init(int _n){
        n=_n;
        p.resize(n+3,0);
        for(int i=1;i<=n;i++) p[i]=i;
    }
    int acs(int u){
        return u==p[u]? u:p[u]=acs(p[u]);
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            p[v]=u;
        }
    }
}dsu[505];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>k>>q;
    for(int i=1;i<=n;i++){
        dsu[i].init(m+2);
    }
    ll ans=0;
    while(q--){
        cin>>x>>y;
        int u=max(1,x-k);
        int v=min(n,x+k);
        for(int i=u;i<=v;i++){
            int c=k-abs(x-i);
            int mn=max(1,y-c);
            int mx=min(m,y+c);
            int l=mn;
            while(l<=mx){
                l=dsu[i].acs(l);
                if(l>mx) break;
                ans++;
                dsu[i].join(l+1,l);
                l++;
            }
        }
        cout<<ans<<'\n';
    }
}
