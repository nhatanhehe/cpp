#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=1e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k1,k2,a[N];
deque<int>dq;
vector<int>open[N],close[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k1>>k2;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    dq.push_back(0);
    a[0]=1e9;
    for(int i=1;i<=n;i++){
        while(dq.size()&&a[dq.back()]<=a[i]) dq.pop_back();
        dq.pb(i);
        if(dq.size()>k2){
            int l=dq[dq.size()-k2-1]+1;
            int r=dq[dq.size()-k2];
            close[l-1].pb(i);
            open[r].pb(i);
        }
    }
    dq.clear();
    dq.push_front(n+1);
    a[n+1]=1e9;
    set<int>s;
    int ans=-1;
    for(int i=n;i>=1;i--){
        while(open[i].size()){
            s.insert(open[i].back());
            open[i].pop_back();
        }
        while(close[i].size()){
            s.erase(close[i].back());
            close[i].pop_back();
        }
        while(dq.size()&&a[dq.front()]<=a[i]) dq.pop_front();
        dq.push_front(i);
        if(dq.size()>k1){
            int r=dq[k1]-1;
            auto it=s.upper_bound(r);
            if(it!=s.begin()){
                it--;
                ans=max(ans,(*it)-i+1);
            }
        }
    }
    cout<<ans;

}
