#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
vector<ll>cp;
ll n,delta,a[N],dp[N],trace[N];
ii tree[N<<2];
int id(int val){
    return upper_bound(all(cp),val)-cp.begin();
}
void up(int pos,ii k,int id=1,int l=1,int r=cp.size()){
    if(l==r){
        tree[id]=k; 
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid) up(pos,k,id*2,l,mid);
    else up(pos,k,id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
ii get(int u,int v,int id=1,int l=1,int r=cp.size()){
    if(l>v||r<u) return ii(0,0);
    if(u<=l&&r<=v) return tree[id];
    int mid=(l+r)>>1;
    return max(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>delta;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        cp.pb(a[i]-delta);
        cp.pb(a[i]);
        cp.pb(a[i]+delta);
    }
    sort(all(cp));  
    cp.erase(unique(all(cp)),cp.end());
    for(int i=1;i<=n;i++){
        ii res=get(id(a[i]-delta),id(a[i]+delta));
        dp[i]=res.fi+1;
        trace[i]=res.se;
        up(id(a[i]),ii(dp[i],i));
    }
    int m=max_element(dp+1,dp+n+1)-dp;
    cout<<*(m+dp)<<'\n';
    vector<int>lis;
    do{
        lis.pb(m);
        m=trace[m];
    }while(m);
    reverse(all(lis));
    for(int x:lis) cout<<a[x]<<" ";
}
