inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,s[N],c[N][56],tree[N<<2],dp[N][56];
void up(int pos,ll k,int id=1,int l=0,int r=1e4){
    if(l==r){
        tree[id]=max(tree[id],k);
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid) up(pos,k,id*2,l,mid);
    else up(pos,k,id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
int get(int u,int v,int id=1,int l=0,int r=1e4){
    if(l>v||r<u) return 0;
    if(u<=l&&r<=v) return tree[id];
    int mid=(l+r)>>1;
    return max(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
}
