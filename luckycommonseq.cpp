inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
string s1,s2,virus;
int n,m,k,dp[N][N][N],kmp[N],nxt[N]['Z'+1];
struct pt{
    int i,j,k;
}trace[N][N][N];
void build_kmp(){
    for(int i=2;i<=k;i++){
        int j=kmp[i-1];
        while(j&&virus[j+1]!=virus[i]) j=kmp[j];
        if(virus[j+1]==virus[i]) kmp[i]=j+1;
        else kmp[i]=0;
    }
    for(int i=0;i<=k;i++){
        for(int c='A';c<='Z';c++){
            if(i==k){
                nxt[i][c]=k;
                continue;
            }
            int j=i;
            while(j&&virus[j+1]!=c) j=kmp[j];
            if(virus[j+1]==c) nxt[i][c]=j+1;
            else nxt[i][c]=0;
        }
    }
}
string res;
void Trace(int i,int j,int t){
    if(i==0||j==0) return;
    auto [x,y,z]=trace[i][j][t];
    if(x==i-1&&y==j-1) res.pb(s1[i]);
    Trace(x,y,z);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>s1>>s2>>virus;
    n=s1.size();
    m=s2.size();
    k=virus.size();
    s1=" "+s1;
    s2=" "+s2;
    virus=" "+virus;
    build_kmp();
    for(int i=1;i<=n;i++){
        for(int j=1;j<=m;j++){
            for(int t=0;t<k;t++){
                if(dp[i-1][j][t]>=dp[i][j-1][t]){
                    dp[i][j][t]=dp[i-1][j][t];
                    trace[i][j][t]={i-1,j,t};
                }
                else{
                    dp[i][j][t]=dp[i][j-1][t];
                    trace[i][j][t]={i,j-1,t};
                }
            }
            if(s1[i]==s2[j]){
                for(int t=0;t<k;t++){
                    int nx=nxt[t][s1[i]];
                    if(nx==k) continue;
                    if(dp[i][j][nx]<dp[i-1][j-1][t]+1){
                        dp[i][j][nx]=dp[i-1][j-1][t]+1;
                        trace[i][j][nx]={i-1,j-1,t};
                    }
                }
            }
        }
    }
    int kk=k-1,mx=0;
    for(int t=0;t<k;t++){
        if(mx<dp[n][m][t]){
            mx=dp[n][m][t];
            kk=t;
        }
    }
    Trace(n,m,kk);
    reverse(all(res));
    if(res.size()) cout<<res;
    else cout<<0;
}
