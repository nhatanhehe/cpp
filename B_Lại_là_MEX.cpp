inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n,a[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n;
        vector<int>c(n+4,0);
        for(int i=1;i<=n;i++){
            cin>>a[i];
            if(a[i]<=n) c[a[i]]++;
        }
        vector<int>dp(n+4,inf);
        int mex=-1;
        for(int i=0;i<=n+1;i++){
            if(!c[i]){
                mex=i;
                break;
            }
        }
        dp[mex]=0;
        for(int i=mex-1;i>=0;i--){
            for(int j=i+1;j<=mex;j++){
                dp[i]=min(dp[i],dp[j]+(c[i]-1)*j+i);
            }
        }
        cout<<dp[0]<<'\n';
    }
}
