#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,a[N],l[N];
ii c[N];
vector<int>tree[N<<2][2];
void build(int id=1,int l=1,int r=m){
    if(l==r){
        tree[id][0].pb(c[l].se-c[l].fi);
        tree[id][1].pb(c[l].se+c[l].fi);
        return;
    }
    int mid=(l+r)>>1;
    build(id*2,l,mid);
    build(id*2+1,mid+1,r);
    for(int i=0;i<=1;i++){
        tree[id][i].resize(tree[id*2][i].size()+tree[id*2+1][i].size());
        merge(all(tree[id*2][i]),all(tree[id*2+1][i]),tree[id][i].begin());
    }
}
int get(int u,int v,int k,int tp,int id=1,int l=1,int r=m){
    if(l>v||r<u) return 0;
    if(u<=l&&r<=v){
        return upper_bound(all(tree[id][tp]),k)-tree[id][tp].begin();
    }
    int mid=(l+r)>>1;
    return get(u,v,k,tp,id*2,l,mid)+get(u,v,k,tp,id*2+1,mid+1,r);
}
