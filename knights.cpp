#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n,dp[N][20][20];
bool check_pre1(int mask1,int mask2){
    for(int i=0;i<=3;i++){
        if(i-2>=0) if((mask1>>i)&1) if((mask2>>(i-2))&1) return 0;
        if(i+2<=3) if((mask1>>i)&1) if((mask2>>(i+2))&1) return 0;
    }
    return 1;
}
bool check_pre2(int mask1,int mask2){
    for(int i=0;i<=3;i++){
        if(i-1>=0) if((mask1>>i)&1) if((mask2>>(i-1))&1) return 0;
        if(i+1<=3) if((mask1>>i)&1) if((mask2>>(i+1))&1) return 0;
    }
    return 1;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n;
    for(int mask=0;mask<(1<<4);mask++){
        dp[1][mask]=1;
    }
    for(int i=2;i<=n;i++){
        for(int mask=0;mask<(1<<4);mask++){
            for(int mask2=0;mask2<(1<<4);mask2++){
                if(check_pre1(mask,mask2)) dp[i][mask]=add(dp[i][mask],dp[i-1][mask2]);
                if(i>=3&&check_pre2(mask,mask2)) dp[i][mask]=add(dp[i][mask],dp[i-2][mask2]);
            }
        }
    }
    ll ans=0;
    for(int mask=0;mask<(1<<4);mask++){
        ans=add(ans,dp[n][mask]);
    }
    cout<<ans;
}
