#define se second
const ll inf=1e18;
const ll N=5e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n,a[N],b[N],dp[N];
vector<int>g[N];
int f(int x,int i){
    auto it=lower_bound(all(g[x]),i);
    return (it==g[x].end()? n+1:(*it));
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n;
        for(int i=1;i<=n;i++){
            cin>>a[i];
            g[a[i]].pb(i);
        }
        for(int i=1;i<=n;i++){
            cin>>b[i];
            g[b[i]].pb(i);
        }
        for(int i=1;i<=n;i++) sort(all(g[i]));
        vector<int>nxt(n+4,0);
        for(int i=1;i<=n;i++){
            if(a[i]==1||b[i]==1) nxt[i]=i;
            else nxt[i]=nxt[i-1];
        }
        for(int i=n;i>=1;i--){
            if(a[i]==b[i]){
                int pos=f(a[i]+1,i+1);
                if(pos==n+1) dp[i]=n;
                else{
                    if(a[pos]==b[pos]) dp[i]=dp[pos];
                    else dp[i]=pos-1;
                }
            }
        }
        //debug(dp[2]);
        //debug(dp[1]);
        ll ans=0;
        for(int i=1;i<=n;i++){
            if(a[i]==b[i]&&a[i]==1){
                ll l=i-nxt[i-1];
                ans+=l*(dp[i]-i+1);
            }
        }
        //debug(ans);
        g[1].pb(0);
        g[1].pb(n+1);
        sort(all(g[1]));
        for(int i=1;i<(int)g[1].size();i++){
            ll len=max(0LL,g[1][i]-g[1][i-1]-1);
            //cout<<g[1][i-1]<<" "<<g[1][i]<<" "<<len*(len+1)/2<<'\n';
            ans+=len*(len+1)/2;
        }
        cout<<ans<<'\n';
        for(int i=1;i<=n;i++){
            dp[i]=0;
            g[i].clear();
        }
    }
}
