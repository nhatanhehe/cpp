inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int dp[N][2],a[N],n,check[N][2];
int calc(int x,int tp){
//    cout <<x<<" "<<sum<<" "<<tp<<'\n';
    if(x>n||x<1) return 0;
    if(check[x][tp]) return -1;
    else if(dp[x][tp]!=-2) return dp[x][tp];
    check[x][tp]=1;
    dp[x][tp]=0;
    if(tp==1){
        int res=calc(x+a[x],tp^1);
        dp[x][tp]=(res!=-1? res+a[x]:-1);
        check[x][tp]=0;
    }
    else{
        int res=calc(x-a[x],tp^1);
        dp[x][tp]=(res!=-1? res+a[x]:-1);
        check[x][tp]=0;
    }
    return dp[x][tp];
}
