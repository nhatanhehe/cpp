inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,p[N],ans;
unordered_map<int,int>mp[N];
int get(int u){
	return (u==p[u]? u:p[u]=get(p[u]));
}
void join(int u,int v){
	u=get(u);
	v=get(v);
	if(u!=v){
		if(mp[u].size()<mp[v].size()){
			swap(u,v);
		}
		for(auto x:mp[v]){
			int e=mp[u][x.fi];
			ans-=e*(e-1)/2;
			ans-=x.se*(x.se-1)/2;
			mp[u][x.fi]+=x.se;
			e=mp[u][x.fi];
			ans+=e*(e-1)/2;
		}
		p[v]=u;
	}
}
