#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<ll,ll>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll tree[N<<2][2],n,q,tp,x,p,a[N];
void up(int pos,ll k,int id=1,int l=1,int r=n){
    if(l==r){
        tree[id][0]=k;
        tree[id][1]=k;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid) up(pos,k,id*2,l,mid);
    else up(pos,k,id*2+1,mid+1,r);
    tree[id][0]=tree[id*2][0]+tree[id*2+1][0];
    tree[id][1]=max(tree[id*2][1],tree[id*2+1][1]);
}
ii get(int u,int v,int id=1,int l=1,int r=n){
    if(l>v||r<u) return {0,0};
    if(u<=l&&r<=v) return ii(tree[id][0],tree[id][1]);
    int mid=(l+r)>>1;
    ii p1=get(u,v,id*2,l,mid);
    ii p2=get(u,v,id*2+1,mid+1,r);
    return ii(p1.fi+p2.fi,max(p1.se,p2.se));
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        up(i,a[i]);
    }
    while(q--){
        cin>>tp;
        if(tp==1){
            cin>>p>>x;
            up(p,x);
        }
        else{
            int l,r;
            cin>>l>>r;
            ii res=get(l,r);
            cout<<(res.fi>2*res.se)<<'\n';
        }
    }
}
