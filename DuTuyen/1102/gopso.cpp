inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,p[N],q,x,y,nxt[N],c[N];
int acs(int u){
    return p[u]==u? u:p[u]=acs(p[u]);
}
void join(int u,int v){
    u=acs(u);
    v=acs(v);
    if(u!=v){
        p[u]=v;
    }
}
int get(int u){
    return nxt[u]==u? u:nxt[u]=get(nxt[u]);
}
void uni(int u,int v){
    u=get(u);
    v=get(v);
    if(u!=v){
        nxt[u]=v;
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q;
    for(int i=1;i<=n+1;i++){
        p[i]=i;
        nxt[i]=i;
    }
    while(q--){
        int tp;
        cin>>tp>>x>>y;
        if(tp==1){
            if(x==y) continue;
            join(x,y);
        }
        else if(tp==2){
            if(x==y) continue;
            while(x<=y){
                x=acs(x);
                if(!c[x]){
                    c[x]=1;
                    join(x,x+1);
                    uni(x,x+1);
                }
                else x++;
            }
        }
        else{
            cout<<(acs(x)==acs(y)? "YES\n":"NO\n");
        }
    }
}
