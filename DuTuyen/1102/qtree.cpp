inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct Node{
    int child[2]={0,0};
    set<int>s;
}trie[N*32];
int node=1;
void ins(int x,int idx){
    int p=1;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        if(!trie[p].child[c]){
            trie[p].child[c]=++node;
        }
        p=trie[p].child[c];
        trie[p].s.insert(idx);
    }
}
int getMax(int l,int r,int x){
    int p=1;
    int res=0;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        if(trie[p].child[c^1]){
            set<int>&s=trie[trie[p].child[c^1]].s;
            auto it=s.upper_bound(r);
            if(it!=s.begin()){
                it--;
                if((*it)>=l){
                    res|=(1<<i);
                    p=trie[p].child[c^1];
                    continue;
                }
            }
        }
        if(trie[p].child[c]){
            p=trie[p].child[c];
            continue;
        }
        break;
    }
    return res;
}
vector<ii>g[N];
int q,n=1;
struct Query{
    string tp;
    int a,b;
}Q[N];
int in[N],Xor[N],timer,out[N];
void dfs(int u){
    in[u]=++timer;
    for(auto [v,w]:g[u]){
        Xor[v]=Xor[u]^w;
        dfs(v);
    }
    out[u]=timer;
}
