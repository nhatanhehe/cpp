bool inside(int x,int y){
    return 1<=x&&x<=n&&1<=y&&y<=n;
}
int H(int x,int y){
    return (x-1)*n+y;
}
ii solve(int x,int y,int a,int b){
    ll tu=a-x;
    ll mau=y-b;
    if(!tu&&!mau) return ii(0,0);
    if(!tu) return ii(0,1);
    if(!mau) return ii(-inf,-inf);
    ll gcd=abs(fgcd(abs(tu),abs(mau)));
    tu/=gcd;
    mau/=gcd;
    if(mau<0){
        tu=-tu;
        mau=-mau;
    }
    return ii(tu,mau);
}
