 int fgcd ( unsigned  int u ,  unsigned  int v )  {
  int shift , uz , vz ;
  if  ( u ==  0 )  return v ;
  if  ( v ==  0 )  return u ;
  uz = __builtin_ctz ( u ) ;
  vz = __builtin_ctz ( v ) ;
  shift = uz > vz ? vz : uz ;
  u >>=uz ;
  do  {
   v>>= vz ;
   int diff = v ;
   diff -= u ;
   vz = __builtin_ctz ( diff ) ;
   if  ( diff ==  0 )  break ;
   if  ( v < u ) u = v ;
   v =  abs ( diff ) ;
  }  while  ( 1 ) ;
  return u << shift ;
}

struct DSU{
    vector<int>p,sz;
    int n;
    int mx;
    stack<ii>his;
    void init(int _n){
        n=_n;
        mx=1;
        p.resize(n+4);
        sz.resize(n+4,1);
        for(int i=1;i<=n;i++) p[i]=i;
    }
    int acs(int u){
        while(u!=p[u]) u=p[u];
        return u;
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            cnt++;
            if(sz[u]<sz[v]) swap(u,v);
            his.push(ii(v,p[v]));
            his.push(ii(u,sz[u]));
            his.push(ii(u,mx));
            sz[u]+=sz[v];
            mx=max(mx,sz[u]);
            p[v]=u;
        }
    }
    void rollback(int step){
        while(step--){
            auto [sk,Max]=his.top(); his.pop();
            mx=Max;
            auto [u,old_sz]=his.top(); his.pop();
            sz[u]=old_sz;
            auto [v,old_par]=his.top(); his.pop();
            p[v]=old_par;
        }
    }
}uni;
