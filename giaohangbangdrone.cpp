inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,u,l,r,dist[N<<2];
vector<ii>g[N*5];
void build(int id=1,int l=1,int r=n){
    if(l==r){
        g[id].pb({l+4*n,l});
        //cout<<id<<" "<<l+4*n<<" "<<l<<'\n';
        return;
    }
    int mid=(l+r)>>1;
    build(id*2,l,mid);
    build(id*2+1,mid+1,r);
  //  cout<<id<<" "<<id*2<<" "<<0<<'\n';
    //cout<<id<<" "<<id*2+1<<" "<<0<<'\n';
    g[id].pb({id*2,0});
    g[id].pb({id*2+1,0});
}

void addedge(int u,int v,int a,int w,int id=1,int l=1,int r=n){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
       // cout<<a<<" "<<id<<" "<<w<<'\n';
        g[a].pb({id,w});
        return;
    }
    int mid=(l+r)>>1;
    addedge(u,v,a,w,id*2,l,mid);
    addedge(u,v,a,w,id*2+1,mid+1,r);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    build();
    for(int i=1;i<=m;i++){
        cin>>u>>l>>r;
        addedge(l,r,u+n*4,(1-l));
    }
    fill(dist+1,dist+n+n*4+1,inf);
    priority_queue<ii,vector<ii>,greater<ii>>pq;
    pq.push({0,1+n*4});
    dist[1+n*4]=0;
    while(pq.size()){
        auto [cost,u]=pq.top(); pq.pop();
        if(cost>dist[u]) continue;
        for(auto [v,w]:g[u]){
            if(dist[v]>dist[u]+w){
                dist[v]=dist[u]+w;
                pq.push({dist[v],v});
            }
        }
    }
    for(int i=1;i<=n;i++){
        cout<<(dist[i+n*4]==inf? -1:dist[i+n*4])<<" ";
    }
}
