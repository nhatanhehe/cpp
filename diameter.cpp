inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,p[N],root,dp[N],mx;
vector<int>g[N];
void dfs(int u,int p){
    vector<int>vec;
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]=max(dp[v]+1,dp[u]);
            vec.pb(dp[v]+1);
        }
    }
    sort(all(vec),greater<int>());
    if(vec.size()==1) mx=max(mx,vec[0]);
    else if(vec.size()>=2) mx=max(mx,vec[0]+vec[1]);
}
