#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "bsr"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=5e2+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll a[N][N],m,n,pre[N][N],d[10];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n;
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
            pre[i][j]=(pre[i][j-1]+a[i][j])%9;
        }
    }
    ll ans=0;
    for(int l=1;l<=n;l++){
        for(int r=l;r<=n;r++){
            memset(d,0,sizeof(d));
            ll sum=0;
            d[0]=1;
            for(int i=1;i<=m;i++){
                sum=(sum+(((pre[i][r]-pre[i][l-1])%9+9)%9))%9;
                ans+=d[sum];
                d[sum]++;
            }
        }
    }
    cout<<ans;
}
