inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],k;
namespace sub1{
    int dist[3003][3003];
    void solve(){
        for(int i=0;i<=3000;i++){
            for(int j=0;j<=3000;j++) dist[i][j]=1e9;
        }
        int c0=0,c1=0,c2=0;
        for(int i=1;i<=n;i++){
            if(a[i]%3==0) c0++;
            else if(a[i]%3==1) c1++;
            else c2++;
        }
        dist[c1][c2]=0;
        queue<ii>q;
        q.push({c1,c2});
        while(q.size()){
            auto [u1,u2]=q.front(); q.pop();
            int u0=n-u1-u2;
            if(u1==0&&u2==0){
                cout<<dist[0][0];
                return;
            }
            for(int k0=0;k0<=k;k0++){
                for(int k1=0;k1<=k-k0;k1++){
                    int k2=k-k1-k0;
                    if(k0<=u0&&k1<=u1&&k2<=u2){
                        if(k0){
                            int v1=u1-k1+k2;
                            int v2=u2-k2+k0;
                            // chon mot thang du 0 de cong k-1
                            int md=(k-1)%3;
                            // so thang du 1 tiep theo
                            v2--;
                            if(md==1) v1++;
                            else if(md==2) v2++;
                            if(dist[v1][v2]>dist[u1][u2]+1){
                                dist[v1][v2]=dist[u1][u2]+1;
                                q.push({v1,v2});
                            }
                        }
                        if(k1){
                            int v1=u1-k1+k2;
                            int v2=u2-k2+k0;
                            // chon mot thang du 1 de cong k-1
                            int md=k%3;
                            // so thang du 1 tiep theo
                            if(md==2) v2++;
                            if(md==1) v1++;
                            if(dist[v1][v2]>dist[u1][u2]+1){
                                dist[v1][v2]=dist[u1][u2]+1;
                                q.push({v1,v2});
                            }
                        }
                        if(k2){
                            int v1=u1-k1+k2;
                            int v2=u2-k2+k0;
                            // chon mot thang du 2 de cong k-1
                            int md=(k+1)%3;
                            // so thang du 1 tiep theo
                            v1--;
                            if(md==2) v2++;
                            if(md==1) v1++;
                            if(dist[v1][v2]>dist[u1][u2]+1){
                                dist[v1][v2]=dist[u1][u2]+1;
                                q.push({v1,v2});
                            }
                        }
                    }
                }
            }
        }
        cout<<-1;
    }
}
