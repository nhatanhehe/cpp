int exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    int t=exp(a,n/2);
    if(n&1) return ((t*t)%mod*a%mod)%mod;
    else return (t*t)%mod;
}
int C(int n,int k){
    int a=f[n];
    int b=(f[k]*(f[n-k]))%mod;
    return a*exp(b,mod-2)%mod;
}
