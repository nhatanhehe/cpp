inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,u,v,w,dp[N],up[N],sz[N],ups[N],upd[N],ans[N];
vector<ii>g[N];
void dfs(int u,int p){
    sz[u]=1;
    for(auto [v,w]:g[u]){
        if(v!=p){
            dfs(v,u);
            sz[u]+=sz[v];
            dp[u]+=dp[v]+w*sz[v];
        }
    }
}
void reroot(int u,int p){
    for(auto [v,w]:g[u]){
        if(v!=p){
            ups[v]=ups[u]+sz[u]-sz[v];
            upd[v]=upd[u]+dp[u]-(dp[v]+w*sz[v])+ups[v]*w;
            reroot(v,u);
        }
    }
}
