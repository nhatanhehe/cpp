#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,u,v,dp[N],up[N];
vector<int>g[N],rev[N];
void dfs(int u,int p){
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]+=dp[v];
        }
    }
    for(int v:rev[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]+=dp[v]+1;
        }
    }
}
void reroot(int u,int p){
    for(int v:g[u]){
        if(v!=p){
            up[v]=(dp[u]-dp[v]+1)+up[u];
            reroot(v,u);
        }
    }
    for(int v:rev[u]){
        if(v!=p){
            up[v]=(dp[u]-dp[v]-1)+up[u];
            reroot(v,u);
        }
    }
}
