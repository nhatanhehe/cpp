inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,v[N],p[N],t,source,sink,work[N],dist[N];
struct edge{
    int to,rev,flow,cap;
};
vector<edge>g[N];
void addedge(int u,int v,int cap){
    edge a={v,g[v].size(),0,cap};
    edge b={u,g[u].size(),0,0};
    g[u].pb(a);
    g[v].pb(b);
}
bool bfs(){
    for(int i=0;i<=sink;i++){
        dist[i]=-1;
    }
    queue<int>q;
    dist[source]=0;
    q.push(source);
    while(q.size()){
        int u=q.front(); q.pop();
        for(auto [v,rev,flow,cap]:g[u]){
            if(dist[v]<0&&flow<cap){
                dist[v]=dist[u]+1;
                q.push(v);
            }
        }
    }
    return dist[sink]>0;
}
int dfs(int u,int fl){
    if(u==sink){
        return fl;
    }
    for(int &s=work[u];s<g[u].size();s++){
        edge &e=g[u][s];
        int v=e.to;
        if(dist[v]==dist[u]+1&&e.flow<e.cap){
            int df=dfs(v,min(fl,e.cap-e.flow));
            if(df<=0) continue;
            e.flow+=df;
            g[v][e.rev].flow-=df;
            return df;
        }
    }
    return 0;
}
void solve(){
    cin>>m>>n;
    source=0;
    sink=m+n+1;
    ll sum=0;
    for(int i=1;i<=m;i++){
        cin>>p[i];
        sum+=p[i];
        addedge(i+n,sink,p[i]);
    }
    for(int i=1;i<=n;i++){
        cin>>v[i];
        addedge(source,i,v[i]);
    }
    for(int i=1;i<=n;i++){
        int k;
        cin>>k;
        for(int j=1;j<=k;j++){
            int idx;
            cin>>idx;
            addedge(i,idx+n,1e9);
        }
    }
    ll dec=0;
    while(bfs()){
        memset(work,0,sizeof work);
        while(ll fl=dfs(source,1e9)) dec+=fl;
    }
    cout<<sum-dec<<'\n';
    for(int i=source;i<=sink;i++){
        g[i].clear();
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        solve();
    }
}
