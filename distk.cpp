inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,cen[N],p,sz[N];
vector<int>g[N];
void dfs(int u,int p){
    sz[u]=1;
    for(int v:g[u]){
        if(!cen[v]&&v!=p){
            dfs(v,u);
            sz[u]+=sz[v];
        }
    }
}
int fcen(int u,int p,int tree_sz){
    for(int v:g[u]){
        if(v!=p&&!cen[v]&&sz[v]>tree_sz/2) return fcen(v,u,tree_sz);
    }
    return u;
}
void dfs2(int u,int p,int h,vector<int>&dist){
    dist.pb(h);
    for(int v:g[u]){
        if(v!=p&&!cen[v]){
            dfs2(v,u,h+1,dist);
        }
    }
}
ll ans;
void calc(int u,int p,int h,int neg){
    vector<int>a;
    dfs2(u,p,h,a);
    sort(all(a));
    int l=0,r=a.size()-1;
    while(l<r){
        if(a[l]+a[r]<k) l++;
        else if(a[l]+a[r]>k) r--;
        else{
            if(a[l]==a[r]){
                int len=r-l+1;
                ans+=neg*(len-1)*len/2;
                break;
            }
            int x=a[l],y=a[r];
            int cntx=0,cnty=0;
            while(l<=r&&a[l]==x) cntx++,l++;
            while(l<=r&&a[r]==y) cnty++,r--;
            ans+=neg*cntx*cnty;
        }
    }
}
void build(int u){
    dfs(u,-1);
    int centroid=fcen(u,-1,sz[u]);
    cen[centroid]=1;
    calc(centroid,-1,0,1);
    for(int v:g[centroid]){
        if(!cen[v]){
            calc(v,centroid,1,-1);
        }
    }
    for(int v:g[centroid]){
        if(!cen[v]) build(v);
    }
}
