inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll m,n,p[N],u,v,cost,d[N],old[N];
vector<int>g[N],rev[N];
// Tat u thi loang tim v la cha u
void dfs1(int u){
    cost-=p[u];
    d[u]=0;
    for(int v:rev[u]){
        if(d[v]){
            dfs1(v);
        }
    }
}
// Bat u
void dfs2(int u){
    cost+=p[u];
    d[u]=1;
    for(int v:g[u]){
        if(!d[v]){
            dfs2(v);
        }
    }
}
