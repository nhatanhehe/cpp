inline ll add(ll a, ll b)
{
    ll res = a + b;
    if (res >= mod)
        res -= mod;
    return res;
}
ll sub(ll a, ll b)
{
    return ((a - b) % mod + mod) % mod;
}
inline ll mul(ll a, ll b)
{
    ll res = a * b;
    if (res >= mod)
        res %= mod;
    return res;
}
ll n, a[N], k;
main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);
    if (fopen(Task ".inp", "r"))
    {
        freopen(Task ".inp", "r", stdin);
        freopen(Task ".out", "w", stdout);
    }
    cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    sort(a + 1, a + n + 1);
    ll l = 1, r = n, ans = inf, Max = a[n], Min = a[1];
    while (l < r)
    {
        while (l < r && a[l] == a[l + 1])
            l++;
        while (l < r && a[r] == a[r - 1])
            r--;
        if (l >= r)
            break;
        ll suml = l * (a[l + 1] - Min);
        ll sumr = (n - r + 1) * (Max - a[r - 1]);
        if (l < (n - r + 1))
        {
            if (k >= suml)
            {
                k -= suml;
                Min = a[l + 1];
                l++;
            }
            else
            {
                Min += k / l;
                k = 0;
                break;
            }
        }
        else
        {
            if (k >= sumr)
            {
                k -= sumr;
                Max = a[r - 1];
                r--;
            }
            else
            {
                Max -= k / (n - r + 1);
                k = 0;
                break;
            }
        }
    }
    if (l < r)
    {
        if (l < (n - r + 1))
            Min += k / l;
        else
            Max -= k / (n - r + 1);
    }
    cout << max({0LL, Max - Min});
}
