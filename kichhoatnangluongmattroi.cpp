#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int st[N],en[N],n,u,v,tree[N<<2],lz[N<<2],it[N<<2],lz2[N<<2],p[N],cnt,idx[N],q,t[N];
vector<int>g[N];
void build(int id=1,int l=1,int r=n){
    if(l==r){
        tree[id]=-t[idx[l]];
        return;
    }
    int mid=(l+r)>>1;
    build(id*2,l,mid);
    build(id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
void dfs(int u,int p){
    st[u]=++cnt;
    idx[cnt]=u;
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
        }
    }
    en[u]=cnt;
}
void fix(int id,int k){
    tree[id]+=k;
    lz[id]+=k;
}
void push(int id){
    if(lz[id]){
        fix(id*2,lz[id]);
        fix(id*2+1,lz[id]);
        lz[id]=0;
    }
}
void up(int u,int v,int k,int id=1,int l=1,int r=n){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
        fix(id,k);
        return;
    }
    push(id);
    int mid=(l+r)>>1;
    up(u,v,k,id*2,l,mid);
    up(u,v,k,id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
void fix2(int id,int k){
    it[id]+=k;
    lz2[id]+=k;
}
void push2(int id){
    if(lz2[id]){
        fix2(id*2,lz2[id]);
        fix2(id*2+1,lz2[id]);
        lz2[id]=0;
    }
}
void up2(int u,int v,int k,int id=1,int l=1,int r=n){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
        fix2(id,k);
        return;
    }
    push2(id);
    int mid=(l+r)>>1;
    up2(u,v,k,id*2,l,mid);
    up2(u,v,k,id*2+1,mid+1,r);
    it[id]=max(it[id*2],it[id*2+1]);
}
int getmax(int id=1,int l=1,int r=n){
    if(l==r){
        return l;
    }
    push(id);
    int mid=(l+r)>>1;
    if(tree[id*2]>=0)  return getmax(id*2,l,mid);
    else if(tree[id*2+1]>=0) return getmax(id*2+1,mid+1,r);
    else return -1;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    memset(tree,-0x3f,sizeof tree);
    cin>>n>>q;
    for(int i=2;i<=n;i++){
        cin>>p[i];
        g[p[i]].pb(i);
        g[i].pb(p[i]);
    }
    dfs(1,-1);

    for(int i=1;i<=n;i++){
        cin>>t[i];
    }
    build();
    for(int i=1;i<=q;i++){
        cin>>u>>v;
        up(st[u],en[u],v);
        int ver;
        while((ver=getmax())!=-1){
            int o=idx[ver];
            up2(st[o],en[o],1);
            up(st[o],st[o],-inf);
        }
        cout<<it[1]<<'\n';
    }
}
