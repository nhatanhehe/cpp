inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q;
ll tp,col,x,y;
struct pt{
    ll a,c,id;
}a[N];
int st[N],nxt[N];
struct BIT {
    int n;
    vector<long long> bit1, bit2;

    BIT(int _n = 0) {
        init(_n);
    }

    void init(int _n) {
        n = _n;
        bit1.assign(n + 1, 0);
        bit2.assign(n + 1, 0);
    }

    void add(vector<long long> &bit, int idx, long long val) {
        for (; idx <= n; idx += idx & -idx)
            bit[idx] += val;
    }

    long long sum(const vector<long long> &bit, int idx) {
        long long res = 0;
        for (; idx > 0; idx -= idx & -idx)
            res += bit[idx];
        return res;
    }

    void update(int l, int r, long long val) {
        add(bit1, l, val);
        add(bit1, r + 1, -val);

        add(bit2, l, val * (l - 1));
        add(bit2, r + 1, -val * r);
    }

    long long prefix_sum(int x) {
        return sum(bit1, x) * x - sum(bit2, x);
    }

    long long query(int l, int r) {
        return prefix_sum(r) - prefix_sum(l - 1);
    }
}bit;
