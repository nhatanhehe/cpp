#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=1e3+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n,k,A,B,a[N][N],dist[N][N];
int dx[]={1,-1,0,0};
int dy[]={0,0,1,-1};
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n>>k>>A>>B;
    for(int i=1;i<=k;i++){
        int l,r;
        cin>>l>>r;
        a[l][r]=1;
    }
    deque<ii>dq;
    dq.pb(ii(1,1));
    memset(dist,0x3f,sizeof dist);
    dist[1][1]=0;
    while(dq.size()){
        auto [u,v]=dq.front();
        if(u==A&&v==B){
            return cout<<dist[u][v],0;
        }
        dq.pop_front();
        for(int k=0;k<4;k++){
            int x=u+dx[k];
            int y=v+dy[k];
            if(1<=x&&x<=m&&1<=y&&y<=n){
                int w=a[x][y];
                if(w){
                    if(dist[x][y]>dist[u][v]+w){
                        dist[x][y]=dist[u][v]+w;
                        dq.pb(ii(x,y));
                    }
                }
                else{
                    if(dist[x][y]>dist[u][v]){
                        dist[x][y]=dist[u][v];
                        dq.push_front(ii(x,y));
                    }
                }
            }
        }
    }
}
