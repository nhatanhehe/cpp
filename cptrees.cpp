inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,rt1,rt2,st[N],en[N],bit[N],timer,ver[N],heavy[N],in[N],ou[N];
vector<int>g[N],adj[N];
void dfs(int u,int p){
    in[u]=++timer;
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
        }
    }
    ou[u]=timer;
}
int dfs2(int u,int p){
    st[u]=++timer;
    ver[timer]=u;
    int sz=1,mx=0,child_sz;
    for(int v:adj[u]){
        if(v!=p){
            child_sz=dfs2(v,u);
            if(mx<child_sz){
                mx=child_sz;
                heavy[u]=v;
            }
            sz+=child_sz;
        }
    }
    en[u]=timer;
    return sz;
}
void up(int i,int k){
    for(;i<=n;i+=i&-i){
        bit[i]+=k;
    }
}
int get(int i){
    int res=0;
    for(;i;i-=i&-i){
        res+=bit[i];
    }
    return res;
}
int query(int l,int r){
    return get(r)-get(l-1);
}
ll ans=0;
void Sack(int u,int p,bool keep){
    for(int v:adj[u]){
        if(v!=p&&v!=heavy[u]) Sack(v,u,0);
    }
    if(heavy[u]) Sack(heavy[u],u,1);
    for(int v:adj[u]){
        if(v!=p&&v!=heavy[u]){
            for(int i=st[v];i<=en[v];i++){
                int vertex=ver[i];
                up(in[vertex],1);
            }
        }
    }
    ans+=query(in[u],ou[u]);
    up(in[u],1);
    if(!keep){
        for(int i=st[u];i<=en[u];i++){
            int vertex=ver[i];
            up(in[vertex],-query(in[vertex],in[vertex]));
        }
    }
}
