#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N];
ii dp[N];
void add(ii &p, int id) {
    if (id <= 0) return;
    if (id > p.fi) {
        p.se = p.fi;
        p.fi = id;
    } else if (id > p.se && id != p.fi) {
        p.se = id;
    }
}
void merge(ii &p1, ii p2) {
    add(p1, p2.fi);
    add(p1, p2.se);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        add(dp[a[i]],i);
    }
    //for(int mask=0;mask<(1<<21);mask++) swap(dp[mask].fi,dp[mask].se);
    for(int i=0;i<21;i++){
        for(int mask=0;mask<(1<<21);mask++){
            if(!(mask>>i&1)){
                merge(dp[mask],dp[On(mask,i)]);
            }
        }
    }
    int ans=0;
    for(int i=1;i<=n-2;i++){
        int cur=0;
        for(int b=20;b>=0;b--){
            if(!(a[i]>>b&1)){
                if(dp[On(cur,b)].se>i){
                    cur|=(1<<b);
                }
            }
        }
        ans=max(ans,a[i]|cur);
    }
    cout<<ans;
}
