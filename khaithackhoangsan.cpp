inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,w,h,tree[N<<2],sz,lz[N<<2];
struct pt{
    int x,y,w;
}c[N];
unordered_map<int,int>mp;
void fix(int id,int k){
    tree[id]+=k;
    lz[id]+=k;
    return;
}
void push(int id){
    if(lz[id]){
        fix(id*2,lz[id]);
        fix(id*2+1,lz[id]);
        lz[id]=0;
    }
}
void up(int u,int v,int k,int id=1,int l=1,int r=sz){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
        fix(id,k);
        return;
    }
    push(id);
    int mid=(l+r)>>1;
    up(u,v,k,id*2,l,mid);
    up(u,v,k,id*2+1,mid+1,r);
    tree[id]=max(tree[id*2],tree[id*2+1]);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>w>>h;
    for(int i=1;i<=n;i++){
        cin>>c[i].x>>c[i].y>>c[i].w;
    }
    sort(c+1,c+n+1,[&](const pt &x,const pt &y){
        return x.x<y.x;
    });
    vector<int>cp;
    for(int i=1;i<=n;i++){
        cp.pb(c[i].y);
        cp.pb(c[i].y+h-1);
    }
    sort(all(cp));
    cp.erase(unique(all(cp)),cp.end());
    sz=cp.size();
    for(int i=1;i<=n;i++){
        mp[c[i].y]=lower_bound(all(cp),c[i].y)-cp.begin()+1;
        mp[c[i].y+h-1]=lower_bound(all(cp),c[i].y+h-1)-cp.begin()+1;
    }
    int j=1;
    ll ans=0;
    for(int i=1;i<=n;i++){
        up(mp[c[i].y],mp[c[i].y+h-1],c[i].w);
        while(c[j].x<=c[i].x-w){
            up(mp[c[j].y],mp[c[j].y+h-1],-c[j].w);
            j++;
        }
        //cout<<j<<'\n';
        ans=max(ans,tree[1]);
    }
    cout<<ans;
}
