#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "rmov"
#define ii pair<ll,ll>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n,k;
vector<vector<ll>>a;
vector<vector<ii>>dp;
ii check(ll lamda){
    dp.assign(m+3,vector<ii>(n+4,ii(-inf,-inf)));
    dp[1][1]=ii(0,0);
    dp[1][1]=max(dp[1][1],ii(dp[1][1].fi-lamda+a[1][1],1));
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            if(i>=2) dp[i][j]=max({dp[i][j],ii(dp[i-1][j].fi+a[i][j]-lamda,dp[i-1][j].se+1),dp[i-1][j]});
            if(j>=2) dp[i][j]=max({dp[i][j],ii(dp[i][j-1].fi+a[i][j]-lamda,dp[i][j-1].se+1),dp[i][j-1]});
        }
    }
    return dp[m][n];
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n>>k;
    a.resize(m+3,vector<ll>(n+4,0));
    dp.resize(m+3,vector<ii>(n+4,ii(0,0)));
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
        }
    }
    ll l=1,r=2e9,ans=0;
    while(l<=r){
        ll mid=(l+r)>>1;
        if(check(mid).se>=k){
            l=mid+1;
            ans=mid;
        }
        else r=mid-1;
    }
    cout<<check(ans).fi+ans*k;
}
