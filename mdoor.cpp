#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll c,m,n,a[1004][1004],dp1[1004][1004],dp2[1004][1004],d[1004][1004],dp3[1004][1004];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n>>c;
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            cin>>d[i][j];
        }
    }
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
        }
    }
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            dp1[i][j]=dp2[i][j]=dp3[i][j]=-inf;
        }
    }
    for(int i=1;i<=n;i++){
        dp1[1][i]=a[1][i];
        dp2[m][i]=a[m][i];
    }
    ll mx_start=-inf,mx_end=-inf,res=-inf,ans=-inf;
    for(int i=2;i<=m;i++){
        for(int j=1;j<=n;j++){
            dp1[i][j]=dp1[i-1][j];
            if(j>=2) dp1[i][j]=max(dp1[i][j],dp1[i-1][j-1]);
            if(j<n) dp1[i][j]=max(dp1[i][j],dp1[i-1][j+1]);
            dp1[i][j]+=a[i][j];
        }
    }
    for(int j=1;j<=n;j++) ans=max(ans,dp1[m][j]);
    for(int i=m-1;i>=1;i--){
        for(int j=1;j<=n;j++){
            dp2[i][j]=dp2[i+1][j];
            if(j>=2) dp2[i][j]=max(dp2[i][j],dp2[i+1][j-1]);
            if(j<n) dp2[i][j]=max(dp2[i][j],dp2[i+1][j+1]);
            dp2[i][j]+=a[i][j];
        }
    }
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            if(d[i][j]){
                dp3[i][j]=a[i][j];
                mx_start=max(mx_start,dp1[i][j]);
                mx_end=max(mx_end,dp2[i][j]);
            }
        }
    }
    // Tính DP3: Đường đi giữa 2 cửa thần kì
    for(int i=2;i<=m;i++){
        for(int j=1;j<=n;j++){
            ll prev = -inf;
            // Tìm đường đi lớn nhất từ 3 ô hàng trên
            if (dp3[i-1][j] != -inf) prev = max(prev, dp3[i-1][j]);
            if (j >= 2 && dp3[i-1][j-1] != -inf) prev = max(prev, dp3[i-1][j-1]);
            if (j < n && dp3[i-1][j+1] != -inf) prev = max(prev, dp3[i-1][j+1]);
            
            // Nếu có đường đi từ cửa ở phía trên đi xuống
            if (prev != -inf) {
                dp3[i][j] = max(dp3[i][j], prev + a[i][j]);
            }
        }
    }

    // Cập nhật res (lợi ích chu trình) CHỈ TẠI CÁC Ô CÓ CỬA
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            if(d[i][j]){
                res = max(res, dp3[i][j]);
            }
        }
    }

    // Chốt kết quả
    if(c >= 1 && mx_start != -inf && mx_end != -inf){
        ll jump_score = mx_start + mx_end;
        // Chỉ farm điểm bằng cửa thần kì nếu dư số lần nhảy (c > 1) và nó mang lại điểm dương
        if(c > 1 && res > 0) {
            jump_score += (c - 1) * res;
        }
        ans = max(ans, jump_score);
    }
    
    cout << ans;
}
