inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
bool p[1000004];
void sang(){
    memset(p,1,sizeof p);
    p[0]=p[1]=0;
    for(int i=2;i<=sqrt(1e6);i++){
        if(p[i]) for(int j=i*i;j<=1e6;j+=i) p[j]=0;
    }
}
ll dp[20][1800],n;
ll calc(int i,int sum){
    if(i>15){
        return dp[i][sum]=p[sum];
    }
    ll &ans=dp[i][sum];
    if(ans!=-1)  return ans;
    ans=0;
    for(int j=0;j<=9;j++){
        dp[i][sum]+=calc(i+1,sum+j*j);
    }
    return dp[i][sum];
}
string res;
void trace(int i,int sum,ll n){
    if(i>15) return;
   // cerr<<i<<" "<<sum<<" "<<n<<'\n';
    for(int j=0;j<=9;j++){
        if(n<=dp[i+1][sum+j*j]){
            res.pb(j+'0');
            trace(i+1,sum+j*j,n);
            break;
        }
        else{
            n-=dp[i+1][sum+j*j];
        }
    }
}
