#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=3e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n,a[N];
map<int,int>mp;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n;
        for(int i=1;i<=n;i++){
            cin>>a[i];
            mp[a[i]]++;
        }
        priority_queue<int>pq1,pq2;
        for(auto e:mp){
            if(e.se>=2) pq1.push(e.fi);
            if(e.se>=4) pq2.push(e.fi);
        }
        int ans=-1;
        if(pq1.size()>=2){
            int x=pq1.top();
            pq1.pop();
            int y=pq1.top();
            ans=max(ans,x*y);
        }
        if(pq2.size()){
            ans=max(ans,pq2.top()*pq2.top());
        }
        cout<<ans<<'\n';
        mp.clear();
    }
}
