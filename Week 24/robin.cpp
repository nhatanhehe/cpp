inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,c,a[N],u,v,dp[N][2];
vector<int>g[N];
void dfs(int u,int p){
    dp[u][1]=a[u];
    //debug(u);
    //debug(a[u]);
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
            dp[u][0]+=max(dp[v][0],dp[v][1]);
            dp[u][1]+=max(dp[v][0],dp[v][1]-2*c);
        }
    }
}
