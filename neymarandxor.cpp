inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,a[N],tp,x,l,r,tree[N<<2][2];
struct pt{
    int tp,x,l,r;
}Q[N];
void build(int id=1,int l=0,int r=n-1){
    if(l==r){
        tree[id][0]=a[l];
        tree[id][1]=a[l]*l;
        return;
    }
    int mid=(l+r)>>1;
    build(id*2,l,mid);
    build(id*2+1,mid+1,r);
    for(int i=0;i<=1;i++) tree[id][i]=tree[id*2][i]+tree[id*2+1][i];
}
int get(int u,int v,int tp,int id=1,int l=0,int r=n-1){
    if(l>v||r<u) return 0;
    if(u<=l&&r<=v) return tree[id][tp];
    int mid=(l+r)>>1;
    return get(u,v,tp,id*2,l,mid)+get(u,v,tp,id*2+1,mid+1,r);
}
