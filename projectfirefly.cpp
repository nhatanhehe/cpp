inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a,b,c,d,f[N],inv[N];
string s;
ll exp(ll a,ll n){
    if(n==0) return 1;
    if(n==1) return a;
    ll t=exp(a,n/2);
    t=mul(t,t);
    if(n&1) return mul(t,a);
    return t;
}
void precum(){
    f[0]=inv[0]=1;
    int maxn=2e6;
    for(int i=1;i<=maxn;i++){
        f[i]=mul(f[i-1],i);
    }
    inv[maxn]=exp(f[maxn],mod-2);
    for(int i=maxn-1;i>=1;i--){
        inv[i]=mul(inv[i+1],i+1);
    }
}
ll nCk(int n,int k){
    if(k<0||n<0||n<k) return 0;
    return mul(f[n],mul(inv[k],inv[n-k]));
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    precum();
    cin>>s;
    n=s.size(); s=" "+s;
    for(int i=1;i<=n;i++){
        if(s[i]==')') c++;
        if(s[i]=='?') d++;
    }
    ll res=0;
    for(int i=0;i<=n;i++){
        if(i){
            if(s[i-1]=='(') a++;
            if(s[i-1]==')') c--;
            if(s[i-1]=='?'){
                b++;
                d--;
            }
        }
        int kc=c-a;
        ll ans1=mul(a,nCk(b+d,kc+d));
        ll ans2=mul(b,nCk(b+d-1,kc+d-1));
        res=add(res,add(ans1,ans2));
    }
    cout<<res;
}
