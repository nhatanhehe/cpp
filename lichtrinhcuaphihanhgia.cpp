const ll inf=1e18;
const ll N=8e3+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int pre[4][N],n,k,t,ans=-inf;
int S(int tp,int l,int r){
    if(l>r) return 0;
    return pre[tp][r]-pre[tp][l-1];
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k>>t;
    for(int i=1;i<=n;i++){
        char c;
        cin>>c;
        pre[1][i]=pre[1][i-1]+(c=='1');
        pre[2][i]=pre[2][i-1]+(c=='2');
        pre[3][i]=pre[3][i-1]+(c=='3');
    }
    if(pre[1][n]<=k){
        int x=pre[1][n]+pre[2][n]-k;
        x=max(x,0LL);
        ans=max(ans,n-x);
    }
    if(pre[1][n]+pre[2][n]<=k){
        ans=max(ans,n);
    }
    t++;
    for(int i=t;i<=n;i++){
        for(int j=i;j+t<=n+1;j++){
            if(S(1,1,i-1)+S(2,1,i-1)+S(1,j+1,n)+S(2,j+1,n)<=k){
                ans=max(S(1,1,i-t)+S(1,j+t,n)+S(2,1,i-t)+S(2,j+t,n)+S(3,1,i-t)+S(3,j+t,n),ans);
            }
            else{
                int ned=S(1,1,i-1)+S(2,1,i-1)+S(1,j+1,n)+S(2,j+1,n)-k;
                ans=max(ans,S(1,1,i-t)+S(1,j+t,n)+S(2,1,i-t)+S(2,j+t,n)+S(3,1,i-t)+S(3,j+t,n)-ned);
            }
        }
    }
    cout<<(ans==-inf? -1:ans);
}
