inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
string s,t;
int cnt1=0,cnt0=0;
int n,m,pi[N];
void crash(){
    while(cnt1--) cout<<1;
    while(cnt0--) cout<<0;
    exit(0);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>s>>t;
    for(char c:s) if(c=='1') cnt1++; else cnt0++;
    n=s.size();
    m=t.size();
    s=" "+s;
    t=" "+t;
    //cout<<cnt1<<" "<<cnt0<<'\n';
    for(int i=2;i<=m;i++){
        int j=pi[i-1];
        while(j&&t[j+1]!=t[i]) j=pi[j];
        if(t[j+1]==t[i]) pi[i]=j+1;
        else pi[i]=0;
    }
    //or(int i=1;i<=m;i++) cout<<t[i];
   // cout<<pi[m]<<'\n';
    for(int i=1;i<=m;i++){
        //cout<<"9490 "<<" "<<t[i]<<'\n';
        if(t[i]=='1'){
            if(!cnt1) crash();
            cnt1--;
            cout<<1;
        }
        if(t[i]=='0'){
            if(!cnt0) crash();
            cnt0--;
            cout<<0;
        }
    }
    n-=m;
    while(n){
        for(int i=pi[m]+1;i<=m;i++){
            if(t[i]=='1'){
                if(!cnt1) crash();
                cnt1--;
                cout<<1;
                n--;
                if(n==0) exit(0);
            }
            if(t[i]=='0'){
                if(!cnt0) crash();
                cnt0--;
                cout<<0;
                n--;
                if(n==0) exit(0);
            }
        }
    }
}
