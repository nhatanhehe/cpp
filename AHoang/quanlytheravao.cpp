#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,u,v,p[N],state[N],sz[N],id[N],cnt;
char tp;
int acs(int u){
    return u==p[u]? u:p[u]=acs(p[u]);
}
void join(int u,int v){
    u=acs(u);
    v=acs(v);
    if(u==v){
        state[u]=2;
    }
    else{
        p[v]=u;
        sz[u]+=sz[v];
        state[u]=(state[v]==2||state[u]==2? 2:1);
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q;
    cnt=n;
    for(int i=1;i<=n;i++){
        p[i]=i;
        sz[i]=1;
        id[i]=i;
    }
    while(q--){
        cin>>tp;
        if(tp=='+'){
            cin>>u>>v;
            join(id[u],id[v]);
        }
        if(tp=='-'){
            cin>>u;
            int par=acs(id[u]);
            if(state[par]==1&&--sz[par]==1) state[par]=0;
            id[u]=++cnt;
            p[cnt]=cnt;
            sz[id[u]]=1;
        }
        if(tp=='?'){
            cin>>u;
            u=acs(id[u]);
            if(state[u]==0) cout<<0;
            else if(state[u]==1) cout<<'?';
            else cout<<1;
        }
    }
}
