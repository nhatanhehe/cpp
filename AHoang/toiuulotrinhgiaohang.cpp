inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,dp[N],l;
struct pt{
    int g,p,r;
}a[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>l;
    for(int i=1;i<=n;i++){
        cin>>a[i].g>>a[i].p>>a[i].r;
    }
    sort(a+1,a+n+1,[&](const pt &x,const pt &y){
        return x.g<y.g;
    });
    for(int i=1;i<=n;i++){
        dp[i]=a[i].r;
        for(int j=i-1;j>=1;j--){
            if(abs(a[i].p-a[j].p)<=l){
                dp[i]=max(dp[i],dp[j]+(abs(a[i].p-a[j].p)<=abs(a[i].g-a[j].g))*a[i].r);
            }
        }
    }
    cout<<*max_element(dp+1,dp+n+1);
}
