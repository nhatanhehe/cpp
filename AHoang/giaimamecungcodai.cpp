inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,t[N],u,v,h[N],d[N];
vector<int>g[N];
int sz[N],is_centroid[N];
void dfs(int u,int par){
    sz[u]=1;
    for(int v:g[u]){
        if(par!=v&&!is_centroid[v]){
            dfs(v,u);
            sz[u]+=sz[v];
        }
    }
}
int find_centroid(int u,int tree_sz,int par){
    for(int v:g[u]){
        if(v!=par&&!is_centroid[v]&&sz[v]>tree_sz/2) return find_centroid(v,tree_sz,u);
    }
    return u;
}
int root,id;
unordered_map<int,vector<ii>>lis[N];
unordered_map<int,int>iter[N];
struct pt{
    int len,u,branch;
};
vector<pt>node,up[N];
void dfs3(int u,int p,int h,int id){
    node.pb({h,u,id});
    for(int v:g[u]){
        if(v!=p&&!is_centroid[v]){
            dfs3(v,u,h+1,id);
        }
    }
}
void build_centroid(int u,int pre_centroid){
    dfs(u,-1);
    int centroid=find_centroid(u,sz[u],-1);
    if(!root) root=centroid;
    is_centroid[centroid]=1;
    id=0;
    node.clear();
    for(int v:g[centroid]){
        if(!is_centroid[v]){
            dfs3(v,-1,1,++id);
        }
    }
    for(auto [len,cen,branch]:node){
        up[cen].pb({len,centroid,branch});
        lis[centroid][len].pb({cen,branch});
    }
    lis[centroid][0].pb({centroid,-1});
    up[centroid].pb({0,centroid,-1});
    for(int v:g[centroid]){
        if(!is_centroid[v]) build_centroid(v,centroid);
    }
}
