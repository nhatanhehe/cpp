#define fi first
#define se second
const ll inf=1e18;
const ll N=7e3+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,m,c[N],s[N],e[N],dist[N],vis[N];
vector<int>adj[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k>>m;
    vector<int>dp(m+3,1e18);
    for(int i=1;i<=n;i++){
        cin>>c[i]>>s[i]>>e[i];
        adj[c[i]].pb(i);
    }
    dp[0]=0;
    for(int j=1;j<=k;j++){
        vector<int>ndp(m+3,1e18);
        for(int i=0;i<m;i++){
            for(int idx:adj[j]){
                int p=(i-s[idx]);
                if(p<0) p+=m;
                else p%=m;
                ndp[i]=min(ndp[i],dp[p]+e[idx]);
            }
        }
        swap(dp,ndp);
    }
    vector<ii>avl;
    for(int i=0;i<m;i++){
        if(dp[i]!=1e18) avl.pb({i,dp[i]});
    }
    fill(dist+1,dist+m+1,1e18);
    dist[0]=0;
    while(true){
        ii f={1e18,1e18};
        for(int i=0;i<m;i++){
            if(!vis[i]) f=min(f,ii(dist[i],i));
        }
        if(f==ii(1e18,1e18)) break;
        auto [cost,u]=f;
        vis[u]=1;
        for(auto [i,w]:avl){
            int v=(u+i)%m;
            if(dist[v]>dist[u]+w){
                dist[v]=dist[u]+w;
            }
        }
    }
    for(int i=0;i<m;i++) cout<<(dist[i]==1e18? -1:dist[i])<<'\n';
}
