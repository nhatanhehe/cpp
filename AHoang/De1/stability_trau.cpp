namespace sub4{
    int pre[N],npre[N];
    void solve(){
        pre[0]=0;
        for(int i=1;i<=n;i++){
            pre[i]=pre[i-1]+a[i];
        }
        int last=0,ans=0;
        for(int j=1;j>=0;j--){
            memset(npre,0,sizeof npre);
            int num=(1<<j);
            int S=0;
            npre[0]=1;
            for(int i=1;i<=n;i++){
                S=add(S,npre[pre[i]%num]);
                npre[pre[i]%num]=add(npre[pre[i]%num],1);
            }
            S=sub(S,last);
            ans=add(ans,mul(S,num));
            last=S;
        }
        cout<<ans;
    }
}
