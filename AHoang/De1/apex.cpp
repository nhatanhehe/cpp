inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N];
map<vector<int>,bool>mp;
namespace sub1{
    ll ans=0;
    void ql(vector<int>a){
        ll sum=0;
        if(mp.find(a)!=mp.end()) return;
        for(int i=0;i<a.size();i++){
            sum+=a[i];
            ans=add(ans,sum);
        }
        mp[a]=1;
        int mx=0;
        for(int i=0;i<a.size();i++){
            if(i>0&&a[i]>mx){
                swap(a[i],a[i-1]);
                ql(a);
                swap(a[i],a[i-1]);
            }
            mx=max(mx,a[i]);
        }
    }
    void solve(){
        vector<int>b;
        for(int i=1;i<=n;i++){
            b.pb(a[i]);
        }
        ql(b);
        cout<<ans<<'\n';
    }
}
namespace sub2{
    void solve(){
        ll sum=0;
        ll s2=1;
        for(int i=1;i<=n;i++){
            sum=add(a[i],sum);
            if(i<n) s2=mul(s2,a[i]);
        }
        ll ans=0;
        for(int i=1;i<=n;i++){
            ans=add(ans,mul(mul(sum,s2),i));
        }
        cout<<ans;
    }
}
namespace sub3{
    void solve(){
        int it1=0,it2=0,mx=0;
        ll pre=0,sum=0;
        for(int i=1;i<=n;i++){
            pre=add(pre,a[i]);
            sum=add(sum,pre);
            if(i>1&&a[i]>mx){
                if(!it1) it1=i;
                else if(!it2) it2=i;
            }
            mx=max(mx,a[i]);
        }
        ll ans=0;
        if(!it1){
            ans=sum;
        }
        if(!it2){
            for(int i=it1;i>=1;i--){
                ans=add(ans,sum);
                sum=add(sum,a[i]);
                sum=sub(sum,a[i-1]);
                swap(a[i],a[i-1]);
            }
        }
        else{
            for(int i=it1;i>=1;i--){
                ll save=sum;
                for(int j=it2;j>=1;j--){
                    //cout<<save<<'\n';
                    ans=add(ans,save);
                    save=add(save,a[it2]);
                    save=sub(save,a[j-1]);
                }
                sum=add(sum,a[i]);
                sum=sub(sum,a[i-1]);
                swap(a[i],a[i-1]);
            }
        }
        cout<<ans;
    }
}
