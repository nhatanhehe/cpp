inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,q,c[N],p[N],leaf[N];
multiset<int,greater<int>>col[N];
void build(int id=1,int l=1,int r=m){
    if(l==r){
        leaf[l]=id;
        return;
    }
    int mid=(l+r)>>1;
    build(id*2,l,mid);
    build(id*2+1,mid+1,r);
}
struct SegtreeSum{
    vector<ll>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(4*n+6,0);
    }

    inline void up(int pos){
        int id=leaf[pos];
        tree[id]=(*col[pos].begin());
        int i=id>>1;
        while(i){
            tree[i]=tree[i*2]+tree[i*2+1];
            i>>=1;
        }
    }
};
struct SegtreeMax{
    vector<ll>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(4*n+5,-1e18);
    }

    inline void up(int pos){
        int id=leaf[pos];
        auto it=col[pos].begin();
        it++;
        if(it!=col[pos].end()) tree[id]=(*it);
        else tree[id]=-1e18;
        int i=id>>1;
        while(i){
            tree[i]=max(tree[i*2],tree[i*2+1]);
            i>>=1;
        }
    }

};
struct SegtreeMin{
    vector<ll>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(4*n+4,0);
    }

    inline void up(int pos){
        int id=leaf[pos];
        tree[id]=(*col[pos].begin());
        int i=id>>1;
        while(i){
            tree[i]=min(tree[i*2],tree[i*2+1]);
            i>>=1;
        }
    }
};
int tp,id,pp,cl;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>q;
    build();
    SegtreeSum sum;
    sum.init(m);
    SegtreeMax Max;
    Max.init(m);
    SegtreeMin Min;
    Min.init(m);
    for(int i=1;i<=n;i++){
        cin>>c[i]>>p[i];
        col[c[i]].insert(p[i]);
        sum.up(c[i]);
        Max.up(c[i]);
        Min.up(c[i]);
    }
    cout<<max(sum.tree[1],sum.tree[1]-Min.tree[1]+Max.tree[1])<<'\n';
    while(q--){
        cin>>tp;
        if(tp==1){
            cin>>id>>cl;
            int &x=c[id];
            col[x].erase(col[x].find(p[id]));
            sum.up(x);
            Max.up(x);
            Min.up(x);
            x=cl;
            col[x].insert(p[id]);
            sum.up(x);
            Max.up(x);
            Min.up(x);
        }
        else{
            cin>>id>>pp;
            int x=c[id];
            col[x].erase(col[x].find(p[id]));
            col[x].insert(pp);
            sum.up(x);
            Max.up(x);
            Min.up(x);
            p[id]=pp;
        }
        ll mx1=sum.tree[1];
        ll mx2=-1e18;
        if(Max.tree[1]!=-1e18) mx2=sum.tree[1]-Min.tree[1]+Max.tree[1];
        cout<<max(mx1,mx2)<<'\n';
    }
}
