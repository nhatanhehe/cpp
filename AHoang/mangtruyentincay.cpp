const ll inf=1e18;
const ll N=1e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,q,a[1004][1004],res;
int dx[]={0,1,0,-1};
int dy[]={1,0,-1,0};
int d[N];
void up(int i,int j,int tp,int lim){
    for(int kk=0;kk<lim;kk++){
        int x=i+dx[kk],y=j+dy[kk];
        if(1<=x&&x<=n&&1<=y&&y<=n){
            if(abs(a[i][j]-a[x][y])==1){
                int mn=min(a[i][j],a[x][y]);
                if(tp==1){
                    d[mn]++;
                    if(d[mn]==1) res--;
                }
                else{
                    d[mn]--;
                    if(d[mn]==0) res++;
                }
            }
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
        }
    }
    res=k-1;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            up(i,j,1,2);
        }
    }
    cout<<res<<'\n';
    int q;
    cin>>q;
    while(q--){
        int i,j,val;
        cin>>i>>j>>val;
        up(i,j,2,4);
        a[i][j]=val;
        up(i,j,1,4);
        cout<<res<<'\n';
    }
}
