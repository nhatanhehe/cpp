#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "tdiam"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,u,v,w,st[N],en[N],p[N][20],h[N],timer,k,q,Min[N][20],chain[N],dsu[N];
vector<ii>g[N],adj[N];
vector<int>ord;
void dfs(int u,int par){
    st[u]=++timer;
    for(auto [v,w]:g[u]){
        if(v!=par){
            p[v][0]=u;
            Min[v][0]=w;
            h[v]=h[u]+1;
            dfs(v,u);
        }
    }
    en[u]=timer;
}
bool cmp(int i,int j){
    return st[i]<st[j];
}
ii lca(int u,int v){
    if(h[u]<h[v]) swap(u,v);
    int res=1e9;
    for(int i=19;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)){
            res=min(Min[u][i],res);
            u=p[u][i];
        }
    }
    if(u==v) return ii(u,res);
    for(int i=19;i>=0;i--){
        if(p[u][i]!=p[v][i]){
            res=min({res,Min[u][i],Min[v][i]});
            u=p[u][i];
            v=p[v][i];
        }
    }
    res=min({res,Min[u][0],Min[v][0]});
    return ii(p[u][0],res);
}
bool is_acs(int u,int v){
    return st[u]<=st[v]&&st[v]<=en[u];
}
struct pt{
    int u,v,w;
};
vector<pt>edges;
int acs(int u){
    return dsu[u]==u? u:dsu[u]=acs(dsu[u]);
}
bool join(int u,int v){
    u=acs(u);
    v=acs(v);
    if(u!=v){
        dsu[v]=u;
        chain[u]+=chain[v];
        if(chain[u]>=2) return 1;
    }
    return 0;
}
void build_virtual_tree(){
    cin>>k;
    ord.resize(k);
    for(int i=0;i<k;i++){
        cin>>ord[i];
        chain[ord[i]]=1;
    }
    sort(all(ord),cmp);
    for(int i=0;i<k-1;i++){
        //cout<<ord[i]<<" "<<ord[i+1]<<" "<<lca(ord[i],ord[i+1]).fi<<'\n';
        ord.pb(lca(ord[i],ord[i+1]).fi);
    }
    sort(all(ord),cmp);
    ord.erase(unique(all(ord)),ord.end());
    for(int x:ord) dsu[x]=x;
    stack<int>st;
    for(int u:ord){
        while(st.size()&&!is_acs(st.top(),u)) st.pop();
        if(st.size()){
            //cout<<st.top()<<" "<<u<<" "<<lca(st.top(),u).se<<'\n';
            edges.pb({st.top(),u,lca(st.top(),u).se});
        }
        st.push(u);
    }
    sort(all(edges),[&](const pt &x,const pt &y){
        return x.w>y.w;
    });
    int ans=0;
    for(auto [u,v,w]:edges){
        bool tf=join(u,v);
        if(tf){
            ans=w;
            break;
        }
    }
    cout<<ans<<'\n';
    edges.clear();
    for(int x:ord){
        chain[x]=0;
    }
    ord.clear();
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<n;i++){
        cin>>u>>v>>w;
        g[u].pb({v,w});
        g[v].pb({u,w});
    }
    dfs(1,-1);
    for(int j=1;(1<<j)<=n;j++){
        for(int i=1;i<=n;i++){
            p[i][j]=p[p[i][j-1]][j-1];
            Min[i][j]=min(Min[i][j-1],Min[p[i][j-1]][j-1]);
        }
    }

    cin>>q;
    while(q--){
        build_virtual_tree();
    }
}
