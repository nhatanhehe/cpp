inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,u,v,q,k,h[N],st[N],en[N],p[N][20],timer;
vector<int>g[N];
void dfs(int u,int par){
    st[u]=++timer;
    for(int v:g[u]){
        if(v!=par){
            h[v]=h[u]+1;
            p[v][0]=u;
            dfs(v,u);
        }
    }
    en[u]=timer;
}
int lca(int u,int v){
    if(h[u]<h[v]) swap(u,v);
    for(int i=19;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)) u=p[u][i];
    }
    if(u==v) return u;
    for(int i=19;i>=0;i--){
        if(p[u][i]!=p[v][i]){
            u=p[u][i];
            v=p[v][i];
        }
    }
    return p[u][0];
}
bool cmp(int x,int y){
    return st[x]<st[y];
}
bool is_acs(int u,int v){
    return st[u]<=st[v]&&en[v]<=en[u];
}
int dsu[N],sz[N],d[N];
bool riel[N];
int acs(int u){
    return u==dsu[u]? u:dsu[u]=acs(dsu[u]);
}
void join(int u,int v){
    u=acs(u);
    v=acs(v);
    if(u!=v){
        dsu[v]=u;
        sz[u]+=sz[v];
    }
}
void solve(){
    cin>>k;
    vector<int>ord(k);
    for(int i=0;i<k;i++){
        cin>>ord[i];
        riel[ord[i]]=1;
    }
    sort(all(ord),cmp);
    for(int i=0;i<k-1;i++){
        int lc=lca(ord[i],ord[i+1]);
        if(lc==ord[i]){
            ord.pb(p[ord[i+1]][0]);
        }
        else ord.pb(lc);
    }
    sort(all(ord),cmp);
    ord.erase(unique(all(ord)),ord.end());
    stack<int>st;
    vector<ii>edg;
   // cout<<is_acs(1,2)<<'\n';
    for(int u:ord){
        dsu[u]=u;
        sz[u]=1;
    }
    for(int u:ord){
        while(st.size()&&!is_acs(st.top(),u)){
           // cout<<is_acs(st.top(),u)<<'\n';
            st.pop();
        }
        if(st.size()){
            int lc=lca(st.top(),u);
            if(lc==st.top()){
                if(h[st.top()]+1==h[u]){
                    if(riel[st.top()]&&riel[u]) join(st.top(),u);
                }
            }
            else if(riel[st.top()]&&riel[u]) join(st.top(),u);
        }
        st.push(u);
    }
    ll ans=0;
    for(int u:ord){
        int par=acs(u);
        if(!d[par]){
            ans+=1LL*sz[par]*(sz[par]-1)/2;
            d[par]=1;
        }
    }
    cout<<ans<<'\n';
    for(int u:ord){
        riel[u]=0;
        d[u]=0;
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<n;i++){
        cin>>u>>v;
        g[u].pb(v);
        g[v].pb(u);
    }
    dfs(1,-1);
    for(int j=1;j<=19;j++){
        for(int i=1;i<=n;i++){
            p[i][j]=p[p[i][j-1]][j-1];
        }
    }
    cin>>q;
    while(q--){
        solve();
    }
}
