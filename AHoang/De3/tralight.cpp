inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,a[N],x,y,k;
int intersect(int l,int r,int u,int v){
    return min(r,v)-max(l,u)+1;
}
bool check_in(int l,int r,int u,int v){
    return max(l,u)<=min(r,v);
}
bool inside(int l,int r,int u,int v){
    return u<=l&&r<=v;
}
namespace sub2{
    ll dp[505][504][2];
    void solve(){
        while(m--){
            cin>>x>>y>>k;
            vector<ii>li;
            ll dist=0;
            int state=0;
            for(int i=1;i<=n;i++){
                if(check_in(x,y,dist+1,dist+a[i])){
                    li.pb(ii(intersect(x,y,dist+1,dist+a[i]),i%2));
                }
                dist+=a[i];
            }
           // for(auto [len,col]:li) cout<<len<<" "<<col<<'\n'; cout<<'\n';

            vector<ii>it={ii(0,0)};
            for(int i=0;i<li.size();i++){
                if(li[i].se==1){
                    int cost=0;
                    if(i>0) cost++;
                    if(i<li.size()-1) cost++;
                    it.pb(ii(li[i].fi,cost));
                }
            }
            //for(auto [item,cost]:it) cout<<item<<" "<<cost<<'\n';

            vector<vector<ll>>dp(it.size()+2,vector<ll>(k+4,0));
            ll ans=0;
            for(int i=1;i<it.size();i++){
                for(int j=0;j<=k;j++){
                    dp[i][j]=dp[i-1][j];
                    if(j>=it[i].se){
                        dp[i][j]=max(dp[i][j],dp[i-1][j-it[i].se]+it[i].fi);
                    }
                    ans=max(ans,dp[i][j]);
                }
            }
            //cout<<dp[3][2]<<'\n';
            //cout<<'\n';
            cout<<ans<<'\n';
        }
    }
}
