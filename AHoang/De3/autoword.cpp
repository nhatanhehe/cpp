namespace sub3{
    string t;
    int k;
    int kmp[N],nxt[N]['z'+3];
    void build_kmp(){
        for(int i=2;i<=k;i++){
            int j=kmp[i-1];
            while(j&&t[j+1]!=t[i]) j=kmp[j];
            if(t[j+1]==t[i]) kmp[i]=j+1;
            else kmp[i]=0;
        }
        for(int i=0;i<=k;i++){
            for(int c='a';c<='z';c++){
                if(i==k){
                    nxt[i][c]=k;
                    continue;
                }
                int j=i;
                while(j&&t[j+1]!=c) j=kmp[j];
                if(t[j+1]==c) nxt[i][c]=j+1;
                else nxt[i][c]=0;
            }
        }
    }
    ll dp[N][N];
    void solve(){
        t=s[1];
        k=t.size();
        t=" "+t;
        build_kmp();
        dp[0][0]=1;
        for(int i=0;i<=n;i++){
            for(int j=0;j<k;j++){
                for(int c='a';c<='z';c++){
                    int nx=nxt[j][c];
                    if(nx==k) continue;
                    dp[i+1][nx]=add(dp[i+1][nx],dp[i][j]);
                }
            }
        }
        ll ans=0;
        for(int j=0;j<k;j++){
            ans=add(ans,dp[n][j]);
        }
        cout<<ans;
    }
}
