using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "qcsys"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=3e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,a[3][N];
char tp;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q;
    for(int i=1;i<=2;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
        }
    }
    while(q--){
        cin>>tp;
        if(tp=='P'){
            int l,r;
            cin>>l>>r;
            vector<int>p;
            for(int i=l;i<=r;i++) p.pb(i);
            int ans=1e9;
            do{
                multiset<int>s;
                s.insert(a[1][p[0]]);
                for(int i:p){
                    s.insert(a[2][i]);
                }
                int mid=(r-l+3)/2;
                for(int it:s){
                    mid--;
                    if(!mid){
                        ans=min(ans,it);
                        break;
                    }
                }
                for(int t=1;t<p.size();t++){
                    s.insert(a[1][p[t]]);
                    s.erase(s.find(a[2][p[t-1]]));
                    int mid=(r-l+3)/2;
                    for(int it:s){
                        mid--;
                        if(!mid){
                            ans=min(ans,it);
                            break;
                        }
                    }
                }
            }while(next_permutation(all(p)));
            cout<<ans<<'\n';
        }
        else{
            int x,y,val;
            cin>>x>>y>>val;
            a[x][y]=val;
        }
    }
}
