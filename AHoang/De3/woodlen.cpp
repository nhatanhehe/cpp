inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,a[N],cnt[N];
namespace sub2{
    void solve(){
        sort(a+1,a+n+1,greater<int>());
        multiset<int>s;
        for(int i=1;i<=n;i++) s.insert(a[i]);
        for(int i=1;i<=2;i++){
            s.erase(a[i]);
            int k=a[i]/2;
            s.insert(k);
            s.insert(a[i]-k);
            cout<<(*s.rbegin())-(*s.begin())<<" ";
        }
    }
}
namespace sub3{
    void solve(){
        int sum=0;
        for(int i=1;i<=n;i++){
            if(a[i]==3) sum+=2;
            if(a[i]==2) sum+=1;
        }
        for(int i=1;i<=m;i++){
            if(i<sum) cout<<1<<" ";
            else cout<<0<<" ";
        }
    }
}
