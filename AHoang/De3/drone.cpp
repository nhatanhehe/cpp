inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m;
int a[N][N],row[N][N],col[N][N];
ll f[1000006];
ll exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    int t=exp(a,n/2);
    if(n&1) return ((t*t)%mod*a%mod)%mod;
    else return (t*t)%mod;
}
ll C(int n,int k){
    int a=f[n];
    int b=(f[k]*(f[n-k]))%mod;
    return a*exp(b,mod-2)%mod;
}
void cal(){
    f[0]=1;
    for(int i=1;i<=1e6;i++){
        f[i]=mul(f[i-1],i);
    }
}
namespace sub3{
    int pre[55][55][55];
    void solve(){
        vector<ii>vec;
        for(int i=1;i<=m;i++){
            for(int l=1;l<=n;l++){
                for(int r=l;r<=n;r++){
                    pre[i][l][r]=pre[i-1][l][r]+row[i][r]-row[i][l-1];
                }
            }
        }
        for(int x=1;x<=n;x++){
            for(int i=1;i<=m;i++){
                for(int j=1;j+x-1<=n;j++){
                    if(row[i][j+x-1]-row[i][j-1]!=0) continue;
                    int l=i,r=m,mx_y=1;
                    while(l<=r){
                        int mid=(l+r)>>1;
                        if(pre[mid][j][j+x-1]-pre[i-1][j][j+x-1]==0){
                            l=mid+1;
                            mx_y=mid;
                        }
                        else r=mid-1;
                    }
                    vec.pb(ii(x,mx_y));
                }
            }
        }
        sort(all(vec));
        vec.erase(unique(all(vec)),vec.end());
        for(int i=vec.size()-2;i>=0;i--){
            vec[i].se=max(vec[i].se,vec[i+1].se);
        }
        ll ans=0;
        for(int a=0;a<n;a++){
            int it=0;
            for(int b=0;b<n;b++){
                if(a+b+1>n) continue;
                while(it<vec.size()&&vec[it].fi<a+b+1) it++;
                if(it<vec.size()){
                    for(int c=0;c<n;c++){
                        for(int d=0;d<n;d++){
                            if(c+d+1>n) continue;
                            if(vec[it].se>=c+d+1){
                                ans=add(ans,f[a+b+c+d]);
                            }
                        }
                    }
                }
            }
        }
        cout<<sub(ans,1);
    }
}
namespace sub1{
    void solve(){
        vector<int>vec;
        int cnt=0;
        for(int i=1;i<=n;i++){
            if(a[1][i]==0) cnt++;
            else{
                if(cnt) vec.pb(cnt);
                cnt=0;
            }
        }
        if(cnt) vec.pb(cnt);
        sort(all(vec));
        vec.erase(unique(all(vec)),vec.end());
        ll ans=0;
        for(int a=0;a<n;a++){
            int it=0;
            for(int b=0;b<n;b++){
                if(a+b+1>n) continue;
                while(it<vec.size()&&vec[it]<a+b+1) it++;
                if(it<vec.size()){
                    ans=add(ans,f[a+b]);
                }
            }
        }
        cout<<ans;
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cal();
    cin>>m>>n;
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            char x;
            cin>>x;
            a[i][j]=x-'0';
        }
    }
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            row[i][j]=row[i][j-1]+a[i][j];
        }
    }
    for(int j=1;j<=n;j++){
        for(int i=1;i<=m;i++){
            col[i][j]=col[i-1][j]+a[i][j];
        }
    }
    if(m==1) sub1::solve();
    else sub3::solve();
}
