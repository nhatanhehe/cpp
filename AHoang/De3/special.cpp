inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
string s,p;
int n,m,pre[N],suf[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>s>>p;
    n=s.size();
    m=p.size();
    s=" "+s;
    p=" "+p;
    //if(n==1) return cout<<1<<" "<<p[1],0;
    int j=1;
    for(int i=1;i<=n;i++){
        //cout<<i<<" "<<s[i]<<" "<<p[j]<<'\n';
        while(j<=m&&p[j]!=s[i]){
           //cout<<p[j]<<" "<<s[i]<<'\n';
            j++;
        }
        pre[i]=j;
        j++;
       // cout<<i<<" "<<pre[i]<<'\n';
    }
    j=m;
    suf[n+1]=m+1;
    for(int i=n;i>=1;i--){
        while(j>=1&&p[j]!=s[i]) j--;
        suf[i]=j;
        j--;
    }
    for(int i=1;i<=n;i++){
        //cout<<i-1<<" "<<pre[i-1]<<" "<<i+1<<" "<<suf[i+1]<<'\n';
        if(pre[i-1]<suf[i+1]-1){
            if(pre[i]>=suf[i+1]){
                cout<<i<<" "<<p[pre[i-1]+1];
                return 0;
            }
            else if(pre[i]-1>pre[i-1]) return cout<<i<<" "<<p[pre[i]-1],0;
        }
    }
}
