inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],dp[N],pre[N];
namespace sub1{
    int dp[705][705];
    void solve(){
        for(int i=1;i<=n;i++){
            for(int j=1;j<=i;j++){
                if(j==1){
                    if(pre[i]-pre[j-1]>0) dp[i][j]=1;
                }
                else{
                    for(int k=j-1;k>=1;k--){
                        if(pre[j-1]-pre[k-1]>0&&pre[j-1]-pre[k-1]<=pre[i]-pre[j-1]) dp[i][j]=max(dp[i][j],dp[j-1][k]+1);
                    }
                }
            }
        }
        int ans=0;
        for(int i=1;i<=n;i++) ans=max(ans,dp[n][i]);
        cout<<ans;
    }
}
namespace sub2{
    vector<ii>dpb[2504];
    int dp[2504][2504];
    void solve(){
        dpb[0].pb(ii(0,0));
        for(int i=1;i<=n;i++){
            for(int j=1;j<=i;j++){
                if(pre[i]-pre[j-1]>0){
                    if(dpb[j-1].empty()) continue;
                    int k=upper_bound(all(dpb[j-1]),ii(pre[i]-pre[j-1],1e9))-dpb[j-1].begin()-1;
                    if(k==-1) continue;
                    dp[i][j]=dpb[j-1][k].se+1;
                    dpb[i].pb(ii(pre[i]-pre[j-1],dp[i][j]));
                }
            }
            sort(all(dpb[i]));
            for(int j=1;j<dpb[i].size();j++){
                dpb[i][j].se=max(dpb[i][j].se,dpb[i][j-1].se);
            }
        }
        int ans=0;
        for(int i=1;i<=n;i++){
            ans=max(ans,dp[n][i]);
        }
        cout<<ans;
    }
}
