inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,a[N][N],dp_cur[N*N],dp_before[N*N];
vector<ii>col[N];
struct SegmentTree{
    vector<ll>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(n*4+4,1e18);
    }

    void up(int pos,ll k,int id,int l,int r){
        if(l==r){
            tree[id]=min(k,tree[id]);
            return;
        }
        int mid=(l+r)>>1;
        if(pos<=mid) up(pos,k,id*2,l,mid);
        else up(pos,k,id*2+1,mid+1,r);
        tree[id]=min(tree[id*2],tree[id*2+1]);
    }

    void up(int pos,int k){
        up(pos,k,1,1,n);
    }

    void reset(){
        fill(all(tree),1e18);
    }

    int get(int u,int v,int id,int l,int r){
        if(l>v||r<u) return 1e18;
        if(u<=l&&r<=v) return tree[id];
        int mid=(l+r)>>1;
        return min(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
    }

    int get(int u,int v){
        return get(u,v,1,1,n);
    }
};
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
            if(a[i][j]) col[a[i][j]].pb(ii(i,j));
        }
    }
    sort(all(col[1]),[&](const ii &x,const ii &y){
            return x.fi<y.fi;
    });
    for(int i=0;i<col[1].size();i++){
        auto [x,y]=col[1][i];
        dp_before[i+1]=abs(x-1)+abs(y-1);
    }
    //cout<<dp_before[1]<<'\n';
    for(int k=2;k<=m;k++){
        // TH1: xu>=xv
        vector<iii>tmp;
        for(int i=0;i<col[k-1].size();i++){
            tmp.pb({col[k-1][i].fi,col[k-1][i].se,dp_before[i+1]});
        }
        sort(all(tmp),[&](const iii &x,const iii &y){
            auto [xx,yx,costx]=x;
            auto [xy,yy,costy]=y;
            return xx<xy;
        });
        sort(all(col[k]),[&](const ii &x,const ii &y){
            return x.fi<y.fi;
        });
        SegmentTree seg1,seg2;
        seg1.init(n+3);
        seg2.init(n+3);
        int j=-1;
        for(int i=0;i<col[k].size();i++){
            dp_cur[i+1]=1e18;
        }
        vector<int>changes;
        for(int i=0;i<col[k].size();i++){
            while(j<tmp.size()-1&&get<0>(tmp[j+1])<=col[k][i].fi){
                j++;
                auto [x,y,dp]=tmp[j];
                seg1.up(y,dp-(x+y));
                seg2.up(y,dp-x+y);
                //change.pb(y);
            }
             auto [xu, yu] = col[k][i];
            ll v1 = seg1.get(1, (int)yu);
            dp_cur[i+1] = min(dp_cur[i+1], xu + yu + v1);
            ll v2 = seg2.get((int)yu, n);
            dp_cur[i+1] = min(dp_cur[i+1], xu - yu + v2);
        }
       // for(int x:change) seg.up_reset(x);
        // TH2 xu<=xy va yu<=yv
        seg1.reset();
        seg2.reset();
        j=tmp.size();
        for(int i=col[k].size()-1;i>=0;i--){
            while(j>0&&get<0>(tmp[j-1])>=col[k][i].fi){
                j--;
                auto [x,y,dp]=tmp[j];
                seg1.up(y,dp+x+y);
                seg2.up(y,dp+x-y);
            }
            auto [xu, yu] = col[k][i];
            ll v1 = seg1.get(yu, n);
            dp_cur[i+1] = min(dp_cur[i+1], v1 - (xu + yu));
            ll v2 = seg2.get(1, yu);
            dp_cur[i+1] = min(dp_cur[i+1], v2 - (xu - yu));

        }
        for(int i=0;i<col[k].size();i++) dp_before[i+1]=dp_cur[i+1];
    }
    ll ans=1e18;
    for(int i=0;i<col[m].size();i++) ans=min(ans,dp_before[i+1]);
    cout<<ans+1;
}
