inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,q,s[N],t[N],d[N],ori[N];
ii e[N];
namespace sub2{
    void solve(){
        for(int i=1;i<=n;i++){
            d[e[i].fi+offset]=e[i].se;
            ori[e[i].fi+offset]=e[i].se;
        }
        for(int i=1;i<=q;i++){
            int cur=s[i]+offset;
            vector<int>change;
            while(t[i]--){
                //cout<<cur-offset<<'\n';
                if(cur<=6000&&d[cur]){
                    d[cur]*=2;
                    change.pb(cur);
                    cur+=d[cur]/2;
                   // cout<<d[cur]<<'\n';
                }
                else{
                    cur--;
                }
            }
            cout<<cur-offset<<'\n';
            for(int id:change) d[id]=ori[id];
        }
    }
}
namespace sub3{
    void solve(){
        unordered_map<int,int>mp,ori;
        for(int i=1;i<=n;i++){
            mp[e[i].fi]=e[i].se;
            ori[e[i].fi]=i;
        }
        for(int i=1;i<=q;i++){
            vector<int>change;
            ll cur=s[i];
            while(t[i]>0){
                if(mp.find(cur)!=mp.end()){
                    mp[cur]*=2;
                    change.pb(ori[cur]);
                    cur+=mp[cur]/2;
                }
                else{
                    int l=1,r=n,ans;
                    while(l<=r){
                        int mid=(l+r)>>1;
                        if(e[mid].fi<=cur){
                            ans=mid;
                            l=mid+1;
                        }
                        else r=mid+1;
                    }
                    ll mn=min(t[i],cur-e[ans].fi);
                    t[i]-=mn;
                    cur-=mn;
                }
                t[i]--;
            }
            cout<<cur<<'\n';
            for(int id:change){
                mp[e[id].fi]=e[id].se;
            }
        }
    }
}
