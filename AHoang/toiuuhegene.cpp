#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,a[N],b[N],t[N],k,last[N];
vector<int>p[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>k;
    for(int i=1;i<=m;i++) cin>>a[i];
    for(int i=1;i<=m;i++) cin>>b[i];
    for(int i=1;i<=n;i++){
        cin>>t[i];
        for(int j=1;j<=t[i];j++){
            int x;
            cin>>x;
            p[i].pb(x);
        }
    }
    ll ans=-1e18;
    for(int i=1;i<=n;i++){
        for(int x:p[i]){
            last[x]=i;
        }
        vector<int>mp;
        for(int j=1;j<=m;j++) if(last[j]) mp.pb(j);
        sort(all(mp),[&](const int &x,const int &y){
            return last[x]>last[y];
        });
        int cur=last[mp[0]],it=0;
        ll sum_a=0,sum_b=0;
        while(it<mp.size()){
            while(it<mp.size()&&last[mp[it]]==cur){
                if(cur!=0){
                    sum_a+=a[mp[it]];
                    sum_b+=b[mp[it]];
                }
                it++;
            }
            if(sum_b<=k) ans=max(ans,sum_a);
            if(it==mp.size()) break;
            cur=last[mp[it]];
        }
    }
    cout<<ans;
}
