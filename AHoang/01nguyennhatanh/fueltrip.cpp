inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m;
ii a[N],b[N];
namespace sub1{
    void solve(){
        int fuel=a[1].se;
        int dist=a[1].fi;
        b[m+1]=ii(1e18,0);
        for(int i=1;i<=m+1;i++){
            if(b[i].fi<a[1].fi) continue;
            if(b[i].fi-dist>fuel){
                cout<<dist+fuel-a[1].fi;
                break;
            }
            else{
                fuel+=b[i].se-(b[i].fi-dist);
                dist=b[i].fi;
            }
        }
    }
}
namespace sub2{
    vector<int>tn;
    bool check(int x){
        int cnt=0;
        for(int i:tn){
            if(a[i].se<=x) cnt+=x-a[i].se;
        }
        return cnt<=b[1].se;
    }
    void solve(){
        ll ans=1e18;
        for(int i=1;i<=n;i++){
            if(a[i].fi>b[1].fi){
                ans=min(ans,a[i].se);
                continue;
            }
            if(b[1].fi-a[i].fi>a[i].se){
                ans=min(a[i].se,ans);
                continue;
            }
            tn.pb(i);
        }
        int l=1,r=1e18,res=0;
        while(l<=r){
            int mid=(l+r)>>1;
            if(check(mid)){
                res=mid;
                l=mid+1;
            }
            else r=mid-1;
        }
        cout<<min(ans,res);
    }
}
