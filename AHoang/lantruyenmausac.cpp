inline ll add(ll a, ll b) {
    a += b;
    if (a >= mod) a -= mod;
    return a;
}
inline ll sub(ll a, ll b) {
    a -= b;
    if (a < 0) a += mod;
    return a;
}
inline ll mul(ll a, ll b) {
    return (a * b) % mod;
}

ll f[1000006];
ll exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    int t=exp(a,n/2);
    if(n&1) return mul(t,mul(t,a));
    else return mul(t,t);
}
ll C(int n,int k){
    int a=f[n];
    int b=(f[k]*(f[n-k]))%mod;
    return a*exp(b,mod-2)%mod;
}
void cal(){
    f[0]=1;
    for(int i=1;i<=1e6;i++){
        f[i]=mul(f[i-1],i);
    }
}
int n,c[N],dp[N][N],sum[N];
