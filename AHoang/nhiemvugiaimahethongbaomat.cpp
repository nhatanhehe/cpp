#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=5e4+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,a[N],u,v,w;
vector<ii>g[N];
map<int,int>dist[N],f[N];
int res=1e18,ans=0;
struct pt{
    int cost,u,col;
};
struct cmp{
    bool operator() (const pt &x,const pt &y) const{
        return x.cost>y.cost;
    }
};
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=2;i<n;i++) cin>>a[i];
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        g[u].pb({v,w});
        g[v].pb({u,w});
    }
    priority_queue<pt,vector<pt>,cmp>pq;
    dist[1][0]=0;
    f[1][0]=1;
    pq.push({0,1,0});
    while(pq.size()){
        auto [cost,u,col]=pq.top(); pq.pop();
        if(cost>dist[u][col]) continue;
        for(auto [v,w]:g[u]){
            if(v==1) continue;
            if(v==n){
                if(res>cost+w){
                    res=cost+w;
                    ans=0;
                }
                if(res==cost+w){
                    ans=add(ans,f[u][col]);
                }
                continue;
            }
            if(!col){
                if(a[v]==a[u]){
                    if(dist[v].find(col)==dist[v].end()||dist[v][col]>dist[u][col]+w){
                        dist[v][col]=dist[u][col]+w;
                        f[v][col]=0;
                        pq.push({dist[v][col],v,col});
                    }
                    if(dist[v][col]==dist[u][col]+w){
                        f[v][col]=add(f[v][col],f[u][col]);
                    }
                }
                else{
                    if(dist[v].find(a[u])==dist[v].end()||dist[v][a[u]]>dist[u][col]+w){
                        dist[v][a[u]]=dist[u][col]+w;
                        f[v][a[u]]=0;
                        pq.push({dist[v][a[u]],v,a[u]});
                    }
                    if(dist[v][a[u]]==dist[u][col]+w){
                        f[v][a[u]]=add(f[v][a[u]],f[u][col]);
                    }
                }
            }
            else{
                if(a[v]==a[u]){
                    if(dist[v].find(col)==dist[v].end()||dist[v][col]>dist[u][col]+w){
                        dist[v][col]=dist[u][col]+w;
                        f[v][col]=0;
                        pq.push({dist[v][col],v,col});
                    }
                    if(dist[v][col]==dist[u][col]+w){
                        f[v][col]=add(f[v][col],f[u][col]);
                    }
                }
                else{
                    if(a[v]==col){
                        if(dist[v].find(a[u])==dist[v].end()||dist[v][a[u]]>dist[u][col]+w){
                            dist[v][a[u]]=dist[u][col]+w;
                            f[v][a[u]]=0;
                            pq.push({dist[v][a[u]],v,a[u]});
                        }
                        if(dist[v][a[u]]==dist[u][col]+w){
                            f[v][a[u]]=add(f[v][a[u]],f[u][col]);
                        }
                    }
                }
            }
        }
    }
    cout<<res<<'\n'<<ans<<'\n';
}
