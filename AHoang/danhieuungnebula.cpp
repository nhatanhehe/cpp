inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,d[N],t[N],a[N],pre[N];
vector<int>tree[N<<2];
void build(int id=1,int l=1,int r=n){
    if(l==r){
        tree[id].pb(a[l]);
        return;
    }
    int mid=(l+r)>>1;
    build(id*2,l,mid);
    build(id*2+1,mid+1,r);
    tree[id].resize(tree[id*2].size()+tree[id*2+1].size());
    merge(all(tree[id*2]),all(tree[id*2+1]),tree[id].begin());
}
int get(int u,int v,int k,int id=1,int l=1,int r=n){
    if(l>v||r<u) return 0;
    if(u<=l&&r<=v){
        return tree[id].size()-(lower_bound(all(tree[id]),k)-tree[id].begin());
    }
    int mid=(l+r)>>1;
    return get(u,v,k,id*2,l,mid)+get(u,v,k,id*2+1,mid+1,r);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>d[i];
        pre[i]=pre[i-1]+d[i];
    }
    for(int i=1;i<=n;i++){
        cin>>t[i];
        a[i]=pre[i]-t[i];
    }
    build();
    int ans=0,sum=0;
    for(int i=1;i<=n;i++){
        ans=max(ans,get(i,n,sum));
        sum+=d[i];
    }
    cout<<ans;
}
