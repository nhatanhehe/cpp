#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=1e2+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
const int lim=32000;
int n,u,v,w,t,p[N],m,dp1[N][lim],dp2[N][lim];
vector<ii>g[N],rev[N];
struct pt{
    int cost,u,ts;
};
struct cmp{
    bool operator()(const pt &x,const pt &y) const{
        return x.cost<y.cost;
    }
};
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n>>m;
        for(int i=1;i<=n;i++){
            cin>>p[i];
        }
        vector<pt>edge;
        for(int i=1;i<=m;i++){
            cin>>u>>v>>w;
            edge.pb({u,v,w});
            g[u].pb({v,w});
            rev[v].pb({u,w});
        }
        queue<ii>q;
        dp1[1][1]=1;
        q.push({1,1});
        while(q.size()){
            auto [u,cost]=q.front(); q.pop();
            for(auto [v,w]:g[u]){
                if(cost*w<=min(lim,p[v])&&!dp1[v][cost*w]){
                    dp1[v][cost*w]=1;
                    q.push(ii(v,cost*w));
                }
            }
        }
        priority_queue<pt,vector<pt>,cmp>pq;
        dp2[n][1]=p[n];
        pq.push({p[n],n,1});
        while(pq.size()){
            auto [cost,u,ts]=pq.top(); pq.pop();
            if(cost<dp2[u][ts]) continue;
            for(auto [v,w]:rev[u]){
                if(ts*w<=lim){
                    if(dp2[v][ts*w]<min(p[v],dp2[u][ts]/w)){
                        dp2[v][ts*w]=min(p[v],dp2[u][ts]/w);
                        pq.push({dp2[v][ts*w],v,ts*w});
                    }
                }
            }
        }
        int ans=-1;
        for(auto [u,v,w]:edge){
            vector<ii>vec;
            for(int s=sqrt(1e9);s>=1;s--){
                if(dp2[v][s]) vec.pb({dp2[v][s],s});
            }
            if(vec.empty()) continue;
            sort(all(vec));
            for(int i=(int)vec.size()-2;i>=0;i--){
                vec[i].se=max(vec[i].se,vec[i+1].se);
            }
            int j=(int)vec.size()-1;
            for(int s=sqrt(1e9);s>=1;s--){
                while(j>0&&vec[j-1].fi>=s*w){
                    j--;
                }
                if(dp1[u][s]&&vec[j].fi>=s*w){
                    ans=max(ans,s*w*vec[j].se);
                }
            }
        }
        cout<<ans<<'\n';
        for(int i=1;i<=n;i++){
            g[i].clear();
            rev[i].clear();
            for(int s=0;s<=sqrt(1e9);s++){
                dp1[i][s]=0;
                dp2[i][s]=0;
            }
        }
    }
}
