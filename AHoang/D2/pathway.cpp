inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,r,p[N],st[N],en[N],timer,dist[3004][3003],ver[N],w[N];
vector<int>g[N],adj[N];
void dfs(int u,int p){
    st[u]=++timer;
    ver[timer]=u;
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
        }
    }
    en[u]=timer;
}
int ans;
namespace sub2{
    void solve(){
        for(int i=1;i<=n;i++){
            int x=p[i],mx=i,mn=i;
            //cerr<<i<<": ";
            while(x!=0){
                //cerr<<x<<'\n';
                mx=max(mx,x);
                mn=min(mn,x);
                if(x==r) break;
                x=p[x];
            }
            int mx2=-1e9,mn2=1e9;
            for(int j=st[i]+1;j<=en[i];j++){
                mx2=max(mx2,ver[j]);
                mn2=min(mn2,ver[j]);
            }
            if(mx!=-1e9) adj[i].pb(mx);
            if(mx2!=-1e9) adj[i].pb(mx2);
            if(mn!=1e9) adj[i].pb(mn);
            if(mn2!=1e9) adj[i].pb(mn2);
        }
        for(int i=1;i<=n;i++){
            fill(dist[i]+1,dist[i]+n+1,1e9);
            dist[i][i]=0;
            queue<int>q;
            q.push(i);
            while(q.size()){
                int u=q.front(); q.pop();
                for(int v:adj[u]){
                    if(dist[i][v]>dist[i][u]+1){
                        dist[i][v]=dist[i][u]+1;
                        q.push(v);
                    }
                }
            }
            for(int j=1;j<=n;j++){
                if(dist[i][j]!=1e9&&i!=j) ans+=w[i]*w[j];
            }
        }
        cout<<ans<<'\n';
    }
}
