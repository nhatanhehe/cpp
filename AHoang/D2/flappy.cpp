inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n,h,k,s,l[N],r[N];
namespace sub1{
    void solve(){
        bool tf=1;
        for(int i=2;i<=n;i++){
            if(s<l[i]+1){
                s+=k;
                if(s!=l[i]+1){
                    tf=0;
                    break;
                }
            }
            else if(s>r[i]-1){
                s--;
                if(s!=r[i]-1){
                    tf=0;
                    break;
                }
            }
            else if(s==l[i]+1){
                tf=0;
                break;
            }
        }
        cout<<(tf? "Yes\n":"No\n");
    }
}
namespace sub2{
    bool tf;
    void ql(int i,int height){
        if(tf) return;
        if(i==n){
            tf=1;
            return;
        }
        if(l[i+1]+1<=height+k&&height+k<=r[i+1]-1) ql(i+1,height+k);
        if(l[i+1]+1<=height-1&&height-1<=r[i+1]-1) ql(i+1,height-1);
    }
    void solve(){
        tf=0;
        ql(1,s);
        cout<<(tf? "Yes\n":"No\n");
    }
}
namespace sub3{
    void solve(){
        vector<vector<int>>dp(n+3,vector<int>(100+4,0));
        dp[1][s]=1;
        for(int i=1;i<n;i++){
            for(int j=l[i]+1;j<=r[i]-1;j++){
                if(dp[i][j]){
                    if(l[i+1]+1<=j+k&&j+k<=r[i+1]-1) dp[i+1][j+k]=1;
                    if(l[i+1]+1<=j-1&&j-1<=r[i+1]-1) dp[i+1][j-1]=1;
                }
            }
        }
        bool tf=0;
        for(int i=l[n]+1;i<=r[n]-1;i++){
            if(dp[n][i]) tf=1;
        }
        cout<<(tf? "Yes\n":"No\n");
    }
}
namespace sub4{
    void solve(){
        vector<vector<int>>dp(n+3,vector<int>(110,0));
        dp[1][s-l[1]]=1;
        for(int i=1;i<n;i++){
            for(int j=1;j<=100;j++){
                if(dp[i][j]){
                    int height=j+l[i];
                    if(l[i+1]+1<=height+k&&height+k<=r[i+1]-1) dp[i+1][height+k-l[i+1]]=1;
                    if(l[i+1]+1<=height-1&&height-1<=r[i+1]-1) dp[i+1][height-1-l[i+1]]=1;
                }
            }
        }
        bool tf=0;
        for(int i=1;i<=100;i++){
            if(dp[n][i]) tf=1;
        }
        cout<<(tf? "Yes\n":"No\n");
    }
}
