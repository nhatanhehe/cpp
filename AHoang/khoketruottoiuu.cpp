#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=1e2+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,k,l[N],r[N],f[N][N],dp[N][N],c[N],mx,cost[N];
bool check(int i,int l,int r){
    return l<=i&&i<=r;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>k;
    for(int i=1;i<=n;i++){
        cin>>l[i]>>r[i]>>c[i];
        mx=max(mx,r[i]-l[i]+1);
    }
    for(int i=1;i<=m;i++){
        for(int t=1;t<=n;t++){
            if(check(i,l[t],r[t])) cost[i]+=c[t];
        }
        for(int j=i+1;j<=n;j++){
            for(int t=1;t<=n;t++){
                if(check(i,l[t],r[t])&&!check(j,l[t],r[t])){
                    f[i][j]+=c[t];
                }
            }
        }
    }
    vector<vector<ll>>dp;
    int ans=0;
    for(int lim=1;lim+mx-1<=m;lim++){
        vector<int>v;
        v.pb(0);
        for(int i=1;i<=m;i++){
            if(check(i,lim,lim+mx-1)) continue;
            v.pb(i);
        }
        int sz=v.size()-1;
        dp.assign(sz+2,vector<ll>(sz+2,1e18));
        for(int i=0;i<=sz;i++) dp[i][0]=0;
        for(int i=1;i<=sz;i++){
            dp[i][1]=0;
            for(int j=1;j<=i;j++){
                for(int k=1;k<i;k++){
                    dp[i][j]=min(dp[i][j],dp[k][j-1]+f[v[k]][v[i]]);
                }
            }
        }
        for(int i=1;i<=sz;i++){
            for(int j=i;j>=1;j--){
                if(dp[i][j]+cost[v[i]]<=k){
                    ans=max(ans,j);
                }
            }
        }
    }
    cout<<ans;
}
