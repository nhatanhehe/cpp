#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "daidich"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (masks|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,w,k,q,dist[N],p[N],l[N],r[N],ans[N],s[N],t[N];
vector<ii>g[N];
ii V[N];
vector<int>Q[N];
int acs(int u){
    return p[u]==u? u:p[u]=acs(p[u]);
}
void join(int u,int v){
    u=acs(u);
    v=acs(v);
    if(u!=v){
        p[v]=u;
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        g[u].pb({v,w});
        g[v].pb({u,w});
    }
    priority_queue<ii,vector<ii>,greater<ii>>pq;
    fill(dist+1,dist+n+1,inf);
    cin>>k;
    for(int i=1;i<=k;i++){
        cin>>u;
        dist[u]=0;
        pq.push({0,u});
    }
    while(pq.size()){
        auto [cost,u]=pq.top(); pq.pop();
        if(cost>dist[u]) continue;
        for(auto [v,w]:g[u]){
            if(dist[v]>dist[u]+w){
                dist[v]=dist[u]+w;
                pq.push({dist[v],v});
            }
        }
    }
    for(int i=1;i<=n;i++){
        V[i]=ii(dist[i],i);
    }
    sort(V+1,V+n+1,greater<ii>());
    cin>>q;
    for(int i=1;i<=q;i++){
        cin>>s[i]>>t[i];
        ans[i]=-1;
        l[i]=1;
        r[i]=n;
    }
    for(int cnt=1;cnt<=20;cnt++){
        bool any=0;
        for(int i=1;i<=q;i++){
            if(l[i]>r[i]) continue;
            int mid=(l[i]+r[i])>>1;
            Q[mid].pb(i);
            any=1;
        }
        if(!any) break;
        for(int i=1;i<=n;i++) p[i]=0;
        for(int i=1;i<=n;i++){
            p[V[i].se]=V[i].se;
            for(auto [v,w]:g[V[i].se]){
                if(p[v]){
                    join(V[i].se,v);
                }
            }
            for(int x:Q[i]){
                if(p[s[x]]&&p[t[x]]&&acs(s[x])==acs(t[x])){
                    r[x]=i-1;
                    ans[x]=V[i].fi;
                }
                else l[x]=i+1;
            }
        }
        for(int i=1;i<=n;i++){
            Q[i].clear();
        }
    }
    for(int i=1;i<=q;i++){
        cout<<ans[i]<<'\n';
    }
}
