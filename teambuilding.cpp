#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<ll,ll>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ii a[N];
ll n,s[N][10],p,k,dp[N][1<<7];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>p>>k;
    for(int i=1;i<=n;i++){
        cin>>a[i].fi;
        a[i].se=i;
    }
    for(int i=1;i<=n;i++){
        for(int j=0;j<p;j++){
            cin>>s[i][j];
        }
    }
    sort(a+1,a+n+1,greater<ii>());
    memset(dp,-0x3f,sizeof dp);
    dp[0][0]=0;
    for(int i=1;i<=n;i++){
        for(int mask=0;mask<(1<<p);mask++){
            dp[i][mask]=dp[i-1][mask];
            for(int j=0;j<p;j++){
                if(mask>>j&1){
                    dp[i][mask]=max(dp[i][mask],dp[i-1][Off(mask,j)]+s[a[i].se][j]);
                }
            }
            if(i-__builtin_popcount(mask)<=k) dp[i][mask]=max(dp[i][mask],dp[i-1][mask]+a[i].fi);
        }
    }
    cout<<dp[n][(1<<p)-1];
}
