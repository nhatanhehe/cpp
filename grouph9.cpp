const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,t,a,b,k,indeg[N],deg[N],u,v;
vector<int>g[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>u>>v;
        g[u].pb(v);
        g[v].pb(u);
    }
    cin>>t;
    for(int j=1;j<=t;j++){
        cin>>a>>b>>k;
        memset(deg,0,sizeof deg);
        for(int i=a;i<=b;i++){
            for(int v:g[i]){
                if(a<=v&&v<=b){
                    deg[i]++;
                }
            }
        }
        queue<int>q;
        for(int i=a;i<=b;i++){
            if(deg[i]<k) q.push(i);
        }
        int res=b-a+1;
        while(q.size()){
            int u=q.front(); q.pop();
            res--;
            for(int v:g[u]){
                if(deg[v]==k){
                    q.push(v);
                }
                deg[v]--;
            }
        }
        cout<<res<<'\n';
    }
}
