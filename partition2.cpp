inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int f[1000006];
int exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    int t=exp(a,n/2);
    if(n&1) return ((t*t)%mod*a%mod)%mod;
    else return (t*t)%mod;
}
int C(int n,int k){
    int a=f[n];
    int b=(f[k]*(f[n-k]))%mod;
    return a*exp(b,mod-2)%mod;
}
void cal(){
    f[0]=1;
    for(int i=1;i<=1e6;i++){
        f[i]=mul(f[i-1],i);
    }
}
int B[105],n,m,Q[13][102],t[N],p[N],tplt;
int acs(int u){
    return p[u]==u? u:p[u]=acs(p[u]);
}
void join(int u,int v){
    u=acs(u);
    v=acs(v);
    if(u!=v){
        p[v]=u;
        tplt--;
    }
}
void init(){
    tplt=n;
    for(int i=1;i<=n;i++) p[i]=i;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cal();
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>t[i];
        for(int j=1;j<=t[i];j++){
            cin>>Q[i][j];
        }
    }
    B[0]=1;
    for(int i=1;i<=100;i++){
        for(int k=0;k<=i-1;k++){
            B[i]=add(B[i],mul(C(i-1,k),B[k]));
        }
    }
    ll ans=0;
    for(int mask=0;mask<(1<<m);mask++){
        init();
        for(int j=0;j<m;j++){
            if((mask>>j)&1){
                for(int id=1;id<t[j+1];id++){
                    join(Q[j+1][id],Q[j+1][id+1]);
                }
            }
        }
        if(__builtin_popcount(mask)%2==0) ans=add(ans,B[tplt]);
        else ans=sub(ans,B[tplt]);
    }
    cout<<ans;
}
