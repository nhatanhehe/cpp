#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n[N],x[N],k,cnt[N],cnt_;
int exp(int a,int n){
    if(n==0) return 1;
    if(n==1) return a;
    int t=exp(a,n/2);
    if(n&1) return mul(a,mul(t,t));
    return mul(t,t);
}
map<int,vector<int>>mp;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>k;
    int pre=1,ans=0;
    for(int i=1;i<=k;i++){
        cin>>n[i];
        ans=add(ans,n[i]-1);
    }
    for(int i=1;i<=k;i++){
        cin>>x[i];
        mp[n[i]-x[i]+1].pb(i);
        mp[x[i]].pb(i);
        cnt[i]=2;
    }
    cnt_=k;
    bool ok=1;
    for(auto [val,v]:mp){
        ans=add(ans,mul(val-pre,exp(2,cnt_)));
        for(int x:v){
            cnt[x]--;
            if(cnt[x]==1) cnt_--;
            if(!cnt[x]) ok=0;
        }
        if(!ok) break;
        pre=val;
    }
    cout<<ans;
}
