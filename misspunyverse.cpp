inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n,t,u,v,sz[N],b[N],s[N];
vector<vector<ii>>dp;
vector<int>g[N];
vector<ii> merge(vector<ii>&fu,vector<ii>&fv){
    int lim=(int)fu.size()+(int)fv.size();
    vector<ii>f(lim,ii(-1,-1e9));
    for(int i=0;i<fu.size();i++){
        if(fu[i].fi==-1) continue;
        for(int j=0;j<fv.size();j++){
            if(i+j<lim) f[i+j]=max(f[i+j],ii(fu[i].fi+fv[j].fi,fu[i].se+fv[j].se));
            if(i+j+1<lim)f[i+j+1]=max(f[i+j+1],ii((fv[j].se>0)+ fu[i].fi+fv[j].fi,fu[i].se));
        }
    }
    return f;
}
void dfs(int u,int p){
    sz[u]=1;
    dp[u].assign(1,ii(0,s[u]));
    for(int v:g[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]=merge(dp[u],dp[v]);
            sz[u]+=sz[v];
        }
    }
}
