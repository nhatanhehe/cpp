inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int k,n;
bool p[N];
void sang(){
    memset(p,1,sizeof p);
    p[0]=p[1]=0;
    for(int i=2;i<=sqrt(1e6);i++){
        if(p[i])
        for(int j=i*i;j<=1e6;j+=i){
            p[j]=0;
        }
    }
}
