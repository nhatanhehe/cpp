inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,dp[N][N][3][3],cur,match[N];
string s;
ll calc(int l,int r,int cl,int cr){
    ll &ans=dp[l][r][cl][cr];
    if(ans!=-1) return ans;
    if(match[l]==r){
        if(!((cl==0&&cr>0)||(cl>0&&cr==0))) return 0;
    }
    if(l+1==r) return ans=1;
    ans=0;
    if(match[l]==r){
        for(int nl=0;nl<=2;nl++){
            for(int nr=0;nr<=2;nr++){
                if(nl&&nl==cl) continue;
                if(nr&&nr==cr) continue;
                ans=add(ans,calc(l+1,r-1,nl,nr));
            }
        }
    }
    else{
        int k=match[l];
        for(int nl=0;nl<=2;nl++){
            for(int nr=0;nr<=2;nr++){
                if(nl&&nl==nr) continue;
                ans=add(ans,mul(calc(l,k,cl,nl),calc(k+1,r,nr,cr)));
            }
        }
    }
    return ans;
}
