inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,tp,l,r;
string s;
struct pt{
    int l1,r1,l2,r2;
    bool ok;
}tree[N<<2],ban={-1,-1,-1,-1,0};
bool operator==(const pt &a, const pt &b) {
    return a.l1 == b.l1 && a.r1 == b.r1 &&
           a.l2 == b.l2 && a.r2 == b.r2 &&
           a.ok == b.ok;
}
pt merge(pt l,pt r){
    if(l==ban) return r;
    if(r==ban) return l;
    pt res;
    res.l1=l.l1;
    res.r1=r.r1;
    res.l2=min(l.l1+1,r.l1);
    res.r2=max(r.r1-1,l.r1);
    res.ok=(l.ok|r.ok);
    res.ok|=(s[l.r1]==s[r.l1]);
    res.ok|=(l.r2!=-1&&s[l.r2]==s[r.l1]);
    res.ok|=(r.l2!=-1&&s[l.r1]==s[r.l2]);
    return res;
}
void build(int id=1,int l=1,int r=n){
    if(l==r){
        tree[id].l1=l;
        tree[id].r1=l;
        tree[id].l2=-1;
        tree[id].r2=-1;
        tree[id].ok=0;
        return;
    }
    int mid=(l+r)>>1;
    build(id*2,l,mid);
    build(id*2+1,mid+1,r);
    tree[id]=merge(tree[id*2],tree[id*2+1]);
}
void up(int pos,int id=1,int l=1,int r=n){
    if(l==r){
        tree[id].l1=l;
        tree[id].r1=l;
        tree[id].l2=-1;
        tree[id].r2=-1;
        tree[id].ok=0;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid) up(pos,id*2,l,mid);
    else up(pos,id*2+1,mid+1,r);
    tree[id]=merge(tree[id*2],tree[id*2+1]);
}
pt get(int u,int v,int id=1,int l=1,int r=n){
    if(l>v||r<u) return ban;
    if(u<=l&&r<=v) return tree[id];
    int mid=(l+r)>>1;
    return merge(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
}
