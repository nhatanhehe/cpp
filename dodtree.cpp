inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,a[N],u,v;
vector<int>g[N];
ii dp[N][2];
void dfs(int u,int p,int lamda){
    int sum_fi=0,sum_se=0;
    for(int v:g[u]){
        if(v!=p){
            /// khong ghep cap
            dfs(v,u,lamda);
            ii x=max(dp[v][0],dp[v][1]);
            dp[u][0].fi+=x.fi;
            dp[u][0].se+=x.se;
            sum_fi+=x.fi;
            sum_se+=x.se;
        }
    }
    ///ghep u voi v
    for(int v:g[u]){
        if(v!=p){
            ii x=max(dp[v][0],dp[v][1]);
            dp[u][1]=max(dp[u][1],ii(dp[v][0].fi-lamda+(a[u]^a[v])+(sum_fi-x.fi),dp[v][0].se+sum_se-x.se+1));
        }
    }
}
ii check(int mid){
    for(int i=1;i<=n;i++){
        dp[i][0]=dp[i][1]=ii(0,0);
    }
    dfs(1,-1,mid);
    return max(dp[1][0],dp[1][1]);
}
void alien_trick(){
    int l=1,r=2e9,ans=-nameless;
    while(l<=r){
        int mid=(l+r)>>1;
        if(check(mid).se>=k){
            l=mid+1;
            ans=mid;
        }
        else r=mid-1;
    }
    cout<<(ans==-nameless? -1:check(ans).fi+ans*k);
}
