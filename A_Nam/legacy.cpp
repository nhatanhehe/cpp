inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
vector<ii>g[N];
int n,q,s,t,u,v,l,r,dist[N];
void build1(int id=1,int l=1,int r=n){
    if(l==r){
        g[id+n].pb({l,0});
        return;
    }
    int mid=(l+r)>>1;
    build1(id*2,l,mid);
    build1(id*2+1,mid+1,r);
    g[id+n].pb({id*2+n,0});
    g[id+n].pb({id*2+1+n,0});
}
void build2(int id=1,int l=1,int r=n){
    if(l==r){
        g[l].pb({5*n+id,0});
        return;
    }
    int mid=(l+r)>>1;
    build2(id*2,l,mid);
    build2(id*2+1,mid+1,r);
    g[id*2+5*n].pb({id+5*n,0});
    g[id*2+1+5*n].pb({id+5*n,0});
}
void up1(int u,int v,int ver,int w,int id=1,int l=1,int r=n){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
        g[ver].pb({id+n,w});
        return;
    }
    int mid=(l+r)>>1;
    up1(u,v,ver,w,id*2,l,mid);
    up1(u,v,ver,w,id*2+1,mid+1,r);
}
void up2(int u,int v,int ver,int w,int id=1,int l=1,int r=n){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
        g[id+5*n].pb({ver,w});
        return;
    }
    int mid=(l+r)>>1;
    up2(u,v,ver,w,id*2,l,mid);
    up2(u,v,ver,w,id*2+1,mid+1,r);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>q>>s;
    build1();
    build2();
    while(q--){
        int t;
        cin>>t;
        if(t==1){
            int u,v,w;
            cin>>u>>v>>w;
            up1(v,v,u,w);
        }
        if(t==2){
            int l,r,u,w;
            cin>>u>>l>>r>>w;
            up1(l,r,u,w);
        }
        if(t==3){
            int l,r,u,w;
            cin>>u>>l>>r>>w;
            up2(l,r,u,w);
        }
    }
    fill(dist,dist+1000000,1e18);
    dist[s]=0;
    priority_queue<ii,vector<ii>,greater<ii>>pq;
    pq.push({0,s});
    while(pq.size()){
        auto [cost,u]=pq.top(); pq.pop();
        if(cost>dist[u]) continue;
        for(auto [v,w]:g[u]){
            if(dist[v]>dist[u]+w){
                dist[v]=dist[u]+w;
                pq.push({dist[v],v});
            }
        }
    }
    for(int i=1;i<=n;i++){
        cout<<(dist[i]!=1e18? dist[i]:-1)<<' ';
    }
}
