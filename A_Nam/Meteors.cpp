#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define ii pair<int,int>
#define all(x) x.begin(),x.end()
#define iii pair<int,pair<int,int>>
#define fi first
#define se second
const ll inf=1e18;
const int N=4e5+5;
const ll mod=1e9+7;
const int base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
ll mul(ll a,ll b){
    return (a%mod)*(b%mod)%mod;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
ll add(ll a,ll b){
    return (a%mod+b%mod)%mod;
}
ll n,m,k;
ll a[N],p[N],l[N],r[N],u[N],v[N],ans[N],bit[N];
vector<ll>tc[N];
vector<ll>queries[N];
inline void up(int i,ll k){
    for(;i<=m;i+=i&-i){
        bit[i]+=k;
    }
}
inline void up_range(int l,int r,ll k){
    up(l,k); up(r+1,-k);
}
inline ll get(int i){
    ll res=0;
    for(;i;i-=i&-i){
        res+=bit[i];
    }
    return res;
}
inline bool check(int x){
    ll sum=0;
    for(ll u:tc[x]){
        sum+=get(u);
        if(sum>=p[x]) return 1;
    }
    return 0;
}
main(){
     ios_base::sync_with_stdio(false);
     cin.tie(NULL);
       cout.tie(NULL);
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>a[i];
        tc[a[i]].pb(i);
    }
    for(int i=1;i<=n;i++){
        cin>>p[i];
    }
    cin>>k;
    for(int i=1;i<=k;i++){
        cin>>u[i]>>v[i]>>a[i];
    }
    for(int i=1;i<=n;i++){
        l[i]=1,r[i]=k,ans[i]=-1;
    }
    for(int id=1;id<=20;id++){
        int chec=1;
        for(int i=1;i<=n;i++){
            if(l[i]>r[i]) continue;
            chec=0;
            queries[(l[i]+r[i])/2].pb(i);
        }
        if(chec) break;
        for(int i=1;i<=k;i++){
            if(u[i]>v[i]){
                up_range(u[i],m,a[i]);
                up_range(1,v[i],a[i]);
            }
            else up_range(u[i],v[i],a[i]);
            for(int x:queries[i]){
                if(check(x)){
                    r[x]=i-1;
                    ans[x]=i;
                }
                else l[x]=i+1;
            }
        }
        for(int i=1;i<=k;i++) queries[i].clear();
        memset(bit,0,sizeof(bit));
    }
    for(int i=1;i<=n;i++){
        if(ans[i]!=-1) cout<<ans[i]<<'\n';
        else cout<<"NIE\n";
    }
}
