inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,a[N],l,r,b[N];
struct Matrix{
    int x[3][3];
    Matrix(){}
    Matrix(int a[3][3]){
        for(int i=1;i<=2;i++){
            for(int j=1;j<=2;j++){
                x[i][j]=a[i][j];
            }
        }
    }

    Matrix operator*(const Matrix &b){
        Matrix c;
        for(int i=1;i<=2;i++){
            for(int j=1;j<=2;j++){
                c.x[i][j]=0;
                for(int k=1;k<=2;k++){
                    c.x[i][j]=add(c.x[i][j],mul(x[i][k],b.x[k][j]));
                }
            }
        }
        return c;
    }
}tree[N<<2];
void build(int id=1,int l=1,int r=n){
    if(l==r){
        tree[id].x[1][1]=a[l];
        tree[id].x[1][2]=1;
        tree[id].x[2][1]=1;
        tree[id].x[2][2]=0;
        return;
    }
    int mid=(l+r)>>1;
    build(id*2,l,mid);
    build(id*2+1,mid+1,r);
    tree[id]=tree[id*2]*tree[id*2+1];
}
Matrix out;
Matrix get(int u,int v,int id=1,int l=1,int r=n){
    if(l>v||r<u) return out;
    if(u<=l&&r<=v) return tree[id];
    int mid=(l+r)>>1;
    return get(u,v,id*2,l,mid)*get(u,v,id*2+1,mid+1,r);
}
