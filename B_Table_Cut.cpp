inline ll add(ll a, ll b)
{
    ll res = a + b;
    if (res >= mod)
        res -= mod;
    return res;
}
ll sub(ll a, ll b)
{
    return ((a - b) % mod + mod) % mod;
}
inline ll mul(ll a, ll b)
{
    ll res = a * b;
    if (res >= mod)
        res %= mod;
    return res;
}
int n, m, t;
main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);
    if (fopen(Task ".inp", "r"))
    {
        freopen(Task ".inp", "r", stdin);
        freopen(Task ".out", "w", stdout);
    }
    cin >> t;
    while (t--)
    {
        cin >> m >> n;
        vector<vector<int>> a(m + 4, vector<int>(n + 4, 0));
        vector<int> s(m + 4, 0);
        int cnt = 0;
        for (int i = 1; i <= m; i++)
        {
            for (int j = 1; j <= n; j++)
            {
                cin >> a[i][j];
                s[i] += a[i][j];
            }
            cnt += s[i];
        }
        int sum = 0;
        int x = cnt / 2;
        cout << x * (cnt - x) << '\n';
        if (x == 0)
        {
            for (int i = 1; i <= m; i++)
                cout << 'D';
            for (int i = 1; i <= n; i++)
                cout << 'R';
            cout << '\n';
            continue;
        }
        for (int i = 1; i <= m; i++)
        {
            sum += s[i];
            if (sum < x)
                cout << 'D';
            if (sum >= x)
            {
                int cnt2 = sum - s[i], idx=n+1;
                for (int j = n; j >= 1; j--)
                {
                    cnt2 += a[i][j];
                    if (cnt2 == x)
                    {
                        idx = j;
                        break;
                    }
                }
                 //cout<<" "<<i<<' '<<" "<<idx<<' ';
                for (int j = 1; j < idx; j++)
                    cout << 'R';
                cout << 'D';
                for (int j = 1; j <= n - idx + 1; j++)
                    cout << 'R';
                for (int j = 1; j <= m - i; j++)
                    cout << 'D';
                break;
            }
        }
        cout << '\n';
    }
}
