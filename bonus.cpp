const ll inf=1e18;
const ll N=3e6+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int a[1003][1003],n,k,r,x,y,b[1003][1003];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>r>>k;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            cin>>a[i][j];
        }
    }
    while(k--){
        cin>>x>>y;
        int u=x+r-1;
        int v=y+r-1;
        b[u][v]+=1;
        b[x-1][v]-=1;
        b[u][y-1]-=1;
        b[x-1][y-1]+=1;
    }
    for(int i=n;i>=1;i--){
        for(int j=n;j>=1;j--){
            b[i][j]=b[i+1][j]+b[i][j+1]-b[i+1][j+1]+b[i][j];
        }
    }
    ll ans=0;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            //cout<<b[i][j]<<" ";
            if(b[i][j]) ans+=a[i][j];
        }
        //cout<<'\n';
    }
    cout<<ans;
}
