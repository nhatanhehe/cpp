inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll m,p[N],k[N],A,B;
struct pt{
    ll p,k;
}x[N];
vector<ll>L,R;
void ql1(int i,ll res){
    if(res>1e9) return;
    if(i>m/2){
        L.pb(res);
        return;
    }
    ql1(i+1,res);
    ll prod=1;
    for(int j=1;j<=x[i].k;j++){
        prod*=x[i].p;
        if(prod>1e9) break;
        ql1(i+1,res*prod);
    }
}
void ql2(int i,ll res){
    if(res>1e9) return;
    if(i>m){
        R.pb(res);
        return;
    }
    ql2(i+1,res);
    ll prod=1;
    for(int j=1;j<=x[i].k;j++){
        prod*=x[i].p;
        if(prod>1e9) break;
        ql2(i+1,res*prod);
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m;
    for(int i=1;i<=m;i++){
        cin>>x[i].p>>x[i].k;
    }
    random_shuffle(x+1,x+m+1);
    ql1(1,1);
    sort(all(L));
    L.erase(unique(all(L)),L.end());
    ql2(m/2+1,1);
    sort(all(R));
    R.erase(unique(all(R)),R.end());
    while(cin>>A>>B){
        ll ans=0;
        for(ll x:L){
            ll min_y=(A==0?1:(A+x-1)/x);
            ll max_y=B/x;
            auto l=lower_bound(all(R),min_y);
            auto r=upper_bound(all(R),max_y);
            ans+=(r-l);
        }
        cout<<ans<<'\n';
    }
}
