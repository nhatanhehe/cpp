#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],target;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    ll ans=0;
    for(int len=1;len<=n;len++){
        vector<vector<int>>dp(len+1,vector<int>(len+2,0));
        vector<vector<int>>ndp(len+1,vector<int>(len+2,0));
        dp[0][0]=1;
        for(int i=1;i<=n;i++){
            ndp=vector<vector<int>>(len+1,vector<int>(len+2,0));
            for(int cnt=0;cnt<=len;cnt++){
                for(int rem=0;rem<=len;rem++){
                    if(cnt) ndp[cnt][rem]=add(dp[cnt-1][((rem-a[i])%len+len)%len],ndp[cnt][rem]);
                    ndp[cnt][rem]=add(ndp[cnt][rem],dp[cnt][rem]);
                }
            }
            dp=ndp;
        }
        ans=add(ans,ndp[len][0]);
    }
    cout<<ans;
}
