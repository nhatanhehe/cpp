inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,a[N];
map<ll,ll>mp;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    ll res=(n*(n+1)/2%mod)* ((m+1)*m/2%mod)%mod;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        if(!mp[a[i]]) res=sub(res,mul(a[i],n*(n+1)/2%mod));
        ll len=(i-mp[a[i]]-1);
        res=add(res,a[i]*len*(len+1)/2);
        mp[a[i]]=i;
    }
    for(auto [val,pos]:mp){
        ll len=(n-pos);
        res=add(res,mul(val,len*(len+1)/2%mod));
    }
    cout<<res;
}
