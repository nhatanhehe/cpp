inline ll add(ll a, ll b) {
    a %= mod; b %= mod;
    ll res = a + b;
    if (res >= mod) res -= mod;
    return res;
}
ll sub(ll a,ll b){
    a%=mod;
    b%=mod;
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    a%=mod; b%=mod;
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,q,l[N],r[N],sum[N],pref[N],odd[N],even[N];
struct Query{
    char tp;
    ll u,v,c;
}Q[N];
unordered_map<ll,ll>pre;
unordered_set<ll>s;
void sub3(){
    for(int i=1;i<=n;i++){
        s.insert(l[i]);
        s.insert(r[i]);
    }
    for(int i=1;i<=q;i++){
        if(Q[i].tp!='Q'){
            s.insert(Q[i].c);
        }
    }
    for (ll x : s) {
        ll parity = 0;
        if(__builtin_popcount(x)&1) pre[x]++;
        for (int j=60;j>=0;j--){
            if ((x>>j)&1) {
                int need=parity^1;
                if (j==0) {
                    if(need==0) pre[x]=add(pre[x],1);
                }else{
                    pre[x]=add(pre[x],(1LL<<(j-1)));
                }
                parity^=1;
            }
        }
    }
    for(int i=1;i<=n;i++){
        sum[i]=sub(pre[r[i]],pre[l[i]-1]);
     //   cout<<sum[i]<<" "<<r[i]-l[i]+1-sum[i]<<'\n';
    }
    for(int i=1;i<=q;i++){
        auto [tp,u,v,c]=Q[i];
        if(tp=='L'){
            for(int j=u;j<=v;j++){
                sum[j]=sub(pre[r[j]],pre[c-1]);
                l[j]=c;
            }
        }
        if(tp=='R'){
            for(int j=u;j<=v;j++){
                sum[j]=sub(pre[c],pre[l[j]-1]);
                r[j]=c;
            }
        }
        if(tp=='Q'){
            ll sum_le=0,sum_chan=0,ans_le=0,ans_chan=0;
            for(int j=u;j<=v;j++){
                ans_le=add(add(ans_le,mul(sum[j],sum_chan)),mul(sub(sub(r[j],l[j]-1),sum[j]),sum_le));
                ans_chan=add(add(ans_chan,mul(sub(sub(r[j],l[j]-1),sum[j]),sum_chan)),mul(sum[j],sum_le));
                sum_le=add(sum_le,sum[j]);
                sum_chan=add(sum_chan,sub(sub(r[j],l[j]-1),sum[j]));
            }
            cout<<ans_chan<<" "<<ans_le<<'\n';
        }
    }
}
