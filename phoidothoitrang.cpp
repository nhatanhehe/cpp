inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,q,c[N],p[N];
set<int,greater<int>>col[N];
struct SegtreeSum{
    vector<int>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(4*n+6,0);
    }

    void up(int pos,int id,int l,int r){
        if(l==r){
            tree[id]=(*col[l].begin());
            return;
        }
        int mid=(l+r)>>1;
        if(pos<=mid) up(pos,id*2,l,mid);
        else up(pos,id*2+1,mid+1,r);
        tree[id]=tree[id*2]+tree[id*2+1];
    }

    void up(int pos){
        up(pos,1,1,n);
    }
};
struct SegtreeMax{
    vector<int>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(4*n+5,-2e9);
    }

    void up(int pos,int id,int l,int r){
        if(l==r){
            auto it=col[l].begin();
            it++;
            if(it!=col[l].end()) tree[id]=(*it);
            else tree[id]=-2e9;
            return;
        }
        int mid=(l+r)>>1;
        if(pos<=mid) up(pos,id*2,l,mid);
        else up(pos,id*2+1,mid+1,r);
        tree[id]=max(tree[id*2],tree[id*2+1]);
    }

    void up(int pos){
        up(pos,1,1,n);
    }
};
struct SegtreeMin{
    vector<int>tree;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(4*n+4,0);
    }

    void up(int pos,int id,int l,int r){
        if(l==r){
            tree[id]=(*col[l].begin());
            return;
        }
        int mid=(l+r)>>1;
        if(pos<=mid) up(pos,id*2,l,mid);
        else up(pos,id*2+1,mid+1,r);
        tree[id]=min(tree[id*2],tree[id*2+1]);
    }

    void up(int pos){
        up(pos,1,1,n);
    }
};
