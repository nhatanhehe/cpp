inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a,b,c,u,v,m,cnt,low[N],num[N],dp[N],vis[N],par[N],dist[N],res[N];
vector<ii>g[N];
vector<int>tree[N];
void tarjan(int u,int id){
    low[u]=num[u]=++cnt;
    for(auto [v,nw_id]:g[u]){
        if(nw_id==id) continue;
        if(num[v]) low[u]=min(low[u],num[v]);
        else{
            tree[u].pb(v);
            tree[v].pb(u);
            //cout<<u<<" "<<v<<'\n';
            tarjan(v,nw_id);
            low[u]=min(low[u],low[v]);
        }
    }
}
void color(int u,int p,int &cnt,int mau){
    if(cnt==0) return;
    cnt--;
    res[u]=mau;
    for(int v:tree[u]){
        if(v!=p){
            color(v,u,cnt,mau);
        }
    }
}
void dfs(int u,int p){
    dp[u]=1;
    for(int v:tree[u]){
        if(v!=p){
            dfs(v,u);
            dp[u]+=dp[v];
        }
    }
    if(dp[u]>=a){
        if(n-dp[u]>=a){
            int source=u;
            int sink=p;
            if(n-dp[u]<dp[u]) swap(source,sink);
            int cnt=0;
            memset(dist,0x3f,sizeof dist);
            dist[source]=0;
            queue<int>q;
            q.push(source);
            while(q.size()){
                int uu=q.front(); q.pop();
                res[uu]=1;
                cnt++;
                if(cnt==a) break;
                for(int v:tree[uu]){
                    if(v!=sink&&dist[v]>dist[uu]+1){
                        dist[v]=dist[uu]+1;
                        q.push(v);
                    }
                }
            }
            while(q.size()) q.pop();
            cnt=0;
            q.push(sink);
            memset(dist,0x3f,sizeof dist);
            dist[sink]=0;
            while(q.size()){
                int uu=q.front(); q.pop();
                res[uu]=2;
                cnt++;
                if(cnt==b) break;
                for(int v:tree[uu]){
                    if(v!=source&&dist[v]>dist[uu]+1){
                        dist[v]=dist[uu]+1;
                        q.push(v);
                    }
                }
            }
            for(int i=1;i<=n;i++){
                if(res[i]==0) res[i]=3;
                cout<<res[i]<<" ";
            }
            exit(0);
        }
        else{
            int h=dp[u],q=n-dp[u];
            for(int v:tree[u]){
                if(low[v]<num[u]&&h-dp[v]>=a){
                    q+=dp[v];
                    h-=dp[v];
                }
            }
            if(h>=a&&q>=a){
                h=dp[u],q=n-dp[u];
                int cnt=a;
                for(int v:tree[u]){
                    if(low[v]<num[u]&&h-dp[v]>=a){
                        color(v,-1,b,2);
                        q+=dp[v];
                        h-=dp[v];
                    }
                    else color(v,-1,cnt,1);
                }
                memset(dist,0x3f,sizeof dist);
                dist[p]=0;
                queue<int>q;
                q.push(p);
                while(q.size()){
                    int uu=q.front(); q.pop();
                    res[uu]=2;
                    b--;
                    if(b==0) break;
                    for(int v:tree[uu]){
                        if(v!=u&&dist[v]>dist[uu]+1){
                            dist[v]=dist[uu]+1;
                            q.push(v);
                        }
                    }
                }
                for(int i=1;i<=n;i++){
                    if(!res[i]) cout<<3<<" ";
                    else cout<<res[i]<<" ";
                }
                exit(0);
            }
        }
    }
}
