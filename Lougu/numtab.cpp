inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,a[1004][1004],k,p,q;
vector<vector<int>> calc(vector<vector<int>>a){
    vector<vector<int>>maxW(m+4,vector<int>(m+4,0)),dp(m+4,vector<int>(m+4,0));
    vector<int>h(n+4,0);
    for(int i=1;i<=m;i++){
        stack<int>st;
        vector<int>l(n+4,0),r(n+4,0);
        for(int j=1;j<=n;j++){
            if(a[i][j]==1) h[j]++;
            else h[j]=0;
        }
        for(int j=1;j<=n;j++){
            while(st.size()&&h[st.top()]>=h[j]) st.pop();
            if(st.size()) l[j]=st.top();
            else l[j]=0;
            st.push(j);
        }
        while(st.size()) st.pop();
        for(int j=n;j>=1;j--){
            while(st.size()&&h[st.top()]>=h[j]) st.pop();
            if(st.size()) r[j]=st.top();
            else r[j]=n+1;
            st.push(j);
        }
        for(int j=1;j<=n;j++){
            int up=i-h[j]+1;
            int down=i;
            maxW[up][down]=max(maxW[up][down],r[j]-l[j]-1);
        }
    }
    for(int r=m;r>=1;r--){
        for(int l=1;l<=r;l++){
            maxW[l][r]=max({maxW[l][r],maxW[l-1][r],maxW[l][r+1]});
        }
    }
    for(int l=1;l<=m;l++){
        for(int r=l;r<=m;r++){
            dp[l][r]=(r-l+1)*maxW[l][r];
        }
    }
    for(int r=1;r<=m;r++){
        for(int l=r-1;l>=1;l--){
            dp[l][r]=max({dp[l][r],dp[l+1][r],dp[l][r-1]});
        }
    }
    return dp;
}
