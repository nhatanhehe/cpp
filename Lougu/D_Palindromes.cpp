inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,dp[505][505],f[505][505],trace[505][505];
string s;
string T(int l,int r,string res){
    res+=s[l];
    if(l==r){
        string r2=res;
        reverse(all(r2));
        res.pop_back();
        return res+r2;
    }
    if(l+1==r){
        string r2=res;
        reverse(all(r2));
        return res+r2;
    }
    return T(l+1,r-1,res);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>s>>k;
    n=s.size();
    s=" "+s;
    for(int r=1;r<=n;r++){
        for(int l=r-1;l>=1;l--){
            if(l+1==r){
                if(s[l]==s[r]) dp[l][r]=0;
                else dp[l][r]=1;
            }
            else{
                dp[l][r]=dp[l+1][r-1]+(s[l]!=s[r]);
            }
        }
    }
    for(int t=0;t<=k;t++) for(int i=0;i<=n;i++) f[i][t]=1e9;
    f[0][0]=0;
    int ans=dp[1][n],mt=0;
    for(int t=1;t<=k;t++){
        for(int i=1;i<=n;i++){
            for(int j=1;j<=i;j++){
                if(f[j-1][t-1]!=1e9){
                    if(f[i][t]>f[j-1][t-1]+dp[j][i]){
                        f[i][t]=f[j-1][t-1]+dp[j][i];
                        trace[i][t]=j-1;
                    }
                }
            }
        }
        if(ans>f[n][t]){
            ans=f[n][t];
            mt=t;
        }
    }
    cout<<ans<<'\n';
    int N=n;
    vector<int>idx={n};
    while(trace[N][mt]){
        idx.pb(trace[N][mt]);
        N=trace[N][mt--];
    }
    reverse(all(idx));
    int pre=1;
    for(int i=0;i<idx.size();i++){
        int x=idx[i];
        cout<<T(pre,x,"");
        pre=x+1;
        if(i!=idx.size()-1) cout<<'+';
    }
}
