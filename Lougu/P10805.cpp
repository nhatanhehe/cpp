inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,k,u,v,w,cen[N],sz[N],d[N],nxt[N],fa[N][20],LG,dp1[N],dp2[N],rem[N],cur,vec[N],ans[N],s[N];
vector<ii>g[N];
void dfs(int u,int p){
    sz[u]=1;
    for(auto [v,w]:g[u]){
        if(!cen[v]&&v!=p){
            dfs(v,u);
            sz[u]+=sz[v];
        }
    }
}   
int fcen(int u,int p,int tree_sz){
    for(auto [v,w]:g[u]){
        if(v!=p&&!cen[v]&&sz[v]>tree_sz/2) return fcen(v,u,tree_sz);
    }
    return u;
}
void clear_dp(int u, int p){
    dp1[u]=dp2[u]=0;
    for(auto [v,w]:g[u]) {
        if(v!=p&&!cen[v]) clear_dp(v,u);
    }
}
void buildSPT(int u,int p){
    fa[u][0]=p;
    sz[u]=1;
    for(int i=1;i<=LG;i++) fa[u][i]=fa[fa[u][i-1]][i-1];
    for(auto [v,w]:g[u]){
        if(v!=p&&!cen[v]){
            d[v]=d[u]+w;
            buildSPT(v,u);
            sz[u]+=sz[v];
        }
    }
}
// Tinh u -> centroid
void dfs2(int u,int p,int rt){
    ll jump=0;
    if(d[u]<=k){
        rem[u]=k-d[u];
        vec[++cur]=rem[u];
        jump=rt;
    }
    else{
        jump=u;
        for(int i=LG;i>=0;i--){
            // tim diem tram can sac dau tien
            if(fa[jump][i]&&-d[fa[jump][i]]+d[u]<=k) jump=fa[jump][i];
        }
        rem[u]=rem[jump];
        vec[++cur]=rem[u];
    }
    for(auto [v,w]:g[u]){
        if(v!=p&&!cen[v]){
            dfs2(v,u,rt);
        }
    }
    if(jump!=rt) dp1[jump]+=dp1[u]+1;
}
// Tinh centroid -> v
/*Nhan xet
 - Ta se xet cha cua v, vi neu xet duong di tu cen -> v thi se khong biet di duong nao tiep theo
 - Co 2 truong hop can tinh 
 - TH1 cha cua u la thang dau tien duoc sac tu centroid di xuong
 - De giai quyet, ta gom nhung thang rem (la luong xang du tu ben u->centroid) thoa man bieu thuc 
 - rem + d[fa[u]] <=k && rem + d[u] > k
 - Day chinh la so thang dong gop vao dp2[fa[u]]
 - TH2 to tien cua cha cua u da sac truoc do -> phai cong dp2 cua cac to tien thoa man 
 -  d[fa[u]] - d[x] <=k && d[u] - d[x] > k  => d[fa[u]] - k <= d[x] < d[u] - k 
*/
//  k - d[u] < rem && rem <= k - d[fa[u]]
ll query(ll df,ll du){   
    if(df>du) return 0;
    return upper_bound(vec+1,vec+cur+1,du) - lower_bound(vec+1,vec+cur+1,df);
}
void dfs3(int u,int rt,int p){
    if(u!=rt){
        // TH1 
        dp2[u]=query(d[fa[u][0]],d[u]-1);
        // TH2
        if(d[u]>k){
            int low=u,high=u;
            for(int i=LG;i>=0;i--){
                if(fa[low][i]&&d[u]-d[fa[low][i]]<=k) low=fa[low][i];
            }
            for(int i=LG;i>=0;i--){
                if(fa[high][i]&&d[fa[u][0]]-d[fa[high][i]]<=k) high=fa[high][i];
            }
            dp2[u]+=s[low]-s[high];
        }
    }
    if(u==rt) s[u]=0;
    else s[u]=s[fa[u][0]]+dp2[u];
    for(auto [v,w]:g[u]){
        if(v!=p&&!cen[v]){
            dfs3(v,rt,u);
        }
    }
}
void dfs4(int u,int p,int rt,ll sgn,ll siz){
    if(u!=rt){
        ans[u]+=dp1[u]*siz*sgn;
        ans[fa[u][0]]+=dp2[u]*sgn*sz[u];
    }
    for(auto [v,w]:g[u]){
        if(v!=p&&!cen[v]){
            dfs4(v,u,rt,sgn,siz);
        }
    }
}
void calc(int rt,int centroid,ll sgn){
    clear_dp(rt,0);
    cur=0;
    s[rt]=0;
    int p=(rt==centroid) ? 0:fa[rt][0];
    dfs2(rt,p,centroid);
    sort(vec+1,vec+cur+1);
    dfs3(rt,centroid,p);
    dfs4(rt,p,centroid,sgn,sz[rt]);
}
void solve(int centroid){
    cen[centroid]=1;
    LG=18;
    d[centroid]=0;
    buildSPT(centroid,0);
    calc(centroid,centroid,1);
    for(auto [v,w]:g[centroid]){
        if(!cen[v]){
            calc(v,centroid,-1);
        }
    }
    for(auto [v,w]:g[centroid]){
        if(!cen[v]){
            dfs(v,0);
            int nw_root=fcen(v,centroid,sz[v]);
            solve(nw_root);
        }
    }
}
