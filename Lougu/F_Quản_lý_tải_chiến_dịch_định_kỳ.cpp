#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll q,x,k,t,S,sum[N];
bool check[N][467];
string tp;
ll bit[N];
void update(int x,ll val){
    for(int i=x;i<N;i+=i&-i)
        bit[i]+=val;
}

ll get(int x){
    ll res=0;
    for(int i=x;i;i-=i&-i)
        res+=bit[i];
    return res;
}

void range_update(int l,int r,ll val){
    update(l,val);
    update(r+1,-val);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>q;
    S=sqrt(2e5);
    for(int k=1;k<=S;k++){
        for(int i=1;i<=2e5;i++){
            int tmp=(i+k-1)/k;
            if(tmp&1) check[i][k]=1;
        }
    }
    while(q--){
        cin>>tp;
        if(tp=="ADD"){
            cin>>x>>k;
            if(k>S){
                for(int i=1,j=1;i<=2e5;i+=k,j++){
                    if(j&1) range_update(i,min(200000LL,i+k-1),x);
                }
            }
            else{
                sum[k]+=x;
            }
        }
        else if(tp=="DEL"){
            cin>>x>>k;
            if(k>S){
                for(int i=1,j=1;i<=2e5;i+=k,j++){
                    if(j&1) range_update(i,min(200000LL,i+k-1),-x);
                }
            }
            else{
                sum[k]-=x;
            }
        }
        else{
            int t;
            cin>>t;
            ll res=get(t);
            for(int k=1;k<=S;k++){
                if(check[t][k]) res+=sum[k];
            }
            cout<<res<<'\n';
        }
    }
}
