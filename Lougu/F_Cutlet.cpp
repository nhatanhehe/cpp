inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,l,r,flip[N];
vector<int> precum(vector<int>dp,int len){
    vector<int>best(n+4,1e9);
    deque<int>dq;
    for(int i=0;i<=n;i++){
        while(dq.size()&&dq.front()<i-len) dq.pop_front();
        while(dq.size()&&dp[dq.back()]>=dp[i]) dq.pop_back();
        dq.push_back(i);
        if(dq.size()) best[i]=dp[dq.front()];
    }
    return best;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    vector<int>dp0(n+4,1e9),dp1(n+4,1e9);
    // dp0[j] la mat b ran duoc j, mat hien tai la a
    // dp1[j] la mat b ran duoc j, mat hien tai la b
    dp0[0]=dp1[0]=0;
    int curT=0;
    for(int i=1;i<=k;i++){
        cin>>l>>r;
        vector<int>ndp0=dp0,ndp1(n+4,1e9),f1(n+4,1e9);
        int G=l-curT;
        for(int j=0;j<=n;j++){
            if(j+G<=n&&dp1[j]!=1e9) f1[j+G]=min(f1[j+G],dp1[j]);
        }
        dp1=f1;
        for(int j=r-l;j<=n;j++) ndp1[j]=dp1[j-(r-l)];
        // Trans
        // Lat 1 lan
        // T-x >= T-len
        // dp0[T]=min(dp0[T],min(dp1[T-x])+1) -> T-x -> [T-len,T]
        // dp1[T]=min(dp0[T],min(dp0[T-x])+1) -> T-x -> [T-len,T]

        // Lat 2 lan

        // dp0[T]=min(dp0[T],min(dp0[T-x])+2)
        // dp1[T]=min(dp1[T],min(dp1[T-x])+2)
        vector<int>best0=precum(dp0,r-l),best1=precum(dp1,r-l);
        for(int j=0;j<=n;j++){
            if(best0[j]!=1e9){
                ndp1[j]=min(ndp1[j],best0[j]+1);
                ndp0[j]=min(ndp0[j],best0[j]+2);
            }
            if(best1[j]!=1e9){
                ndp0[j]=min(ndp0[j],best1[j]+1);
                ndp1[j]=min(ndp1[j],best1[j]+2);
            }
        }
        curT=r;
        dp0=ndp0;
        dp1=ndp1;
        ///if(i==2) cout<<dp0[n]<<" "<<dp1[n]<<'\n';
    }
    if(curT<2*n){
        vector<int>f1(n+4,1e9);
        int G=2*n-curT;
        for(int j=0;j<=n;j++){
            if(j+G<=n&&dp1[j]!=1e9) f1[j+G]=min(f1[j+G],dp1[j]);
        }
        dp1=f1;
    }
    int ans=min(dp0[n],dp1[n]);
    if(ans==1e9) return cout<<"Hungry",0;
    cout<<"Full\n"<<ans;
}
