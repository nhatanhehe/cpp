inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,l,w[N],dp[N],h[N];
struct SegmentTree{
    vector<ll>tree,lz;
    int n;
    void init(int _n){
        n=_n;
        tree.resize(n*4+10,0);
        lz.resize(n*4+10,0);
    }
    void apply(int id,int k){
        tree[id]+=k;
        lz[id]+=k;
    }
    void push(int id){
        if(lz[id]){
            apply(id*2,lz[id]);
            apply(id*2+1,lz[id]);
        }
        lz[id]=0;
    }
    void up(int u,int v,ll k,int id=1,int l=0,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return;
        if(u<=l&&r<=v){
            apply(id,k);
            return;
        }
        push(id);
        int mid=(l+r)>>1;
        up(u,v,k,id*2,l,mid);
        up(u,v,k,id*2+1,mid+1,r);
        tree[id]=min(tree[id*2],tree[id*2+1]);
    }
    ll get(int u,int v,int id=1,int l=0,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u) return inf;
        if(u<=l&&r<=v) return tree[id];
        push(id);
        int mid=(l+r)>>1;
        return min(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
    }
}seg;
