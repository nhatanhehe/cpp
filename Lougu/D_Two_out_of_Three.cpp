#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],dp[1005][1005];
tuple<int,int,int,int>trace[1004][1005];
bool minimize(int &x,int y){
    if(x>=y){
        x=y;
        return 1;
    }
    return 0;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    for(int i=1;i<=n+1;i++){
        for(int j=0;j<=n;j++) dp[i][j]=1e9;
    }
    dp[2][1]=0;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=n;j++){
            if(dp[i][j]==1e9) continue;
            // Dau hang hien tai co dang [j,i,i+1]
            // TH1 lay j,i
            if(minimize(dp[i+2][i+1],dp[i][j]+max(a[j],a[i]))){
                trace[i+2][i+1]={i,j,j,i};
            }
            // TH2 j,i+1
            if(minimize(dp[i+2][i],dp[i][j]+max(a[j],a[i+1]))){
                trace[i+2][i]={i,j,j,i+1};
            }
            // TH3 i, i+1
            if(minimize(dp[i+2][j],dp[i][j]+max(a[i],a[i+1]))){
                trace[i+2][j]={i,j,i,i+1};
            }
        }
    }
    if(n%2==0){
        vector<ii>res;
        int mxj=1e9,ans=1e9;
        for(int j=1;j<=n;j++) if(dp[n][j]!=1e9) dp[n][j]+=max(a[n],a[j]);
        for(int j=1;j<=n;j++){
            if(minimize(ans,dp[n][j])){
                mxj=j;
            }
        }
        res.pb(ii(mxj,n));
        cout<<ans<<'\n';
        while(n>2){
            auto [nxt_n,nxt_j,p1,p2]=trace[n][mxj];
            res.pb(ii(p1,p2));
            n=nxt_n;
            mxj=nxt_j;
        }
        reverse(all(res));
        for(auto [u,v]:res) cout<<u<<" "<<v<<'\n';
    }
    else{
        vector<ii>res;
        int mxj=1e9,ans=1e9;
        for(int j=1;j<=n;j++) if(dp[n+1][j]!=1e9) dp[n+1][j]+=a[j];
        for(int j=1;j<=n;j++){
            if(minimize(ans,dp[n+1][j])){
                mxj=j;
            }
        }
        cout<<ans<<'\n';
        res.pb(ii(mxj,0));
        n++;
        while(n>2){
            auto [nxt_n,nxt_j,p1,p2]=trace[n][mxj];
            res.pb(ii(p1,p2));
            n=nxt_n;
            mxj=nxt_j;
        }
        reverse(all(res));
        for(auto [u,v]:res){
            if(v) cout<<u<<" "<<v<<'\n';
            else cout<<u;
        }
    }
}
