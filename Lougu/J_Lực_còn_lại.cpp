inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,a[N],ans[N],d,Q[N],L[N],R[N],D[N];
vector<ii>g[N];
struct SegmentTree{
    // lz0 la lazy gan
    // lz1 la lazy cong
    vector<ll>tree,lz0,lz1;
    int n;
    void init(int _n){
        n=_n;
        tree.assign(n*4+10,0);
        lz0.assign(n*4+10,-1);
        lz1.assign(n*4+10,0);
    }
    void apply_set(int id,int k){
        tree[id]=k;
        lz0[id]=k;
        lz1[id]=0;
    }
    void apply_add(int id,int k){
        tree[id]+=k;
        lz1[id]+=k;
    }
    void push(int id){
        if(lz0[id]!=-1){
            apply_set(id*2,lz0[id]);
            apply_set(id*2+1,lz0[id]);
        }
        lz0[id]=-1;
        if(lz1[id]){
            apply_add(id*2,lz1[id]);
            apply_add(id*2+1,lz1[id]);
        }
        lz1[id]=0;
    }
    void up_set(int u,int v,int k,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u||l>r) return;
        if(u<=l&&r<=v){
            apply_set(id,k);
            return;
        }
        push(id);
        int mid=(l+r)>>1;
        up_set(u,v,k,id*2,l,mid);
        up_set(u,v,k,id*2+1,mid+1,r);
        tree[id]=min(tree[id*2],tree[id*2+1]);
    }
    void up_add(int u,int v,int k,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u||l>r) return;
        if(u<=l&&r<=v){
            apply_add(id,k);
            return;
        }
        push(id);
        int mid=(l+r)>>1;
        up_add(u,v,k,id*2,l,mid);
        up_add(u,v,k,id*2+1,mid+1,r);
        tree[id]=min(tree[id*2],tree[id*2+1]);
    }
    int get(int pos,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l==r){
            return tree[id];
        }
        push(id);
        int mid=(l+r)>>1;
        if(pos<=mid) return get(pos,id*2,l,mid);
        else return get(pos,id*2+1,mid+1,r);
    }
    // ham tim thg i phai nhat ma ans[i] < a_i
    int f1(int ai,int u,int v,int id=1,int l=1,int r=-1){
        if(r==-1) r=n;
        if(l>v||r<u||tree[id]>=ai) return u-1;
        if(l==r) return l;
        push(id);
        int mid=(l+r)>>1;
        int res=f1(ai,u,v,id*2+1,mid+1,r);
        if(res>u-1) return res;
        else return f1(ai,u,v,id*2,l,mid);
    }
}seg;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    
    cin>>n>>q;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    bool same_d = true;
    for(int i=1;i<=q;i++){
        cin>>L[i]>>R[i]>>D[i];
        if(i > 1 && D[i] != D[i-1]) same_d = false;
    }
    
    if(same_d && q > 0) {
        d = D[1];
        seg.init(n);
        for(int i=1;i<=q;i++){
            g[R[i]].pb(ii(L[i],i));
        }
        for(int r=1;r<=n;r++){
            ans[r]=d;
            seg.up_set(r,r,d);
            //tim doan ma ans[x] < x
            int m1=seg.f1(a[r],1,r);
            int m2=seg.f1(2*a[r]-1,m1+1,r);
            // voi cac x thoa man a[r] <= x < 2*a[r]-1 thi gia tri toi uu cua x se la a[r]-1
            seg.up_set(m1+1,m2,a[r]-1);
            // nguoc lai x >= 2*a[r]-1 thi x toi uu la x-a[r]
            seg.up_add(m2+1,r,-a[r]);
            for(auto [l,id]:g[r]){
                Q[id]=seg.get(l);
            }
        }
        for(int i=1;i<=q;i++){
            cout<<Q[i]<<'\n';
        }
    } else {
        for(int i=1;i<=q;i++){
            int cur_d = D[i];
            for(int j=L[i];j<=R[i];j++){
                if(a[j]<=cur_d) cur_d=max(cur_d-a[j],a[j]-1);
            }
            cout<<cur_d<<'\n';
        }
    }
}
