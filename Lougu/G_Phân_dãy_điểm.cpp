#define On(mask,i) (mask||(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,x[N][12],k;
vector<ll>dp;
void ql(int i,int id,ll sum,int mask,vector<ll>&mx){
    if(i==k){
        mx[mask]=max(mx[mask],dp[id]+sum);
        return;
    }
    ql(i+1,id,sum-x[id+1][i+1],mask,mx);
    ql(i+1,id,sum+x[id+1][i+1],mask|(1<<i),mx);
}
void ql2(int i,int id,ll sum,int mask,vector<ll>&mx){
    if(i==k){
        int fmask=(1<<k)-1;
        fmask^=mask;
        dp[id]=max(dp[id],mx[fmask]+sum);
        return;
    }
    ql2(i+1,id,sum-x[id][i+1],mask,mx);
    ql2(i+1,id,sum+x[id][i+1],mask|(1<<i),mx);
}
