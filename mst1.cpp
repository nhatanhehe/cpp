inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct DSU{
    vector<int>p;
    int n;
    void init(int _n){
        n=_n;
        p.resize(n+3,0);
        for(int i=1;i<=n;i++) p[i]=i;
    }
    int acs(int u){
        return u==p[u]? u:p[u]=acs(p[u]);
    }
    void join(int u,int v){
        u=acs(u);
        v=acs(v);
        if(u!=v){
            p[v]=u;
        }
    }
}dsu;
struct edges{
    int u,v,w;
};
vector<edges>e;
