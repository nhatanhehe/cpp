#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=5e2+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll n,m,s[N][N],t,k,a[N][N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>m>>n>>k;
        for(int i=1;i<=m;i++){
            for(int j=1;j<=n;j++){
                cin>>a[i][j];
            }
        }
        ll sum0=0,sum1=0;
        for(int i=1;i<=m;i++){
            for(int j=1;j<=n;j++){
                char x;
                cin>>x;
                s[i][j]=s[i-1][j]+s[i][j-1]-s[i-1][j-1]+(x=='0');
                if(x=='0') sum0+=a[i][j];
                else sum1+=a[i][j];
            }
        }
        // lech = 1 - 0
        ll dif=sum1-sum0;
        vector<ll>d;
        for(int i=1;i<=m-k+1;i++){
            for(int j=1;j<=n-k+1;j++){
                int x=i+k-1;
                int y=j+k-1;
                ll s0=s[x][y]-s[i-1][y]-s[x][j-1]+s[i-1][j-1];
                ll s1=k*k-s0;
                d.pb(s1-s0);
            }
        }
        if(*max_element(all(d))==0&&*min_element(all(d))==0){
            if(dif==0) cout<<"YES\n";
            else cout<<"NO\n";
        }
        else{
            ll gcd=0;
            for(ll x:d){
                gcd=__gcd(gcd,x);
            }
            if(dif%gcd==0) cout<<"YES\n";
            else cout<<"NO\n";
        }
    }
}
