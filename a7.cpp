#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int d[N],u,v,w,n,m,k,ans[N];
vector<ii>g[N];
struct ed{
    int u,v,w;
}edge[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>k;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        edge[i]={u,v,w};
        g[u].pb({v,w});
        g[v].pb({u,w});
    }
    memset(d,0x3f,sizeof d);
    d[1]=0;
    deque<int>q={1};
    while(q.size()){
        int u=q.front(); q.pop_front();
        for(auto [v,w]:g[u]){
            if(d[v]>d[u]+w){
                d[v]=d[u]+w;
                if(w) q.pb(v);
                else q.push_front(v);
            }
        }
    }
    if(d[n]<k) return cout<<"No",0;
    cout<<"Yes\n";
    for(int i=1;i<=m;i++){
        auto [u,v,w]=edge[i];
        if(w==0) continue;
        if(d[u]>1e8||d[v]>1e8){
            cout<<1<<'\n';
            continue;
        }
        int x=min(d[v],d[u]);
        if(x>=k) cout<<1<<'\n';
        else cout<<x+1<<'\n';
    }
}
