const ll inf=1e18;
const ll N=1e2+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll dist[N],cap[N][N],flow[N][N],u,v,w,c,source,sink,n,m,k,inv[N],tr[N],cost[N][N],ans,a[N][N],A[N],B[N],b[N][N];
vector<int>g[N];
void add_edge(int u,int v,int c,int w){
    cap[u][v]=c;
    cap[v][u]=0;
    cost[u][v]=w;
    cost[v][u]=w;
    g[u].pb(v);
    g[v].pb(u);
}
bool fbm(){
    for(int i=source;i<=sink;i++){
        dist[i]=inf;
        tr[i]=0;
        inv[i]=0;
    }
    queue<int>q;
    q.push(source);
    dist[source]=0;
    while(q.size()){
        int u=q.front(); q.pop();
        inv[u]=0;
        for(int v:g[u]){
            if(flow[u][v]<cap[u][v]){
                int co=cost[u][v]*(flow[u][v]>=0? 1:-1);
                if(dist[v]>dist[u]+co){
                    tr[v]=u;
                    dist[v]=dist[u]+co;
                    if(!inv[v]){
                        inv[v]=1;
                        q.push(v);
                    }
                }
            }
        }
    }
    return dist[sink]<inf;
}
void inc(){
    ll del=inf;
    for(int i=sink;i!=source;i=tr[i]){
        int pre=tr[i];
        del=min(del,(flow[pre][i]>=0? cap[pre][i]-flow[pre][i]:-flow[pre][i]));
    }
    del=min(del,k);
    for(int i=sink;i!=source;i=tr[i]){
        int pre=tr[i];
        flow[pre][i]+=del;
        flow[i][pre]-=del;
    }
    k-=del;
    if(!k){
        for(int i=1;i<=n;i++){
            for(int j=1;j<=m;j++){
                if(flow[i][j+n]>0){
                    b[i][j]=1;
                }
            }
        }
        int cnt=0;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=m;j++){
                cnt+=(a[i][j]!=b[i][j]);
            }
        }
        cout<<cnt;
        exit(0);
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++){
        for(int j=1;j<=m;j++){
            cin>>a[i][j];
        }
    }
    for(int i=1;i<=n;i++){
        cin>>A[i];
        k+=A[i];
    }
    for(int i=1;i<=m;i++) cin>>B[i];
    source=0;
    sink=m+n+1;
    for(int i=1;i<=n;i++){
        add_edge(source,i,A[i],0);
    }
    for(int i=1;i<=n;i++){
        for(int j=1;j<=m;j++){
            add_edge(i,j+n,1,a[i][j]^1);
        }
    }
    for(int i=1;i<=m;i++){
        add_edge(i+n,sink,B[i],0);
    }
    while(fbm()) inc();
    cout<<-1;
}
