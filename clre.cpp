#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define ci pair<char,ll>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e3+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
string a,b;
vector<ci>A,B;
ll dp[N][N];
vector<int>P['z'+1];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>a>>b;
    for(int i=0;i<a.size();i++){
        if(isalpha(a[i])) A.pb({a[i],0});
        else A.back().se=A.back().se*10LL+(a[i]-'0');
    }
    for(int i=0;i<b.size();i++){
        if(isalpha(b[i])) B.pb({b[i],0});
        else B.back().se=B.back().se*10LL+(b[i]-'0');
    }
    /// lcs
    for(int i=0;i<B.size();i++){
        P[B[i].fi].pb(i);
    }
    for(int i=1;i<=A.size();i++){
        for(int j=1;j<=B.size();j++){
            dp[i][j]=max(dp[i-1][j],dp[i][j-1]);
            if(A[i-1].fi==B[j-1].fi){
                ll s1=0;
                for(int i_=i;i_>=1;i_--){
                    if(A[i_-1].fi==A[i-1].fi) s1+=A[i_-1].se;
                    ll s2=0;
                    for(int j_=j;j_>=1;j_--){
                        if(B[j_-1].fi==B[j-1].fi) s2+=B[j_-1].se;
                        if(A[i_-1].fi==B[j_-1].fi){
                            dp[i][j]=max(dp[i_-1][j_-1]+min(s1,s2),dp[i][j]);
                        }
                    }
                }
            }
        }
    }
    cout<<dp[A.size()][B.size()]<<'\n';
    memset(dp,0,sizeof dp);
    for(int i=1;i<=A.size();i++){
        for(int j=1;j<=B.size();j++){
            if(A[i-1].fi==B[j-1].fi){
                dp[i][j]=min(A[i-1].se,B[j-1].se);
                if(A[i-1].se==B[j-1].se){
                    dp[i][j]=max(dp[i][j],dp[i-1][j-1]+A[i-1].se);
                }
            }
            else dp[i][j]=0;
        }
    }
    ll ans=0;
     for(int i=1;i<=A.size();i++) {
        for (int j=1;j<=B.size();j++) {
            ll val=dp[i][j];
            if(i<A.size()&&j<B.size()&&A[i].fi==B[j].fi){
                val+=min(A[i].se,B[j].se);
            }
            ans=max(ans,val);
        }
    }
    cout<<ans;
}
