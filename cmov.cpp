struct Matrix{
    int x[4][4];
    Matrix(){}
    Matrix(int a[4][4]){
        for(int i=1;i<=3;i++){
            for(int j=1;j<=3;j++) x[i][j]=a[i][j];
        }
    }
    Matrix operator * (Matrix const &b){
        Matrix c;
        for(int i=1;i<=3;i++){
            for(int j=1;j<=3;j++){
                c.x[i][j]=0;
                for(int k=1;k<=3;k++){
                    c.x[i][j]=add(c.x[i][j],mul(x[i][k],b.x[k][j]));
                }
            }
        }
        return c;
    }
    friend Matrix operator ^ (Matrix const &a,int const &b){
        if(b==1) return a;
        Matrix c=a^(b/2);
        if(b&1) return c*c*a;
        return c*c;
    }
};
