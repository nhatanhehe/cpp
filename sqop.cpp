inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
struct BIT{
    vector<int>bit;
    int n;
    void init(int _n){
        n=_n;
        bit.resize(n+4,0);
    }
    void up(int i,int k){
        for(;i<=n;i+=i&-i){
            bit[i]+=k;
        }
    }
    int get(int i){
        int res=0;
        for(;i;i-=i&-i){
            res+=bit[i];
        }
        return res;
    }
    int query(int l,int r){
        return get(r)-get(l-1);
    }
}bit;
int n,q,a[N];
