BigInt calc(int i,int depth){
    if(depth>k||depth<0) return 0;
    BigInt &ans=dp[i][depth];
    if(i==s.size()){
        ans=(depth==0);
        return ans;
    }
    if(vis[i][depth]) return ans;
    ans=0;
    vis[i][depth]=1;
    if(s[i]=='(') ans=ans+calc(i+1,depth+1);
    if(s[i]==')') ans=ans+calc(i+1,depth-1);
    if(s[i]=='?') ans=ans+calc(i+1,depth+1)+calc(i+1,depth-1);
    return ans;
}
