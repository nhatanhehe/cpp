const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (masks(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
ll t,n,k,a[N],mu,ad,seed;
struct Node{
    Node *child[2];
    int cnt;
    Node(){
        child[0]=child[1]=NULL;
        cnt=0;
    }
};
struct Trie{
    Node *root;
    void init(){
        root=new Node();
    }
    void ins(int x){
        Node *p=root;
        for(int i=15;i>=0;i--){
            int c=(x>>i)&1;
            if(!p->child[c]) p->child[c]=new Node();
            p=p->child[c];
            p->cnt++;
        }
    }

    void del(int x){
        Node *p=root;
        for(int i=15;i>=0;i--){
            int c=(x>>i)&1;
            p=p->child[c];
            p->cnt--;
        }
    }

    int find_k(int k){
        Node *p=root;
        int res=0;
        for(int i=15;i>=0;i--){
            int lcnt=(p->child[0]? p->child[0]->cnt:0);
            if(lcnt>=k){
                if(p->child[0]) p=p->child[0];
                else break;
            }
            else{
                k-=lcnt;
                res+=(1<<i);
                if(p->child[1]) p=p->child[1];
                else break;
            }
        }
        return res;
    }
};
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    #define Task "a"
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>seed>>mu>>ad>>n>>k;
        Trie trie;
        trie.init();
        a[1]=seed;
        ll sum=0;
        for(int i=1;i<=n;++i){
            if(i>=2) a[i]=(a[i-1]*mu+ad)%65536;
            trie.ins(a[i]);
            if(i-k>=1){
                trie.del(a[i-k]);
            }
            //cout<<i<<" "<<s.size()<<'\n';
            if(i>=k) sum+=trie.find_k((k+1)/2);

            //cout<<(*s.find_by_order((k-1)/2+1)).fi<<'\n';
        }
        cout<<sum<<' ';
    }
}
