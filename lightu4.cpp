#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,s[N],u,v,vis[N],cnt;
vector<ii>g[N];
vector<int>op;
void dfs(int u,int p){
    vis[u]=1;
    if(s[u]==0) cnt++;
    for(auto [v,id]:g[u]){
        if(v!=p&&!vis[v]){
            dfs(v,u);
            if(s[v]==0){
                s[v]^=1;
                s[u]^=1;
                op.pb(id);
            }
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=n;i++) cin>>s[i];
    for(int i=1;i<=m;i++){
        cin>>u>>v;
        g[u].pb({v,i});
        g[v].pb({u,i});
    }
    for(int i=1;i<=n;i++){
        if(!vis[i]){
            cnt=0;
            dfs(i,-1);
            if(cnt&1){
                cout<<-1;
                return 0;
            }
        }
    }
    cout<<op.size()<<'\n';
    for(int x:op) cout<<x<<" ";
}
