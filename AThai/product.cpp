inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int d[N],t,n,dp[N];
vector<int>uoc;
void ql(int i,int sum){
    if(i>6){
        d[sum]++;
        if(sum>0) uoc.pb(sum);
        return;
    }
    ql(i+1,sum*10);
    ql(i+1,sum*10+1);
}
