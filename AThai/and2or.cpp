#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,q,a[N],b[N],f[N][20],t[N][20],d[N],lz[N<<2],tree[N<<2];
int get1(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return f[l][k]&f[r-(1<<k)+1][k];
}
int get2(int l,int r){
    int k=31-__builtin_clz(r-l+1);
    return t[l][k]|t[r-(1<<k)+1][k];
}
vector<ii>g[N],Q[N];
int ans[N];
void fix(int id,int l,int r,int k){
    tree[id]+=(r-l+1)*k;
    lz[id]+=k;
}
void push(int id,int l,int r){
    if(lz[id]){
        int mid=(l+r)>>1;
        fix(id*2,l,mid,lz[id]);
        fix(id*2+1,mid+1,r,lz[id]);
        lz[id]=0;
    }
}
void up(int u,int v,int k,int id=1,int l=1,int r=n){
    if(l>v||r<u) return;
    if(u<=l&&r<=v){
        fix(id,l,r,k);
        return;
    }
    push(id,l,r);
    int mid=(l+r)>>1;
    up(u,v,k,id*2,l,mid);
    up(u,v,k,id*2+1,mid+1,r);
    tree[id]=tree[id*2]+tree[id*2+1];
}
int get(int u,int v,int id=1,int l=1,int r=n){
    if(l>v||r<u) return 0;
    if(u<=l&&r<=v) return tree[id];
    push(id,l,r);
    int mid=(l+r)>>1;
    return get(u,v,id*2,l,mid)+get(u,v,id*2+1,mid+1,r);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>q;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        f[i][0]=a[i];
    }
    for(int i=1;i<=m;i++){
        cin>>b[i];
        t[i][0]=b[i];
    }
    for(int j=1;(1<<j)<=n;j++){
        for(int i=1;i+(1<<(j-1))<=n;i++){
            f[i][j]=f[i][j-1]&f[i+(1<<(j-1))][j-1];
        }
    }
    for(int j=1;(1<<j)<=m;j++){
        for(int i=1;i+(1<<(j-1))<=m;i++){
            t[i][j]=t[i][j-1]|t[i+(1<<(j-1))][j-1];
        }
    }
    for(int i=1;i<=q;i++){
        int l,r;
        cin>>l>>r;
        Q[r].pb({l,i});
    }
    for(int i=1;i<=m;i++){
        int j=i,last=b[j];
        while(true){
            int l=1,r=j,ans=r;
            while(l<=r){
                int mid=(l+r)>>1;
                if(get2(mid,i)==last){
                    r=mid-1;
                    ans=mid;
                }
                else l=mid+1;
            }
            d[last]=1;
            if(ans==1) break;
            last|=b[ans-1];
            j=ans-1;
        }
    }
    for(int i=1;i<=n;i++){
        int j=i,last=a[j];
        while(true){
            int l=1,r=j,ans=r;
            while(l<=r){
                int mid=(l+r)>>1;
                if(get1(mid,i)==last){
                    r=mid-1;
                    ans=mid;
                }
                else l=mid+1;
            }
            if(d[last]){
                g[i].pb({ans,j});
            }
            if(ans==1) break;
            last&=a[ans-1];
            j=ans-1;
        }
    }
    for(int i=1;i<=n;i++){
        for(auto [l,r]:g[i]){
            up(l,r,1);
        }
        for(auto [l,pos]:Q[i]){
            ans[pos]=get(l,i);
        }
    }
    for(int i=1;i<=q;i++){
        cout<<ans[i]<<'\n';
    }
}
