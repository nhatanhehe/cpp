inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,a[N],tree[N<<2];
set<int>s[35];
void up(int pos,int k,int id=1,int l=1,int r=n){
    if(l==r){
        tree[id]+=k;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid) up(pos,k,id*2,l,mid);
    else up(pos,k,id*2+1,mid+1,r);
    tree[id]=min(tree[id*2],tree[id*2+1]);
}
int get(int u,int v,int id=1,int l=1,int r=n){
    if(l>v||r<u) return 1e9;
    if(u<=l&&r<=v){
        return tree[id];
    }
    int mid=(l+r)>>1;
    return min(get(u,v,id*2,l,mid),get(u,v,id*2+1,mid+1,r));
}
