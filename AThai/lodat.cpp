inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int m,n,pre[1003][1004],a,b;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n;
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            int x;
            cin>>x;
            pre[i][j]=pre[i-1][j]+pre[i][j-1]-pre[i-1][j-1]+x;
        }
    }
    cin>>a>>b;
    int ans=1e9;
    for(int i=1;i<=m-a+1;i++){
        for(int j=1;j<=n-b+1;j++){
            int x=i+a-1;
            int y=j+b-1;
            ans=min(ans,pre[x][y]-pre[i-1][y]-pre[x][j-1]+pre[i-1][j-1]);
        }
    }
    for(int i=1;i<=m-b+1;i++){
        for(int j=1;j<=n-a+1;j++){
            int x=i+b-1;
            int y=j+a-1;
            ans=min(ans,pre[x][y]-pre[i-1][y]-pre[x][j-1]+pre[i-1][j-1]);
        }
    }
    cout<<ans;
}
