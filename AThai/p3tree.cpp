inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,st[N],en[N],timer,p1,p2,p3,ver[N],par[N],sz[N];
vector<int>g[N];
void dfs(int u,int p){
    st[u]=++timer;
    sz[u]=1;
    ver[timer]=u;
    for(int v:g[u]){
        if(v!=p){
            par[v]=u;
            dfs(v,u);
            sz[u]+=sz[v];
        }
    }
    en[u]=timer;
}
int bit[N];
void up(int i,int k){
    for(;i<=n;i+=i&-i){
        bit[i]+=k;
    }
}
int get(int i){
    int res=0;
    for(;i;i-=i&-i){
        res+=bit[i];
    }
    return res;
}
int query(int l,int r){
    if(r<l) return 0;
    return get(r)-get(l-1);
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>p1>>p2>>p3;
    for(int i=1;i<n;i++){
        cin>>u>>v;
        g[u].pb(v);
        g[v].pb(u);
    }
    dfs(1,-1);
    ll res=0;
    for(int i=1;i<=n;i++){
        if(p2>p1&&p2>p3){
            int out=query(en[i]+1,n)+query(1,st[i]-1);
            int in=query(st[i],en[i]);
            res+=out*in;
            vector<int>v;
            for(int j=0;j<g[i].size();j++){
                if(g[i][j]!=par[i]){
                    v.pb(g[i][j]);
                }
            }
            for(int j=0;j<(int)v.size()-1;j++){
                int v1=v[j];
                int v2=v[j+1];
                res+=query(st[v1],en[v1])*query(st[v2],en[i]);
            }
        }
        else if(p2<p1&&p2<p3){
            int out=sz[1]-sz[i]-(query(en[i]+1,n)+query(1,st[i]-1));
            int in=sz[i]-1-query(st[i],en[i]);
            res+=1LL*out*in;
            ll sum=0;
            vector<int>v;
            for(int j=0;j<g[i].size();j++){
                if(g[i][j]!=par[i]){
                    sum+=sz[g[i][j]];
                    v.pb(g[i][j]);
                }
            }
            for(int j=0;j<(int)v.size()-1;j++){
                int v1=v[j];
                int v2=v[j+1];
                sum-=sz[v1];
                res+=(sz[v1]-query(st[v1],en[v1]))*(sum-query(st[v2],en[i]));
            }
        }
        else{
            int out=query(en[i]+1,n)+query(1,st[i]-1);
            int in=query(st[i],en[i]);
            int out_l=sz[1]-sz[i]-out;
            int in_l=sz[i]-1-in;
            res+=in_l*out+out_l*in;
            for(int v:g[i]){
                if(v!=par[i]){
                    int rr=query(st[v],en[v]);
                    int rr2=(sz[v]-rr);
                    res+=rr*(in_l-rr2);
                }
            }
        }
        up(st[i],1);
    }
    cout<<res;
}
