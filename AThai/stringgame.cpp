inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,T,c,cur,trie[N][2][2],root[2],dist[N],work[N];
string s[N],t;
struct edge{
    int to,rev,flow,cap;
};
vector<edge>g[N];
void addedge(int u,int v,int cap){
    edge a={v,g[v].size(),0,cap};
    edge b={u,g[u].size(),0,0};
    g[u].pb(a);
    g[v].pb(b);
}
void changecap(int u,int v,int cap){
    for(auto &e:g[u]){
        if(e.to==v){
            e.cap=min(e.cap,cap);
        }
    }
}
bool bfs(){
    queue<int>q;
    memset(dist,-1,sizeof(dist));
    q.push(0);
    dist[0]=0;
    while(q.size()){
        int u=q.front(); q.pop();
        for(auto [v,rev,flow,cap]:g[u]){
            if(dist[v]<0&&flow<cap){
                dist[v]=dist[u]+1;
                q.push(v);
            }
        }
    }
    return dist[root[1]]>0;
}
ll dfs(int u,int fl){
    if(u==root[1]){
        return fl;
    }
    for(int &s=work[u];s<g[u].size();s++){
        edge &e=g[u][s];
        int v=e.to;
        if(dist[v]==dist[u]+1&&e.flow<e.cap){
            int df=dfs(v,min(fl,e.cap-e.flow));
            if(df<=0) continue;
            e.flow+=df;
            g[v][e.rev].flow-=df;
            return df;
        }
    }
    return 0;
}
unordered_map<string,int>mp;
void ins(string s){
    int p=0;
    for(char x:s){
        if(!trie[p][x-'0'][0]){
            trie[p][x-'0'][0]=++cur;
            addedge(p,cur,1e9);
        }
        p=trie[p][x-'0'][0];
    }
    mp[s]=cur;
}
void ins2(string s){
    int p=root[1];
    for(char x:s){
        if(!trie[p][x-'0'][1]){
            trie[p][x-'0'][1]=++cur;
            addedge(cur,p,1e9);
        }
        p=trie[p][x-'0'][1];
    }
    string t=s;
    reverse(all(t));
    addedge(mp[t],cur,1e9);
}
void up1(string s,int cap){
    int p=0,last_p;
    for(char x:s){
        if(!trie[p][x-'0'][0]) return;
        last_p=p;
        p=trie[p][x-'0'][0];
    }
    changecap(last_p,p,cap);
}
void up2(string s,int cap){
    int p=root[1],last_p;
    for(char x:s){
        if(!trie[p][x-'0'][1]) return;
        last_p=p;
        p=trie[p][x-'0'][1];
    }
    changecap(p,last_p,cap);
}
