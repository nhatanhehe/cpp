#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int t,n;
string s;
int dp[N][2],trace[N][2];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>t;
    while(t--){
        cin>>n>>s;
        s=" "+s;
        for(int i=1;i<=n;i++){
            dp[i][0]=dp[i][1]=1e9;
        }
        if(s[1]=='?') dp[1][0]=dp[1][1]=0;
        else if(s[1]=='R'){
            dp[1][0]=0;
        }
        else{
            dp[1][1]=0;
        }
        for(int i=2;i<=n;i++){
            if(s[i]=='?'||s[i]=='R'){
                if(dp[i-1][0]!=1e9){
                    if(dp[i][0]>dp[i-1][0]+1){
                        dp[i][0]=dp[i-1][0]+1;
                        trace[i][0]=0;
                    }
                }
                if(dp[i-1][1]!=1e9){
                    if(dp[i][0]>dp[i-1][1]){
                        dp[i][0]=dp[i-1][1];
                        trace[i][0]=1;
                    }
                }
            }
            if(s[i]=='?'||s[i]=='B'){
                if(dp[i-1][0]!=1e9){
                    if(dp[i][1]>dp[i-1][0]){
                        dp[i][1]=dp[i-1][0];
                        trace[i][1]=0;
                    }
                }
                if(dp[i-1][1]!=1e9){
                    if(dp[i][1]>dp[i-1][1]+1){
                        dp[i][1]=dp[i-1][1]+1;
                        trace[i][1]=1;
                    }
                }
            }
        }
        int pos=n,tp;
        if(dp[n][0]>dp[n][1]) tp=1;
        else tp=0;
        string res;
        while(pos>=1){
            if(tp==1) res.pb('B');
            else res.pb('R');
            tp=trace[pos][tp];
            pos--;
        }
        reverse(all(res));
        cout<<res<<'\n';
    }
}
