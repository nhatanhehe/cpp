#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define debug(x) cout<< #x << " = "<< x <<'\n'
#define Task "a"
#define ii pair<int,int>
#define di pair<ld,ii>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=5e2+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,s,t,v0,x,y,len,vel;
struct pt{
    int v,s,vel;
};
vector<pt>g[N];
ld dist[N][N];
#define eps 1e-7
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>s>>t>>v0;
    for(int i=1;i<=m;i++){
        cin>>x>>y>>len>>vel;
        g[x].pb({y,len,vel});
    }
    priority_queue<di,vector<di>,greater<di>>pq;
    for(int i=1;i<=n;i++){
        for(int j=0;j<=500;j++) dist[i][j]=1e18;
    }
    dist[s][v0]=0;
    pq.push({0,{s,v0}});
    while(pq.size()){
        di x=pq.top();
        pq.pop();
        ld cost=x.fi;
        int u=x.se.fi;
        int velo=x.se.se;
        if(u==t){
            cout<<fixed<<setprecision(10)<<dist[u][velo];
            return 0;
        }
        if(cost>dist[u][velo]+eps) continue;
        for(auto [v,s,vel]:g[u]){
            if(vel==0){
                if(dist[v][velo]>dist[u][velo]+1.0*s/velo+eps){
                    dist[v][velo]=dist[u][velo]+1.0*s/velo;
                    pq.push({dist[v][velo],{v,velo}});
                }
            }
            else{
                if(dist[v][vel]>dist[u][velo]+1.0*s/vel+eps){
                    dist[v][vel]=dist[u][velo]+1.0*s/vel;
                    pq.push({dist[v][vel],{v,vel}});
                }
            }
        }
    }
}
