#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e5+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,p[N],tplt;
int acs(int u){
    return u==p[u]? u:p[u]=acs(p[u]);
}
void join(int u,int v){
    u=acs(u);
    v=acs(v);
    if(u!=v){
        tplt--;
        p[v]=u;
    }
}
int x[N],y[N],d[N],pos[N],ans[N];
map<ii,int>mp;
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    tplt=n;
    for(int i=1;i<=n;i++) p[i]=i;
    for(int i=1;i<=m;i++){
        cin>>x[i]>>y[i];
        if(x[i]>y[i]) swap(x[i],y[i]);
        mp[ii(x[i],y[i])]=i;
    }
    int t;
    cin>>t;
    for(int i=1;i<=t;i++){
        int u,v;
        cin>>u>>v;
        if(u>v) swap(u,v);
        if(mp.find(ii(u,v))!=mp.end()){
            d[mp[ii(u,v)]]=1;
            pos[i]=mp[ii(u,v)];
        }
    }
    for(int i=1;i<=m;i++){
        if(!d[i]){
            join(x[i],y[i]);
        }
    }
    for(int i=t;i>=1;i--){
        if(pos[i]==0) continue;
        ans[i]=tplt;
        join(x[pos[i]],y[pos[i]]);
    }
    for(int i=1;i<=t;i++){
        cout<<ans[i]<<'\n';
    }
}
