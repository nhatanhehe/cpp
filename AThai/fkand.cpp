const ll inf=1e18;
const ll N=1e2+2;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k;
bool dp[N][N];
ll a[N],mx;
bool check(ll n,vector<int>tm){
    for(int bit:tm){
        if(!((n>>bit)&1)) return 0;
    }
    return 1;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        mx+=a[i];
    }
    int LOG=log2(mx);
    vector<int>tm;
    ll mask=0;
    for(int bit=LOG+1;bit>=0;bit--){
        mask=On(mask,bit);
        for(int i=0;i<=n;i++){
            for(int j=0;j<=min(i,k);j++){
                dp[i][j]=0;
            }
        }
        dp[0][0]=1;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=min(k,i);j++){
                ll suf=0;
                for(int t=i;t>=1;t--){
                    suf+=a[t];
                    if((suf&mask)==mask){
                        dp[i][j]|=dp[t-1][j-1];
                    }
                }
            }
        }
        if(!dp[n][k]) mask=Off(mask,bit);
    }
    cout<<mask;
}
