#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=2e6+5;
const ll mod=1e9+7;
const ll base=311;
const ll phainon=33550336;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,a[N],f[N],dp[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        f[a[i]]++;
    }
    for(int k=0;k<=19;k++){
        for(int mask=0;mask<(1<<20);mask++){
            if(!((mask>>k)&1)){
                f[mask]+=f[On(mask,k)];
            }
        }
    }
    for(int mask=0;mask<(1<<20);mask++){
        dp[mask]=-1e18;
    }
    dp[(1<<20)-1]=0;
    for(int mask=(1<<20)-1;mask>=0;mask--){
        if(dp[mask]==-1e18) continue;
        for(int j=0;j<=19;j++){
            if((mask>>j)&1){
                int child=Off(mask,j);
                int cnt=f[child]-f[mask];
                dp[child]=max(dp[child],dp[mask]+cnt*child);
            }
        }
    }
    int ans=0;
    for(int mask=0;mask<(1<<20);mask++){
        ans=max(ans,dp[mask]);
    }
    cout<<ans;
}
