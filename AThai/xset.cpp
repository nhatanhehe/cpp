#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask&~(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int dp[20][N],n,k,a[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    k=min(k,15);
    dp[0][0]=1;
    for(int i=1;i<=n;i++){
        for(int mask=0;mask<(1<<15);mask++){
            if((mask^a[i])==mask+a[i]){
                for(int j=1;j<=k;j++){
                    dp[j][mask^a[i]]=add(dp[j][mask^a[i]],dp[j-1][mask]);
                }
            }
        }
    }
    ll res=0;
    for(int i=1;i<=k;i++){
        for(int mask=0;mask<(1<<15);mask++){
            res=add(res,mul(dp[i][mask],mask));
        }
    }
    cout<<res;
}
