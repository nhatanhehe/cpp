#define fi first
#define se second
const int inf=1e18;
const int N=2e5+5;
const int mod=1e9+7;
const int base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
int mul(int a,int b){
    return (a%mod)*(b%mod)%mod;
}
int sub(int a,int b){
    return ((a-b)%mod+mod)%mod;
}
int add(int a,int b){
    return (a%mod+b%mod)%mod;
}
int n,m,d[N],low[N],dp[N];
ii edges[N];
vector<ii>adj[N];
vector<int>ed[N];
bool vis[N],cc[N];
stack<int>s;
int cnt,tplt,scc[N];
void dfs(int u,int id){
    low[u]=d[u]=++cnt;
    s.push(u);
    for(auto x:adj[u]){
        int v=x.fi;
        int idx=x.se;
        if(idx!=id&&!vis[v]){
            if(d[v]) low[u]=min(low[u],d[v]);
            else{
                dfs(v,idx);
                low[u]=min(low[u],low[v]);
            }
        }
    }
    if(low[u]==d[u]){
        tplt++;
        int v;
        do{
            v=s.top();
            vis[v]=1;
            scc[v]=tplt;
            s.pop();
        }while(u!=v);
    }
}
map<ii,int>mp;
int res,leaf;
void dfs2(int u,int p){
    if(ed[u].size()==1) leaf++;
    for(int v:ed[u]){
        if(v!=p){
            dfs2(v,u);
        }
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>edges[i].fi>>edges[i].se;
        adj[edges[i].fi].pb({edges[i].se,i});
        adj[edges[i].se].pb({edges[i].fi,i});
    }
    for(int i=1;i<=n;i++){
        if(!d[i]) dfs(i,0);
    }
    int bridge=0;
    for(int i=1;i<=m;i++){
        int u=scc[edges[i].fi];
        int v=scc[edges[i].se];
        if(u!=v){
            ed[u].pb(v);
            ed[v].pb(u);
            bridge++;
        }
    }
    dfs2(1,-1);
    cout<<(leaf+1)/2;
}
