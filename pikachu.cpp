#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "pikachu"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=1e2+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,dist[N][N][2][2];
char A[N][N];
vector<ii>tp['Z'+1];
int dx[]={-1,0,1,0};
int dy[]={0,-1,0,1};
struct pt{
    int u,v,dir,ch;
};

main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>m>>n;
    for(int i=1;i<=m;i++){
        for(int j=1;j<=n;j++){
            cin>>A[i][j];
            tp[A[i][j]].pb({i,j});
        }
    }
    for(int i=0;i<=n+1;i++){
        A[0][i]='.';
        A[m+1][i]='.';
    }
    for(int i=0;i<=m+1;i++){
        A[i][0]='.';
        A[i][n+1]='.';
    }
    int ans=0;
    for(char c='A';c<='Z';c++){
        for(ii a:tp[c]){
            memset(dist,0x3f,sizeof dist);
            dist[a.fi][a.se][0][0]=1;
            dist[a.fi][a.se][1][0]=1;
            deque<pt>q;
            q.pb({a.fi,a.se,0,0});
            q.pb({a.fi,a.se,1,0});
            while(q.size()){
                auto [u,v,dir,ch]=q.front();
                q.pop_front();
                if(ch) continue;
                for(int k=0;k<4;k++){
                    int x=dx[k]+u,y=dy[k]+v;
                    if(0<=x&&x<=m+1&&0<=y&&y<=n+1&&(A[x][y]=='.'||(A[x][y]==c))){
                        int nw_ch=(A[x][y]==c);
                        if(dir==0){
                            if(dy[k]==0){
                                if(dist[x][y][0][nw_ch]>dist[u][v][0][ch]){
                                    dist[x][y][0][nw_ch]=dist[u][v][0][ch];
                                    q.push_front({x,y,0,nw_ch});
                                }
                            }
                            else{
                                if(dist[x][y][1][nw_ch]>dist[u][v][0][ch]+1){
                                    dist[x][y][1][nw_ch]=dist[u][v][0][ch]+1;
                                    q.push_back({x,y,1,nw_ch});
                                }
                            }
                        }
                        else{
                            if(dx[k]==0){
                                if(dist[x][y][1][nw_ch]>dist[u][v][1][ch]){
                                    dist[x][y][1][nw_ch]=dist[u][v][1][ch];
                                    q.push_front({x,y,1,nw_ch});
                                }
                            }
                            else{
                                if(dist[x][y][0][nw_ch]>dist[u][v][1][ch]+1){
                                    dist[x][y][0][nw_ch]=dist[u][v][1][ch]+1;
                                    q.push_back({x,y,0,nw_ch});
                                }
                            }
                        }
                    }
                }
            }
            for(ii b:tp[c]){
                if(b!=a){
                    if(dist[b.fi][b.se][0][1]<=3||dist[b.fi][b.se][1][1]<=3) ans++;
                }
            }
        }
    }
    cout<<ans/2;
}
