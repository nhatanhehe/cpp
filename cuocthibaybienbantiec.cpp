int n,q,a[N],l,r,f[N];
struct segTree{
    vector<int>tree[N<<2];
    void build(int id=1,int l=1,int r=n){
        if(l==r){
            tree[id].pb(a[l]);
            return;
        }
        int mid=(l+r)>>1;
        build(id*2,l,mid);
        build(id*2+1,mid+1,r);
        tree[id].resize(tree[id*2].size()+tree[id*2+1].size());
        merge(all(tree[id*2]),all(tree[id*2+1]),tree[id].begin());
    }
    int getMax(int u,int v,int k,int id=1,int l=1,int r=n){
        if(l>v||r<u) return 0;
        if(u<=l&&r<=v){
            int pos=upper_bound(all(tree[id]),k)-tree[id].begin()-1;
            return (pos<0)? 0:tree[id][pos];
        }
        int mid=(l+r)>>1;
        return max(getMax(u,v,k,id*2,l,mid),getMax(u,v,k,id*2+1,mid+1,r));
    }
    int get(int u,int v,int k,int id=1,int l=1,int r=n){
        if(l>v||r<u) return 0;
        if(u<=l&&r<=v){
            return lower_bound(all(tree[id]),k)-tree[id].begin();
        }
        int mid=(l+r)>>1;
        return get(u,v,k,id*2,l,mid)+get(u,v,k,id*2+1,mid+1,r);
    }
};
int exp(int a,int b){
    int res=1;
    while(b>0){
        if(b&1) res=mul(res,a);
        a=mul(a,a);
        b>>=1;
    }
    return res;
}
int A(int n,int k){
    return mul(f[n],exp(f[n-k],mod-2));
}
