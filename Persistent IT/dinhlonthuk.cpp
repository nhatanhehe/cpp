inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,a[N],l,r,cur,root[N],pos[N];
ii b[N];
struct Node{
    int l,r,val;
    Node(){
        l = r = val = 0;
    }
}tree[N*23];
void build(int id=1,int l=1,int r=n){
    if(l==r){
        tree[id].val=0;
        return;
    }
    int mid=(l+r)>>1;
    tree[id].l=++cur;
    tree[id].r=++cur;
    build(tree[id].l,l,mid);
    build(tree[id].r,mid+1,r);
    tree[id].val=tree[tree[id].l].val+tree[tree[id].r].val;
}
void up(int pos,int k,int id,int l=1,int r=n){
    if(l==r){
        tree[id].val+=k;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid){
        tree[++cur]=tree[tree[id].l];
        tree[id].l=cur;
        up(pos,k,tree[id].l,l,mid);
    }
    else{
        tree[++cur]=tree[tree[id].r];
        tree[id].r=cur;
        up(pos,k,tree[id].r,mid+1,r);
    }
    tree[id].val=tree[tree[id].l].val+tree[tree[id].r].val;
}
int get(int idu,int idv,int idlca,int idp,int k,int l=1,int r=n){
    if(l==r) return l;
    int mid=(l+r)>>1;
    if(tree[tree[idu].l].val+tree[tree[idv].l].val-tree[tree[idlca].l].val-tree[tree[idp].l].val<k){
        k-=tree[tree[idu].l].val+tree[tree[idv].l].val-tree[tree[idlca].l].val-tree[tree[idp].l].val;
        return get(tree[idu].r,tree[idv].r,tree[idlca].r,tree[idp].r,k,mid+1,r);
    }
    else return get(tree[idu].l,tree[idv].l,tree[idlca].l,tree[idp].l,k,l,mid);
}
vector<int>g[N];
int p[N][20],h[N];
void dfs(int u,int par){
    root[u]=++cur;
    tree[root[u]]=tree[root[par]];
    up(pos[u],1,root[u]);
    for(int v:g[u]){
        if(v!=par){
            h[v]=h[u]+1;
            p[v][0]=u;
            dfs(v,u);
        }
    }
}
int lca(int u,int v){
    if(h[u]<h[v]) swap(u,v);
    for(int i=19;i>=0;i--){
        if(h[u]-h[v]>=(1<<i)) u=p[u][i];
    }
    if(u==v) return u;
    for(int i=19;i>=0;i--){
        if(p[u][i]!=p[v][i]){
            u=p[u][i];
            v=p[v][i];
        }
    }
    return p[u][0];
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    cin>>n>>q;
    for(int i=1;i<=n;i++){
        cin>>a[i];
        b[i]={a[i],i};
    }
    for(int i=1;i<n;i++){
        int u,v;
        cin>>u>>v;
        g[u].pb(v);
        g[v].pb(u);
    }
    sort(b+1,b+n+1);
    for(int i=1;i<=n;i++){
        pos[b[i].se]=i;
    }
    root[0]=cur=1;
    build();
    dfs(1,0);
    for(int j=1;j<=19;j++){
        for(int i=1;i<=n;i++){
            p[i][j]=p[p[i][j-1]][j-1];
        }
    }
    while(q--){
        int u,v,k;
        cin>>u>>v>>k;
        int lc=lca(u,v);
        if(h[u]+h[v]-2*h[lc]+1<k) cout<< -1<<'\n';
        else cout<<b[get(root[u],root[v],root[lc],root[p[lc][0]],k)].fi<<'\n';
    }
}
