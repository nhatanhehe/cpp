inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,q,r,premin,premax,a[N],id,p,w;
struct Node{
    Node *child[2];
    Node(){
        child[0] = child[1] = NULL;
    }
};
map<int,Node*>root;
void ins(Node *ver,int x){
    Node *p=ver;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        if(!p->child[c]){
            p->child[c]=new Node();
            p=p->child[c];
            continue;
        }
        Node *nw=new Node();
        nw->child[0]=p->child[c]->child[0];
        nw->child[1]=p->child[c]->child[1];
        p->child[c]=nw;
        p=p->child[c];
    }
}

int getMax(Node *ver,int x){
    Node *p=ver;
    int res=0;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        if(p->child[c^1]){
            res+=(1<<i);
            p=p->child[c^1];
        }
        else if(p->child[c]) p=p->child[c];
        else break;
    }
    return res;
}

int getMin(Node *ver,int x){
    Node *p=ver;
    int res=0;
    for(int i=31;i>=0;i--){
        int c=(x>>i)&1;
        if(p->child[c]){
            p=p->child[c];
        }
        else if(p->child[c^1]){
            res+=(1<<i);
            p=p->child[c^1];
        }
        else break;
    }
    return res;
}

