inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,cur,a[N],q,root[N];
struct Node{
    int l,r,val;
    Node(){
        l = r = val = 0;
    }
}tree[21*N];
void build(int id,int l=1,int r=n){
    if(l==r){
        tree[id].val=a[l];
        return;
    }
    int mid=(l+r)>>1;
    tree[id].l=++cur;
    tree[id].r=++cur;
    build(tree[id].l,l,mid);
    build(tree[id].r,mid+1,r);
    tree[id].val=tree[tree[id].l].val+tree[tree[id].r].val;
}
void up(int id,int pos,int k,int l=1,int r=n){
    if(l==r){
        tree[id].val=k;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid){
        tree[++cur]=tree[tree[id].l];
        tree[id].l=cur;
        up(tree[id].l,pos,k,l,mid);
    }
    else{
        tree[++cur]=tree[tree[id].r];
        tree[id].r=cur;
        up(tree[id].r,pos,k,mid+1,r);
    }
    tree[id].val=tree[tree[id].l].val+tree[tree[id].r].val;
}
int get(int id,int u,int v,int l=1,int r=n){
    if(l>v||r<u) return 0;
    if(u<=l&&r<=v){
        return tree[id].val;
    }
    int mid=(l+r)>>1;
    return get(tree[id].l,u,v,l,mid)+get(tree[id].r,u,v,mid+1,r);
}
