inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,a[N],cur,root[N];
struct Node{
    int l,r,val;
    Node(){
        l = r = 0;
        val=1e9;
    }
}tree[N*25];
void build(int id=1,int l=1,int r=n){
    if(l==r){
        tree[id].val=1e9;
        return;
    }
    int mid=(l+r)>>1;
    tree[id].l=++cur;
    tree[id].r=++cur;
    build(tree[id].l,l,mid);
    build(tree[id].r,mid+1,r);
    tree[id].val=min(tree[tree[id].l].val,tree[tree[id].r].val);
}
void up(int pos,int k,int id,int l=1,int r=n){
    if(l==r){
        tree[id].val=k;
        return;
    }
    int mid=(l+r)>>1;
    if(pos<=mid){
        tree[++cur]=tree[tree[id].l];
        tree[id].l=cur;
        up(pos,k,tree[id].l,l,mid);
    }
    else{
        tree[++cur]=tree[tree[id].r];
        tree[id].r=cur;
        up(pos,k,tree[id].r,mid+1,r);
    }
    tree[id].val=min(tree[tree[id].l].val,tree[tree[id].r].val);
}
int get(int u,int v,int id,int l=1,int r=n){
    if(l>v||r<u) return 1e9;
    if(u<=l&&r<=v) return tree[id].val;
    int mid=(l+r)>>1;
    return min(get(u,v,tree[id].l,l,mid),get(u,v,tree[id].r,mid+1,r));
}
