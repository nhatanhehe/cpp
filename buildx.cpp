#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "buildx"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=5e3+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,m,u,v,cnt,low[N],d[N],vis[N],scc[N],q,tp,c;
stack<int>s;
vector<int>tplt;
vector<int>g[N],xuoi[N],nguoc[N];
bitset<N>sc[N],den[N],di[N],dp_den[N],dp_di[N];
void tarjan(int u){
    s.push(u);
    d[u]=low[u]=++cnt;
    for(int v:g[u]){
        if(!vis[v]){
            if(d[v]) low[u]=min(low[u],low[v]);
            else{
                tarjan(v);
                low[u]=min(low[u],low[v]);
            }
        }
    }
    if(low[u]==d[u]){
        int v=s.top();
        int cur=v;
        tplt.pb(cur);
        do{
            v=s.top();
            scc[v]=cur;
            vis[v]=1;
            sc[cur].set(v);
            //cout<<tplt<<" "<<v<<" "<<" "<<sc[tplt]<<'\n';
            s.pop();
        }while(u!=v);
    }
}
ii edges[N];
void dfs_2(int u){
    vis[u]=1;
    di[u]=sc[u];
    for(int v:xuoi[u]){
        if(!vis[v]){
            dfs_2(v);
        }
        di[u]|=di[v];
    }
}
void dfs_3(int u){
    vis[u]=1;
    den[u]=sc[u];
    for(int v:nguoc[u]){
        if(!vis[v]){
            dfs_3(v);
        }
        den[u]|=den[v];
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m;
    for(int i=1;i<=m;i++){
        cin>>u>>v;
        g[u].pb(v);
        edges[i]=ii(u,v);
    }
    for(int i=1;i<=n;i++){
        if(!vis[i]) tarjan(i);
    }
    for(int i=1;i<=m;i++){
        auto [u,v]=edges[i];
        if(scc[u]!=scc[v]){
            xuoi[scc[u]].pb(scc[v]);
            nguoc[scc[v]].pb(scc[u]);
        }
    }
    memset(vis,0,sizeof vis);
    for(int i:tplt){
        if(!vis[i]) dfs_2(i);
    }
    memset(vis,0,sizeof vis);
    for(int i:tplt){
        if(!vis[i]) dfs_3(i);
    }
    for(int i=1;i<=n;i++){
        den[i]=den[scc[i]];
        di[i]=di[scc[i]];
    }
    cin>>q;
    int node=n;
    while(q--){
        cin>>tp;
        if(tp==1){
            cin>>u>>c;
            node++;
            if(!c){
                den[node]=den[u];
                den[node].set(node);
                //cout<<"node = "<<node<<" "<<den[node]<<'\n';
            }
            else{
                di[node]=di[u];
                di[node].set(node);
                //cout<<"node = "<<node<<" "<<di[node]<<'\n';
            }
        }
        else{
            cin>>u>>v;
            cout<<((di[u][v]|den[v][u])? "Yes\n":"No\n");
        }
    }
}
