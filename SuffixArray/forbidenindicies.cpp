const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
string s,t;
int n,lcp[N],pre[N],l[N],r[N];
vector<int>sa,c;
void build_suffix(){
    if(n==1){
        sa={0};
        c={0};
        return;
    }
    sa.resize(n);
    c.resize(n);
    vector<int>tmp(n);
    for(int i=0;i<n;i++){
        sa[i]=i;
        c[i]=s[i];
    }
    for(int gap=1;gap<n;gap<<=1){
        auto cmp=[&](const int &i,const int &j){
            if(c[i]!=c[j]) return c[i]<c[j];
            int ri=i+gap>=n? -1:c[i+gap];
            int rj=j+gap>=n? -1:c[j+gap];
            return ri<rj;
        };
        sort(all(sa),cmp);
        tmp[sa[0]]=0;
        for(int i=1;i<n;i++){
            tmp[sa[i]]=tmp[sa[i-1]]+cmp(sa[i-1],sa[i]);
        }
        c=tmp;
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>s>>t;
    reverse(all(s));
    reverse(all(t));
    build_suffix();
    ll ans=0;
    for(int i=0;i<n;i++){
        pre[i+1]=pre[i]+(t[sa[i]]=='1');
        if(t[sa[i]]=='0') ans=max(ans,1LL*n-sa[i]);
    }
    int k=0;
    for(int i=0;i<n;i++){
        if(c[i]!=n-1){
            for(int j=sa[c[i]+1];s[i+k]==s[j+k];){
                k++;
            }
            lcp[c[i]]=k;
            if(k) k--;
        }
    }
    stack<int>st;
    for(int i=0;i<n;i++){
        while(st.size()&&lcp[st.top()]>=lcp[i]) st.pop();
        if(st.empty()) l[i]=-1;
        else l[i]=st.top();
        st.push(i);
    }
    while(st.size()) st.pop();
    for(int i=n-1;i>=0;i--){
        while(st.size()&&lcp[st.top()]>=lcp[i]) st.pop();
        if(st.empty()) r[i]=n;
        else r[i]=st.top();
        st.push(i);
    }
    for(int i=0;i<n;i++){
        // so luong lcp forbidden trong doan l[i]+1 den r[i] -> r[i]+1 - l[i]+1
        ll sz=r[i]-l[i]-(pre[r[i]+1]-pre[l[i]+1]);
        ll height=lcp[i];
       // cout<<"1 "<<sz<<" "<<height<<'\n';
        ans=max(ans,sz*height);
    }
    cout<<ans;
}
