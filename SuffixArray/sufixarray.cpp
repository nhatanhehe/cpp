#include<bits/stdc++.h>
using namespace std;
#define ll long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "a"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=3e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,classes,cnt[N],p[N],c[N],pn[N],cn[N];
string s;
void init(){
    for(int i=0;i<n;i++) cnt[s[i]]++;
    for(int i=1;i<=256;i++) cnt[i]+=cnt[i-1];
    for(int i=0;i<n;i++){
        p[--cnt[s[i]]]=i;
    }
    c[p[0]]=0;
    classes=0;
    for(int i=1;i<n;i++){
        if(s[p[i]]!=s[p[i-1]]){
            classes++;
        }
        c[p[i]]=classes;
    }
}
void calc(){
    for(int h=0;(1<<h)<n;h++){
        for(int i=0;i<n;i++){
            pn[i]=p[i]-(1<<h);
            if(pn[i]<0) pn[i]+=n;
        }
        for(int i=0;i<=classes;i++) cnt[i]=0;
        for(int i=0;i<n;i++) cnt[c[pn[i]]]++;
        for(int i=1;i<=classes;i++){
            cnt[i]+=cnt[i-1];
        }
        for(int i=n-1;i>=0;i--){
            p[--cnt[c[pn[i]]]]=pn[i];
        }
        classes=0;
        cn[p[0]]=0;
        for(int i=1;i<n;i++){
            ii x=ii(c[p[i]],c[(p[i]+(1<<h))%n]);
            ii y=ii(c[p[i-1]],c[(p[i-1]+(1<<h))%n]);
            if(x!=y) classes++;
            cn[p[i]]=classes;
        }
        for(int i=0;i<n;i++) c[i]=cn[i];
    }
}
void build_suffix(){
    s+='$';
    n=s.size();
    init();
    calc();
    n--;
    s.pop_back();
    for(int i=0;i<n;i++){
        p[i]=p[i+1];
        cout<<p[i]<<' ';
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>s;
    build_suffix();
}
