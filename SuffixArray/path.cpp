#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "path  "
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=3e5+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,W,na,nb,m,u,v,w,p[N],sz_a[N],sz_b[N],ans;
struct pt{
    int u,v,w;
};
vector<pt>edges;
int acs(int u){
    return p[u]==u? u:p[u]=acs(p[u]);
}
void join(int u,int v,int w){
    u=acs(u);
    v=acs(v);
    if(u!=v){
        if(w==W) ans+=sz_a[u]*sz_b[v]+sz_b[u]*sz_a[v];
        p[v]=u;
        sz_a[u]+=sz_a[v];
        sz_b[u]+=sz_b[v];
    }
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>m>>W>>na>>nb;
    for(int i=1;i<=n;i++) p[i]=i;
    for(int i=1;i<=m;i++){
        cin>>u>>v>>w;
        edges.pb({u,v,w});
    }
    sort(all(edges),[](const pt &x,const pt &y){
        return x.w<y.w;
    });
    for(int i=1;i<=na;i++){
        int x;
        cin>>x;
        sz_a[x]=1;
    }
    for(int i=1;i<=nb;i++){
        int x;
        cin>>x;
        sz_b[x]=1;
    }
    for(auto [u,v,w]:edges){
        if(acs(u)!=acs(v)){
            join(u,v,w);
        }
    }
    cout<<ans;
}
