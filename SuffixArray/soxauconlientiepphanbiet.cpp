inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
vector<int>sa,c;
string s;
int n,lcp[N],l[N],r[N];
vector<int>build_suffix(){
    int n=s.size();
    vector<int>sa(n),tmp(n);
    c.resize(n);
    for(int i=0;i<n;i++){
        sa[i]=i;
        c[i]=s[i];
    }
    for(int gap=1;gap<n;gap<<=1){
        auto cmp=[&](int i,int j){
            if(c[i]!=c[j]) return c[i]<c[j];
            int ri=i+gap<n? c[i+gap]:-1;
            int rj=j+gap<n? c[j+gap]:-1;
            return ri<rj;
        };
        sort(all(sa),cmp);
        tmp[sa[0]]=0;
        for(int i=1;i<n;i++){
            tmp[sa[i]]=tmp[sa[i-1]]+(cmp(sa[i-1],sa[i])? 1:0);
        }
        c=tmp;
    }
    return sa;
}
