#include<bits/stdc++.h>
using namespace std;
#define ll long long
#define int long long
typedef long double ld;
#define pb push_back
#define pf push_front
#define Task "dance"
#define ii pair<int,int>
#define iii pair<int,ii>
#define all(x) x.begin(),x.end()
#define fi first
#define se second
const ll inf=1e18;
const ll N=1e3+5;
const ll mod=1e9+7;
const ll base=311;
#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,k,a[N],dp[N][N],Min[N];
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>n>>k;
    for(int i=1;i<=n;i++){
        cin>>a[i];
    }
    sort(a+1,a+n+1);
    memset(dp,0x3f,sizeof dp);
    dp[0][0]=0;
    Min[0]=0;
    for(int j=1;j<=n;j++) Min[j]=min(Min[j-1],dp[0][j]);
    for(int i=1;i<=k;i++){
        for(int j=2;j<=n;j++){
            dp[i][j]=min(Min[j-2]+abs(a[j-1]-a[j]),dp[i][j]);
        }
        Min[0]=dp[i][0];
        for(int j=1;j<=n;j++){
            Min[j]=min(Min[j-1],dp[i][j]);
        }
    }
    int ans=inf;
    for(int i=1;i<=n;i++){
        ans=min(ans,dp[k][i]);
    }
    cout<<ans;
}
