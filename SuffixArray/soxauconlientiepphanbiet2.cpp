#define On(mask,i) (mask|(1LL<<i))
#define Off(mask,i) (mask^(1LL<<i))
inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
int n,has[N],f[N],lcp[N],d['z'+3];
string s;
vector<int>sa;
vector<int> build_suffix(){
    int n=s.size();
    vector<int>sa(n),rank(n),tmp(n);
    for(int i=0;i<n;i++){
        sa[i]=i;
        rank[i]=s[i];
    }
    for(int gap=1;gap<n;gap<<=1){
        auto cmp=[&](const int &i,const int &j){
            if(rank[i]!=rank[j]) return rank[i]<rank[j];
            int ri=i+gap>=n? -1:rank[i+gap];
            int rj=j+gap>=n? -1:rank[j+gap];
            return ri<rj;
        };
        sort(all(sa),cmp);
        tmp[sa[0]]=0;
        for(int i=1;i<n;i++){
            tmp[sa[i]]=tmp[sa[i-1]]+cmp(sa[i-1],sa[i]);
        }
        rank=tmp;
    }
    return sa;
}
int get_hash(int l,int r){
    l++; r++;
    return sub(has[r],mul(has[l-1],f[r-l+1]));
}
bool check(int i,int j,int mid){
    if(i+mid-1>=n||j+mid-1>=n) return 0;
    return get_hash(i,i+mid-1)==get_hash(j,j+mid-1);
}
int get_len(int i,int j){
    int l=1,r=n,ans=0;
    while(l<=r){
        int mid=(l+r)>>1;
        if(check(i,j,mid)){
            l=mid+1;
            ans=mid;
        }
        else r=mid-1;
    }
    return ans;
}
main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);cout.tie(NULL);
    if (fopen(Task ".inp","r")) {
        freopen(Task ".inp","r", stdin);
        freopen(Task ".out","w", stdout);
    }
    cin>>s;
    n=s.size();
    sa=build_suffix();
    f[0]=1;
    for(int i=1;i<=3e5;i++){
        f[i]=mul(f[i-1],base);
    }
    for(int i=0;i<n;i++){
        has[i+1]=add(mul(has[i],base),s[i]-'a'+1);
    }
    for(int i=1;i<n;i++){
        lcp[i]=get_len(sa[i-1],sa[i]);
    }
    for(int i=0;i<n;i++){
        d[s[sa[i]]]+=(n-sa[i]-lcp[i]);
    }
    for(int i='a';i<='z';i++){
        cout<<d[i]<<' ';
    }
}
