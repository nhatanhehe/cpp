inline ll add(ll a,ll b){
    ll res=a+b;
    if(res>=mod) res-=mod;
    return res;
}
ll sub(ll a,ll b){
    return ((a-b)%mod+mod)%mod;
}
inline ll mul(ll a,ll b){
    ll res=a*b;
    if(res>=mod) res%=mod;
    return res;
}
string s;
vector<int>sa;
vector<int> build_suffix(){
    int n=s.size();
    vector<int>sa(n),rank(n);
    for(int i=0;i<n;i++){
        sa[i]=i;
        rank[i]=s[i];
    }
    vector<int>tmp(n);
    for(int gap=1;gap<n;gap<<=1){
        auto cmp=[&](int i,int j){
            if(rank[i]!=rank[j]) return rank[i]<rank[j];
            int ri=i+gap<n? rank[i+gap]:-1;
            int rj=j+gap<n? rank[j+gap]:-1;
            return ri<rj;
        };
        sort(all(sa),cmp);
        tmp[sa[0]]=0;
        for(int i=1;i<n;i++){
            tmp[sa[i]]=tmp[sa[i-1]]+(cmp(sa[i-1],sa[i])? 1:0);
        }
        rank=tmp;
    }
    return sa;
}
